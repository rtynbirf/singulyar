#!/usr/bin/env node
/* Тест логики ·25 КОШЕЛЁК. Ядро из отгруженного файла (S25:CORE-BEGIN/END),
   реальный WebCrypto. Запуск: node ИНСТРУМЕНТЫ/test_s25_logic.js */
'use strict';
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const { webcrypto } = require('crypto');

const ФАЙЛ = path.join(__dirname, '..', 'СИНГУЛЯР_25_КОШЕЛЁК.html');
const html = fs.readFileSync(ФАЙЛ, 'utf8');

let прошло = 0, всего = 0;
function ок(имя, условие) {
  всего++;
  if (условие) { прошло++; console.log('  ✓ ' + имя); }
  else { console.error('  ✗ ПРОВАЛ: ' + имя); }
}
function раздел(т) { console.log('\n— ' + т); }

раздел('извлечение ядра');
const начало = html.indexOf('/* S25:CORE-BEGIN */');
const конец = html.indexOf('/* S25:CORE-END */');
ок('маркеры найдены', начало >= 0 && конец > начало);
const ядро = html.slice(начало, конец + '/* S25:CORE-END */'.length);
const песочница = {
  crypto: webcrypto, TextEncoder, TextDecoder,
  btoa: (с) => Buffer.from(с, 'binary').toString('base64'),
  atob: (с) => Buffer.from(с, 'base64').toString('binary'),
  console
};
vm.createContext(песочница);
vm.runInContext(ядро + '\nthis.S25 = S25;', песочница);
const S25 = песочница.S25;
ок('S25 определён', !!S25 && typeof S25 === 'object');
ок('версия 1.0.0', S25.VERSION === '1.0.0');
ок('16 людей в реестре', S25.РЕЕСТР.length === 16);
ок('крипто живой', S25.криптоЖивой() === true);

раздел('ТИХИЙ ПЕРЕВОД: без подтверждений и уведомлений');
const БАБУШКА = { имя:'АНЯ', deviceId:'d-anya' };
const ВНУЧКА = { имя:'ЖЕНЯ', deviceId:'d-zhenya' };
const журнал = [
  { id:'f1', тип:'пополнение', от:{ имя:'семейная касса', deviceId:'касса' }, кому:БАБУШКА, сумма:1000, ts:1 }
];
ок('баланс бабушки 1000 из фактов', S25.балансИзФактов(журнал, БАБУШКА) === 1000);
const рез = S25.тихийПеревод(журнал, БАБУШКА, ВНУЧКА, 50, 'на пирожок', 'f2', 2);
ок('перевод прошёл сразу — никаких подтверждений', рез.ok === true);
ок('факт перевода содержит записку только для получателя', рез.факт.записка === 'на пирожок');
ок('у факта нет поля уведомления/подтверждения', JSON.stringify(res_нет(рез.факт)) === '[]');
function res_нет(ф){ return Object.keys(ф).filter(function(к){ return /уведом|подтвер|confirm|notify/i.test(к); }); }
ок('баланс после перевода: бабушка 950, внучка 50', S25.балансИзФактов(журнал.concat([рез.факт]), БАБУШКА) === 950 && S25.балансИзФактов(журнал.concat([рез.факт]), ВНУЧКА) === 50);
ок('не хватает — отказ честно', !S25.тихийПеревод(журнал, ВНУЧКА, БАБУШКА, 100, '', 'f3', 3).ok);
ок('дробная сумма отклонена', !S25.тихийПеревод(журнал, БАБУШКА, ВНУЧКА, 10.5, '', 'f4', 4).ok);
ок('отрицательная отклонена', !S25.тихийПеревод(журнал, БАБУШКА, ВНУЧКА, -5, '', 'f5', 5).ok);
ок('самому себе отклонено', !S25.тихийПеревод(журнал, БАБУШКА, { имя:'аня', deviceId:'d-anya' }, 10, '', 'f6', 6).ok);
ок('длинная записка обрезается до 200', S25.тихийПеревод(журнал, БАБУШКА, ВНУЧКА, 1, 'х'.repeat(300), 'f7', 7).факт.записка.length === 200);
ок('без записки поля нет', S25.тихийПеревод(журнал, БАБУШКА, ВНУЧКА, 1, '', 'f8', 8).факт.записка === undefined);

раздел('валидация фактов и merge');
ок('битый факт отклонён', !S25.валидныйФакт({ id:'x', тип:'перевод' }).ok);
ок('неизвестный тип отклонён', !S25.валидныйФакт({ id:'x', тип:'взлом', от:БАБУШКА, кому:ВНУЧКА, сумма:1, ts:1 }).ok);
ок('сумма-небbigint отклонена', !S25.валидныйФакт({ id:'x', тип:'перевод', от:БАБУШКА, кому:ВНУЧКА, сумма:1e9, ts:1 }).ok);
ок('merge дедуп по id', S25.объединитьФакты([рез.факт], [рез.факт]).length === 1);
ок('подписанный факт сильнее в merge', (() => {
  const голый = { id:'g', тип:'пополнение', от:{ имя:'семейная касса', deviceId:'касса' }, кому:ВНУЧКА, сумма:5, ts:9 };
  const подписанный = Object.assign({}, голый, { sig:'sig' });
  return S25.объединитьФакты([голый], [подписанный])[0].sig === 'sig';
})());

раздел('ХОТЕЛКИ: молчаливое финансирование (бабушкин сценарий)');
const хотелка = { id:'h1', хозяин:ВНУЧКА, что:'пирожок в школе', сколько:50, статус:'ждёт', ts:10 };
ок('хотелка валидна', S25.валиднаяХотелка(хотелка).ok);
ок('пустая хотела отклонена', !S25.валиднаяХотелка(Object.assign({}, хотелка, { что:'   ' })).ok);
ок('дробная цена отклонена', !S25.валиднаяХотелка(Object.assign({}, хотелка, { сколько:5.5 })).ok);
const закрытие = S25.закрытьХотелкуМолча(журнал.concat([рез.факт]), хотелка, БАБУШКА, 'f10', 20);
ок('закрыта молча: перевод создан', закрытие.ok && закрытие.факт.сумма === 50);
ок('закрыта молча: никого не спрашивали (нет полей согласования)', !закрытие.хотелка.согласовано && !закрытие.хотелка.подтверждение && !('уведомления' in закрытие.хотелка));
ок('статус стал «закрыта», закрыл известен', закрытие.хотелка.статус === 'закрыта' && закрытие.хотелка.закрыл.имя === 'АНЯ');
ок('повторное закрытие отклонено', !S25.закрытьХотелкуМолча(журнал, закрытие.хотелка, БАБУШКА, 'f11', 21).ok);
ок('без денег хотелка не закроется', !S25.закрытьХотелкуМолча([], Object.assign({}, хотелка), ВНУЧКА, 'f12', 22).ok);
ок('merge хотелок: закрытая сильнее ждущей', (() => {
  const мерж = S25.объединитьХотелки([хотелка], [закрытие.хотелка]);
  return мерж.length === 1 && мерж[0].статус === 'закрыта';
})());

раздел('БУМАЖКИ: выпуск → передача строкой → приём');
(async function(){
  const пара = await webcrypto.subtle.generateKey({ name:'ECDSA', namedCurve:'P-256' }, false, ['sign','verify']);
  const публ = await webcrypto.subtle.exportKey('jwk', пара.publicKey);
  const бумажка = { v:1, серийник:S25.серийникНовый(), номинал:100, эмитент:{ имя:'АНЯ', deviceId:'d-anya' }, sig:null, pub:публ };
  ок('серийник по формату SNG-hex16', /^SNG-[0-9a-f]{16}$/.test(бумажка.серийник));
  бумажка.sig = await S25.криптоПодпись(пара.privateKey, S25.строкаПодписиБумажки(бумажка));
  ок('подпись бумажки верна', await S25.проверитьБумажку(бумажка) === true);
  ок('подделанный номинал ловится', await S25.проверитьБумажку(Object.assign({}, бумажка, { номинал:1000 })) === false);
  const строка = S25.бумажкаСтрокой(бумажка);
  ок('строка по формату', строка.startsWith('СНГ-БУМАЖКА|1|'));
  const обратно = S25.бумажкаИзСтроки(строка);
  ок('бумажка выживает строку туда-обратно', обратно.ok && обратно.бумажка.серийник === бумажка.серийник && обратно.бумажка.номинал === 100);
  ок('мусор не бумажка', !S25.бумажкаИзСтроки('привет').ok);
  const фальшивая = S25.бумажкаИзСтроки(S25.бумажкаСтрокой(Object.assign({}, бумажка, { номинал:999 })));
  ок('подделанная строка ловится', фальшивая.ok && !(await S25.проверитьБумажку(фальшивая.бумажка)));
  /* приём у ЖЕНИ */
  const приём = S25.приёмБумажки(бумажка, ВНУЧКА, [], 'f20', 30);
  ок('приём создаёт факт бумажки', приём.ok && приём.факт.тип === 'бумажка' && приём.факт.сумма === 100);
  ок('баланс внучки вырос', S25.балансИзФактов([приём.факт], ВНУЧКА) === 100);
  ок('повторный приём той же купюры отклонён', !S25.приёмБумажки(бумажка, ВНУЧКА, [бумажка.серийник], 'f21', 31).ok);
  ок('бумажка без серийника отклонена', !S25.приёмБумажки({ номинал:5 }, ВНУЧКА, [], 'f22', 32).ok);

  console.log('\n═══ ИТОГ ·25: ' + прошло + '/' + всего + ' ═══');
  process.exit(прошло === всего ? 0 : 1);
})().catch(function(ошибка){ console.error('АСИНХРОННАЯ ОШИБКА:', ошибка); process.exit(1); });
