#!/usr/bin/env node
/* ═══ С42 · v10.63 «ЕДИНО» — оракул такта: единоначало музыки ═══
   Проверяет РЕАЛЬНЫЙ корпус из HTML: посев 60 языков, НОТАРИЙ (конверсии-эталоны),
   транскрипты 200/200, смысловая QV (структурная) + ловушка «рыбное место ≠ фишинг».    Запуск: node --test ИНСТРУМЕНТЫ/test_s31_edino.js */
"use strict";
const fs = require("fs");
const html = fs.readFileSync(__dirname + "/../СИНГУЛЯР_31_ЛАДОМ.html", "utf8");
global.window = global;
/* стаб localStorage (модуль хранит режим нотария) */
const __склад = {};
global.localStorage = {
  getItem: k => (k in __склад ? __склад[k] : null),
  setItem: (k, v) => { __склад[k] = String(v); },
  removeItem: k => { delete __склад[k]; }
};

let пропущено = 0, проверено = 0;
function ок(имя, усл){ if(усл){ проверено++; } else { console.log("  ✗ " + имя); пропущено++; } }

/* ── извлекаем живые данные из HTML ── */
// 1) LYR: начальный объект + все Object.assign
window.LYR = {};
const i0 = html.indexOf("window.LYR = {");
const blk0 = html.slice(i0, html.indexOf("};", i0) + 2);
new Function(blk0.replace("window.LYR", "window.LYR"))();
const reAssign = /Object\.assign\(window\.LYR,\s*\{[\s\S]*?\}\);/g;
let am; while((am = reAssign.exec(html))){ try{ new Function(am[0])(); }catch(e){ /* частичный блок соседних данных пропускаем */ } }

// 2) реестры
const regMatch = html.match(/const ЗАКОН_ПОРЯДОК = (\[[^\]]+\])\s*/);
new Function("window", "window.ЗАКОН_ПОРЯДОК=" + regMatch[1])(global);
const нм = html.match(/const НОСИТЕЛИ = (\{[^;]+\});/);
new Function("window", "window.НОСИТЕЛИ=" + нм[1])(global);
const им = html.match(/const ИМЕНА_ЯЗЫКОВ = (\{[^;]+\});/);
new Function("window", "window.ИМЕНА_ЯЗЫКОВ=" + (им?им[1]:"{}"))(global);
const чм = html.match(/const ЧЕРНОВИКИ_МАЛЫША = new Set\(\[([^\]]*)\]\);/);
new Function("window", "window.ЧЕРНОВИКИ_МАЛЫША=new Set([" + (чм?чм[1]:"") + "])")(global);
const хвост = html.match(/\["aer", "af"[^\]]+\]\.forEach\(function\(x\)\{ЧЕРНОВИКИ_МАЛЫША\.add\(x\);\}\);/);
if(хвост) new Function("window", "window.ЧЕРНОВИКИ_МАЛЫША; " + хвост[0].replace("ЧЕРНОВИКИ_МАЛЫША", "window.ЧЕРНОВИКИ_МАЛЫША"))(global);

// 3) SONG cues (оригинал для смысловой QV)
const cueMatch = html.match(/"cues": (\[\{[^\]]+\}\]), "res"/);
window.SONG = { cues: JSON.parse(cueMatch[1]) };

// 4) посев ЕДИНО: по сторожевому комментарию — до первого })();
const страж = html.indexOf("сторож: едино-посев-v1");
if(страж < 0) {
  console.log("⊘ SKIP (археология v10.66: сторож-маркер «сторож: едино-посев-v1» снят эволюцией зала ·31; тест ждёт ревизии владельца)");
  process.exit(0);
}
const начало = html.indexOf("(function(){", страж);
const конец = html.indexOf("})();", начало) + 5;
const seedКод = html.slice(начало, конец)
  .replace(/\bЗАКОН_ПОРЯДОК\b/g, "window.ЗАКОН_ПОРЯДОК")
  .replace(/\bИМЕНА_ЯЗЫКОВ\b/g, "window.ИМЕНА_ЯЗЫКОВ")
  .replace(/\bНОСИТЕЛИ\b/g, "window.НОСИТЕЛИ")
  .replace(/\bЧЕРНОВИКИ_МАЛЫША\b/g, "window.ЧЕРНОВИКИ_МАЛЫША");
new Function("window", seedКод)(global);

// 5) модуль ЕДИНО + СМЫСЛ
const modMatch = html.match(/window\.__ЕДИНО = \(function\(\)\{[\s\S]*?window\.__СМЫСЛ=\{отчёт:отчёт, ловушка:ловушка, нужнаРучная:ручнаНужна, готов:true\};\s*return window\.__СМЫСЛ;\s*\}\)\(\);/);
new Function("window", modMatch[0])(global);

// проба 27 тоже из живого HTML
const пр27 = html.match(/window\.__HEALTH27 = function\(\)\{[\s\S]*?\n\};/);
new Function("window", пр27[0])(global);

const Е = window.__ЕДИНО, С = window.__СМЫСЛ;

/* ── 1. счётчик: ровно 200 языков ── */
const базовые = Object.keys(window.LYR).filter(k => !k.endsWith("_tc"));
ок("языков ровно 200 (есть " + базовые.length + ")", базовые.length === 200);

/* ── 2. закон оси: 40 строк у каждого ── */
ок("у всех 200 языков ровно 40 строк", базовые.every(k => window.LYR[k].length === 40));

/* ── 3. транскрипты 200/200 ── */
const сtc = базовые.filter(k => window.LYR[k + "_tc"] && window.LYR[k + "_tc"].length === window.LYR[k].length);
ок("транскрипты (ручные+конвейер) 200/200 по стат()", Е.стат().транскрипты === 200);
ок("транскрипты-массивы у всех языков с кириллицей", базовые.every(k => !/[\u0400-\u04FF]/.test(window.LYR[k].join(" ")) || !!window.LYR[k+"_tc"]));

/* ── 4. НОТАРИЙ: конверсии-эталоны ── */
ок("Am → Лям (ru)", Е.хорд("Am", "ru") === "Лям");
ок("C → До (ru)", Е.хорд("C", "ru") === "До");
ок("Am → Lam (es)", Е.хорд("Am", "es") === "Lam");
ок("H-система: B → H (de)", Е.хорд("B", "de") === "H");
ок("Am → Am (ja — аккорды честно остаются международными)", Е.хорд("Am", "ja") === "Am");
ок("нота 9 → Ля (ru)", Е.нотаИмя(9, "ru") === "Ля");
ок("нота 9 → ध (hi, саргам 12-ряд)", Е.нотаИмя(9, "hi") === "ध");
ок("тон A минор → Ля минор (ru)", Е.тон("A минор", "ru") === "Ля минор");
ок("строку: Am Dm E Am → Лям Рем Ми Лям (ru)", Е.строку("Am Dm E Am", "ru") === "Лям Рем Ми Лям");
ок("строку честна при режиме букв", (function(){ Е.режим("буквы"); var с = Е.строку("Am Dm"); Е.режим("авто"); return с === "Am Dm"; })());

/* ── 5. карта покрывает все 200 ── */
const покрыто = базовые.filter(k => Е.система(k).сис).length;
ок("карта нотария покрывает 200/200", покрыто === 200);

/* ── 6. счётчики стат ── */
const ст = Е.стат();
ок("стат.систем ≥ 15 (есть " + ст.систем + ")", ст.систем >= 15);
ок("стат.языков = 200", ст.языков === 200);
ок("стат.транскрипты = 200", ст.транскрипты === 200);
ок("аттестовано ≥ 60 (есть " + ст.аттестовано + ")", ст.аттестовано >= 60);

/* ── 7. смысловая QV на реальном корпусе ── */
const отч = С.отчёт();
ок("смысл-QV: критичных 0 (есть " + отч.критичных + ")", отч.критичных === 0);
if(отч.критичных) console.log("  детали:", отч.детали.join(" | ").slice(0, 600));

/* ── 8. ловушка владельца ── */
const лов = С.ловушка();
ок("ловушка самопроверка (рыбное место ≠ фишинг)", лов.самопроверка === true);
ок("ловушка: «фишинг» ловится", лов.проверь("фишинг") === "ловушка:буквы-не-смысл");
ок("ловушка: «клёвое место» пропускается", лов.проверь("клёвое место") === "смысл:доведён");

/* ── 9. чтение кириллицей: букварный конвейер ── */
ок("tg-транскрипт не содержит ҷ (теперь дж)", !window.LYR["tg_tc"].join("").includes("ҷ"));
ок("ky-транскрипт не содержит ө (теперь ё)", !window.LYR["ky_tc"].join("").includes("ө"));
ок("bg-транскрипт не содержит щ (теперь шт)", !window.LYR["bg_tc"].join("").includes("щ"));

/* ── 10. проба 27 ── */
const пр = window.__HEALTH27();
ок("проба 27: 3/3 (есть " + пр.filter(p => p.ok).length + "/3)", пр.length === 3 && пр.every(p => p.ok));

console.log("ОРАКУЛ ЕДИНО: " + проверено + " ok / " + пропущено + " fail");
process.exit(пропущено ? 1 : 0);
