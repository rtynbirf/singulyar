test('I-01 ЧЕЛОВЕК РЕШАЕТ: запрет человека перекрывает словарь намерения', () => {
  подьмиРеестр();
  const р = compose({
    кто: 'человек-A', намерение: 'споём', контекст: ОКРУЖЕНИЕ,
    выбор: { запретить: ['запись', 'память'] }
  });
  assert.ok(р.ок);
  const м = р.варианты[0];
  assert.ok(!м.примитивы.includes('запись'));
  assert.ok(!м.примитивы.includes('память'));
  assert.ok(м.примитивы.includes('аудио'));
  const всёЗапретил = compose({ кто: 'человек-A', намерение: 'споём', контекст: ОКРУЖЕНИЕ, выбор: { запретить: ['люди', 'аудио', 'синхронизация', 'слова', 'запись', 'память'] } });
  assert.equal(всёЗапретил.ок, false);
  assert.equal(всёЗапретил.причина, 'ЧЕЛОВЕК_ЗАПРЕТИЛ_ВСЁ');
});

test('EMERGENCE: новый примитив без правки движка порождает новый режим человека', () => {
  подьмиРеестр();
  const до = compose({ кто: 'человек-A', намерение: 'посмотрим', контекст: ОКРУЖЕНИЕ });
  assert.ok(до.ок);
  assert.ok(!до.варианты[0].примитивы.includes('проектор'));
  assert.ok(!до.варианты[0].расширения.includes('проектор'));
  /* пришёл новый примитив (адаптер/устройство), объявивший расширение
     «посмотрим» — ядро и движок НЕ тронуты. Машина только ПРЕДЛАГАЕТ: */
  assert.equal(объявиПримитив({ имя: 'проектор', требует: ['экран-двойной'], даёт: ['большой-экран'], расширяет: ['посмотрим'] }).ok, true);
  const после = compose({ кто: 'человек-A', намерение: 'посмотрим', контекст: ОКРУЖЕНИЕ });
  assert.ok(после.варианты[0].расширения.includes('проектор'), 'расширение предложено — не вписано молча');
  /* человек решил взять — среда выросла; выбор человека высшего ранга (I-01): */
  const решено = compose({
    кто: 'человек-A', намерение: 'посмотрим', контекст: ОКРУЖЕНИЕ,
    выбор: { примитивы: ['люди', 'экран', 'синхронизация', 'чат', 'проектор'] }
  });
  assert.ok(решено.ок, решено.причина);
  assert.ok(решено.варианты[0].примитивы.includes('проектор'));
  /* новое слово человека = новая композиция старыми примитивами */
  assert.equal(объявиНамерение('споём-вдвоём', ['люди', 'аудио', 'синхронизация']).ok, true);
  const новаяСреда = compose({ кто: 'человек-A', намерение: 'споём-вдвоём', контекст: ОКРУЖЕНИЕ });
  assert.ok(новаяСреда.ок, новаяСреда.причина);
  assert.equal(validate(новаяСреда.варианты[0]).ok, true);
});

