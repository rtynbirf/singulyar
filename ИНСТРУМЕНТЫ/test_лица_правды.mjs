import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const корень = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const читай = (п) => fs.readFileSync(path.join(корень, п), 'utf8');
const реестр = JSON.parse(читай('data/versions.json'));
const сч = реестр.счётчики;

function бирка(текст, ключ) {
  const м = текст.match(new RegExp('data-реестр="' + ключ + '">([^<]*)<'));
  return м ? м[1] : null;
}

test('T-071: футер хаба — фолбэки = правде реестра (и все бирки обслуживаются)', () => {
  const хаб = читай('index.html');
  assert.equal(бирка(хаб, 'дверей'), String(сч.дверей), 'фолбэк дверей ≠ реестру');
  assert.equal(бирка(хаб, 'песен'), String(сч.песен), 'фолбэк песен ≠ реестру');
  assert.equal(бирка(хаб, 'языков'), String(сч.языков), 'фолбэк языков ≠ реестру');
  assert.equal(бирка(хаб, 'версия'), реестр.дом.версия, 'фолбэк версии ≠ реестру');
  assert.equal(бирка(хаб, 'такт'), реестр.дом.такт, 'фолбэк такта ≠ реестру');
  assert.equal(бирка(хаб, 'кэш'), реестр.дом.поколение_кэша, 'фолбэк кэша ≠ реестру');
  assert.ok(бирка(хаб, 'деплой') !== null, 'бирка деплоя (SHA выкладки) отсутствует в футере');
});

test('T-071: meta sng-build ≡ реестру + ГОТОВНОСТИ; SHA-место для pages.yml на месте', () => {
  const хаб = читай('index.html');
  const м = хаб.match(/<meta name="sng-build" content="([^"]*)">/);
  assert.ok(м, 'meta sng-build не найдена');
  const содержимое = м[1];
  assert.ok(содержимое.includes('такт v' + реестр.дом.версия + ' «' + реестр.дом.такт + '»'), 'мета: такт ≠ реестру');
  assert.ok(содержимое.includes('кэш ' + реестр.дом.поколение_кэша), 'мета: кэш ≠ реестру');
  const готов = JSON.parse(читай('ГОТОВНОСТЬ.manifest.json'));
  assert.ok(содержимое.includes('v' + готов.version), 'мета: сборка ГОТОВНОСТИ ≠ файлу');
  assert.ok(хаб.includes('СНГ:SHA-ДЕПЛОЯ-МЕСТО'), 'нет якоря для SHA-меты pages.yml');
  /* pages.yml обязан ставить SHA на живое лицо */
  const пайп = читай('.github/workflows/pages.yml');
  assert.ok(пайп.includes('sng-deploy-sha'), 'pages.yml не ставит sng-deploy-sha');
});

test('T-071: S15_CACHE в воркере ≡ поколению в реестре (одна тройка на всех лицах)', () => {
  const воркер = читай('sw15.js');
  const м = воркер.match(/var S15_CACHE = 's15-orkestrator-([^']+)'/);
  assert.ok(м, 'S15_CACHE не найден');
  assert.equal(м[1], реестр.дом.поколение_кэша, 'S15_CACHE ≠ реестру — пять поколений чисел возвращаются');
});

test('T-071: README «одна правда» — числа строк из словаря', () => {
  const ридми = читай('README.md');
  const строка = (имя) => {
    const м = ридми.match(new RegExp('\\|\\s*' + имя + '\\s*\\|\\s*\\*\\*([^*]+)\\*\\*'));
    assert.ok(м, 'строка «' + имя + '» не найдена в таблице правды');
    return м[1];
  };
  assert.ok(строка('Такт').startsWith(реестр.дом.версия + ' «' + реестр.дом.такт + '»'), 'README: такт ≠ реестру');
  assert.equal(строка('Поколение кэша'), 's15-orkestrator-' + реестр.дом.поколение_кэша, 'README: кэш ≠ реестру');
  assert.equal(строка('Двери'), сч.дверей_человек, 'README: двери ≠ словарю');
  assert.equal(строка('Песни фонда'), String(сч.песен), 'README: песни ≠ словарю');
  assert.equal(строка('Языки флагмана'), String(сч.языков), 'README: языки ≠ словарю');
  /* шапка README — тоже лицо: число песен = словарю */
  assert.ok(new RegExp('\\*\\*' + сч.песен + ' песни').test(ридми), 'шапка README: число песен ≠ словарю');
});

test('T-073: JSON-LD ·35 — числа производные словаря, раз счётчики разведены честно', () => {
  const фак = читай('СИНГУЛЯР_35_ВОПРОСЫ.html');
  const м = фак.match(/<script type="application\/ld\+json">\s*([\s\S]*?)\s*<\/script>/);
  assert.ok(м, 'JSON-LD не найден');
  const д = JSON.parse(м[1]); // валидность машины-читателя — обязательна
  const первый = д.mainEntity[0].acceptedAnswer.text;
  assert.ok(первый.includes(String(сч.дверей) + ' '), 'JSON-LD: двери ≠ словарю');
  assert.ok(первый.includes(String(сч.песен) + ' '), 'JSON-LD: песни ≠ словарю');
  assert.ok(первый.includes(String(сч.языков) + ' языков'), 'JSON-LD: языки ≠ словарю');
  /* ручное «41» и прочие старые числа в лицах отсутствуют */
  assert.ok(!фак.includes('>41<'), 'в ·35 остался ручной фолбэк 41');
});

test('T-073: очередь фонда в ·35 — по словарю (песен_очередь_фонд), не общий «песен»', () => {
  const фак = читай('СИНГУЛЯР_35_ВОПРОСЫ.html');
  assert.ok(фак.includes('data-реестр="песен_очередь_фонд"'), 'бирки очереди фонда не переведены на словарь');
  const фонд = JSON.parse(читай('data/фонд.json'));
  assert.equal(сч.песен_очередь_фонд, фонд.треки.length, 'словарь: очередь ≠ data/фонд.json');
  assert.equal(сч.релизы_канала, фонд.релизы.length, 'словарь: релизы ≠ data/фонд.json');
});

test('T-073: словарь счётчиков существует, производные сходятся с файлами', () => {
  assert.ok(сч.словарь && typeof сч.словарь === 'object', 'нет словаря счётчиков в реестре');
  for (const ключ of ['дверей', 'дверей_реестр', 'дверей_человек', 'песен', 'песен_очередь_фонд', 'релизы_канала', 'языков', 'деплой']) {
    const опр = сч.словарь[ключ];
    assert.ok(typeof опр === 'string' && опр.length > 10, 'нет однострочного определения для «' + ключ + '»');
  }
  assert.equal(сч.дверей_реестр, реестр.двери.length, 'дверей_реестр ≠ len(двери)');
  assert.equal(сч.дверей, реестр.двери.length - 1, 'дверей ≠ len(двери)−1');
  assert.equal(сч.дверей_человек, 'хаб + ' + сч.дверей, 'дверей_человек не производное');
});

test('T-072: строка о ветке деплоя в AGENTS.md ≡ pages.yml', () => {
  const агенты = читай('AGENTS.md');
  const пайп = читай('.github/workflows/pages.yml');
  const м = пайп.match(/push:[\s\S]*?branches:\s*\[([^\]]*)\]/);
  assert.ok(м, 'push-ветки pages.yml не найдены');
  const ветка = м[1].split(',')[0].trim();
  assert.ok(агенты.includes('ветка `' + ветка + '`'), 'AGENTS.md: ветка деплоя ≠ pages.yml (агентов дезинформируют)');
  /* гейт обязан красить ветку деплоя (F-021) */
  const гейт = читай('.github/workflows/такт_гейт.yml');
  assert.ok(/branches:\s*\[[^\]]*rumu[^\]]*\]/.test(гейт), 'такт-гейт не запускается на ветке деплоя rumu');
});

test('T-073: каждая бирка data-реестр в лицах обслуживается sg-registry', () => {
  const рег = читай('js/sg-registry.js');
  const обслуживаются = new Set([...рег.matchAll(/case '([^']+)':/g)].map((м) => м[1]));
  const лица = ['index.html', 'СИНГУЛЯР_35_ВОПРОСЫ.html'];
  const использованы = new Set();
  for (const л of лица) {
    for (const м of читай(л).matchAll(/data-реестр="([^"]+)"/g)) использованы.add(м[1]);
  }
  for (const ключ of использованы) {
    assert.ok(обслуживаются.has(ключ), 'бирка «' + ключ + '» в лицах не обслуживается sg-registry — число-ложь');
  }
  assert.ok(использованы.size >= 7, 'мало живых бирок: ' + [...использованы].join(','));
});
