#!/usr/bin/env node
/* Тест логики ·24 ПОЧТА. Ядро извлекается ИЗ ОТГРУЖЕННОГО файла (маркеры
   S24:CORE-BEGIN/END) и исполняется в песочнице с реальным WebCrypto (Node).
   Запуск: node ИНСТРУМЕНТЫ/test_s24_logic.js */
'use strict';
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const { webcrypto } = require('crypto');

const ФАЙЛ = path.join(__dirname, '..', 'СИНГУЛЯР_24_ПОЧТА.html');
const html = fs.readFileSync(ФАЙЛ, 'utf8');

let прошло = 0, всего = 0;
function ок(имя, условие) {
  всего++;
  if (условие) { прошло++; console.log('  ✓ ' + имя); }
  else { console.error('  ✗ ПРОВАЛ: ' + имя); }
}
function раздел(т) { console.log('\n— ' + т); }

раздел('извлечение ядра из отгруженного файла');
const начало = html.indexOf('/* S24:CORE-BEGIN */');
const конец = html.indexOf('/* S24:CORE-END */');
ок('маркеры найдены и в правильном порядке', начало >= 0 && конец > начало);
const ядро = html.slice(начало, конец + '/* S24:CORE-END */'.length);

const песочница = {
  crypto: webcrypto,
  TextEncoder, TextDecoder,
  btoa: (с) => Buffer.from(с, 'binary').toString('base64'),
  atob: (с) => Buffer.from(с, 'base64').toString('binary'),
  console,
  setTimeout, clearTimeout
};
vm.createContext(песочница);
vm.runInContext(ядро + '\nthis.S24 = S24;', песочница);
const S24 = песочница.S24;
ок('S24 определён', !!S24 && typeof S24 === 'object');
ок('версия 1.0.0', S24.VERSION === '1.0.0');
ок('домен singulyar', S24.ДОМЕН === 'singulyar');
ок('шесть папок', S24.ФОРДЕРЫ.length === 6 && S24.ФОРДЕРЫ.includes('исходящие') && S24.ФОРДЕРЫ.includes('корзина'));
ок('крипто живой (WebCrypto доступен)', S24.криптоЖивой() === true);

раздел('адресация');
ок('адрес по id', S24.адресПоИд('pasha') === 'pasha@singulyar');
ок('человек по адресу', S24.человекПоАдресу('anya@singulyar') && S24.человекПоАдресу('anya@singulyar').имя === 'АНЯ');
ок('чужой домен не признаётся', S24.человекПоАдресу('anya@gmail.com') === null);
ок('несуществующий id — null', S24.человекПоАдресу('ivan@gmail.singulyar') === null && S24.человекПоАдресу('zzz@singulyar') === null);
ок('адрес гостя стабилен и по формату', /^g\d{4}@singulyar$/.test(S24.адресГостя('dev-123')));
ок('адрес гостя зависит от deviceId', S24.адресГостя('a') !== S24.адресГостя('b'));
ок('мой адрес для своих — по имени круга', S24.мойАдрес({ имя:'АНЯ', тип:'свой', deviceId:'d1' }) === 'anya@singulyar');
ок('мой адрес для гостя — от устройства', S24.мойАдрес({ имя:'ГОСТЬ МАША', тип:'гость', deviceId:'d2' }) === S24.адресГостя('d2'));
ок('без личности адреса нет', S24.мойАдрес(null) === null);

раздел('разбор «Кому»: имена, алиасы, адреса');
ок('имя круга', S24.разбериКому('АНЯ').ok && S24.разбериКому('АНЯ').адреса[0] === 'anya@singulyar');
ок('алиас БАБУШКА → anya', S24.разбериКому('БАБУШКА').адреса[0] === 'anya@singulyar');
ок('Ё/Е: ВАНЁК → ivan', S24.разбериКому('ВАНЁК').адреса[0] === 'ivan@singulyar');
ок('несколько через запятую + дедуп', S24.разбериКому('АНЯ, anya@singulyar, ВАНЯ').ok && S24.разбериКому('АНЯ, anya@singulyar, ВАНЯ').адреса.length === 2);
ок('чужой домен отклонён с причиной', !S24.разбериКому('spammer@gmail.com').ok && S24.разбериКому('spammer@gmail.com').причины.length === 1);
ок('неизвестное имя отклонено', !S24.разбериКому('НЕЗНАКОМЕЦ').ok);
ок('пусто — не ok', !S24.разбериКому('').ok);

раздел('гвард коротких имён');
ок('МАША защищена', !S24.проверьИмя('МАША').ok);
ок('алиас БАБА защищён', !S24.проверьИмя('БАБА').ok);
ок('ГОСТЬ МАША проходит', S24.проверьИмя('ГОСТЬ МАША').ok);
ок('сбор с префиксом', S24.собериСПрефиксом('СОСЕД', 'ВАНЯ').ok && S24.собериСПрефиксом('СОСЕД', 'ВАНЯ').имя === 'СОСЕД ВАНЯ');
ок('защищённый префикс отклонён', !S24.собериСПрефиксом('ПАПА', 'КТО-ТО').ok);

раздел('валидация письма и очередь');
const письмо = { id:'l1', от:{ адрес:'anya@singulyar', имя:'АНЯ', deviceId:'d1' }, кому:['pasha@singulyar'], тема:'привет', текст:'как дела?', ts:1000 };
ок('валидное письмо проходит', S24.валидноеПисьмо(письмо).ok);
ок('без id — отказ', !S24.валидноеПисьмо(Object.assign({}, письмо, { id:undefined })).ok);
ок('пустой текст допустим (письмо-вложение)', S24.валидноеПисьмо(Object.assign({}, письмо, { текст:'' })).ok);
ок('текст-не-строка — отказ', !S24.валидноеПисьмо(Object.assign({}, письмо, { текст:null })).ok);
ок('нечитаемая длина текста — отказ', !S24.валидноеПисьмо(Object.assign({}, письмо, { текст:'х'.repeat(60001) })).ok);
ок('слишком длинная тема — отказ', !S24.валидноеПисьмо(Object.assign({}, письмо, { тема:'х'.repeat(201) })).ok);
const в_исх = S24.письмо_в_исходящие(письмо);
ок('в исходящие: папка и флаг', в_исх.ok && в_исх.письмо.папка === 'исходящие');
ок('доставка: из исходящих в отправленные', S24.письмо_доставлено(в_исх.письмо).ok && S24.письмо_доставлено(в_исх.письмо).письмо.папка === 'отправленные');
ок('доставка не-исходящего отклоняется', !S24.письмо_доставлено(Object.assign({}, письмо, { папка:'черновики' })).ok);
ок('в архив и в корзину', S24.письмо_в_архив(письмо).папка === 'архив' && S24.письмо_в_корзину(письмо).папка === 'корзина');

раздел('слияние истории (дедуп по id)');
const дубль = Object.assign({}, письмо, { ts:2000 });
ок('дубликат не размножается', S24.объединитьИсторию([письмо], [дубль]).length === 1);
ок('невалидные из сети отбрасываются', S24.объединитьИсторию([], [{ id:'x' }]).length === 0);
const п2 = Object.assign({}, письмо, { id:'l2', ts:500 });
ок('сортировка по времени', S24.объединитьИсторию([письмо], [п2])[0].id === 'l2');

раздел('EML-экспорт');
const eml = S24.экспортEML(Object.assign({}, письмо, { sig:'SIG123' }));
ок('EML: From/To/Subject', eml.includes('From: АНЯ <anya@singulyar>') && eml.includes('To: pasha@singulyar') && eml.includes('Subject: привет'));
ок('EML: честная пометка сети', eml.includes('X-Singulyar-Network: P2P singulyar (не SMTP)'));
ок('EML: подпись в заголовке', eml.includes('X-Singulyar-Sig: SIG123'));

раздел('балиджи папок (считаются)');
const б = S24.балиджиПапок([Object.assign({}, письмо, { папка:'входящие', прочитано:false }), Object.assign({}, письмо, { id:'l3', папка:'входящие', прочитано:true }), Object.assign({}, письмо, { id:'l4', папка:'архив' })]);
ок('входящие 2, архив 1, непрочитанных 1', б['входящие'] === 2 && б['архив'] === 1 && б._непрочит === 1);

раздел('крипто: подпись и проверка (реальный WebCrypto)');
(async function(){
  const пара = await webcrypto.subtle.generateKey({ name:'ECDSA', namedCurve:'P-256' }, false, ['sign','verify']);
  const публ = await webcrypto.subtle.exportKey('jwk', пара.publicKey);
  const строка = S24.строкаПодписи(письмо);
  const sig = await S24.криптоПодпись(пара.privateKey, строка);
  ок('подпись непустая base64', typeof sig === 'string' && sig.length > 40);
  ок('проверка верной подписи', await S24.криптоПроверка(публ, строка, sig) === true);
  ок('подделанный текст ловится', await S24.криптоПроверка(публ, S24.строкаПодписи(Object.assign({}, письмо, { текст:'подделано' })), sig) === false);
  ок('битая подпись не валит процесс', await S24.криптоПроверка(публ, строка, 'невалидная-подпись') === false);
  /* подписанное письмо прикладывает pub и sig */
  const подписанное = S24.письмо_подписано(в_исх.письмо, sig, публ);
  ок('письмо_подписано: sig+pub на месте', подписанное.sig === sig && подписанное.pub && подписанное.подписано === true);

  console.log('\n═══ ИТОГ ·24: ' + прошло + '/' + всего + ' ═══');
  process.exit(прошло === всего ? 0 : 1);
})().catch(function(ошибка){ console.error('АСИНХРОННАЯ ОШИБКА:', ошибка); process.exit(1); });
