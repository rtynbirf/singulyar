#!/usr/bin/env node
/* ТЕСТ логики LLM-среза (правило №10: против живых файлов).
   БИБЛИОТЕКИ/adapter-os/llm.mjs — чистый ESM без window/document:
   — словарь фраз вшит (версия ≥ v0.6, ≥ 100 фраз; доучка v0.5: круг/почта/
     кошелёк/линия/хор/караоке, манеры; v0.6 — словарь не менялся);
     правила ≥ 12 пунктов (ДОМ, ТАКТ, ВМЕСТИЛИЩЕ);
   — нормализация речи (регистр, ё/е, пунктуация) не ломает команды;
   — разобрать() возвращает намерение для всех команд словаря;
   — префиксные намерения (send, llm) извлекают текст после префикса;
   — неизвестная фраза → null (уходит модели или честному «не поняла»);
   — адаптер llm.local без загрузки честно UNAVAILABLE с причиной;
   — адаптер input.speech честен о среде;
   — правило-слой исполняет команды без модели;
  — решитьСтраницу() резолвит живую речь в реальные файлы страниц.
Запуск: node ИНСТРУМЕНТЫ/test_llm_logic.mjs   (пути от файла) */
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = dirname(HERE);
const { ФРАЗЫ, СЛОВАРЬ_ВЕРСИЯ, ПРАВИЛА_ТЕКСТ, нормализовать, разобрать, решитьСтраницу,
        создатьLlmАдаптер, создатьРечьАдаптер, создатьПравилоСлой } = await import('file://' + join(ROOT, 'БИБЛИОТЕКИ', 'adapter-os', 'llm.mjs'));

let ok = 0, fail = 0;
function check(name, cond, extra = '') {
  if (cond) { ok++; console.log('  OK   ' + name); }
  else { fail++; console.log('  FAIL ' + name + ' ' + extra); }
}

/* 1. Словарь жив, версионирован и покрывает все намерения */
check('словарь ≥ 100 фраз (76 v0.4 + доучка v0.5)', Array.isArray(ФРАЗЫ) && ФРАЗЫ.length >= 100, String(ФРАЗЫ && ФРАЗЫ.length));
const НАМЕРЕНИЯ = new Set(['stop', 'status', 'send', 'read', 'clear', 'clear_field', 'read_log', 'help', 'llm', 'load_model', 'open', 'repeat', 'ping', 'count', 'identity']);
check('намерения словаря из известного набора', ФРАЗЫ.every(f => НАМЕРЕНИЯ.has(f.намерение)));
check('намерение load_model присутствует (загрузка модели голосом)', ФРАЗЫ.some(f => f.намерение === 'load_model'));
for (const н of ['open', 'repeat', 'ping', 'count', 'identity']) {
  check('намерение ' + н + ' присутствует (доучка v0.4)', ФРАЗЫ.some(f => f.намерение === н));
}
check('версия словаря ≥ v0.6', typeof СЛОВАРЬ_ВЕРСИЯ === 'string' && СЛОВАРЬ_ВЕРСИЯ >= 'v0.6', СЛОВАРЬ_ВЕРСИЯ);
check('правила (инструкционный слой) вшиты: ≥ 12 пунктов', typeof ПРАВИЛА_ТЕКСТ === 'string' && (ПРАВИЛА_ТЕКСТ.match(/^\d+\./gm) || []).length >= 12);
check('правила знают новый дом (кошелёк, почта, круг)', typeof ПРАВИЛА_ТЕКСТ === 'string' && /кошел/.test(ПРАВИЛА_ТЕКСТ) && /почт/.test(ПРАВИЛА_ТЕКСТ) && /круг/.test(ПРАВИЛА_ТЕКСТ));
check('правила держат такт: деньги-тишина и гости', typeof ПРАВИЛА_ТЕКСТ === 'string' && /ТИКТ|не спрашивай/.test(ПРАВИЛА_ТЕКСТ) && /ГОСТЬ/.test(ПРАВИЛА_ТЕКСТ));
check('правила называют голосовую навигацию', typeof ПРАВИЛА_ТЕКСТ === 'string' && /открой/.test(ПРАВИЛА_ТЕКСТ));
check('правило 12: человек — вместилище (наполняется, не растёт)', typeof ПРАВИЛА_ТЕКСТ === 'string' && /12\. ЧЕЛОВЕК — ВМЕСТИЛИЩЕ/.test(ПРАВИЛА_ТЕКСТ) && /НАПОЛНЯЕТСЯ/.test(ПРАВИЛА_ТЕКСТ) && /вселенная/.test(ПРАВИЛА_ТЕКСТ) && /созреешь/.test(ПРАВИЛА_ТЕКСТ));

/* 2. Все фразы словаря разбираются */
let неразобранных = 0;
for (const f of ФРАЗЫ) {
  if (f.намерение === 'llm') continue; /* фразы llm — примеры свободной речи, не команды */
  const r = разобрать(f.фраза);
  if (!r || r.намерение !== f.намерение) { неразобранных++; console.log('       не разобрано: «' + f.фраза + '» → ' + JSON.stringify(r)); }
}
check('все команды словаря (кроме примеров llm) дают своё намерение', неразобранных === 0, String(неразобранных));

/* 3. Живая речь не ломает команды */
const живые = [
  ['СТОП', 'stop'],
  ['Статус!', 'status'],
  ['что у тебя работает?', 'status'],
  ['Очисти журнал.', 'clear'],
  ['ё… прочитай журнал', null], /* невалидные данные перед фразой — не команда */
  ['ЗАМОЛЧИ', 'stop'],
  ['какие каналы работают', 'status'],
  ['отправь: привет из голоса', 'send'],
  ['Отправь: тест', 'send'],
  ['загрузи модель', 'load_model'],
  ['Загрузи модель!', 'load_model'],
  ['скачай модель', 'load_model'],
  /* доучка v0.4 */
  ['открой зал', 'open'],
  ['ОТКРОЙ ЗАЛ!', 'open'],
  ['пойди в суфлёр', 'open'],
  ['открой, пожалуйста, связь', 'open'],
  ['откройте зал', 'open'],
  ['вернись на главную', 'open'],
  ['повтори: раз два три', 'repeat'],
  ['Повтори раз два', 'repeat'],
  ['скажи: проверка', 'repeat'],
  ['пинг', 'ping'],
  ['ты здесь?', 'ping'],
  ['откликнись', 'ping'],
  ['сколько команд ты знаешь', 'count'],
  ['кто ты', 'identity'],
  ['ты кто', 'identity'],
  ['привет, кто ты', 'llm'], /* пример свободной речи из словаря → намерение llm (без модели — честное «не загружена») */
  /* доучка v0.5 */
  ['открой круг', 'open'],
  ['ОТКРОЙ ПОЧТУ', 'open'],
  ['открой кошелёк', 'open'],
  ['открой кошелек', 'open'],
  ['открой линию', 'open'],
  ['открой, пожалуйста, чаты', 'open'],
  ['откройте звонки', 'open'],
  ['пойди в хор', 'open'],
  ['открой караоке', 'open'],
  ['открой смс', 'open'],
  ['открой письма', 'open'],
  ['хватит', 'stop'],
  ['ау', 'ping'],
  ['ты робот', 'identity'],
  ['ты человек', 'identity'],
  ['что такое кристалл', 'llm'],
  ['кто в круге', 'llm'],
  ['куда бабушка потратила деньги', 'llm'],
];
for (const [фраза, ожид] of живые) {
  const r = разобрать(фраза);
  check('речь «' + фраза + '» → ' + ожид, (r ? r.намерение : null) === ожид, JSON.stringify(r));
}

/* 4. Префиксные намерения извлекают текст */
const р1 = разобрать('отправь: проверка связи — раз');
check('send извлекает текст после префикса', р1 && р1.намерение === 'send' && р1.текст === 'проверка связи — раз', JSON.stringify(р1));
const р2 = разобрать('скажи получателю: до связи');
check('send вариант «скажи получателю:»', р2 && р2.намерение === 'send' && р2.текст === 'до связи', JSON.stringify(р2));
const р3 = разобрать('объясни: зачем смысл и представление');
check('llm-префикс «объясни:» проходит сквозь', р3 && р3.намерение === 'llm' && /зачем смысл/.test(р3.текст), JSON.stringify(р3));
const р4 = разобрать('перепиши короче: длинный текст тут');
check('llm-префикс «перепиши короче:»', р4 && р4.намерение === 'llm' && /длинный текст/.test(р4.текст), JSON.stringify(р4));
check('нормализация: регистр, ё→е, знаки', нормализовать('Статус!') === 'статус' && нормализовать('Ёжик') === 'ежик');

/* 4b. Доучка v0.4: префиксы repeat и порядок «скажи получателю:» раньше «скажи:» */
const р5 = разобрать('повтори: текст эха');
check('repeat извлекает текст после префикса', р5 && р5.намерение === 'repeat' && р5.текст === 'текст эха', JSON.stringify(р5));
const р6 = разобрать('скажи: привет');
check('repeat-префикс «скажи:»', р6 && р6.намерение === 'repeat' && р6.текст === 'привет', JSON.stringify(р6));
const р7 = разобрать('скажи получателю: привет');
check('порядок префиксов: «скажи получателю:» остался send', р7 && р7.намерение === 'send' && р7.текст === 'привет', JSON.stringify(р7));
const р8 = разобрать('открой');
check('голое «открой» — open без цели (исполнитель спросит)', р8 && р8.намерение === 'open', JSON.stringify(р8));

/* 4c. решитьСтраницу: живая речь → реальные файлы репы */
const стр = [
  ['зал', 'СИНГУЛЯР_17_ЗАЛ.html'],
  ['пожалуйста, суфлер', 'СИНГУЛЯР_16_СУФЛЁР.html'],
  ['связь', 'СИНГУЛЯР_22_СВЯЗЬ.html'],
  ['общение', 'СИНГУЛЯР_21_ОБЩЕНИЕ.html'],
  ['фонетику', 'СИНГУЛЯР_20_ФОНЕТИКА.html'],
  ['событие', 'СИНГУЛЯР_18_СОБЫТИЕ.html'],
  ['человека', 'СИНГУЛЯР_19_ЧЕЛОВЕК.html'],
  ['оркестратор', 'СИНГУЛЯР_15_ОРКЕСТРАТОР.html'],
  ['фабрику', 'СИНГУЛЯР_02_ФАБРИКА_эмерджентная_архитектура.html'],
  ['резонанс', 'СИНГУЛЯР_02_РЕЗОНАНС_Когда_теряем_157_голосов.html'],
  ['когда теряем', 'СИНГУЛЯР_01_Когда_теряем_157_голосов.html'],
  ['на главную', 'index.html'],
  ['домой', 'index.html'],
  /* доучка v0.5 — новый дом */
  ['круг', 'СИНГУЛЯР_23_КРУГ.html'],
  ['пожалуйста, почту', 'СИНГУЛЯР_24_ПОЧТА.html'],
  ['кошелёк', 'СИНГУЛЯР_25_КОШЕЛЁК.html'],
  ['кошелек', 'СИНГУЛЯР_25_КОШЕЛЁК.html'],
  ['линию', 'СИНГУЛЯР_26_ЛИНИЯ.html'],
  ['смс', 'СИНГУЛЯР_26_ЛИНИЯ.html'],
  ['номер', 'СИНГУЛЯР_26_ЛИНИЯ.html'],
  ['чаты', 'СИНГУЛЯР_23_КРУГ.html'],
  ['звонки', 'СИНГУЛЯР_23_КРУГ.html'],
  ['письма', 'СИНГУЛЯР_24_ПОЧТА.html'],
  ['переводы', 'СИНГУЛЯР_25_КОШЕЛЁК.html'],
  ['караоке', 'СИНГУЛЯР_17_ЗАЛ.html'],
  ['хор', 'СИНГУЛЯР_15_ОРКЕСТРАТОР.html'],
];
for (const [цель, файл] of стр) {
  const р = решитьСтраницу(цель);
  check('страница «' + цель + '» → ' + файл, р && р.файл === файл, JSON.stringify(р));
}
check('неведомая цель → честный null', решитьСтраницу('чепуху неведомую') === null);
check('пустая цель → null', решитьСтраницу('') === null);

/* 5. Неизвестное — честный null */
check('свободная фраза без модели → null', разобрать('какая завтра погода') === null);
check('пустая строка → null', разобрать('   ') === null);
check('пусто не команда', разобрать('') === null);

/* 6. Адаптер llm.local: честный статус до загрузки */
const llm = создатьLlmАдаптер();
const ст0 = llm.status();
check('llm.local: state UNAVAILABLE до загрузки', ст0.state === 'UNAVAILABLE', JSON.stringify(ст0));
check('llm.local: причина названа', !!(ст0.reason && ст0.reason.length > 4), JSON.stringify(ст0));
check('llm.local: privacy local', ст0.privacy === 'local');
check('llm.local: kind llm, есть id', llm.id === 'llm.local' && llm.kind === 'llm');
let генОшибка = null;
try { await llm.generate('привет'); } catch (e) { генОшибка = e; }
check('generate до загрузки бросает честную ошибку', генОшибка !== null);

/* 7. Адаптер input.speech: честный статус среды */
const речь = создатьРечьАдаптер();
check('input.speech: id/kind', речь.id === 'input.speech' && речь.kind === 'input');
const стР = речь.status();
check('input.speech: состояние из набора STATUS', ['READY', 'UNAVAILABLE', 'BROWSER_DEPENDENT', 'PERMISSION_REQUIRED'].includes(стР.state), JSON.stringify(стР));

/* 8. Правило-слой: исполнение без модели */
const вызовы = [];
const исполнитель = {
  send: (т) => вызовы.push(['send', т]),
  read: () => вызовы.push(['read']),
  clear: () => вызовы.push(['clear']),
  clearField: () => вызовы.push(['clearField']),
  readLog: () => вызовы.push(['readLog']),
  status: () => вызовы.push(['status']),
  help: () => вызовы.push(['help']),
  stop: () => вызовы.push(['stop']),
  loadModel: () => вызовы.push(['loadModel']),
  say: (т) => вызовы.push(['say', т]),
  open: (т) => вызовы.push(['open', т]),
  repeat: (т) => вызовы.push(['repeat', т]),
  ping: () => вызовы.push(['ping']),
  count: () => вызовы.push(['count']),
  identity: () => вызовы.push(['identity']),
};
const слой = создатьПравилоСлой(исполнитель);
await слой.исполнить('статус');
await слой.исполнить('отправь: привет, как дела');
await слой.исполнить('очисти журнал');
await слой.исполнить('стоп');
check('исполнитель получил команды', JSON.stringify(вызовы.slice(0, 4)) === JSON.stringify([['status'], ['send', 'привет, как дела'], ['clear'], ['stop']]), JSON.stringify(вызовы));
await слой.исполнить('открой зал');
await слой.исполнить('повтори: раз');
await слой.исполнить('пинг');
await слой.исполнить('кто ты');
await слой.исполнить('сколько команд ты знаешь');
check('исполнитель получил доучку v0.4', JSON.stringify(вызовы.slice(4, 9)) === JSON.stringify([['open', 'зал'], ['repeat', 'раз'], ['ping'], ['identity'], ['count']]), JSON.stringify(вызовы));
await слой.исполнить('открой круг');
await слой.исполнить('открой кошелёк');
await слой.исполнить('открой почту');
await слой.исполнить('открой линию');
check('исполнитель получил доучку v0.5', JSON.stringify(вызовы.slice(9, 13)) === JSON.stringify([['open', 'круг'], ['open', 'кошелек'], ['open', 'почту'], ['open', 'линию']]), JSON.stringify(вызовы));
const свободный = await слой.исполнить('какая завтра погода');
check('свободная фраза вне модели → null, без выдумок', свободный === null);

console.log('\nИТОГ: ' + ok + ' OK / ' + fail + ' FAIL');
process.exit(fail ? 1 : 0);
