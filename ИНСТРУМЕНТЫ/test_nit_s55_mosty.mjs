/* ═══════════════════════════════════════════════════════════════════════════
   СТРАЖ НИТИ s55 ⇄ ·18–·26 (О-3: их мосты С125 «ЗАКРЫТО» — канон; мой страж держит симметрию) (такт v11.49 С127)
   Симметрия: s55.связи в манифесте ⇄ обратные мосты в файлах дверей
   ⇄ строка ·55 в меню SG65 каждой двери-нити.
   node --test ИНСТРУМЕНТЫ/test_nit_s55_mosty.mjs
   ═══════════════════════════════════════════════════════════════════════════ */
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const корень = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const ДВЕРИ_НИТИ = {
  s18: 'СИНГУЛЯР_18_СОБЫТИЕ.html',
  s19: 'СИНГУЛЯР_19_ЧЕЛОВЕК.html',
  s20: 'СИНГУЛЯР_20_ФОНЕТИКА.html',
  s21: 'СИНГУЛЯР_21_ОБЩЕНИЕ.html',
  s22: 'СИНГУЛЯР_22_СВЯЗЬ.html',
  s23: 'СИНГУЛЯР_23_КРУГ.html',
  s24: 'СИНГУЛЯР_24_ПОЧТА.html',
  s25: 'СИНГУЛЯР_25_КОШЕЛЁК.html',
  s26: 'СИНГУЛЯР_26_ЛИНИЯ.html',
};
const ФАЙЛ_55 = 'СИНГУЛЯР_43_ЕДИНОЕ_ОКНО_КОММУНИКАЦИИ.html';

test('манифест: s55.связи перечисляет все девять нитей ·18–·26', () => {
  const ядро = fs.readFileSync(path.join(корень, 'singulyar-modules.js'), 'utf8');
  const м = ядро.match(/\{ id: 's55'[\s\S]*?связи: \[([^\]]*)\]/);
  assert.ok(м, 'нет записи s55 в манифесте-нити');
  const связи = м[1].match(/'s\d+'/g).map((x) => x.slice(1, -1)).sort();
  assert.deepEqual(связи, Object.keys(ДВЕРИ_НИТИ).sort(), 's55.связи не симметрична списку нитей');
});

for (const [ид, файл] of Object.entries(ДВЕРИ_НИТИ)) {
  test('нить ' + ид + ': мост в файле и строка в SG65 (' + файл + ')', () => {
    const s = fs.readFileSync(path.join(корень, файл), 'utf8');
    /* их канон С125: мосты-ответы ·18–·26 → ·55 в каждой двери */
    assert.ok(s.includes(ФАЙЛ_55), 'нет ссылки на ·55 (их мост С125 пропал) в ' + файл);
  });
}

test('обратная нить: ·55 помнит все девять дверей (сг47-помеченные мосты с их стороны)', () => {
  const s55 = fs.readFileSync(path.join(корень, ФАЙЛ_55), 'utf8');
  for (const файл of Object.values(ДВЕРИ_НИТИ)) {
    assert.ok(s55.includes(файл), '·55 не знает нити ' + файл);
  }
});
