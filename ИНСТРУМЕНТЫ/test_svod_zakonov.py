#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Тест СВОДА ЗАКОНОВ ДОМА (такт v1.37.0 «СВОД»).
Свод — не плакат, а проверяемый закон: этот тест подтверждает, что
1) СВОД_ЗАКОНОВ.json валиден и полон (10 законов I-01..I-10);
2) md и json согласованы (те же id и имена законов);
3) каждый файл из «живёт» и «доказательства» существует на диске;
4) доказательства — реальные test_* файлы дома;
5) источник и правило свода на месте.
Запуск: python3 ИНСТРУМЕНТЫ/test_svod_zakonov.py"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

прошло = 0
провалы = []
def ок(имя, условие):
    global прошло
    if условие:
        прошло += 1
        print('  ✓ ' + имя)
    else:
        провалы.append(имя)
        print('  ✗ ПРОВАЛ: ' + имя)

print('СВОД ЗАКОНОВ — согласованность и живучесть')
св = json.load(open('ДОКУМЕНТЫ/СВОД_ЗАКОНОВ.json', encoding='utf-8'))
мд = open('ДОКУМЕНТЫ/СВОД_ЗАКОНОВ.md', encoding='utf-8').read()

ок('JSON: 10 законов', isinstance(св.get('законы'), list) and len(св['законы']) == 10)
иды = [з['id'] for з in св.get('законы', [])]
ок('JSON: id идут I-01..I-10 без пропусков и повторов',
   иды == ['I-%02d' % i for i in range(1, 11)])
ок('JSON: у каждого закона есть имя, закон, живёт, доказательства',
   all(з.get('имя') and з.get('закон') and з.get('живёт') and з.get('доказательства') for з in св['законы']))
ок('JSON: указан источник — инварианты ТЗ HUMAN RUNTIME',
   'HUMAN RUNTIME' in св.get('источник', ''))

print('md ↔ json — два голоса одного свода')
ок('md: каждый id назван в тексте', all(('## %s ·' % з['id']) in мд for з in св['законы']))
ок('md: каждое имя закона названо в тексте', all(з['имя'] in мд for з in св['законы']))
ок('md: правило свода (закон = код + тест) на месте',
   'закон живёт в коде и доказывается тестом' in мд)
ок('md: честный GAP-принцип заявлен', 'честный GAP' in мд)

print('каждый файл свода существует на диске')
файлов = {}
для_з = [(з, путь) for з in св['законы'] for путь in (з['живёт'] + з['доказательства'])]
битые = []
for з, путь in для_з:
    if not os.path.exists(os.path.join(ROOT, путь)):
        битые.append(путь)
ок('живёт+доказательства: %d ссылок, битых 0' % len(для_з), len(битые) == 0
   or (print('   битые: ' + ', '.join(sorted(set(битые)))) and False))

print('доказательства — настоящие тесты дома')
тесты = [п for з in св['законы'] for п in з['доказательства']]
ок('все доказательства — файлы test_*',
   all(os.path.basename(п).startswith('test_') for п in тесты))
ок('каждый закон доказан минимум двумя тестами',
   all(len(з['доказательства']) >= 2 for з in св['законы']))
ок('новый тест эмерджентности в доказательствах (такт v1.37.0)',
   any('test_composition.mjs' in п for з in св['законы'] for п in з['доказательства']))

print('законы соответствуют своим пунктам ТЗ')
ок('пункт_ТЗ указан у всех и ссылается на §29 I-xx',
   all('§29 I-' in з.get('пункт_ТЗ', '') for з in св['законы']))

print('\nИТОГ: %d/%d прошло' % (прошло, прошло + len(провалы)))
sys.exit(1 if провалы else 0)
