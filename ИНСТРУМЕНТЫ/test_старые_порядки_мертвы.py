#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""test_старые_порядки_мертвы.py — страж С146 «ДЕКЛАРАЦИЯ = РЕАЛЬНОСТЬ» (RUM23-12).
Закон владельца I-12: РУССКИЙ → СЕРБСКИЙ → КАЗАХСКИЙ → НЕМЕЦКИЙ → СССР-15 (конституционный
порядок) → 101 язык народов СССР → все языки по количеству носителей убыв.
ПРИКАЗ (2026-10-17): «УБИРАЙ ВСЮ СТАРУЮ ПОЕБЕНЬ ИЗ САЙТА ЦЕЛИКОМ ЧТОБ ОТ НИХ И ДУХА НЕ БЫЛО
ОТ СТАРЫХ СТАРОРЕЖИМНЫХ ПОРЯДКОВ» — ни одна живая поверхность дома не смеет нести:
  · старорежимные последовательности оси (до С142, С142, С143, С144);
  · старые числа канонов (119, 209) как «канон цел»;
  · ложные декларации («зона пуста», «в корпусе зала пока нет»);
  · старый чип-селект (РУС→ENG→ESP→DEU);
  · чипы имён вместо полных русских имён (владелец незрячий — TTS читает);
  · НОСИТЕЛИ, не равные канону (дискриминация чисел).
Запуск из корня дома: python3 ИНСТРУМЕНТЫ/test_старые_порядки_мертвы.py"""
import json, os, re, sys

T = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ок = 0

def проверь(что, да):
    global ок
    assert да, 'НЕ СОШЛОСЬ: ' + что
    ок += 1
    print('  ok ·', что)

ЖИВЫЕ = ['СИНГУЛЯР_31_ЛАДОМ.html', 'СИНГУЛЯР_20_ФОНЕТИКА.html',
         'СИНГУЛЯР_01_Когда_теряем_157_голосов.html', 'СИНГУЛЯР_02_РЕЗОНАНС_Когда_теряем_157_голосов.html',
         'СИНГУЛЯР_32_СЦЕНА.html', 'КАРАОКЕ/Qb8xb0vUYDg.js', 'КАРАОКЕ/МАНИФЕСТ.json', 'sw15.js',
         'index.html', 'ДАННЫЕ/ПОРЯДОК_ЯЗЫКОВ.json']
Ст = {}
for f in ЖИВЫЕ:
    p = os.path.join(T, f)
    if os.path.exists(p):
        Ст[f] = open(p, encoding='utf-8').read()

С_ДО_142 = 'en es fr de it pt uk zh ja ko ar hi'
С_142 = 'de uk es en pt fr it'
С_143 = 'sr kk de uk es en'
С_144 = 'zh hi es ar en pt'
ЧИПЫ = ['УКР', 'БЕЛ', 'АНГЛ', 'ИСП', 'ПОРТ', 'ФРАН', 'ИТАЛ', 'ПОЛ', 'РУМ',
        'НИД', 'ШВЕ', 'БОЛ', 'ГРЕЧ', 'НЕМ', 'РУС', 'КИТ', 'ХИН', 'АРА', 'ЯПО', 'КОР', 'СРБ', 'КАЗ']

for f, s in Ст.items():
    for ст in (С_ДО_142, С_142, С_143, С_144):
        проверь(f'{f}: старорежимный порядок «{ст}» мёртв', ст not in s)
    проверь(f'{f}: «РУС→ENG→ESP→DEU» мёртв', 'РУС→ENG→ESP→DEU' not in s and 'ENG→ESP→DEU' not in s)

зал = Ст['СИНГУЛЯР_31_ЛАДОМ.html']
канон = json.load(open(os.path.join(T, 'ДАННЫЕ', 'ПОРЯДОК_ЯЗЫКОВ.json'), encoding='utf-8'))

проверь('·31: ложь «зона пуста» / «в корпусе зала пока нет» стёрта',
        'зона пуста' not in зал and 'в корпусе зала пока нет' not in зал)
проверь('·31: проба «канон цел — 119 кодов» стёрта', '119 кодов' not in зал and 'length===119' not in зал)
проверь('·31: чипы имён мертвы как значения имён',
        not re.search(r':\s*"' + '(' + '|'.join(ЧИПЫ) + ')' + r'"', зал))
проверь('·31: декларация несёт «101 язык народов, населяющих СССР»',
        '101 язык народов, населяющих СССР' in зал)
проверь('·31: декларация несёт конституционный перечень (УКР БЕЛ УЗБ ГРУЗ АЗЕР ЛИТ МОЛД ЛАТ КИРГ ТАДЖ АРМ ТУРКМ ЭСТ)',
        'УКР БЕЛ УЗБ ГРУЗ АЗЕР ЛИТ МОЛД ЛАТ КИРГ ТАДЖ АРМ ТУРКМ ЭСТ' in зал)
проверь('·31: декларация несёт хвост по носителям (АНГЛИЙСКИЙ → КИТАЙСКИЙ → ХИНДИ…)',
        'АНГЛИЙСКИЙ → КИТАЙСКИЙ' in зал and 'УРДУ' in зал and 'ИНДОНЕЗИЙСКИЙ' in зал)

м = re.search(r'const НОСИТЕЛИ = (\{.*?\});\nwindow\.НОСИТЕЛИ', зал, re.S)
нз = json.loads(м.group(1)) if м else {}
проверь('·31: НОСИТЕЛИ == канону (все числа канона, ни одного урезанного)',
        all(нз.get(k) == v for k, v in канон['носители'].items()))
проверь('·31: НОСИТЕЛИ не потерял корпусные числа МАЛЫША',
        all(k in нз for k in ('kok', 'mni', 'brx', 'sat', 'tcy')))

м = re.search(r'const ЗАКОН_ПОРЯДОК = \[([^\]]*)\]', зал)
коды = re.findall(r'"([A-Za-z_][A-Za-z_0-9-]*)"', м.group(1)) if м else []
проверь('·31: ЗАКОН_ПОРЯДОК == канону (289, байт-в-байт)', коды == канон['порядок_ладом'])
iEt, iEn = коды.index('et'), коды.index('en')
проверь('·31: народы СССР (101) стоят между СССР-зоной и хвостом: ku первый, liv последний',
        iEn > iEt and коды[iEt+1] == 'ku' and коды[iEn-1] == 'liv' and (iEn - iEt - 1) == 101)
проверь('·31: голова хвоста — АНГЛИЙСКИЙ→КИТАЙСКИЙ→ХИНДИ→ИСПАНСКИЙ→ФРАНЦУЗСКИЙ→БЕНГАЛЬСКИЙ→АРАБСКИЙ→ПОРТУГАЛЬСКИЙ→УРДУ→ИНДОНЕЗИЙСКИЙ',
        коды[iEn:iEn+10] == ['en', 'zh', 'hi', 'es', 'fr', 'bn', 'ar', 'pt', 'ur', 'id'])

ось = Ст['КАРАОКЕ/Qb8xb0vUYDg.js']
ключи = re.findall(r'(?:^|[,{])\s*"?([a-z]{2})"?\s*:\s*\["', ось[ось.find('"lyr"'):], )
проверь('ось: 14 языков', len(ключи) == 14)
законные_ключи = [k for k in канон['порядок_ладом'] if k in ключи]
проверь('ось: порядок ключей законный (канон-фильтр) + ничьи в хвосте',
        ключи == законные_ключи + [k for k in ключи if k not in канон['порядок_ладом']])
проверь('ось: шапка честна — ×14 языков', '972 строк × 14 языков' in ось)
проверь('ось: шапка не печатает старый порядок', '(en es fr de it pt uk zh ja ko ar hi)' not in ось)

ман = json.load(open(os.path.join(T, 'КАРАОКЕ', 'МАНИФЕСТ.json'), encoding='utf-8'))
сыр = json.dumps(ман, ensure_ascii=False)
проверь('манифест сборника: не несёт старорежимных последовательностей',
        all(ст not in сыр for ст in (С_144, 'sr kk de uk zh hi es ar en pt ja ko fr it')))
проверь('манифест сборника: порядок оси объявлен законным (С145/С146)',
        'С145: sr kk de uk en zh hi es fr ar pt ja ko it' in сыр)

sw = Ст['sw15.js']
проверь('sw15: кэш поднят — законсервированное старьё у владельца умирает (v207, пин такта v11.55 «СВОЙ ПЕРЕВОД»)',
        "S15_CACHE = 's15-orkestrator-v207'" in sw)
проверь('sw15: стейл-гонка навигаций мертва — стейл только на упавшей сети (С147)',
        "Promise.race" not in sw[sw.find("req.mode === 'navigate'"):sw.find("req.mode === 'navigate'")+1500])
проверь('·31: лицо перезагружается само при смене св-воркера (С147)',
        'controllerchange' in Ст['СИНГУЛЯР_31_ЛАДОМ.html'])

print(f'\nИТОГ: {ок}/{ок} прошло — старорежимные порядки мертвы, декларация = реальность')
sys.exit(0)
