'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const ROOT = path.resolve(__dirname, '..');
const КОД_ЯДРА = fs.readFileSync(path.join(ROOT, 'singulyar-modules.js'), 'utf8');

/* ядро грузится в песочнице с минимальными window/document — как в браузере */
function ядро(pathname) {
  const sandbox = {
    window: {}, navigator: {}, location: { pathname: pathname || '/index.html' },
    document: {
      readyState: 'complete',
      querySelector: () => null,
      createElement: () => ({ style: {}, setAttribute() {}, appendChild() {}, removeAttribute() {}, classList: { add() {} } }),
      createElementNS: () => ({ style: {}, setAttribute() {}, appendChild() {}, firstChild: null, removeChild() {} }),
      insertBefore() {},
      addEventListener() {},
      head: { appendChild() {} }
    },
    ResizeObserver: class { observe() {} },
    requestAnimationFrame() {}
  };
  sandbox.window.matchMedia = () => ({ matches: true });
  vm.createContext(sandbox);
  vm.runInContext(КОД_ЯДРА, sandbox, { filename: 'singulyar-modules.js' });
  return sandbox.window.SNG;
}

/* ── 1. версии и место ──
   ЗАКАЛКА v1.43.0: точная прошивка версии здесь рвалась каждый такт
   (ядро растёт — v1.5.0 → v1.7.0 — а тест ждал старое). Нить вводилась
   в v1.5.0: значит, семантический пол — 1.5.0, потолка нет. Формат —
   строго semver, чтобы неслучайная строка не пролезла. */
const ПОЛ_НИТИ = [1, 5, 0];
function не_ниже(версия, пол) {
  const ч = String(версия).split('.').map(Number);
  if (ч.length !== 3 || ч.some(Number.isNaN)) return false;
  for (let и = 0; и < 3; и++) {
    if (ч[и] > пол[и]) return true;
    if (ч[и] < пол[и]) return false;
  }
  return true; /* ровно пол */
}
test('ядро (semver, нить с 1.5.0) несёт ЖИВУЮ НИТЬ: API на месте', () => {
  const SNG = ядро();
  assert.ok(/^\d+\.\d+\.\d+$/.test(SNG.версия), 'версия semver: ' + SNG.версия);
  assert.ok(не_ниже(SNG.версия, ПОЛ_НИТИ), 'версия не ниже нити 1.5.0: ' + SNG.версия);
  for (const имя of ['связи', 'визит', 'визиты', 'путь', 'нитьПрогресс'])
    assert.equal(typeof SNG[имя], 'function', 'API нити: ' + имя);
});

/* ── 2. связи: манифест — истина ──
   ЗАКАЛКА v1.43.0: число нитей растёт вместе с домом (20 → 23 при ·30).
   Морозим не цифру, а ЗАКОН: манифест держит ровно столько уникальных
   симметричных пар, сколько заявляет, каждая дверь связана, а пол —
   23 нити (состояние на такт v1.43) не даёт нитям молча сыпаться. */
test('связи: манифесту верим — пары уникальны, симметричны, ведут на живые двери, без петель; пол 23', () => {
  const SNG = ядро();
  const нити = SNG.связи();
  /* манифест — истина: уникальных пар в объявлениях столько же, сколько отдала карта */
  const заявлено = new Set();
  for (const м of SNG.модуль) (м.связи || []).forEach(к => заявлено.add([м.id, к].sort().join('·')));
  assert.equal(нити.length, заявлено.size, 'карта = манифесту');
  assert.ok(нити.length >= 23, 'пол нитей 23 (такт v1.43): ' + нити.length);

  const ключи = new Set();
  for (const п of нити) {
    const ключ = [п.от, п.к].sort().join('·');
    assert.ok(!ключи.has(ключ), 'пара уникальна: ' + ключ);
    ключи.add(ключ);
    assert.notEqual(п.от, п.к, 'без петель: ' + ключ);
    assert.ok(SNG.поId(п.от), 'от — живая дверь: ' + п.от);
    assert.ok(SNG.поId(п.к), 'к — живая дверь: ' + п.к);
    /* симметрия: манифест обязан держать связь в обе стороны */
    const обрат = SNG.поId(п.к).связи || [];
    assert.ok(обрат.includes(п.от), 'симметрия ' + ключ);
  }
  /* известные нити — мост ·21⇄·22 (написан в манифесте) и хребет ·27→·28→·29 */
  assert.ok(ключи.has('s21·s22'), 'мост ·21⇄·22');
  assert.ok(ключи.has('s27·s28') && ключи.has('s28·s29') && ключи.has('s27·s29'), 'хребет фундамент—узел—свобода');
  /* каждая дверь связана хотя бы одной нитью — дом не рассыпается */
  for (const м of SNG.модуль) {
    if (м.id === 'хаб') continue;
    assert.ok((м.связи || []).length >= 1, 'дверь связана: ' + м.id);
  }
});

/* ── 3. визиты: append-only, хаб не дверь ── */
test('визит пишет первое касание; повтор не перезаписывает; хаб не считается', () => {
  const SNG = ядро();
  assert.equal(SNG.визит('s01'), true, 'первое касание записано');
  assert.equal(SNG.визит('s01'), false, 'повтор не перезаписывает (append-only)');
  assert.equal(SNG.визит('хаб'), false, 'хаб — лицо, не дверь');
  assert.equal(SNG.визит('нет_такой'), false, 'чужой id не записывается');
  const виз = SNG.визиты();
  assert.equal(Object.keys(виз).length, 1);
  assert.ok(!Number.isNaN(Date.parse(виз.s01)), 'момент касания — ISO-время');
  /* копия, не ссылка: чужой код не портит память пути */
  виз.s15 = 'взлом';
  assert.ok(!SNG.визиты().s15, 'визиты() отдаёт копию');
});

/* ── 4. путь и прогресс ── */
test('путь хранит порядок первых касаний; прогресс считает двери и живые нити', () => {
  const SNG = ядро();
  assert.equal(SNG.путь().length, 0, 'в начале путь пуст');
  SNG.визит('s21');
  SNG.визит('s15');
  SNG.визит('s22');
  assert.deepEqual([...SNG.путь()], ['s21', 's15', 's22'], 'порядок касаний сохранён');

  const п1 = SNG.нитьПрогресс();
  /* ПОЛИМАТ v1.44.0: всего = двери манифеста без хаба (21 на такт v1.46.0 — СЦЕНА ·32);
   цифра не морожена вхолостую — сверяется с самим манифестом ядра */
  const дверейВманифесте = SNG.модуль.filter(м => м.id !== 'хаб').length;
  assert.equal(п1.всего, дверейВманифесте, 'всего = дверям манифеста');
  assert.equal(п1.всего, 21, 'лицо дома: 21 дверь (СЦЕНА ·32 на такте v1.46.0)');
  assert.equal(п1.пройдено, 3, 'пройдено 3');
  assert.equal(п1.нитей, 31, 'нитей 31 (такт v1.46.0: +4 нити СЦЕНЫ s01/s15/s16/s20)');
  /* живая нить — обе двери касались; считаем САМИ из манифеста (перекрёстная проверка) */
  const касались = new Set(SNG.путь());
  const живыхСам = SNG.связи().filter(п => касались.has(п.от) && касались.has(п.к)).length;
  assert.equal(п1.нитейЖивых, живыхСам, 'счёт живых нитей честный');
  assert.equal(п1.нитейЖивых, 1, 'жива одна нить: ·21⇄·22');

  SNG.визит('s28');
  const касались2 = new Set(SNG.путь());
  const живых2 = SNG.связи().filter(п => касались2.has(п.от) && касались2.has(п.к)).length;
  const п2 = SNG.нитьПрогресс();
  assert.equal(п2.нитейЖивых, живых2, 's28 без пары: живых нитей не прибавилось');
  assert.equal(п2.нитейЖивых, 1, 's28 без пары: живых нитей не прибавилось');
  SNG.визит('s19');
  /* зажглись: ·21⇄·22, ·19⇄·28 и ·19⇄·21 — все пары касались */
  const касались3 = new Set(SNG.путь());
  const живых3 = SNG.связи().filter(п => касались3.has(п.от) && касались3.has(п.к)).length;
  assert.equal(SNG.нитьПрогресс().нитейЖивых, живых3, 'счёт живых нитей честный');
  assert.equal(SNG.нитьПрогресс().нитейЖивых, 3, 'три живые нити');
});

