#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
test_сборник_частей.py — страж цепи частей Сборника (латка С140, RUM23-9).
Закон владельца: «Сборник можно нарезать как архив по частям, которые положено,
но при произведении просто подставлять одну часть за другую».
Проверяет: манифест частей в оси, покрытие и монотонность, файлы частей в minus/сборник/,
удаление 600-с огрызка, цепь в ·31 и ·32, строки С32 из новой оси, МАНИФЕСТ.
Детерминированный, без сети и ffmpeg.
Запуск из корня дома: python3 ИНСТРУМЕНТЫ/test_сборник_частей.py
"""
import json
import os
import re

T = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ок = 0
ID = 'Qb8xb0vUYDg'


def проверь(что, да):
    global ок
    assert да, 'НЕ СОШЛОСЬ: ' + что
    ок += 1
    print('  ok ·', что)


def читай(имя):
    return open(os.path.join(T, имя), encoding='utf-8').read()


# ── ось Сборника: манифест частей ──
ось_текст = читай('КАРАОКЕ/%s.js' % ID)
мт = re.search(r'window\.КАРАОКЕ_КОРПУС\["%s"\]=(\{.*\});\s*$' % ID, ось_текст, re.S)
проверь('ось Сборника парсится', bool(мт))
ось = json.loads(мт.group(1))
части = ось.get('части')
проверь('в оси есть манифест «части»', isinstance(части, list) and len(части) == 7)
проверь('части: монотонны и покрывают 0 → dur',
        части[0]['a'] == 0 and all(части[i]['b'] == части[i + 1]['a'] for i in range(6))
        and abs(части[-1]['b'] - ось['dur']) < 0.05)
проверь('части: имена файлов честные',
        all(ч['f'] == 'сборник-0%d.mp3' % ч['n'] for ч in части))
проверь('ось: dur = полный мастер (≈4169,45 с), а не 8429',
        4160 < ось['dur'] < 4180)
проверь('ось: 12 языков и длины 1:1',
        len(ось['lyr']) == 12 and all(len(v) == len(ось['cues']) for v in ось['lyr'].values()))
проверь('ось: w по токенам (слоговые веса)',
        all(len(c.get('w', [])) == len(c['t'].split()) for c in ось['cues']))
п_переведено = sum(1 for s in ось['lyr']['en'] if s)
проверь('ось: переводы С141 — все 972 строк в каждом из 12 языков (машинный черновик агентов, редактура за владельцем)',
        п_переведено == len(ось['cues'])
        and len(ось['lyr']) == 12
        and all(all(str(s).strip() for s in v) for v in ось['lyr'].values()))

# ── закон I-12 «ПОРЯДОК ЯЗЫКОВ»: порядок ключей оси (латка С142, RUM23-10) ──
канон_яз = json.load(open(os.path.join(T, 'ДАННЫЕ', 'ПОРЯДОК_ЯЗЫКОВ.json'), encoding='utf-8'))
ключи_яз = list(ось['lyr'].keys())
законные = [k for k in канон_яз['порядок_ладом'] if k in ключи_яз]
ничьи = [k for k in ключи_яз if k not in канон_яз['порядок_ладом']]
проверь('закон I-12: ключи lyr — законные по канону + ничьи в прежнем порядке',
        ключи_яз == законные + ничьи)
проверь('закон I-12: НЕМЕЦКИЙ первый из 12 (4-е место закона), украинский второй (первый СССР-15 после ru/kk)',
        ключи_яз[:2] == ['de', 'uk'])
проверь('закон I-12: хвост по носителям — es en pt fr it (канон 18-22), ничьи zh ja ko ar hi в прежнем порядке',
        ключи_яз == ['de', 'uk', 'es', 'en', 'pt', 'fr', 'it', 'zh', 'ja', 'ko', 'ar', 'hi'])
проверь('закон I-12: сербский (sr) и казахский (kk) в доме всегда вторым и третьим — канон цел',
        канон_яз['зоны']['первые_четыре']['порядок'] == ['ru', 'sr', 'kk', 'de'])

# ── файлы частей ──
для_ч = os.path.join(T, 'minus', 'сборник')
for ч in части:
    п = os.path.join(для_ч, ч['f'])
    проверь('файл части: %s' % ч['f'], os.path.isfile(п))
    if os.path.isfile(п):
        байт = os.path.getsize(п)
        проверь('часть %d: вес разумный (>5 МБ, <100 МБ лимит GitHub)' % ч['n'],
                5 * 1024 * 1024 < байт < 100 * 1024 * 1024)
проверь('паспорт частей на месте', os.path.isfile(os.path.join(для_ч, 'ПАСПОРТ.md')))

# ── огрызок ушёл ──
проверь('600-с огрызок minus/Qb8xb0vUYDg.mp3 удалён',
        not os.path.exists(os.path.join(T, 'minus', 'Qb8xb0vUYDg.mp3')))

# ── ·31 ЛАДОМ: цепь ──
т31 = читай('СИНГУЛЯР_31_ЛАДОМ.html')
проверь('·31: контроллер __СБОРНИК_ЦЕПЬ жив', 'window.__СБОРНИК_ЦЕПЬ' in т31)
проверь('·31: src() ведёт Сборник на часть 1', '"./minus/сборник/сборник-01.mp3"' in т31)
проверь('·31: onEnded подставляет следующую часть',
        'window.__СБОРНИК_ЦЕПЬ.далее()' in т31)
проверь('·31: часы караоке ходят по глобальному времени',
        '?window.__СБОРНИК_ЦЕПЬ.время():(audio.currentTime||0)' in т31)
проверь('·31: seek раскладывает глоб → часть', 'window.__СБОРНИК_ЦЕПЬ.кМесту(t)' in т31)
проверь('·31: живой путь огрызка выпрямлен (indexOf-гарда)',
        'indexOf("./minus/Qb8xb0vUYDg.mp3")' not in т31)

# ── ·32 СЦЕНА: цепь ──
т32 = читай('СИНГУЛЯР_32_СЦЕНА.html')
проверь('·32: цепь сборника жива (сборникДалее)', 'function сборникДалее()' in т32)
проверь('·32: путь Сборника — часть 1', "minus/сборник/сборник-01.mp3" in т32)
проверь('·32: shs0TiOwx-M снят из безголосых (голос 320k с С139)',
        "'shs0TiOwx-M': 1" not in т32)
м32 = re.search(r'window\.S32_КОРПУС = (\{.*\});', т32)
проверь('·32: S32_КОРПУС парсится', bool(м32))
к32 = json.loads(м32.group(1))
с32 = next(s for s in к32['songs'] if s['id'] == ID)
проверь('·32: строки Сборника = строкам новой оси (%d)' % len(ось['cues']),
        len(с32['lines']) == len(ось['cues']))
проверь('·32: время строк совпадает с осью',
        все := all(abs(с32['lines'][i][0] - ось['cues'][i]['a']) < 0.011
                   for i in range(0, len(ось['cues']), 97)))
проверь('·32: мета честно обновлена (1.3.0, калибровка_с140)',
        к32['meta'].get('version') == '1.3.0' and 'калибровка_с140' in к32['meta'])

# ── МАНИФЕСТ ──
ман = json.load(open(os.path.join(T, 'КАРАОКЕ', 'МАНИФЕСТ.json'), encoding='utf-8'))
рm = next(x for x in ман['список'] if x['id'] == ID)
проверь('МАНИФЕСТ: строк Сборника = оси', рm['строк'] == len(ось['cues']))
проверь('МАНИФЕСТ: dur Сборника = оси', abs(рm['dur'] - ось['dur']) < 0.05)
проверь('МАНИФЕСТ: строк_всего = сумме списка', ман['строк_всего'] == sum(x['строк'] for x in ман['список']))

print(f'СБОРНИК · АРХИВ ЧАСТЯМИ (С140): {ок} проверок сошлось')
