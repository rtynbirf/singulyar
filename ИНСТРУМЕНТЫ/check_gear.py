#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""НАДЗОР ШЕСТЕРЁНКИ v1 — урок такта v1.26.6.
Владелец поймал живьём: СИНГУЛЯР_23_КРУГ.html осталась без шестерёнки
(движок singulyar-ux-engine-v8.js не был подключён), хотя футер главной
обещал «на всех 14 страницах». Класс шва «обещал на каждой странице —
промолчал на одной» закрывается машиной: теперь тест сам ходит по диску
и требует шестерёнку на КАЖДОЙ странице, включая будущие.

Что проверяется:
  1) движок существует (singulyar-ux-engine-v8.js);
  2) движок умеет рисовать шестерёнку (id sux-gear в коде движка);
  3) КАЖДАЯ каноническая страница (СИНГУЛЯР_*.html + index.html)
     подключает движок — значит, шестерёнка и «Главное меню» на ней есть;
  4) на странице нет самодельного дубля шестерёнки (id sux-gear в HTML
     страницы = две шестерёнки с одинаковыми id — движок такое чинит,
     но честнее не плодить);
  5) наблюдаемые страницы (organism, ПРОТОКОЛ) — доклад без приговора.

Запуск: python3 ИНСТРУМЕНТЫ/check_gear.py
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

прошло = 0
провалы = []
def ок(имя, условие, детали=''):
    global прошло
    if условие:
        прошло += 1
        print('  ✓ ' + имя)
    else:
        провалы.append(имя)
        print('  ✗ ПРОВАЛ: ' + имя + ((' | ' + str(детали)) if детали else ''))

ДВИЖОК = 'singulyar-ux-engine-v8.js'

print('Часть 1 — движок шестерёнки жив')
путь_движка = os.path.join(ROOT, ДВИЖОК)
ок('движок %s существует' % ДВИЖОК, os.path.isfile(путь_движка))
движок = open(путь_движка, encoding='utf-8').read() if os.path.isfile(путь_движка) else ''
ок('движок рисует шестерёнку (id sux-gear)', 'sux-gear' in движок)
ок('движок умеет «Главное меню»', 'Главное меню' in движок)
ок('движок защищён от двойной вставки (__SINGULYAR_UX_ENGINE__)', '__SINGULYAR_UX_ENGINE__' in движок)

print('Часть 2 — шестерёнка обязана быть на КАЖДОЙ канонической странице')
канонические = sorted(glob.glob('СИНГУЛЯР_*.html')) + ['index.html']
без_движка = []
с_дублем = []
for стр in канонические:
    текст = open(стр, encoding='utf-8').read()
    грузит = (ДВИЖОК in текст)
    if not грузит:
        без_движка.append(стр)
    if re.search(r'id=["\']sux-gear["\']', текст):
        с_дублем.append(стр)
ок('все %d канонические страницы подключают движок' % len(канонические),
   len(без_движка) == 0, 'без движка: ' + ', '.join(без_движка))
for стр in канонические:
    текст = open(стр, encoding='utf-8').read()
    ок('шестерёнка на %s' % стр, ДВИЖОК in текст)
ок('ни одна страница не плодит самодельный дубль #sux-gear', len(с_дублем) == 0)

print('Часть 3 — наблюдаемые (доклад без приговора)')
for стр in ['organism-living-prototype.html', 'ПРОТОКОЛ_ВЫВОДА_НА_ЭКРАН.html']:
    if os.path.isfile(стр):
        грузит = ДВИЖОК in open(стр, encoding='utf-8').read()
        print('  · %s: %s' % (стр, 'движок подключён' if грузит else 'БЕЗ движка (наблюдение)'))

if провалы:
    print('\nНАДЗОР ШЕСТЕРЁНКИ: ПРОВАЛ — %d. Шестерёнка обязана быть на каждой странице.' % len(провалы))
    sys.exit(1)
print('\nИТОГ: %d/%d — шестерёнка на каждой странице, закон соблюдён' % (прошло, прошло + len(провалы)))
sys.exit(0)
