test('W4: ядро контракты/0.1 — шесть типов, default-deny, отзыв, конверт, детерминизм байт-в-байт', () => {
  const сандбокс = песочница();
  vm.runInContext(читай('js/контракты.js'), сандбокс, { filename: 'js/контракты.js' });
  const жив = сандбокс.window.__КОНТРАКТЫ;
  assert.ok(жив, 'ядро не встало в window.__КОНТРАКТЫ');
  assert.equal(жив.ИМЯ, 'контракты/0.1', 'версия канона не та');
  assert.equal(JSON.stringify(жив.ТИПЫ), JSON.stringify(['реестр-возможностей', 'конверт', 'паспорт-объекта', 'представление', 'событие-сессии', 'свидетельство']), 'типы V1 ≠ шести');
  assert.equal(JSON.stringify(жив.ФОРМЫ), JSON.stringify(['текст', 'брайль', 'речь', 'вибро']), 'формы представлений ≠ канону ·21');
  assert.equal(JSON.stringify(жив.ВИДЫ_СВИДЕТЕЛЬСТВ), JSON.stringify(['проба', 'замер', 'скриншот', 'живой прогон']), 'виды свидетельств ≠ канону');

  /* default-deny: нет записи — отказ с причиной, молчаливого «да» не бывает */
  const нет = жив.возможности.для('нет-такого-права');
  assert.equal(нет.разрешено, false, 'default-deny нарушен');
  assert.ok(нет.причина && нет.причина.includes('default-deny'), 'причина default-deny не названа');
  /* выдать → для; невалидное состояние — честный отказ (UNKNOWN не фантазируем) */
  assert.ok(жив.возможности.выдать({ ид: 'п1', дверь: '·54', действие: 'приглашение', состояние: 'готово' }).ок, 'право не выдано');
  assert.equal(жив.возможности.для('п1').разрешено, true, 'выданное право не действует');
  assert.equal(жив.возможности.выдать({ ид: 'п2', дверь: '·54', действие: 'х', состояние: 'фантазия' }).ок, false, 'состояние вне канона принято');
  /* отзыв у держателя — право красится сразу */
  const отв = жив.возможности.отозвать('п1', 'испытание отзыва');
  assert.ok(отв.ок, 'отзыв не лёг');
  assert.equal(жив.возможности.для('п1').разрешено, false, 'отозванное право действует');
  assert.ok(жив.возможности.для('п1').причина.includes('отозвано'), 'отзыв не назван в причине');
  assert.equal(жив.возможности.отозвать('нет-такого', 'х').ок, false, 'отзыв несуществующего права прошёл');

  /* конверт: намерение → результат; падение исполнителя — честное «отказано» */
  const к = жив.конверт.собрать('проверка-канона', { а: 1 });
  assert.ok(к.ок && к.конверт.состояние === 'не готово', 'конверт не собрался');
  жив.конверт.исполнить(к.конверт, (вход) => ({ эхо: вход.а * 2 }));
  assert.equal(к.конверт.состояние, 'готово', 'исполнение не закрыло конверт');
  assert.deepEqual(к.конверт.выход, { эхо: 2 }, 'выход конверта врёт');
  assert.equal(жив.конверт.валидировать(к.конверт).ок, true, 'валидатор не признал живой конверт');
  const к2 = жив.конверт.собрать('падение', null);
  жив.конверт.исполнить(к2.конверт, () => { throw new Error('бум'); });
  assert.equal(к2.конверт.состояние, 'отказано', 'падение не поймано (UNKNOWN не молчит)');
  assert.ok(к2.конверт.причина.includes('бум'), 'причина падения не названа');
  assert.equal(жив.конверт.валидировать({ ид: 'x', намерение: 'н', состояние: 'отказано', произведено: 1 }).ок, false, 'отказ без причины прошёл валидацию');

  /* паспорт-объекта: SHA-256 обязателен, 64 hex */
  const добрый = { ид: 'о1', имя: 'объект', путь: 'js/x.js', схема: 'п/1', версия: '1', ша256: 'a'.repeat(64) };
  assert.equal(жив.паспорт.валидировать(добрый).ок, true, 'паспорт с 64 hex не принят');
  assert.equal(жив.паспорт.валидировать({ ...добрый, ша256: 'ab' }).ок, false, 'короткий SHA принят');
  assert.equal(жив.паспорт.валидировать({ ид: 'о1', имя: 'о', путь: 'p', схема: 'с', версия: '1' }).ок, false, 'паспорт без SHA принят');

  /* представление: форма вне канона — отказ */
  assert.equal(жив.представление.собрать('привет', 'брайль', 'ru', '⠏').ок, true, 'брайль-форма не принята');
  assert.ok(жив.представление.собрать('привет', 'жест', 'ru', 'х').причина.includes('канона четырёх'), 'форма вне канона принята');

  /* событие-сессии и свидетельство: без следа — не свидетельство */
  assert.ok(жив.сессия.событие({ сессия: 'с1', тип: 'рукопожатие', кто: 'человек' }).ок, 'событие не собралось');
  assert.equal(жив.сессия.событие({ тип: 'без-сессии' }).ок, false, 'событие без сессии принято');
  const св = жив.свидетельство.записать({ чего: 'W4', как: 'живой прогон', где: 'страж', след: '8/8' });
  assert.ok(св.ок, 'свидетельство не записалось');
  assert.ok(жив.свидетельство.записать({ чего: 'x', как: 'проба', где: 'y' }).причина.includes('след'), 'свидетельство без следа принято');

  /* детерминизм: два ядра с опорой «сейчас» — байт-в-байт */
  const прогон = () => {
    const с2 = песочница();
    vm.runInContext(читай('js/контракты.js'), с2, { filename: 'js/контракты.js' });
    const я = с2.window.__КОНТРАКТЫ.ядро({ сейчас: () => 1000 });
    я.возможности.выдать({ ид: 'a', дверь: '·1', действие: 'д', состояние: 'готово' });
    const е = я.конверт.собрать('н1', { n: 1 });
    я.конверт.исполнить(е.конверт, (вх) => вх);
    const п = я.представление.собрать('см', 'текст', 'ru', 'тело');
    const эв = я.сессия.событие({ сессия: 'с1', тип: 'рукопожатие', кто: 'человек', деталь: 'х' });
    const эс = я.свидетельство.записать({ чего: 'W4', как: 'живой прогон', где: 'страж', след: '8/8' });
    return JSON.stringify([я.возможности.список(), е.конверт, п.представление, эв.событие, эс.свидетельство]);
  };
  assert.equal(прогон(), прогон(), 'два прогона с той же опорой разошлись — детерминизм нарушен');
});

test('W4: data/контракты.json — каждый контракт имеет файл-канон и страж (не заявление)', () => {
  const конт = JSON.parse(читай('data/контракты.json'));
  assert.equal(конт.схема, 'контракты-дома/v0.1', 'схема реестра не канон');
  const канон = ['реестр-возможностей', 'конверт', 'паспорт-объекта', 'представление', 'событие-сессии', 'свидетельство'];
  assert.ok(Array.isArray(конт.типы_V1) && конт.типы_V1.length === 6, 'типы_V1 ≠ шести');
  for (const т of конт.типы_V1) {
    assert.ok(канон.includes(т.тип), 'тип «' + т.тип + '» вне канона');
    assert.ok(т.суть && т.суть.length > 20, 'тип без сути: ' + т.тип);
    assert.ok(т['в доме'], 'тип без «в доме»: ' + т.тип);
  }
  assert.ok(конт.контракты.length >= 8, 'реестр держит названные контракты волны');
  const ид = [];
  for (const к of конт.контракты) {
    assert.ok(к.ид && к.дверь && к.имя && к.файл && к.страж && к.закон && к.статус, 'неполная запись контракта: ' + JSON.stringify(к.ид));
    assert.ok(fs.existsSync(path.join(корень, к.файл)), 'файл-канон не существует в репо: ' + к.файл);
    /* страж: либо путь-файл (существует), либо честная запись пробы N/N */
    if (к.страж.startsWith('ИНСТРУМЕНТЫ/')) {
      const путь = к.страж.split(' ')[0];
      assert.ok(fs.existsSync(path.join(корень, путь)), 'страж-файл не существует: ' + путь);
    } else {
      assert.ok(/\d+\/\d+/.test(к.страж), 'страж без файла и без записи пробы: ' + к.ид);
    }
    for (const т of к.типы) assert.ok(канон.includes(т), 'тип «' + т + '» контракта ' + к.ид + ' вне канона');
    assert.equal(к.статус, 'в силе', 'контракт реестра обязан быть «в силе» (кандидаты — отдельно): ' + к.ид);
    ид.push(к.ид);
  }
  assert.equal(new Set(ид).size, ид.length, 'дубликаты ид в реестре контрактов');
  /* кандидат дыры №1 назван честно */
  assert.ok(конт.кандидаты && конт.кандидаты.length >= 1, 'кандидат агент-сообщение не назван');
  assert.ok(конт.кандидаты[0].ид === 'агент-сообщение/0.1', 'кандидат не тот');
});

test('W4: data/миры.json — канон миров, могильник MAIN-2026-11-11, честный дрейф-блок', () => {
  const мир = JSON.parse(читай('data/миры.json'));
  assert.equal(мир.схема, 'миры-дома/v0.1', 'схема реестра миров не канон');
  const типы = ['ветка', 'тег', 'коммит-слепок'];
  const статусы = ['живой', 'могильник', 'заморожен'];
  assert.ok(мир.миры.length >= 6, 'карта миров пуста');
  for (const м of мир.миры) {
    assert.ok(м.ид && м.роль && м.закон, 'мир без ид/роли/закона: ' + JSON.stringify(м.ид));
    assert.ok(типы.includes(м.тип), 'тип «' + м.тип + '» вне канона миров');
    assert.ok(статусы.includes(м.статус), 'статус «' + м.статус + '» вне канона миров');
    assert.ok(/^[0-9a-f]{7,40}$/.test(м.голова_на_замер), 'голова_на_замер не SHA: ' + м.ид);
    assert.ok(м.замер && /^\d{4}-\d{2}-\d{2}$/.test(м.замер), 'мир без даты замера: ' + м.ид);
  }
  /* rumu — живая ветка-истина */
  const руму = мир.миры.find((м) => м.ид === 'rumu');
  assert.ok(руму && руму.статус === 'живой' && руму.тип === 'ветка', 'rumu не назван живой веткой');
  /* могильник main назван тегом, кончиком и ADR */
  const мог = мир.миры.find((м) => м.ид === 'могильник-main');
  assert.ok(мог, 'могильник main не в карте');
  assert.equal(мог.статус, 'могильник', 'main не могильник');
  assert.ok(мог.роль.includes('MAIN-2026-11-11'), 'тег могильника не назван');
  assert.ok(мог.роль.includes('e9222f97'), 'кончик могильника не назван');
  assert.ok(мог.закон.includes('ADR-0006'), 'ADR-0006 не назван');
  /* слепок ×5-A (c590c6c9) */
  const слеп = мир.миры.find((м) => м.ид === 'слепок-×5-A');
  assert.ok(слеп && слеп.голова_на_замер.startsWith('c590c6c9'), 'слепок ×5-A не в карте');
  /* дрейф-блок: без права — только карта дрейфа */
  const д = мир.дрейф;
  assert.ok(д && д.статус.includes('исчерпан'), 'дрейф-блок не говорит «исчерпан»');
  assert.ok(д.закон.includes('ADR-0006'), 'дрейф не ссылается на ADR-0006');
  assert.ok(д.историческая_величина.includes('774') && д.историческая_величина.includes('631'), 'историческая величина дрейфа потеряна');
  assert.ok(д.право.includes('правом хозяина'), 'право конвергенции не названо');
  assert.ok(д.конвергенция.includes('не требуется'), 'конвергенция объявлена без права');
});

test('W4: законы ядра в исходнике — 0 сети, 0 innerHTML, 0 eval, 0 случайности, ES2019', () => {
  const код = читай('js/контракты.js');
  /* комменты шапки не в счёт — закон про КОД, не про слова о коде */
  const тело = код.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/[^\n]*$/gm, '');
  assert.ok(!тело.includes('fetch('), 'ядро делает сеть (И-01)');
  assert.ok(!тело.includes('XMLHttpRequest'), 'ядро делает сеть через XHR');
  assert.ok(!/\.innerHTML/.test(тело), 'innerHTML в ядре (CSP-постур А)');
  assert.ok(!тело.includes('eval('), 'eval в ядре');
  assert.ok(!тело.includes('Math.random'), 'случайность в ядре (детерминизм)');
  assert.ok(!тело.includes('?.'), 'optional chaining в ядре (ES2019)');
  assert.ok(!тело.includes('??'), 'nullish coalescing в ядре (ES2019)');
  assert.ok(код.includes("var ИМЯ = 'контракты/0.1'"), 'имя канона потеряно');
  /* опора времени для стражей */
  assert.ok(код.includes('window.__КОНТРАКТЫ.ядро = создатьЯдро'), 'опора-инъекция не отдана стражам');
});

