#!/usr/bin/env node
/* Тест логики ·26 ЛИНИЯ. Ядро из отгруженного файла (S26:CORE-BEGIN/END).
   Запуск: node ИНСТРУМЕНТЫ/test_s26_logic.js */
'use strict';
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const { webcrypto } = require('crypto');

const ФАЙЛ = path.join(__dirname, '..', 'СИНГУЛЯР_26_ЛИНИЯ.html');
const html = fs.readFileSync(ФАЙЛ, 'utf8');

let прошло = 0, всего = 0;
function ок(имя, условие) {
  всего++;
  if (условие) { прошло++; console.log('  ✓ ' + имя); }
  else { console.error('  ✗ ПРОВАЛ: ' + имя); }
}
function раздел(т) { console.log('\n— ' + т); }

раздел('извлечение ядра');
const начало = html.indexOf('/* S26:CORE-BEGIN */');
const конец = html.indexOf('/* S26:CORE-END */');
ок('маркеры найдены', начало >= 0 && конец > начало);
const ядро = html.slice(начало, конец + '/* S26:CORE-END */'.length);
const песочница = { crypto: webcrypto, TextEncoder, TextDecoder, console,
  btoa: (с) => Buffer.from(с, 'binary').toString('base64'),
  atob: (с) => Buffer.from(с, 'base64').toString('binary') };
vm.createContext(песочница);
vm.runInContext(ядро + '\nthis.S26 = S26;', песочница);
const S26 = песочница.S26;
ок('S26 определён', !!S26 && typeof S26 === 'object');
ок('версия 1.0.0', S26.VERSION === '1.0.0');
ок('16 номеров в карте', Object.keys(S26.НОМЕРА).length === 16);
ок('крипто живой', S26.криптоЖивой() === true);

раздел('номера: у круга — 00–15, у гостя — от устройства');
ок('RUVSON = 00', S26.НОМЕРА.ruvson === '00');
ок('ПАША = 01, АНЯ = 02', S26.НОМЕРА.pasha === '01' && S26.НОМЕРА.anya === '02');
ок('человек по номеру', S26.человекПоНомеру('02') && S26.человекПоНомеру('02').имя === 'АНЯ');
ок('номер вне 00–15 — null', S26.человекПоНомеру('99') === null && S26.человекПоНомеру('abc') === null);
ок('номер по алиасу БАБА', S26.номерПоИмени('БАБА') === '02');
ок('гостевой номер по формату G####', /^G\d{4}$/.test(S26.номерГостя('dev-9')));
ок('гостевой номер стабилен', S26.номерГостя('dev-9') === S26.номерГостя('dev-9'));
ок('гостевые номера различны', S26.номерГостя('a') !== S26.номерГостя('b'));
ок('мой номер для своих', S26.мойНомер({ имя:'ЖЕНЯ', тип:'свой', deviceId:'d' }) === '04');
ок('мой номер для гостя', S26.мойНомер({ имя:'ГОСТЬ', тип:'гость', deviceId:'xyz' }) === S26.номерГостя('xyz'));
ок('красивый номер: 02·АНЯ', S26.красивыйНомер('02') === '02·АНЯ');
ок('разбор: имя → номер', S26.разбериНомер('Ванёк').ok && S26.разбериНомер('Ванёк').номер === '03');
ок('разбор: номер → номер', S26.разбериНомер('04').ok && S26.разбериНомер('04').номер === '04');
ок('разбор: гостевой G-номер', S26.разбериНомер('g1234').ok && S26.разбериНомер('g1234').номер === 'G1234');
ок('разбор: невалидный номер отклонён', !S26.разбериНомер('КОСМОНАВТ').ok && !S26.разбериНомер('').ok);

раздел('гвард коротких имён');
ок('ЛЕРА защищена', !S26.проверьИмя('ЛЕРА').ok);
ок('ГОСТЬ ЛЕРА проходит', S26.проверьИмя('ГОСТЬ ЛЕРА').ok);
ок('защищённый префикс отклонён', !S26.собериСПрефиксом('ДЕД', 'Х').ok);

раздел('SMS: валидация, диалоги, непрочитанные');
const смс = { id:'s1', от:'02', кому:'04', текст:'код 123456', ts:1 };
ок('валидное SMS проходит', S26.валидныйСмс(смс).ok);
ок('пустой текст отклонён', !S26.валидныйСмс(Object.assign({}, смс, { текст:'  ' })).ok);
ок('плохой номер отклонён', !S26.валидныйСмс(Object.assign({}, смс, { кому:'12345' })).ok);
ок('текст >2000 отклонён', !S26.валидныйСмс(Object.assign({}, смс, { текст:'х'.repeat(2001) })).ok);
ок('гостевые номера валидны', S26.валидныйСмс({ id:'s', от:'G1234', кому:'04', текст:'привет', ts:1 }).ok);
const список = [
  { id:'s1', от:'02', кому:'04', текст:'а', ts:5 },
  { id:'s2', от:'04', кому:'02', текст:'б', ts:6 },
  { id:'s3', от:'01', кому:'04', текст:'в', ts:7 },
  { id:'s4', от:'02', кому:'01', текст:'чужое', ts:8 }
];
const диалоги = S26.диалогИзСписка(список, '04');
ок('два диалога для номера 04', диалоги.length === 2);
ок('последнее сообщение верное', диалоги[0].номер === '01' && диалоги[0].последнее.текст === 'в');
ок('непрочитанные считаются для моих входящих', S26.непрочитанныеСмс(список, '04') === 2);
ок('чужие SMS не считаются', S26.непрочитанныеСмс([список[3]], '02') === 0);

раздел('СВОИ OTP: 6 цифр, TTL 5 минут, одноразовые');
const код = S26.сгенерируйКод();
ок('код из 6 цифр', /^\d{6}$/.test(код));
ок('код случайный (два разных за серию)', (() => {
  const м = new Set(); for (let i = 0; i < 20; i++) м.add(S26.сгенерируйКод());
  return м.size > 1;
})());
const выданные = [{ код:'111111', кому:'04', ts:1000, использован:false }];
ок('верный код проходит', S26.проверьКод(выданные, '111111', 2000).ok);
ок('чужой код честно отклонён', !S26.проверьКод(выданные, '999999', 2000).ok && S26.проверьКод(выданные, '999999', 2000).причина.includes('не выдавали'));
ок('истёкший код отклонён (5 мин)', !S26.проверьКод(выданные, '111111', 1000 + S26.ОТП_TTL + 1).ok && S26.проверьКод(выданные, '111111', 1000 + S26.ОТП_TTL + 1).причина.includes('истёк'));
ок('пограничное время: ровно TTL-1 проходит', S26.проверьКод(выданные, '111111', 1000 + S26.ОТП_TTL - 1).ok);
ок('невалидный код отклонён', !S26.проверьКод(выданные, 'abc', 2000).ok);
ок('одноразовость: после использования не пускает', (() => {
  const в = [{ код:'222222', кому:'04', ts:0, использован:true }];
  const р = S26.проверьКод(в, '222222', 1000);
  return !р.ok && р.причина.includes('одноразовый');
})());
ок('чистка просроченных', S26.чистьПросроченные([{ код:'333333', кому:'x', ts:0, использован:false }, { код:'444444', кому:'x', ts:S26.ОТП_TTL + 1, использован:false }], S26.ОТП_TTL + 10).length === 1);

раздел('подпись SMS (реальный WebCrypto)');
(async function(){
  const пара = await webcrypto.subtle.generateKey({ name:'ECDSA', namedCurve:'P-256' }, false, ['sign','verify']);
  const sig = await S26.криптоПодпись(пара.privateKey, S26.строкаПодписиСмс(смс));
  ок('подпись непустая', typeof sig === 'string' && sig.length > 40);
  ок('строка подписи не меняется от повторов', S26.строкаПодписиСмс(смс) === S26.строкаПодписиСмс(смс));

  console.log('\n═══ ИТОГ ·26: ' + прошло + '/' + всего + ' ═══');
  process.exit(прошло === всего ? 0 : 1);
})().catch(function(ошибка){ console.error('АСИНХРОННАЯ ОШИБКА:', ошибка); process.exit(1); });
