def зона_фак(старое, р):
    """JSON-LD ·35 ВОПРОСЫ: числа в ответах поисковику — производные словаря.
    Ручные числа здесь не чинятся рантаймом (машины читают JSON) — только цех."""
    новое = старое
    тройка = (str(р["дверей"]) + " " + мн(р["дверей"], "дверь", "двери", "дверей")
              + " · " + str(р["песен"]) + " " + мн(р["песен"], "песня", "песни", "песен")
              + " · " + str(р["языков"]) + " языков")
    новое, n1 = re.subn(r"[0-9]+ двер\S* · [0-9]+ песн\S* · [0-9]+ языков", тройка, новое)
    мин = str(р["очередь"]) + " " + мн(р["очередь"], "минусовка", "минусовки", "минусовок")
    новое, n3 = re.subn(r"[0-9]+ локальн\S* минусовк\S*",
                        str(р["очередь"]) + " локальные " + мн(р["очередь"], "минусовка", "минусовки", "минусовок"), новое)
    новое, n2 = re.subn(r"[0-9]+ минусовк\S*", мин, новое)
    новое, n4 = re.subn(r"тексты [0-9]+ песен", "тексты " + str(р["очередь"]) + " песен", новое)
    if n1 != 1:
        raise RuntimeError("фак: троек дверей/песен/языков нашлось " + str(n1))
    if n2 + n3 < 2:
        raise RuntimeError("фак: минусовок нашлось " + str(n2 + n3))
    if n4 != 1:
        raise RuntimeError("фак: «тексты N песен» нашлось " + str(n4))
    return новое


def зона_фак_q1(старое, р):
    """Видимый ответ q-1 ·35: фолбэки span-бирок = правде реестра."""
    новое = старое
    новое, n1 = re.subn(r'(data-реестр="дверей">)[0-9]+(?=<)', r'\g<1>' + str(р["дверей"]), новое)
    новое, n2 = re.subn(r'(data-реестр="песен">)[0-9]+(?=<)', r'\g<1>' + str(р["песен"]), новое)
    новое, n3 = re.subn(r'(data-реестр="языков">)[0-9]+(?=<)', r'\g<1>' + str(р["языков"]), новое)
    if n1 != 1 or n2 != 1 or n3 != 1:
        raise RuntimeError("фак_q1: дверей=" + str(n1) + " песен=" + str(n2) + " языков=" + str(n3))
    return новое


def зона_фак_очередь(старое, р):
    """Видимые ответы q-8/q-10/q-11 ·35: счётчик минусовок — по словарю это
    «песен_очередь_фонд» (очередь фонда), а не общий «песен»; ключ бирки
    и фолбэк — из реестра (F-020: три счётчика разведены глоссарием).
    Идемпотентно: переименованные бирки считаются как свои."""
    новое = старое
    новое, n1 = re.subn(r'data-реестр="песен"', 'data-реестр="песен_очередь_фонд"', новое)
    всего = новое.count('data-реестр="песен_очередь_фонд"')
    новое, n2 = re.subn(r'(data-реестр="песен_очередь_фонд">)[0-9]+(?=<)', r'\g<1>' + str(р["очередь"]), новое)
    if всего < 1 or n2 != всего:
        raise RuntimeError("фак_очередь: бирок " + str(всего) + ", фолбэков " + str(n2))
    return новое


def зона_ветка(старое, р):
    """AGENTS.md: строка о ветке деплоя — производная pages.yml (F-021/T-072).
    Агент читает правду о потоке, а не устаревшую строку."""
    новое, n = re.subn(r"ветка `[a-z0-9_-]+`, без сборщика", "ветка `" + р["ветка"] + "`, без сборщика", старое)
    if n != 1:
        raise RuntimeError("ветка: нашлось " + str(n))
    return новое


