def установить_маркеры(текст, файл, имя):
    якорь_re, стиль = УСТАНОВКА[имя]
    совпадение = re.search(якорь_re, текст, re.M)
    if not совпадение:
        raise RuntimeError("установка маркеров " + файл + " [" + имя + "]: якорь не найден — снять свежие байты, не по памяти")
    фраг = совпадение.group(0)
    if стиль == "js":
        обёртка = "/*" + НАЧАЛО + "*/" + фраг + "/*" + КОНЕЦ + "*/"
    else:
        обёртка = "<!--" + НАЧАЛО + "-->\n" + фраг + "\n<!--" + КОНЕЦ + "-->"
    return текст[: совпадение.start()] + обёртка + текст[совпадение.end():]


# ── ПРАВДА-2/T-073: общий проход по всем лицам — фолбэки бирок = правде реестра ──

ИСКЛЮЧЁННЫЕ_МИРЫ = ("ladom-prototype/", "ladom-v2/", "ДОКУМЕНТЫ/", "harness/", ".git/")


def правда_бирок(р):
    """Карта ключ бирки → честный фолбэк (производные реестра/файлов)."""
    return {
        "дверей": str(р["дверей"]),
        "дверей_человек": р["дверей_человек"],
        "песен": str(р["песен"]),
        "песен_очередь_фонд": str(р["очередь"]),
        "релизы_канала": str(р.get("релизы", "")),
        "языков": str(р["языков"]),
        "версия": р["вер"],
        "такт": р["такт"],
        "кэш": р["кэш"],
    }


def выровнять_бирки(р):
    """Все data-реестр фолбэки во ВСЕХ живых лицах дома = правде словаря.
    Рантайм sg-registry живит числа на живом URL; фолбэк виден в офлайн-первом
    кадре и в поисковом снимке — он обязан нести правду, а не пятое поколение
    чисел. Файлы ищутся по дереву (новые двери покрываются сами) — класс
    числа-ложь не имеет куда вернуться. Возвращает (дрейф, правки)."""
    правды = правда_бирок(р)
    правки = {}
    for путь in sorted(КОРЕНЬ.rglob("*.html")):
        отн = путь.relative_to(КОРЕНЬ).as_posix()
        if отн.startswith(ИСКЛЮЧЁННЫЕ_МИРЫ):
            continue
        текст = путь.read_text(encoding="utf-8")
        if 'data-реестр=' not in текст:
            continue
        новое = текст
        def замена(м):
            ключ = м.group(2)
            if ключ in правды:
                return м.group(1) + правды[ключ] + м.group(4)
            return м.group(0)
        новое = re.subn(r'(data-реестр="([^"]+)">)([^<]*)(<)', замена, новое)[0]
        if новое != текст:
            правки[отн] = новое
    return правки


def главная():
    парсер = argparse.ArgumentParser(description="Генератор правды дома СИНГУЛЯР")
    парсер.add_argument("--apply", action="store_true", help="применить (по умолчанию dry-run)")
    парсер.add_argument("--report", action="store_true", help="унифицированный дифф")
    арг = парсер.parse_args()

    р = реестр()
    дрейф = 0
    для_файлов = {}
    for файл, имя, функция in ЗОНЫ:
        для_файлов.setdefault(файл, []).append((имя, функция))

    for файл, зоны_файла in для_файлов.items():
        путь = КОРЕНЬ / файл
        текст = путь.read_text(encoding="utf-8")
        for имя, функция in зоны_файла:
            признак = ПРИЗНАК[имя]
            найдено = [s for s in все_зоны(текст) if признак in s[3]]
            if len(найдено) > 1:
                print("ПАДЕНИЕ: " + файл + " [" + имя + "]: зон с признаком — " + str(len(найдено)))
                return 2
            if not найдено:
                если_есть = все_зоны(текст)
                причина = "зона не опознана по признаку" if если_есть else "маркеров нет"
                if not арг.apply:
                    print("ДРЕЙФ: " + файл + " [" + имя + "] — " + причина + " (нужен --apply)")
                    дрейф += 1
                    continue
                try:
                    текст = установить_маркеры(текст, файл, имя)
                except RuntimeError as ошибка:
                    print("ПАДЕНИЕ: " + str(ошибка))
                    return 2
                print("ЦЕХ: маркеры установлены — " + файл + " [" + имя + "]")
                найдено = [s for s in все_зоны(текст) if признак in s[3]]
                if not найдено:
                    print("ПАДЕНИЕ: " + файл + " [" + имя + "]: зона после установки не опознана")
                    return 2
            н, к, стиль_внутри, тело = найдено[0]
            исходник = текст
            тело = тело.strip("\n")  # края зоны нормированы: НАЧАЛО\n + тело + \nКОНЕЦ (идемпотентность)
            try:
                новое_тело = функция(тело, р)
            except RuntimeError as ошибка:
                print("ПАДЕНИЕ: " + файл + " [" + имя + "]: " + str(ошибка))
                return 2
            новое = текст[:н] + зона_построить(новое_тело, стиль_внутри) + текст[к:]
            if новое == исходник:
                print("ЧИСТО: " + файл + " [" + имя + "]")
                continue
            дрейф += 1
            if арг.report:
                для_диффа = difflib.unified_diff(
                    исходник.splitlines(True), новое.splitlines(True),
                    fromfile=файл + " (было)", tofile=файл + ("" if арг.apply else " (будет)"), n=0)
                sys.stdout.writelines(для_диффа)
            else:
                print("ДРЕЙФ: " + файл + " [" + имя + "]")
            if арг.apply:
                путь.write_text(новое, encoding="utf-8", newline="")
                print("ЦЕХ: переписано — " + файл + " [" + имя + "]")
                текст = новое

    # ПРАВДА-2/T-073: общий проход бирок по всем живым лицам дома
    правки = выровнять_бирки(р)
    for отн, новое in sorted(правки.items()):
        дрейф += 1
        if арг.report:
            старое = (КОРЕНЬ / отн).read_text(encoding="utf-8")
            для_диффа = difflib.unified_diff(
                старое.splitlines(True), новое.splitlines(True),
                fromfile=отн + " (было)", tofile=отн + ("" if арг.apply else " (будет)"), n=0)
            sys.stdout.writelines(для_диффа)
        else:
            print("ДРЕЙФ: " + отн + " [бирки]")
        if арг.apply:
            (КОРЕНЬ / отн).write_text(новое, encoding="utf-8", newline="")
            print("ЦЕХ: переписано — " + отн + " [бирки]")

    if дрейф == 0:
        print("ДРЕЙФ НЕТ: дом = реестру (идемпотентно)")
        return 0
    print("ДРЕЙФ: зон " + str(дрейф))
    return 0 if арг.apply else 1


if __name__ == "__main__":
    sys.exit(главная())
