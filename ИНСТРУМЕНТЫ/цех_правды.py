def зона_футер(старое, р):
    """Организм-бирка хаба (#sg-организм): владеем ТЕКСТОМ бирки (фолбэки чисел) —
    span-механизм data-реестр и стиль не трогаем. Фолбэки = правде реестра,
    чтобы даже офлайн-первый кадр не нёс число-ложь."""
    шаблон = ("ДОМ СИНГУЛЯР · <span data-реестр=\"дверей\">{дверей}</span> {дверей_слово} · "
              "<span data-реестр=\"песен\">{песен}</span> {песен_слово} · "
              "<span data-реестр=\"языков\">{языков}</span> языков · "
              "такт v<span data-реестр=\"версия\">{вер}</span> «<span data-реестр=\"такт\">{такт}</span>» · "
              "кэш <span data-реестр=\"кэш\">{кэш}</span> · "
              "сборка <span data-реестр=\"деплой\">SHA при выкладке</span>")
    return шаблон.format(
        дверей=р["дверей"], дверей_слово=мн(р["дверей"], "дверь", "двери", "дверей"),
        песен=р["песен"], песен_слово=мн(р["песен"], "песня", "песни", "песен"),
        языков=р["языков"], вер=р["вер"], такт=р["такт"], кэш=р["кэш"])


