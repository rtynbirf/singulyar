def мн(число, один, два, пять):
    """Русская форма существительного: мн(52, 'дверь','двери','дверей') → 'двери'."""
    н = abs(int(число)) % 100
    if 11 <= н <= 14:
        return пять
    н = н % 10
    if н == 1:
        return один
    if 2 <= н <= 4:
        return два
    return пять


def все_зоны(текст):
    """Все маркер-блоки файла: [(начало, конец, стиль, тело)] — html и js варианты."""
    вышло = []
    пары = [
        ("<!--" + НАЧАЛО + "-->", "<!--" + КОНЕЦ + "-->", "html"),
        ("/*" + НАЧАЛО + "*/", "/*" + КОНЕЦ + "*/", "js"),
    ]
    for нач_м, кон_м, стиль in пары:
        позиция = 0
        while True:
            н = текст.find(нач_м, позиция)
            if н < 0:
                break
            к = текст.find(кон_м, н + len(нач_м))
            if к < 0:
                break
            вышло.append((н, к + len(кон_м), стиль, текст[н + len(нач_м):к]))
            позиция = к + len(кон_м)
    вышло.sort()
    return вышло


