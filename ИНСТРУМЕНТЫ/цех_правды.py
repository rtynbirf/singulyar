#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""цех_правды.py — генератор правды дома СИНГУЛЯР (ТЗ-А/ТЗ-И; латка С128 поверх такта v11.49).

Заявление = проверка = производное: штампы (титул/og:title/window.APP хаба ·31,
README «одна правда», шапка карты) — ПРОИЗВОДНЫЕ от живого реестра data/versions.json,
а не ручные строки. Генератор перезаписывает ТОЛЬКО внутри маркеров-стражей
СНГ:ПРАВДА; всё снаружи — летопись, не трогается (закон «один факт — одно место»).

Зоны (самоописывающиеся — опознаются по признаку внутри, порядок не важен):
  ·31 титул ·31 og:title ·31 window.APP · README таблица · шапка карты

Режимы:
  python3 ИНСТРУМЕНТЫ/цех_правды.py             # dry-run: дрейф виден, exit 1 если есть
  python3 ИНСТРУМЕНТЫ/цех_правды.py --apply     # применить (маркеры ставятся при первом ходе)
  python3 ИНСТРУМЕНТЫ/цех_правды.py --report    # + унифицированный дифф

Идемпотентность: второй прогон --apply меняет 0 байт (страж: ИНСТРУМЕНТЫ/test_цех_правды.mjs).
"""

import argparse
import difflib
import json
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
НАЧАЛО = "СНГ:ПРАВДА-НАЧАЛО"
КОНЕЦ = "СНГ:ПРАВДА-КОНЕЦ"


def реестр():
    d = json.loads((КОРЕНЬ / "data" / "versions.json").read_text(encoding="utf-8"))
    дом = d["дом"]
    return {
        "вер": дом["версия"],
        "такт": дом["такт"],
        "кэш": дом["поколение_кэша"],
        "дата": дом["дата"],
    }


def все_зоны(текст):
    """Все маркер-блоки файла: [(начало, конец, стиль, тело)] — html и js варианты."""
    вышло = []
    пары = [
        ("<!--" + НАЧАЛО + "-->", "<!--" + КОНЕЦ + "-->", "html"),
        ("/*" + НАЧАЛО + "*/", "/*" + КОНЕЦ + "*/", "js"),
    ]
    for нач_м, кон_м, стиль in пары:
        позиция = 0
        while True:
            н = текст.find(нач_м, позиция)
            if н < 0:
                break
            к = текст.find(кон_м, н + len(нач_м))
            if к < 0:
                break
            вышло.append((н, к + len(кон_м), стиль, текст[н + len(нач_м):к]))
            позиция = к + len(кон_м)
    вышло.sort()
    return вышло


# Опознание зоны по содержимому
ПРИЗНАК = {
    "титул": "<title>",
    "ог": "og:title",
    "апп": "window.APP = {",
    "ридми": "| Такт | **",
    "карта": "**Статус:** ✅ Актуально",
}


def зона_построить(содержимое, стиль):
    if стиль == "js":
        return "/*" + НАЧАЛО + "*/" + содержимое + "/*" + КОНЕЦ + "*/"
    return "<!--" + НАЧАЛО + "-->\n" + содержимое + "\n<!--" + КОНЕЦ + "-->"


# ── Владельцы зон: возвращают новое содержимое ВНУТРИ маркеров ───────────────

def зона_титул(старое, р):
    """Строка <title>: владеем штампом «СИНГУЛЯР ·31 vX «Y»», хвост сохраняем."""
    штамп = "СИНГУЛЯР ·31 v" + р["вер"] + " «" + р["такт"] + "»"
    новое, число = re.subn(r"СИНГУЛЯР ·31 v[0-9.]+ «[^»]+»", штамп, старое)
    if число != 1:
        raise RuntimeError("титул: ждал 1 штамп, нашёл " + str(число))
    return новое


def зона_ог(старое, р):
    """Строка og:title: та же собственность на штамп."""
    return зона_титул(старое, р)


def зона_апп(старое, р):
    """Штамп window.APP: владеем полями v/такт/кэш/стр/ver/cache; build и летопись сохраняем."""
    новое = старое
    замены = [
        (r"v:'[0-9.]+', такт:'[^']+'", "v:'" + р["вер"] + "', такт:'" + р["такт"] + "'"),
        (r"кэш:'s15-orkestrator-v[0-9]+'", "кэш:'s15-orkestrator-" + р["кэш"] + "'"),
        (r"cache:'s15-orkestrator-v[0-9]+'", "cache:'s15-orkestrator-" + р["кэш"] + "'"),
        (r"стр:'[0-9]{4}-[0-9]{2}-[0-9]{2}'", "стр:'" + р["дата"] + "'"),
        (r"ver:'v[0-9.]+ «[^»]+»'", "ver:'v" + р["вер"] + " «" + р["такт"] + "»'"),
    ]
    for пат, зам in замены:
        новое, число = re.subn(пат, зам, новое)
        if число != 1:
            raise RuntimeError("APP: поле " + пат + " нашлось " + str(число) + " раз")
    return новое


def зона_ридми(старое, р):
    """Таблица «одна правда»: владеем ТОЛЬКО значением строк Такт и Поколение кэша
    (все три колонки и прочие строки — байт-в-байт)."""
    строки = старое.split("\n")
    вышло = []
    рег_такт = re.compile(r"^(\|\s*Такт\s*\|)(\s*)\*\*[^*]*\*\*(\s*\|.*)$")
    рег_кэш = re.compile(r"^(\|\s*Поколение кэша\s*\|)(\s*)\*\*[^*]*\*\*(\s*\|.*)$")
    найдено = {"такт": 0, "кэш": 0}
    for с in строки:
        м = рег_такт.match(с)
        if м:
            вышло.append(м.group(1) + м.group(2) + "**" + р["вер"] + " «" + р["такт"] + "»**" + м.group(3))
            найдено["такт"] += 1
            continue
        м = рег_кэш.match(с)
        if м:
            вышло.append(м.group(1) + м.group(2) + "**s15-orkestrator-" + р["кэш"] + "**" + м.group(3))
            найдено["кэш"] += 1
            continue
        вышло.append(с)
    if найдено["такт"] != 1 or найдено["кэш"] != 1:
        raise RuntimeError("README: строк-такт=" + str(найдено["такт"]) + ", строк-кэш=" + str(найдено["кэш"]))
    return "\n".join(вышло)


def зона_карта(старое, р):
    """Шапка карты: владеем «**Такт:** vX «Y»» и «**Обновлено:** дата», хвост-летопись сохраняем."""
    новое = старое
    новое, n1 = re.subn(r"\*\*Такт:\*\* v[0-9.]+ «[^»]+»", "**Такт:** v" + р["вер"] + " «" + р["такт"] + "»", новое)
    новое, n2 = re.subn(r"\*\*Обновлено:\*\* [0-9]{4}-[0-9]{2}-[0-9]{2}", "**Обновлено:** " + р["дата"], новое)
    if n1 != 1 or n2 != 1:
        raise RuntimeError("карта: Такт=" + str(n1) + ", Обновлено=" + str(n2))
    return новое


ЗОНЫ = [
    ("СИНГУЛЯР_31_ЛАДОМ.html", "титул", зона_титул),
    ("СИНГУЛЯР_31_ЛАДОМ.html", "ог", зона_ог),
    ("СИНГУЛЯР_31_ЛАДОМ.html", "апп", зона_апп),
    ("README.md", "ридми", зона_ридми),
    ("docs/ДОРОЖНАЯ_КАРТА.md", "карта", зона_карта),
]

# Первичная резка: якорь, вокруг которого ставятся маркеры при первом --apply
УСТАНОВКА = {
    "титул": (r"^[ \t]*<title>ЛАДОМ — пространство своих · СИНГУЛЯР ·31 v[0-9.]+ «[^»]+»[^<]*</title>[ \t]*$", "html"),
    "ог": (r"^[ \t]*<meta property=\"og:title\" content=\"ЛАДОМ — пространство своих · СИНГУЛЯР ·31 v[0-9.]+ «[^»]+»\">[ \t]*$", "html"),
    "апп": (r"^window\.APP = \{ v:'[0-9.]+'[^;]+\};", "js"),
    "ридми": (r"^\| Что \| Сколько \| Где проверять \|\n\|---\|---\|---\|\n(?:\|[^\n]*\|\n)+", "html"),
    "карта": (r"^> \*\*Статус:\*\* ✅ Актуально · \*\*Такт:\*\* v[0-9.]+ «[^»]+» · \*\*Обновлено:\*\* [0-9]{4}-[0-9]{2}-[0-9]{2}.*$", "html"),
}


def установить_маркеры(текст, файл, имя):
    якорь_re, стиль = УСТАНОВКА[имя]
    совпадение = re.search(якорь_re, текст, re.M)
    if not совпадение:
        raise RuntimeError("установка маркеров " + файл + " [" + имя + "]: якорь не найден — снять свежие байты, не по памяти")
    фраг = совпадение.group(0)
    if стиль == "js":
        обёртка = "/*" + НАЧАЛО + "*/" + фраг + "/*" + КОНЕЦ + "*/"
    else:
        обёртка = "<!--" + НАЧАЛО + "-->\n" + фраг + "\n<!--" + КОНЕЦ + "-->"
    return текст[: совпадение.start()] + обёртка + текст[совпадение.end():]


def главная():
    парсер = argparse.ArgumentParser(description="Генератор правды дома СИНГУЛЯР")
    парсер.add_argument("--apply", action="store_true", help="применить (по умолчанию dry-run)")
    парсер.add_argument("--report", action="store_true", help="унифицированный дифф")
    арг = парсер.parse_args()

    р = реестр()
    дрейф = 0
    для_файлов = {}
    for файл, имя, функция in ЗОНЫ:
        для_файлов.setdefault(файл, []).append((имя, функция))

    for файл, зоны_файла in для_файлов.items():
        путь = КОРЕНЬ / файл
        текст = путь.read_text(encoding="utf-8")
        for имя, функция in зоны_файла:
            признак = ПРИЗНАК[имя]
            найдено = [s for s in все_зоны(текст) if признак in s[3]]
            if len(найдено) > 1:
                print("ПАДЕНИЕ: " + файл + " [" + имя + "]: зон с признаком — " + str(len(найдено)))
                return 2
            if not найдено:
                если_есть = все_зоны(текст)
                причина = "зона не опознана по признаку" if если_есть else "маркеров нет"
                if not арг.apply:
                    print("ДРЕЙФ: " + файл + " [" + имя + "] — " + причина + " (нужен --apply)")
                    дрейф += 1
                    continue
                try:
                    текст = установить_маркеры(текст, файл, имя)
                except RuntimeError as ошибка:
                    print("ПАДЕНИЕ: " + str(ошибка))
                    return 2
                print("ЦЕХ: маркеры установлены — " + файл + " [" + имя + "]")
                найдено = [s for s in все_зоны(текст) if признак in s[3]]
                if not найдено:
                    print("ПАДЕНИЕ: " + файл + " [" + имя + "]: зона после установки не опознана")
                    return 2
            н, к, стиль_внутри, тело = найдено[0]
            исходник = текст
            тело = тело.strip("\n")  # края зоны нормированы: НАЧАЛО\n + тело + \nКОНЕЦ (идемпотентность)
            try:
                новое_тело = функция(тело, р)
            except RuntimeError as ошибка:
                print("ПАДЕНИЕ: " + файл + " [" + имя + "]: " + str(ошибка))
                return 2
            новое = текст[:н] + зона_построить(новое_тело, стиль_внутри) + текст[к:]
            if новое == исходник:
                print("ЧИСТО: " + файл + " [" + имя + "]")
                continue
            дрейф += 1
            if арг.report:
                для_диффа = difflib.unified_diff(
                    исходник.splitlines(True), новое.splitlines(True),
                    fromfile=файл + " (было)", tofile=файл + ("" if арг.apply else " (будет)"), n=0)
                sys.stdout.writelines(для_диффа)
            else:
                print("ДРЕЙФ: " + файл + " [" + имя + "]")
            if арг.apply:
                путь.write_text(новое, encoding="utf-8", newline="")
                print("ЦЕХ: переписано — " + файл + " [" + имя + "]")
                текст = новое

    if дрейф == 0:
        print("ДРЕЙФ НЕТ: дом = реестру (идемпотентно)")
        return 0
    print("ДРЕЙФ: зон " + str(дрейф))
    return 0 if арг.apply else 1


if __name__ == "__main__":
    sys.exit(главная())
