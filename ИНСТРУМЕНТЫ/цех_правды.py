def зона_титул(старое, р):
    """Строка <title>: владеем штампом «СИНГУЛЯР ·31 vX «Y»», хвост сохраняем."""
    штамп = "СИНГУЛЯР ·31 v" + р["вер"] + " «" + р["такт"] + "»"
    новое, число = re.subn(r"СИНГУЛЯР ·31 v[0-9.]+ «[^»]+»", штамп, старое)
    if число != 1:
        raise RuntimeError("титул: ждал 1 штамп, нашёл " + str(число))
    return новое


def зона_ог(старое, р):
    """Строка og:title: та же собственность на штамп."""
    return зона_титул(старое, р)


def зона_апп(старое, р):
    """Штамп window.APP: владеем полями v/такт/кэш/стр/ver/cache; build и летопись сохраняем."""
    новое = старое
    замены = [
        (r"v:'[0-9.]+', такт:'[^']+'", "v:'" + р["вер"] + "', такт:'" + р["такт"] + "'"),
        (r"кэш:'s15-orkestrator-v[0-9]+'", "кэш:'s15-orkestrator-" + р["кэш"] + "'"),
        (r"cache:'s15-orkestrator-v[0-9]+'", "cache:'s15-orkestrator-" + р["кэш"] + "'"),
        (r"стр:'[0-9]{4}-[0-9]{2}-[0-9]{2}'", "стр:'" + р["дата"] + "'"),
        (r"ver:'v[0-9.]+ «[^»]+»'", "ver:'v" + р["вер"] + " «" + р["такт"] + "»'"),
    ]
    for пат, зам in замены:
        новое, число = re.subn(пат, зам, новое)
        if число != 1:
            raise RuntimeError("APP: поле " + пат + " нашлось " + str(число) + " раз")
    return новое


def зона_ридми(старое, р):
    """Таблица «одна правда»: владеем ТОЛЬКО значением строк Такт, Поколение кэша,
    Двери, Песни фонда, Языки флагмана (пояснения и прочие строки — байт-в-байт).
    ПРАВДА-2 (F-020): числа строк — из словаря счётчиков, не руками."""
    строки = старое.split("\n")
    вышло = []
    рег_такт = re.compile(r"^(\|\s*Такт\s*\|)(\s*)\*\*[^*]*\*\*(\s*\|.*)$")
    рег_кэш = re.compile(r"^(\|\s*Поколение кэша\s*\|)(\s*)\*\*[^*]*\*\*(\s*\|.*)$")
    рег_двери = re.compile(r"^(\|\s*Двери\s*\|)(\s*)\*\*[^*]*\*\*(.*)$")
    рег_песни = re.compile(r"^(\|\s*Песни фонда\s*\|)(\s*)\*\*[^*]*\*\*(.*)$")
    рег_языки = re.compile(r"^(\|\s*Языки флагмана\s*\|)(\s*)\*\*[^*]*\*\*(.*)$")
    найдено = {"такт": 0, "кэш": 0, "двери": 0, "песни": 0, "языки": 0}
    for с in строки:
        м = рег_такт.match(с)
        if м:
            вышло.append(м.group(1) + м.group(2) + "**" + р["вер"] + " «" + р["такт"] + "»**" + м.group(3))
            найдено["такт"] += 1
            continue
        м = рег_кэш.match(с)
        if м:
            вышло.append(м.group(1) + м.group(2) + "**s15-orkestrator-" + р["кэш"] + "**" + м.group(3))
            найдено["кэш"] += 1
            continue
        м = рег_двери.match(с)
        if м:
            вышло.append(м.group(1) + м.group(2) + "**" + р["дверей_человек"] + "**" + м.group(3))
            найдено["двери"] += 1
            continue
        м = рег_песни.match(с)
        if м:
            вышло.append(м.group(1) + м.group(2) + "**" + str(р["песен"]) + "**" + м.group(3))
            найдено["песни"] += 1
            continue
        м = рег_языки.match(с)
        if м:
            вышло.append(м.group(1) + м.group(2) + "**" + str(р["языков"]) + "**" + м.group(3))
            найдено["языки"] += 1
            continue
        вышло.append(с)
    if найдено["такт"] != 1 or найдено["кэш"] != 1 or найдено["двери"] != 1 or найдено["песни"] != 1 or найдено["языки"] != 1:
        raise RuntimeError("README: строк-такт=" + str(найдено["такт"]) + ", строк-кэш=" + str(найдено["кэш"]) + ", дверей=" + str(найдено["двери"]) + ", песен=" + str(найдено["песни"]) + ", языков=" + str(найдено["языки"]))
    return "\n".join(вышло)


def зона_карта(старое, р):
    """Шапка карты: владеем «**Такт:** vX «Y»» и «**Обновлено:** дата», хвост-летопись сохраняем."""
    новое = старое
    новое, n1 = re.subn(r"\*\*Такт:\*\* v[0-9.]+ «[^»]+»", "**Такт:** v" + р["вер"] + " «" + р["такт"] + "»", новое)
    новое, n2 = re.subn(r"\*\*Обновлено:\*\* [0-9]{4}-[0-9]{2}-[0-9]{2}", "**Обновлено:** " + р["дата"], новое)
    if n1 != 1 or n2 != 1:
        raise RuntimeError("карта: Такт=" + str(n1) + ", Обновлено=" + str(n2))
    return новое


