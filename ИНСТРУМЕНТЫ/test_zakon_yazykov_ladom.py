#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Тест ЗАКОНА ЯЗЫКОВ (I-12 СВОДа) — статики зала ·31, такт v10.90 «ЗАКОН».
Закон владельца (2026-10-13, «эТО ЗАКОН!!!»): РУССКИЙ → СЕРБСКИЙ → КАЗАХСКИЙ →
НЕМЕЦКИЙ → 15 языков СССР → народы СССР → все языки по носителям убыв.
Здесь проверяется страница зала: массив ЗАКОН_ПОРЯДОК, селект автоперевода,
принимающий блок ПУЛЬТа (ПУЛЬТ-чистка середины экрана), пробы ЗДОРОВЬЯ.
Запуск: python3 ИНСТРУМЕНТЫ/test_zakon_yazykov_ladom.py"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

прошло = 0
провалы = []
def ок(имя, условие):
    global прошло
    if условие:
        прошло += 1
        print('  ✓ ' + имя)
    else:
        провалы.append(имя)
        print('  ✗ ПРОВАЛ: ' + имя)

канон = json.load(open('ДАННЫЕ/ПОРЯДОК_ЯЗЫКОВ.json', encoding='utf-8'))
зал = open('СИНГУЛЯР_31_ЛАДОМ.html', encoding='utf-8').read()

print('ЗАКОН ЯЗЫКОВ (I-12) — статики зала ·31')

м = re.search(r'const ЗАКОН_ПОРЯДОК = \[([^\]]*)\]', зал)
ок('зал: массив ЗАКОН_ПОРЯДОК на месте', м is not None)
коды = re.findall(r'"([A-Za-z_][A-Za-z_0-9-]*)"', м.group(1)) if м else []
ок('зал: массив равен канону (байт-в-байт)', коды == канон['порядок_ладом'])
ок('зал: первые четыре — РУС→СРБ→КАЗ→НЕМ', коды[:4] == ['ru', 'sr', 'kk', 'de'])
СССР_ОСТАТОК = ['uk', 'be', 'uz', 'ka', 'az', 'lt', 'mo', 'lv', 'ky', 'tg', 'hy', 'tk', 'et']  # v10.91: ремонт hy
поз = {c: i for i, c in enumerate(коды)}
макс_ссср = max(поз[c] for c in СССР_ОСТАТОК if c in поз)
# С146: сэмпл хвоста — только законный (голова хвоста по носителям), старорежимный сэмпл стёрт
мин_хвост = min(поз[c] for c in ['en', 'zh', 'hi', 'es', 'fr', 'bn', 'ar', 'pt', 'ur', 'id', 'pa', 'ja'] if c in поз)
ок('зал: СССР-блок стоит перед хвостом по носителям', макс_ссср < мин_хвост)
нос = канон['носители']
хвост = коды[мин_хвост:]
значения = [нос.get(c, 0) for c in хвост]
ок('зал: хвост — по убыванию носителей', all(значения[i] >= значения[i+1] for i in range(len(значения)-1)))

мн = re.search(r'const НОСИТЕЛИ = (\{.*?\});\nwindow\.НОСИТЕЛИ', зал, re.S)
нз = json.loads(мн.group(1)) if мн else {}
мс = зал.find('l4selTl')
опции = re.findall(r'<option value="([a-z]{2})">', зал[мс:мс+3000]) if мс >= 0 else []
ок('зал: селект автоперевода — РУС→СРБ→КАЗ→DEU→УКР', опции[:5] == ['ru', 'sr', 'kk', 'de', 'uk'])
# С145: селект несёт весь канон (289, включая 101 народов СССР — никакой дискриминации);
# пин — равенство канону, а не «монотонность хвоста» (народы СССР стоят ПЕРЕД хвостом по закону)
двухбукв_канон = [c for c in канон['порядок_ладом'] if re.fullmatch(r'[a-z]{2}', c)]
ок('зал: селект автоперевода == канону I-12 (включая народы СССР, С145)',
   опции == двухбукв_канон[:len(опции)])

# ── С146 «ДЕКЛАРАЦИЯ = РЕАЛЬНОСТЬ»: старорежимные порядки мертвы, имена полными словами ──
ок('зал: НОСИТЕЛИ == канону целиком (С146: 173 недостающих языка возвращены, никакой дискриминации чисел)',
   all(нз.get(k) == v for k, v in канон['носители'].items()))
ок('зал: чипы имён мертвы — УКР/АНГЛ/КИТ/СРБ/КАЗ/НЕМ как значения имён не встречаются (С146)',
   not re.search(r':\s*"(УКР|БЕЛ|АНГЛ|ИСП|ПОРТ|ФРАН|ИТАЛ|ПОЛ|РУМ|НИД|ШВЕ|БОЛ|ГРЕЧ|НЕМ|РУС|КИТ|ХИН|АРА|ЯПО|КОР|СРБ|КАЗ)"', зал))
ок('зал: старорежимный порядок до С142 вычищен из страницы (en es fr de it pt uk zh ja ko ar hi)',
   'en es fr de it pt uk zh ja ko ar hi' not in зал)
ок('зал: старорежимные порядки С142/С143/С144 вычищены (дефисные последовательности)',
   not re.search(r'de uk es en pt fr it|sr kk de uk es en|zh hi es ar en pt', зал))
ок('зал: ложная декларация «зона пуста» стёрта (С146: в корпусе 101 язык народов)',
   'зона пуста' not in зал and 'в корпусе зала пока нет' not in зал)
ок('зал: старорежимная проба «канон цел — 119 кодов» стёрта (С146)',
   '119 кодов' not in зал and 'length===119' not in зал)
ок('зал: старорежимный селект-чип «РУС→ENG→ESP→DEU» стёрт из летописи страницы',
   'РУС→ENG→ESP→DEU' not in зал and 'ENG→ESP→DEU' not in зал)
ок('зал: LANGS головные имена полными словами (РУССКИЙ/СЕРБСКИЙ/КАЗАХСКИЙ/НЕМЕЦКИЙ)',
   'name:"РУССКИЙ"' in зал and 'name:"СЕРБСКИЙ"' in зал and 'name:"КАЗАХСКИЙ"' in зал and 'name:"НЕМЕЦКИЙ"' in зал)
ок('зал: проба __HEALTH35 несёт закон целиком (народы-101 + голова хвоста + монотонность, С146)',
   'народыЦелы' in зал and 'хвостЦел' in зал and 'монотонен' in зал and 'ИНДОНЕЗИЙСКИЙ' in зал)
ок('зал: ПУЛЬТ-чистка — принимающий блок pModesHost во вкладке ТЕКСТ',
   'id="pModesHost"' in зал and зал.find('id="pModesHost"') > зал.find('data-ptab="text"'))
ок('зал: ПУЛЬТ-чистка — переезжающий скрипт переносит .modes и #takt живыми узлами',
   'host.appendChild(modes)' in зал and 'host.appendChild(такт)' in зал)
import re as _re
ок('зал: пробы ЗДОРОВЬЯ живы — проба-35 определена, агрегатор проб жив (этаж v10.93 = 33/34/35, растёт; v11.44 «ИЗМЕРЕНО»)',
   'window.__HEALTH35 = function' in зал
   and _re.search(r'window\.__HEALTH\d+,window\.__HEALTH\d+\]\.forEach', зал) is not None)
_РЗ = json.load(open('data/versions.json', encoding='utf-8'))
ок('зал: честность версий — титул и APP живёт тактом реестра (v11.44 «ИЗМЕРЕНО»)',
   f"·31 v{_РЗ['дом']['версия']} «{_РЗ['дом']['такт']}»" in зал
   and f"v:'{_РЗ['дом']['версия']}', такт:'{_РЗ['дом']['такт']}'" in зал)

ок('канон: зоны закона описаны (первые четыре, СССР-15, народы СССР, хвост)',
   all(к in канон['зоны'] for к in ('первые_четыре', 'ссср_15_республик', 'народы_ссср_в_корпусе_дома', 'хвост')))
ок('канон: СССР-15 — конституционный порядок', канон['зоны']['ссср_15_республик']['порядок'] ==
   ['ru', 'uk', 'be', 'uz', 'kk', 'ka', 'az', 'lt', 'mo', 'lv', 'ky', 'tg', 'hy', 'tk', 'et'])  # v10.91: ремонт hy

print('\nИТОГ: %d/%d прошло' % (прошло, прошло + len(провалы)))
sys.exit(1 if провалы else 0)
