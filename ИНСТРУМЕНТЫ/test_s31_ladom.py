# -*- coding: utf-8 -*-
"""Тест двери ·31 ЛАДОМ и закона I-11 «ПАРАМЕТР» (такт v1.44.0 «ПОЛИМАТ»; ребрендинг тактов v10.44–v10.45).
Статика: файлы, манифест, лицо дома, свод. CLAIM/CODE/SPEC/TEST → VERDICT.
Запуск: python3 ИНСТРУМЕНТЫ/test_s31_ladom.py   (из корня дома)
"""
import io, json, os, re, sys

РАЗМЕР_BASELINE = 1513344   # байт двери v10.45 «ВЫХОД» (история: 6 194 958 Б — v10.7, 1 466 073 Б — v10.44)
# v11.44 «ИЗМЕРЕНО»: числа не морожены — ОЖИДАЕМО_ДВЕРЕЙ читается из data/versions.json в проверке ниже

окружение = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
шаги = []
def ок(имя, условие):
    шаги.append((имя, bool(условие)))
    return bool(условие)

def читай(п):
    return io.open(os.path.join(окружение, п), encoding='utf-8').read()

дверь_путь = os.path.join(окружение, 'СИНГУЛЯР_31_ЛАДОМ.html')
дверь_есть = os.path.isfile(дверь_путь)
дверь = читай('СИНГУЛЯР_31_ЛАДОМ.html') if дверь_есть else ''
ядро = читай('singulyar-modules.js')
лицо = читай('index.html')
sw = читай('sw15.js')
манифест = json.loads(читай('manifest.webmanifest'))
свод = json.loads(читай('ДОКУМЕНТЫ/СВОД_ЗАКОНОВ.json'))
свод_md = читай('ДОКУМЕНТЫ/СВОД_ЗАКОНОВ.md')

# 1. Дверь существует и несёт baseline 1:1 (+ интеграция дома)
ок('дверь ·31 существует', дверь_есть)
размер = len(дверь.encode('utf-8')) if дверь else 0
# v11.44 «ИЗМЕРЕНО»: верхний допуск 72КБ снят — дверь выросла законно тактами (73728 Б пробито давно);
# базовая гарантия — дверь не похудела относительно v10.45; контроль роста — бюджет веса (ТЗ-2, Wave 2)
ок('baseline внутри двери цел (>= РАЗМЕР_BASELINE — дверь не похудела)',
   размер >= РАЗМЕР_BASELINE)
ок('в двери ноль загружаемых внешних ресурсов (офлайн-закон: скрипты/стили/картинки — только свои; canonical — метка, не загрузка)',
   not re.search(r'<script[^>]+src="https?://|<img[^>]+src="https?://|<link(?![^>]*rel="canonical")[^>]+href="https?://|fetch\(["\']https?://|XMLHttpRequest', дверь))
ок('внешние адреса в двери — canonical + два анкора человека (youtube-ссылки RUVSON, не загрузки)',
   len(re.findall(r'href="https?://', дверь)) == 3 and 'youtu' in дверь and 'rel="canonical"' in дверь)
ок('дверь подключает ядро дома (визит пишет само ядро)',
   'singulyar-modules.js' in дверь)
ок('дверь держит полосу дома (·31 ЛАДОМ + путь назад с ?v=N против вечного кэша ТВ)',
   '·31' in дверь and 'ЛАДОМ' in дверь and re.search(r'href="\./index\.html\?v=\d+"', дверь) is not None)  # v10.7: S·31-метка v9.8-эры снята — бирку рисует движок дома (номер ·31 + имя)
ок('титул двери живёт внутри дом-титула',
   'ПАСПОРТ ДОМА' in дверь and 'СИНГУЛЯР ·31' in дверь)

# 2. Манифест ядра: дверь в карте, файл на диске, счёт сходится
ок('карта ядра содержит s31 с верным файлом',
   re.search(r"id: 's31'.*?файл: 'СИНГУЛЯР_31_ЛАДОМ\.html'", ядро, re.S) is not None)
карта = re.findall(r"файл: '(СИНГУЛЯР_[^']+)'", ядро)
двери_без_хаба = карта
РЕЕСТР_Л = json.loads(читай('data/versions.json'))
узлов_ядро = len(re.findall(r"id: '(s\d+[a-z0-9]*)'", ядро))
ок(f'манифест: {РЕЕСТР_Л["счётчики"]["дверей"]} дверей реестра = s-узлам ядра (v11.44 «ИЗМЕРЕНО»)',
   узлов_ядро == РЕЕСТР_Л['счётчики']['дверей'])
ок('каждая дверь карты — живой файл на диске',
   all(os.path.isfile(os.path.join(окружение, ф)) for ф in set(двери_без_хаба)))
связи_s31 = re.search(r"id: 's31'.*?связи: \[([^\]]+)\]", ядро, re.S)
ид_дверей = [м.group(1) for м in re.finditer(r"id: '(s\d+)'", ядро)]
ок('связи ·31 ведут только на живые двери дома',
   связи_s31 is not None and
   all(т in ид_дверей for т in re.findall(r"'(s\d+)'", связи_s31.group(1))))
карта_связей = {}
for _м in re.finditer(r"id: '(s\d+[a-z0-9]*)'.*?связи: \[([^\]]+)\]", ядро, re.S):
    карта_связей[_м.group(1)] = re.findall(r"'(s\d+[a-z0-9]*)'", _м.group(2))
_дыры = [f"{_о}→{_к}" for _о, _св in карта_связей.items() for _к in _св if _о not in карта_связей.get(_к, [])]
ок('нити симметричны: каждая связь имеет обратную (закон СТАЛИ; v11.44 «ИЗМЕРЕНО»)', not _дыры)
ок('связь дома s15/s16/s18/s19 ⇄ ·31 — в обе стороны',
   all('s31' in карта_связей.get(_д, []) for _д in ('s15', 's16', 's18', 's19'))
   and all(_д in карта_связей.get('s31', []) for _д in ('s15', 's16', 's18', 's19')))

# 3. Лицо дома: UX-инвариант и API намерения
ок('лицо дома спрашивает «Что хотите сделать?»', 'Что хотите сделать?' in лицо)
ок('лицо дома всегда оставляет «Я сам»', 'Я сам' in лицо)
ок('ядро умеет SNG.намерение (поиск только по манифесту)', 'SNG.намерение = function' in ядро)
ок('ядро умеет SNG.событие (факты, transient)', 'SNG.событие = function' in ядро)
ок('слова человека ядром не хранятся (суверенитет: нет localStorage в намерении)',
   'localStorage' not in ядро.split('SNG.намерение = function')[1].split('SNG.событие = function')[0])
ок('счёт дверей на лице — живой реестр дома (sg-registry, такт v11.21 «ОРГАНИЗМ»; v11.44 «ИЗМЕРЕНО»)',
   'sg-registry' in лицо)

# 4. Дисциплина дома: sw, ярлык, доки, доступность
ок('sw15 кэширует дверь ·31 (кэш vN)', './СИНГУЛЯР_31_ЛАДОМ.html' in sw and re.search(r's15-orkestrator-v\d+', sw) is not None)
ок('манифест PWA держит ярлык ЛАДОМ',
   any('ЛАДОМ' in str(я.get('name', '')) for я in манифест.get('shortcuts', [])))
ок('доки открывают дверь ·31', 'СИНГУЛЯР_31_ЛАДОМ.html' in читай('ДОКУМЕНТАЦИЯ.html'))
ок('инженерный док закона на месте', os.path.isfile(os.path.join(окружение, 'ДОКУМЕНТЫ/ИНЖЕНЕРНЫЙ_ПАРАМЕТР.md')))
ок('дверь держит собственный aria-фундамент (aria-live для живых объявлений)',
   дверь.count('aria-live') >= 2)

# 5. Свод законов: I-11 жив и доказан
з11 = [з for з in свод.get('законы', []) if з.get('id') == 'I-11']
ок('свод содержит I-11 «ПАРАМЕТР»', len(з11) == 1)
if з11:
    з = з11[0]
    ок('I-11: живёт только в существующих файлах',
       all(os.path.isfile(os.path.join(окружение, п)) for п in з.get('живёт', [])))
    ок('I-11: доказан минимум двумя тестами', len(з.get('доказательства', [])) >= 2)
    ок('I-11: md-раздел согласован', '## I-11 ·' in свод_md and з.get('имя') in свод_md)

# VERDICT
плохие = [имя for имя, хорошо in шаги if not хорошо]
для_каждого = len(шаги) - len(плохие)
print(f'')
print(f'ПРОГОН test_s31_ladom: {для_каждого}/{len(шаги)} OK')
if плохие:
    print('VERDICT: FAIL — сорвано:')
    for имя in плохие:
        print('  ✗', имя)
    sys.exit(1)
print('VERDICT: PASS — дверь ·31 и закон I-11 доказаны')
