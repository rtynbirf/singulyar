test('W3: ядро внешние-действия/0.1 — журнал append-only, печати цепи, отзыв', () => {
  const сандбокс = песочница();
  vm.runInContext(читай('js/внешние-действия.js'), сандбокс, { filename: 'js/внешние-действия.js' });
  const ВД = сандбокс.window.ВД;
  assert.ok(ВД, 'ядро не встало в window.ВД');
  assert.equal(ВД.ВЕРСИЯ, 'внешние-действия/0.1');
  assert.deepEqual(Object.values(ВД.СОСТОЯНИЯ), ['не готово', 'готово', 'живое', 'отказано', 'истекло', 'отозвано'], 'канон состояний ≠ шести');

  /* append-only: три записи — порядок растёт, печати сходятся */
  const р1 = ВД.журнал.добавить({ дверь: '·47', действие: 'авторизация', куда: 'github.com/login/device', состояние: 'готово', примечание: 'код введён' });
  assert.ok(р1.ок && р1.запись.н === 1 && р1.запись.печать, 'первая запись не легла');
  ВД.журнал.добавить({ дверь: '·33', действие: 'mempool.space', куда: 'mempool.space', состояние: 'живое', бейдж_ид: 'узел-mempool-space' });
  ВД.журнал.добавить({ дверь: '·54', действие: 'приглашение выдано', куда: 'приг-abc', состояние: 'готово', бейдж_ид: 'приг-abc' });
  const список = ВД.журнал.список();
  assert.equal(список.length, 3, 'журнал ≠ трём записям');
  assert.equal(список[2].н, 3, 'номерация не растёт');
  assert.ok(ВД.журнал.печатиСходятся(), 'печати цепи не сходятся');

  /* подмена листа ловится (НЕ ВЕРЬ — ПРОВЕРЬ): правим сырую запись — печати падают */
  const сырой = JSON.parse(сандбокс.localStorage.getItem('внешние.действия.журнал'));
  сырой[0].состояние = 'живое';
  сандбокс.localStorage.setItem('внешние.действия.журнал', JSON.stringify(сырой));
  assert.equal(ВД.журнал.печатиСходятся(), false, 'подмена журнала не поймана печатью цепи');

  /* бейдж: реестр как база, факт устройства перекрывает */
  const реестрОп = { обновлено: '2026-11-14', внешние_действия: [{ ид: 'узел-mempool-space', дверь: '·33', имя: 'mempool.space', состояние: 'не готово' }, { ид: 'приг-abc', дверь: '·54', имя: 'Приглашения пира', состояние: 'не готово' }] };
  const ВД2 = (function () {
    const с2 = песочница({ SG_СТАТУСЫ: реестрОп });
    vm.runInContext(читай('js/внешние-действия.js'), с2, { filename: 'js/внешние-действия.js' });
    return с2.window.ВД;
  }());
  /* факт устройства: разведка mempool ответила живым — запись в журнале этой же песочницы */
  const факт = ВД2.журнал.добавить({ дверь: '·33', действие: 'mempool.space', куда: 'mempool.space', состояние: 'живое', бейдж_ид: 'узел-mempool-space' });
  assert.ok(факт.ок, 'факт разведки не лёг в журнал');
  const б1 = ВД2.бейдж.для('узел-mempool-space');
  assert.equal(б1.состояние, 'живое', 'факт устройства обязан перекрывать замер сборки');
  assert.equal(б1.источник, 'журнал устройства');
  /* отзыв у держателя: бейдж красится сразу (приёмка ТЗ §3) */
  assert.equal(ВД2.отзыв.есть('приг-abc'), false);
  const рв = ВД2.отзыв.отозвать('приг-abc', 'испытание отзыва');
  assert.ok(рв.ок, 'отзыв не лёг');
  assert.ok(ВД2.отзыв.есть('приг-abc'), 'отозванное не в списке');
  assert.equal(ВД2.отзыв.причина('приг-abc'), 'испытание отзыва');
  const б2 = ВД2.бейдж.для('приг-abc');
  assert.equal(б2.состояние, 'отозвано', 'бейдж не покрасился отозванным сразу');
  /* журнал держит запись отзыва */
  const ж2 = ВД2.журнал.список();
  const отз = ж2.find((з) => з.действие === 'приглашение отозвано');
  assert.ok(отз, 'отзыв не записан в журнал');
  /* экспорт честен */
  const эксп = JSON.parse(ВД2.журнал.экспорт());
  assert.ok(эксп.записи.length >= 2, 'экспорт пуст');
  /* неполная запись — честный отказ */
  assert.equal(ВД2.журнал.добавить({ дверь: '·48' }).ок, false, 'неполная запись должна быть отвергнута');
});

