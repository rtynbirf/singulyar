test('W3: пин-ядро/0.1 — PBKDF2-сверка без открытого текста, бэк-офф с потолком', async () => {
  const сандбокс = песочница();
  vm.runInContext(читай('js/pin-core.js'), сандбокс, { filename: 'js/pin-core.js' });
  const ПИН = сандбокс.window.__ПИН;
  assert.ok(ПИН, 'пин-ядро не встало в window.__ПИН');
  assert.equal(ПИН.ИТЕРАЦИИ, 310000, 'итераций PBKDF2 ≠ 310000');
  assert.equal(ПИН.есть(), false, 'PIN задан до всякого действия');

  /* сверка без записи — честный отказ, не «да» */
  const нет = await ПИН.сверить('1234');
  assert.equal(нет.ок, false, 'без заданного PIN сверка обязана честно отказать');
  assert.ok(нет.причина.includes('не задан'), 'причина не названа');

  /* задать + сверить верный/неверный */
  const зад = await ПИН.задать('4711');
  assert.ok(зад.ок, 'PIN не задался: ' + (зад.причина || ''));
  const запись = ПИН.запись();
  assert.equal(запись.алгоритм, 'PBKDF2-SHA256');
  assert.ok(!JSON.stringify(запись).includes('4711'), 'ОТКРЫТЫЙ ТЕКСТ PIN в хранилище — табу нарушено');
  const верно = await ПИН.сверить('4711');
  assert.equal(верно.да, true, 'верный PIN не признался');
  const неверно = await ПИН.сверить('0000');
  assert.equal(неверно.да, false, 'неверный PIN признался');

  /* бэк-офф: 3 неудачи — пауза 30 с; 18 неудач — потолок 15 минут */
  assert.ok(ПИН.попытки.можно().ок, 'попытки закрыты без причины');
  ПИН.попытки.пометитьНеудачу(); ПИН.попытки.пометитьНеудачу();
  assert.ok(ПИН.попытки.можно().ок, 'две неудачи не закрывают попытки');
  const третья = ПИН.попытки.пометитьНеудачу();
  assert.equal(третья.неудач, 3, 'счёт неудач врёт');
  assert.ok(третья.пауза_до && третья.пауза_до - Date.now() > 20000 && третья.пауза_до - Date.now() <= 31000, 'первая пауза ≠ 30 с');
  assert.equal(ПИН.попытки.можно().ок, false, 'бэк-офф не закрыл попытки');
  for (let i = 0; i < 14; i++) ПИН.попытки.пометитьНеудачу();
  const восемьнадцать = ПИН.попытки.пометитьНеудачу();
  assert.equal(восемьнадцать.неудач, 18, 'счёт неудач после серии врёт');
  const остаток = восемьнадцать.пауза_до - Date.now();
  assert.ok(остаток > 890000 && остаток <= 900000, 'потолок паузы ≠ 15 минутам (самозаточение?)');
  ПИН.попытки.сброс();
  assert.ok(ПИН.попытки.можно().ок, 'сброс не открыл попытки');
  /* file:// без SubtleCrypto — честный отказ, не открытый текст: флаг в исходнике */
  const код = читай('js/pin-core.js');
  assert.ok(код.includes('открытый текст не хранится'), 'честная оговорка об отказе потеряна');
  assert.ok(!код.includes('пин ==='), 'сравнение открытым текстом в ядре');
});

