/* ═══════════════════════════════════════════════════════════════════════════
   Запуск: node --test ИНСТРУМЕНТЫ/test_цех_правды.mjs
   ═══   СТРАЖ ЦЕХА ПРАВДЫ (ТЗ-А/ТЗ-И; латка С128 поверх такта v11.49 «ЗАКРЫТИЕ»)
   Держит три закона:
   1) маркеры-стражи СНГ:ПРАВДА стоят на всех пяти зонах;
   2) генератор ИНСТРУМЕНТЫ/цех_правды.py в dry-run видит «ДРЕЙФ НЕТ» —
      дом (штампы ·31, README «одна правда», шапка карты) = живому реестру;
   3) «описание» в реестре существует и не пусто (источник истины для CI-оракула
      описания репозитория в Такт-гейте).
   Дрейф штампов от реестра теперь красит гейт — ручные правки мимо цеха не проходят.
   node --test ИНСТРУМЕНТЫ/test_цех_правды.mjs
   ═══════════════════════════════════════════════════════════════════════════ */
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const корень = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const читай = (п) => fs.readFileSync(path.join(корень, п), 'utf8');

const НАЧАЛО = 'СНГ:ПРАВДА-НАЧАЛО';

test('цех: маркеры-стражи стоят на всех зонах (·31 ×3, README, карта)', () => {
  const зал = читай('СИНГУЛЯР_31_ЛАДОМ.html');
  const титул_ог = (зал.match(new RegExp(НАЧАЛО, 'g')) || []).length;
  assert.ok(титул_ог >= 3, '·31: ждал ≥3 маркера-НАЧАЛО (титул+og+APP), стоит ' + титул_ог);
  assert.ok(зал.includes('/*' + НАЧАЛО + '*/'), '·31: нет JS-маркера вокруг window.APP');
  assert.ok(читай('README.md').includes('<!--' + НАЧАЛО + '-->'), 'README: нет маркеров зоны правды');
  assert.ok(читай('docs/ДОРОЖНАЯ_КАРТА.md').includes('<!--' + НАЧАЛО + '-->'), 'карта: нет маркеров шапки');
});

test('цех: dry-run генератора — «ДРЕЙФ НЕТ» (дом = реестру, идемпотентно)', () => {
  const вых = execFileSync('python3', ['ИНСТРУМЕНТЫ/цех_правды.py'], { cwd: корень, encoding: 'utf8' });
  assert.ok(вых.includes('ДРЕЙФ НЕТ'), 'генератор видит дрейф:\n' + вых);
});

test('цех: «описание» в реестре — источник CI-оракула описания', () => {
  const d = JSON.parse(читай('data/versions.json'));
  assert.ok(typeof d.дом.описание === 'string' && d.дом.описание.length > 10, 'нет ключа дом.описание в реестре');
  assert.ok(d.дом.описание.includes('RUVSON'), 'описание не называет дом');
});
