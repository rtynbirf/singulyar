#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
test_zakon_yazykov_flagmany.py — статика ЗАКОНА ЯЗЫКОВ (I-12) на всех поверхностях, такт v10.91 «ПОРЯДОК» (С67).
Проверяет: оба флагмана (LANGS, ЗАКОН_ПОРЯДОК, сортировка, TRAXML), ·20 ФОНЕТИКА (ЯЗЫКИ_UI), ·31 (ремонт hy).
Запуск из корня дома: python3 ИНСТРУМЕНТЫ/test_zakon_yazykov_flagmany.py
"""
import os, re, sys, json, base64, gzip, ast

T = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ок = 0


def проверь(что, да):
    global ок
    assert да, 'НЕ СОШЛОСЬ: ' + что
    ок += 1
    print('  ok ·', что)


канон = json.load(open(os.path.join(T, 'ДАННЫЕ', 'ПОРЯДОК_ЯЗЫКОВ.json'), encoding='utf-8'))
пф = канон['порядок_флагман']
нос = канон['носители']

первые4 = ['ru-orig', 'ru', 'sr', 'kk', 'de']
проверь('канон порядок_флагман: первые пять = русский(ориг)+русский, СРБ, КАЗ, НЕМ', пф[:5] == первые4)
проверь('канон порядок_флагман: 157 кодов без повторов', len(пф) == 157 and len(set(пф)) == 157)
инд = {c: i for i, c in enumerate(пф)}
ссср = [c for c in ['uk', 'be', 'uz', 'ka', 'az', 'lt', 'lv', 'ky', 'tg', 'hy', 'tk', 'et'] if c in инд]
# С145: народы СССР — вся зона канона (101), а не только те, что были в корпусе ранее
нар = [c for c in канон['зоны']['народы_ссср_в_корпусе_дома']['порядок'] if c in инд]
хвостовые = [c for c in ['es', 'en', 'pt', 'fr', 'it', 'pl'] if c in инд]
проверь('флагман: СССР-блок целиком до народов и хвоста',
        max(инд[c] for c in ссср) < min(инд[c] for c in нар) and max(инд[c] for c in нар) < min(инд[c] for c in хвостовые))
сбой = None
посл = None
for c in пф:
    if c in ссср or c in нар or c in первые4 or c not in нос:
        continue
    з = нос.get(c, 0)
    if посл is not None and з > посл:
        сбой = (c, з, посл)
        break
    посл = з
проверь('флагман: хвост по носителям не возрастает', сбой is None)


def читай(имя):
    return open(os.path.join(T, имя), encoding='utf-8').read()


для_флагманов = ['СИНГУЛЯР_01_Когда_теряем_157_голосов.html', 'СИНГУЛЯР_02_РЕЗОНАНС_Когда_теряем_157_голосов.html']
для_флагманов = [f for f in для_флагманов if os.path.exists(os.path.join(T, f))]
проверь('флагманы на месте (оба файла)', len(для_флагманов) == 2)
for имя in для_флагманов:
    h = читай(имя)
    ст = h.find('const LANGS={')
    ключи = [m.group(1) for m in re.finditer(r'"([a-z][a-zA-Z_-]{1,9})":\{"n":"[^"]+"', h[ст:])]
    проверь(имя + ': ключи LANGS по закону (157, байт-в-байт канону)', ключи == пф)
    массивы = re.findall(r'const ЗАКОН_ПОРЯДОК=\[([^\]]*)\]', h)
    проверь(имя + ': массив(ы) ЗАКОН_ПОРЯДОК присутствуют (живой + рецепт)', len(массивы) >= 1)
    согласовано = all(re.findall(r'["\']([A-Za-z_-]+)["\']', м) == пф for м in массивы)
    проверь(имя + ': все массивы ЗАКОН_ПОРЯДОК == канон (включая рецепт)', согласовано)
    проверь(имя + ': FEATURED снят из кода', 'const FEATURED' not in h and 'FEATURED.indexOf' not in h)
    проверь(имя + ': сортировка только по печёному массиву', 'ЗАКОН_ПОРЯДОК.indexOf(a)' in h)
    if 'TRAXML_B64=' in h:
        b64 = re.search(r"const TRAXML_B64='([^']+)';", h).group(1)
        d = json.loads(gzip.decompress(base64.b64decode(b64)).decode('utf-8'))
        ранк = {c: i for i, c in enumerate(пф)}
        langs = d['langs']
        проверь('TRAXML langs по закону', langs == sorted(set(langs), key=lambda c: (ранк.get(c, 10000), c)))
        сбой = None
        for id_, сл in d['ml'].items():
            коды_мл = list(сл)
            хочу = sorted(коды_мл, key=lambda c: (ранк.get(c, 10000), c))
            if коды_мл != хочу:
                сбой = id_
                break
        проверь('TRAXML ml[id] всех 61 песен по закону', сбой is None)

# ·20 ФОНЕТИКА
h20 = читай('СИНГУЛЯР_20_ФОНЕТИКА.html')
я = re.search(r'const ЯЗЫКИ_UI = (\[\[.*?\]\]);', h20).group(1)
спис = ast.literal_eval(я)
коды20 = [c for c, _ in спис[1:]]
проверь('·20: первые пять языков = ru sr kk de uk (закон)', коды20[:5] == ['ru', 'sr', 'kk', 'de', 'uk'])
проверь('·20: казахский присутствует (третий ВСЕГДА)', 'kk' in коды20)
зона20 = [c for c in ['uk', 'be', 'uz', 'ka', 'az', 'lt', 'mo', 'lv', 'ky', 'tg', 'hy', 'tk', 'et'] if c in коды20]
проверь('·20: вся СССР-зона до хвоста', max(коды20.index(c) for c in зона20) < коды20.index('en'))
проверь('·20: амхарский am честно в хвосте (не в СССР-зоне)', 'am' in коды20 and коды20.index('am') > коды20.index('et'))
сбой = None
посл = None
для_хвоста20 = [c for c in коды20 if c not in ['sr', 'kk', 'de', 'ru'] + зона20]
для_хвоста20 = для_хвоста20[для_хвоста20.index('en'):]
for c in для_хвоста20:
    з = нос.get(c, 0)
    if посл is not None and з > посл:
        сбой = (c, з, посл)
        break
    посл = з
проверь('·20: хвост по носителям не возрастает', сбой is None)

# ·31 ЛАДОМ — ремонт v10.90
h31 = читай('СИНГУЛЯР_31_ЛАДОМ.html')
ст = h31.find('const ЗАКОН_ПОРЯДОК = [')
ен = h31.find(']', ст)
коды31 = re.findall(r'"([a-z_]+)"', h31[ст:ен])
проверь('·31: канон цел (равен порядку канона; С145 — канон владельца, 289)', len(коды31) == len(канон['порядок_ладом']))
проверь('·31: армянский слот = hy (ремонт v10.91)', коды31[14] == 'hy')
проверь('·31: am не сидит в СССР-зоне', 'am' not in коды31[:17])
проверь('·31: первые четыре = ru sr kk de', коды31[:4] == ['ru', 'sr', 'kk', 'de'])
проверь('·31: проба __HEALTH35 живая', 'window.__HEALTH35' in h31)
проверь('·31: проба-35 до агрегатора (агрегатор жив — этаж растёт; v11.44 «ИЗМЕРЕНО»)', h31.find('window.__HEALTH35 = function') < (h31.find('window.__HEALTH2,') if 'window.__HEALTH2,' in h31 else len(h31)))
проверь('·31: проба-34 перепечена (hy)', 'var ссср = ["uk","be","uz","ka","az","lt","mo","lv","ky","tg","hy","tk","et"];' in h31)
проверь('·31: проба-35 в агрегаторе (список проб жив — теперь до 40; v11.44 «ИЗМЕРЕНО»)', 'window.__HEALTH35' in h31 and 'window.__HEALTH39,window.__HEALTH40].forEach' in h31)
_РФ = json.load(open('data/versions.json', encoding='utf-8'))
проверь('·31: APP-паспорт живёт тактом реестра (v11.44 «ИЗМЕРЕНО»)', f"ver:'v{_РФ['дом']['версия']} «{_РФ['дом']['такт']}»'" in h31 and f"cache:'s15-orkestrator-{_РФ['дом']['поколение_кэша']}'" in h31)

print(f'ЗАКОН ЯЗЫКОВ I-12 — статики флагманов/·20/·31: {ок} проверок сошлось')
