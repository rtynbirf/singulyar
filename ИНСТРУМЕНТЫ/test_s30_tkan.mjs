test('транспорт: MEANING ≠ TRANSPORT — возит конверты, не читая их', async () => {
  /* мини-эфир: фабрика выдаёт каждому узлу СВОЮ шину, пост уходит всем, кроме себя */
  const слушатели = new Set();
  const шинаФабрика = function () {
    const ш = { postMessage(м) { [...слушатели].forEach(ф => ф({ data: м })); }, close() {} };
    Object.defineProperty(ш, 'onmessage', {
      set(ф) { ш._ф = ф; слушатели.add(ф); },
      get() { return ш._ф; }
    });
    return ш;
  };
  const а = создатьЛокальныйТранспорт({ шина: шинаФабрика });
  const б = создатьЛокальныйТранспорт({ шина: шинаФабрика });
  assert.ok(а && б);
  а.подключить(); б.подключить();
  assert.equal(связаны(а, б), true);
  const полученные = [];
  б.наУправляющее(т => полученные.push(т));
  const секрет = { тип: ТИПЫ.ОФФЕР, objectId: 'sgo:sha256:' + 'a'.repeat(64), чьёДело: 'только получателя' };
  а.послатьУправляющее(секрет);
  assert.equal(полученные.length, 1, 'своё не эхоится, чужое доезжает');
  assert.deepEqual(полученные[0], секрет);
  assert.equal(а.возможности().чанки, true);
  а.отключить();
  assert.throws(() => а.послатьУправляющее({ тип: 'x' }), /не подключён/, 'спящий провод молчит честно');
});

test('транспорт: чанки доезжают по порядку, конверт не теряет частей', async () => {
  const слушатели = new Set();
  const шинаФабрика = function () {
    const ш = { postMessage(м) { [...слушатели].forEach(ф => ф({ data: м })); }, close() {} };
    Object.defineProperty(ш, 'onmessage', {
      set(ф) { ш._ф = ф; слушатели.add(ф); },
      get() { return ш._ф; }
    });
    return ш;
  };
  const а = создатьЛокальныйТранспорт({ шина: шинаФабрика });
  const б = создатьЛокальныйТранспорт({ шина: шинаФабрика });
  а.подключить(); б.подключить();
  const дошло = [];
  б.наЧанк(т => дошло.push(т));
  const ид = 'sgo:sha256:' + 'b'.repeat(64);
  const куски = резать('волна за волной — так едет ткань', 5);
  куски.forEach(function (к, i) {
    а.послатьЧанк({ тип: ТИПЫ.ЧАНК, objectId: ид, индекс: i, изСкольких: куски.length, байты: вBase64(к) });
  });
  assert.equal(дошло.length, куски.length);
  const собр = собрать(дошло.map(function (ч) { return изBase64(ч.байты); }));
  assert.equal(await дайджест(собр), await дайджест('волна за волной — так едет ткань'),
    'байты доехали теми же байтами (O-04)');
});
