test('протокол: конверты валидны, чанк за пределом — честная ошибка порядка', () => {
  const ид = 'sgo:sha256:' + 'a'.repeat(64);
  assert.equal(проверитьСообщение({ тип: ТИПЫ.ОФФЕР, objectId: ид, манифест: {} }).тип, ТИПЫ.ОФФЕР);
  assert.throws(() => проверитьСообщение({ тип: 'object.взлом' }), /неизвестный тип/);
  assert.throws(() => проверитьСообщение({ тип: ТИПЫ.ЧАНК, objectId: ид, индекс: 5, изСкольких: 5, байты: '' }), /за пределом/);
  assert.throws(() => проверитьСообщение({ тип: ТИПЫ.ЧАНК, objectId: ид, индекс: -1, изСкольких: 3, байты: '' }), /индекс/);
  assert.throws(() => проверитьСообщение({ тип: ТИПЫ.ЧАНК, индекс: 0, изСкольких: 3, байты: '' }), /objectId/);
  assert.equal(проверитьСообщение({ тип: ТИПЫ.ОТПЕЧАТОК, objectId: ид, верено: true }).верено, true);
  assert.throws(() => проверитьСообщение({ тип: ТИПЫ.ОТПЕЧАТОК, objectId: ид }), /вердикт/);
});

