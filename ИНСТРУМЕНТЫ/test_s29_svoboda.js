/* ── движок вживую: те же вызовы, что делает комната ── */
test('I-законы движка вживую: предложение, отказ, эмерджентность, память', async () => {
  const движок = await import(path.join(ROOT, 'БИБЛИОТЕКИ', 'кристалл', 'composition.mjs'));

  движок['объявиПримитив']({ имя: 'слово', требует: [], даёт: ['смысл'],
    представления: ['текст'], транспорты: [], расширяет: ['поговорить'] });
  движок['объявиПримитив']({ имя: 'память', требует: [], даёт: ['память'],
    представления: ['журнал'], транспорты: [], расширяет: ['сохранить'] });
  движок['объявиПримитив']({ имя: 'память-журнал', требует: ['хранилище'], даёт: ['память'],
    представления: ['журнал'], транспорты: [], расширяет: ['сохранить'] });
  движок['объявиПримитив']({ имя: 'речь', требует: ['микрофон'], даёт: ['смысл'],
    представления: ['голос'], транспорты: [], расширяет: ['поговорить'] });

  /* I-01: машина предлагает — состояние «предложено» */
  const пред = движок['compose']({ кто: 'человек-на-устройстве', намерение: 'сохранить',
    контекст: { возможности: ['хранилище'] } });
  assert.ok(пред.ок, 'композиция собралась');
  assert.equal(пред.варианты[0].состояние, 'предложено', 'состояние — предложено (I-01)');
  assert.equal(движок['validate'](пред.варианты[0]).ok, true, 'манифест валиден');

  /* I-09: неизвестное слово — честный отказ без выдумок */
  const отказ = движок['compose']({ кто: 'человек', намерение: 'несуществующее-слово', контекст: {} });
  assert.equal(отказ.ок, false);
  assert.equal(отказ.причина, 'НАМЕРЕНИЕ_НЕИЗВЕСТНО');

  /* EMERGENCE: своё слово без правки ядра (§37) */
  const новое = движок['объявиНамерение']('помолчим', ['слово']);
  assert.equal(новое.ok, true, 'слово объявлено');
  const эмердж = движок['compose']({ кто: 'человек', намерение: 'помолчим', контекст: { возможности: [] } });
  assert.ok(эмердж.ок, 'новое слово собирает среду');
  assert.deepEqual([...эмердж.варианты[0].примитивы], ['слово']);

  /* I-06: машина не ставит вечную память сама */
  const вечное = движок['compose']({ кто: 'человек', намерение: 'сохранить',
    контекст: { возможности: ['хранилище'] }, выбор: { память: 'вечное' } });
  assert.equal(вечное.варианты[0].память.retention, 'persistent');
  assert.equal(вечное.варианты[0].память.решениеЧеловека, true, 'вечная — только решением человека');

  /* I-04: выключенная способность — честный fallback с причиной */
  const урез = движок['compose']({ кто: 'человек', намерение: 'сохранить',
    контекст: { возможности: [] },
    выбор: { примитивы: ['память', 'память-журнал'] } });
  assert.ok(урез.ок && урез.варианты[0].fallback, 'fallback виден');
  assert.ok(урез.варианты[0].причина.indexOf('память-журнал') >= 0,
    'причина урезания названа честно (I-04): ' + урез.варианты[0].причина);
  assert.ok(урез.варианты[0].примитивы.includes('память'),
    'работающее осталось в среде — тихой подмены нет');
});
