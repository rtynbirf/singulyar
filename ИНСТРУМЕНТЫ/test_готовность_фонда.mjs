import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const корень = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const читай = (п) => fs.readFileSync(path.join(корень, п), 'utf8');

test('W2: словарь счётчиков держит шесть новых определений состояний', () => {
  const реестр = JSON.parse(читай('data/versions.json'));
  const сл = реестр.счётчики && реестр.счётчики.словарь;
  assert.ok(сл && typeof сл === 'object', 'нет словаря счётчиков');
  for (const ключ of ['готовность_ядра', 'готовность_песен', 'готовность_моделей', 'готовность_p2p', 'аудио_в_хранилище', 'песня_недоступна']) {
    const опр = сл[ключ];
    assert.ok(typeof опр === 'string' && опр.length > 10, 'нет определения для «' + ключ + '»');
  }
  assert.ok(сл.готовность_песен.includes('SONG_READY'), 'SONG_READY не назван в определении');
  assert.ok(сл.готовность_ядра.includes('CORE_READY'), 'CORE_READY не назван в определении');
  assert.ok(сл.песня_недоступна.includes('SONG_UNAVAILABLE'), 'SONG_UNAVAILABLE не назван в определении');
  assert.ok(сл.готовность_p2p.includes('возможность'), 'P2P_READY обязан быть определён как возможность, не обещание');
});

test('W2: ·32 СЦЕНА — opfs-core подключён, лестница с нулевой ступенью OPFS', () => {
  const сцена = читай('СИНГУЛЯР_32_СЦЕНА.html');
  assert.ok(сцена.includes('<script defer src="js/opfs-core.js">'), 'opfs-core.js не подключён к ·32 (нулевой ступени нет)');
  assert.ok(сцена.includes('ставьЗвук('), 'звук не ставится через ставьЗвук — нулевой ступени OPFS нет');
  assert.ok(сцена.includes('__ОПФС.есть(') && сцена.includes('__ОПФС.взять('), 'лестница не спрашивает хранилище дома');
  assert.ok(сцена.includes('SONG_READY'), 'метка SONG_READY отсутствует у титула');
  assert.ok(сцена.includes('SONG_UNAVAILABLE'), 'честное состояние SONG_UNAVAILABLE отсутствует');
  assert.ok(сцена.includes('песняГотовность'), 'метка готовности у титула песни не живёт');
  /* закон: сборник — честный отказ, фолбэков нет (латка С140 сохранена) */
  assert.ok(сцена.includes('у Сборника честный отказ — фолбэков нет'), 'честный отказ Сборника потерян');
  /* закон: старые ступени лестницы не выброшены */
  assert.ok(сцена.includes("window.minusUrl('голос/' + п.id + '.mp3')"), 'дверь-0 (голос) потеряна из лестницы');
  assert.ok(сцена.includes("window.minusUrl('чистый-минус/' + п.id + '.mp3')"), 'ступень чистый-минус потеряна из лестницы');
});

test('W2: ·38 ПУЛЬС — четыре состояния, счётчик и вечер с отменой на лице', () => {
  const пульс = читай('СИНГУЛЯР_38_ПУЛЬС.html');
  for (const ид of ['готЯдро', 'готПесни', 'готМодели', 'готП2П']) {
    assert.ok(пульс.includes('id="' + ид + '"'), 'лицо ·38 не держит строку состояния «' + ид + '»');
  }
  for (const слово of ['CORE_READY', 'SONG_READY', 'MODEL_READY', 'P2P_READY']) {
    assert.ok(пульс.includes(слово), 'состояние ' + слово + ' не названо на лице ·38');
  }
  for (const ид of ['вечерСобрать', 'вечерГреть', 'вечерСтоп', 'вечерПрогресс', 'вечерТело', 'вечерЯзыки']) {
    assert.ok(пульс.includes('id="' + ид + '"'), 'вечер на ·38 не держит «' + ид + '»');
  }
  assert.ok(пульс.includes('ОТМЕНА'), 'кнопка отмены вечера не названа человеку');
  assert.ok(пульс.includes('готовность_ядра') && пульс.includes('аудио_в_хранилище'), 'лицо не ссылается на словарь определений');
});

test('W2: room-38.js — счётчик из реестра, закрепить перед прогревом, отмена AbortController', () => {
  const код = читай('js/room-38.js');
  assert.ok(код.includes('ДАННЫЕ/МИНУС_ФОНД_РЕЛИЗ.json'), 'прогноз объёма не из манифеста фонда — было бы выдумкой');
  assert.ok(код.includes('__ОПФС.список()'), 'счётчик выученного не из реестра хранилища (len(список))');
  assert.ok(код.includes('.закрепить'), 'закрепление хранилища (persist) не вызывается перед прогревом');
  assert.ok(код.includes('AbortController'), 'отмена вечера без AbortController');
  assert.ok(код.includes('СВОДКА_61_песен.csv'), 'тайтлы не из канона текстов');
  assert.ok(код.includes('ВЕЧЕР_ЯЗЫКИ.json'), 'языки флагмана не из реестра вечера');
  assert.ok(код.includes('./minus/голос/'), 'тела песен берутся не с двери-0 (same-origin)');
  assert.ok(!/innerHTML/.test(код.split('СЕКЦИЯ 7')[1] || ''), 'СЕКЦИЯ 7 вставляет разметку строками — закон репозитория');
  /* ES2019-закон комнаты: без опциональной цепочки и нулевого слияния */
  const седьмая = код.split('СЕКЦИЯ 7')[1] || '';
  assert.ok(!/\?[\.\?]/.test(седьмая), 'опциональная цепочка в СЕКЦИИ 7 — вне канона ES2019');
  assert.ok(!/\|\|=/.test(седьмая) && !/&&=/.test(седьмая), 'логические присваивания в СЕКЦИИ 7 — вне канона ES2019');
  const проверка = execFileSync('node', ['--check', path.join(корень, 'js/room-38.js')], { encoding: 'utf8' });
  assert.ok(проверка !== undefined, 'node --check не прошёл');
});

test('W2: закон «медиа вне пре-кэша» цел — в ядре воркера те же 2 mp3-исключения', () => {
  const воркер = читай('sw15.js');
  const м = воркер.match(/var S15_CORE\s*=\s*\[([\s\S]*?)\];/);
  assert.ok(м, 'S15_CORE не найден в воркере');
  const ядро = м[1];
  const mp3 = ядро.match(/\.mp3/g) || [];
  assert.equal(mp3.length, 2, 'медиа влезло в пре-кэш: mp3 в ядре ' + mp3.length + ', а закон держит 2 (шасси + тон-тест)');
  assert.ok(ядро.includes('./minus/prosto-lubi.mp3'), 'шасси дома (TH-AUDIO-44) выпало из ядра');
  assert.ok(ядро.includes('./звуки/тон-тест.mp3'), 'тон-тест выпал из ядра');
  assert.ok(!/голос\//.test(ядро), 'фонд голоса влез в пре-кэш — закон медиа сломан');
});

test('W2: реестры вечера валидны и полны (манифест, языки флагмана)', () => {
  const манифест = JSON.parse(читай('ДАННЫЕ/МИНУС_ФОНД_РЕЛИЗ.json'));
  const голос = (манифест.файлы || []).filter((ф) => String(ф.было || '').startsWith('minus/голос/'));
  assert.ok(голос.length >= 60, 'в манифесте фонда меньше 60 песен с голосом: ' + голос.length);
  for (const ф of голос) {
    assert.ok(Number(ф.байт) > 0, 'у файла ' + ф.было + ' нет честного веса (байт)');
    assert.ok(/^golos__/.test(String(ф.ассет || '')), 'ассет ' + ф.было + ' без канона релиза');
  }
  const языки = JSON.parse(читай('ДАННЫЕ/ВЕЧЕР_ЯЗЫКИ.json'));
  assert.ok((языки.языки || []).length >= 150, 'языков флагмана в реестре вечера подозрительно мало: ' + (языки.языки || []).length);
  const канон = (языки.языки || []).filter((я) => я.канон === true).map((я) => я.код);
  assert.deepEqual(канон, ['ru-orig', 'ru', 'sr', 'kk', 'de'], 'канон I-12 в реестре вечера не на первых местах: ' + канон.join(','));
  assert.equal(языки.песня, 'rWpYxmFjm9g', 'реестр вечера ведёт не на флагман');
  /* латка живой поверки: «файл» обязан быть полным именем с расширением, и файл обязан жить в репо */
  for (const я of языки.языки) {
    assert.ok(/\.json$/.test(String(я.файл || '')), 'файл языка «' + я.код + '» без расширения .json: ' + я.файл);
    assert.ok(fs.existsSync(path.join(корень, языки.путь, я.файл)), 'файл перевода «' + я.файл + '» не живёт в репо по «путь»');
  }
});
