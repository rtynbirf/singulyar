#!/usr/bin/env python3
# -*- coding: utf-8 -*-
'''Страж латки С130 — СВОЙ КРУГ семьи в ·23 (авто-ID ПАША/МАМА/ЖЕНЯ/ВАНЯ).
Детерминированный, без браузера и сети (канон CI: «Python-оракулы — без браузера/сети»).
Проверяет: панель и слой круга в СИНГУЛЯР_23_КРУГ.html — имена круга канона,
mesh-комната семьи, авто-вход и авто-приём, зов всех, присутствие «в сети»,
0 innerHTML, шестерёнка/движок на месте, CSP не ослаблен, бюджет веса.
Запуск: python3 ИНСТРУМЕНТЫ/test_круг_свой.py'''
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
КРУГ = os.path.join(ROOT, 'СИНГУЛЯР_23_КРУГ.html')

прошло = 0
провалы = []

def ок(имя, условие, дет=''):
    global прошло
    if условие:
        прошло += 1
        print('  ✓ ' + имя)
    else:
        провалы.append(имя)
        print('  ✗ ПРОВАЛ: ' + имя + ((' — ' + дет) if дет else ''))

т = open(КРУГ, encoding='utf-8').read() if os.path.exists(КРУГ) else ''

# 1. Файл есть и в бюджете (ТЗ-Е-дух: лёгкая дверь)
ок('файл СИНГУЛЯР_23_КРУГ.html существует', bool(т))
размер = os.path.getsize(КРУГ) if os.path.exists(КРУГ) else 0
ок('бюджет веса ≤ 5 МБ', 0 < размер <= 5 * 1024 * 1024, f'{размер} байт')

# 2. Свой круг: канон имён семьи (id из РЕЕСТРА дома)
СВОИ = ['pasha', 'anya', 'ivan', 'zhenya']
ок('канон СВОЙ_КРУГ_ИД: ПАША/МАМА(АНЯ)/ВАНЯ(ИВАН)/ЖЕНЯ',
   all(re.search(r"['\"]" + и + r"['\"]", т) for и in СВОИ))
ок('константа СВОЙ_КРУГ_ИД объявлена', 'СВОЙ_КРУГ_ИД' in т)
ок('помощники свойЛи/свойПоЗвонку/свойКругВкл', all(x in т for x in ('function свойЛи(', 'function свойПоЗвонку(', 'function свойКругВкл(')))

# 3. Автомат: ключ памяти, авто-вход по жесту, авто-вход при выборе себя
ок('ключ памяти своего круга', 'singular.krug.v1.свойкруг' in т)
ок('авто-вход: первый жест включает линию', 'pointerdown' in т and 'войдиВКруг(true)' in т)
ок('авто-вход: выбор себя = жест (авто-ID)', 'свойКругВкл() && !свкВЛинии) войдиВКруг(true)' in т)

# 4. Mesh-линия семьи: комната, поток, присутствие, звук
ок('mesh-комната krug-svoy-circle', "СВК_КОМНАТА = 'krug-svoy-circle'" in т)
ок('комната семьи поднимается (кругЗапусти + joinRoom)', 'function кругЗапусти(' in т and 'tr.joinRoom' in т)
ок('присутствие «свкто» с вЛинии/глух', 'makeAction(\'свкто\')' in т and 'вЛинии' in т)
ok_stream = 'function подвесьЗвукПира(' in т and 'onPeerStream' in т
ок('звук пиров: onPeerStream → audio', ok_stream)
ок('holds для звука пиров', 'id="свкЗвукХолд"' in т)
ок('кнопка разблокировки звука (autoplay-политика)', 'id="свкЗвук"' in т and 'включиЗвукКруга' in т)
ок('мик в круге: приглушение дорожки', 'свкПоток.getAudioTracks()' in т)
ок('выход из линии: removeStream + стоп дорожек', 'removeStream' in т and 'getTracks().forEach' in т)

# 5. Зов всех: свой зовёт — у своих круг включается сам
ок('канал зова «зов» в krug-calls', "'звоно','кто','зов'" in т)
ок('зов: принялЗовКруга — только свои', 'function принялЗовКруга(' in т and 'зовут только свои' in т)
ок('зов: зовиВсех шлёт и в локальную шину, и в P2P', 'function зовиВсех(' in т and "звонПочта['зов']" in т)

# 6. Авто-приём звонков своих (семья без вопросов — но кнопка ✕ жива)
ок('авто-приём: свой круг принимает звонок сам', 'свой круг · принимаю сам' in т)
блок_ринг = re.search(r"звонОВерли\('входящий'.*?clearTimeout\(звонТаймер\);", т, re.S)
ok_авто = bool(блок_ринг) and 'свойКругВкл() && свойПоЗвонку(з)' in блок_ринг.group(0)
ок('авто-приём стоит до обычного 30с-таймера', ok_авто)

# 7. Присутствие «в сети» в людях и звонках
ок('метка «в сети» в людях/звонках', т.count("'⌇ в сети'") >= 2)
ок('честное «ждём» без устройства', "'· ждём'" in т)
ок('обновление по таймеру честности (сверьОнлайн)', 'метки «в сети» живут по тому же таймеру' in т)

# 8. Инварианты дома не тронуты
ок('0 фактических innerHTML (только слово в комментарии)', len(re.findall(r'\binnerHTML\b', т)) == 1 and '0 innerHTML' in т)
ок('ScriptProcessorNode = 0', 'ScriptProcessorNode' not in т)
ок('движок UX v9 на месте (check_gear)', 'singulyar-ux-engine-v9.js' in т)
ок('корд дома на месте', './cord.js' in т)
мета = re.search(r'<meta http-equiv="Content-Security-Policy" content="([^"]+)"', т)
ок('CSP: connect-src только self+wss (не ослаблен)', bool(мета) and "connect-src 'self' wss:" in (мета.group(1) if мета else ''))
ок('CSP: object-src \'none\'', bool(мета) and "object-src 'none'" in (мета.group(1) if мета else ''))
ок('чужих script src нет (все — дома: ./cord.js, ./модули, ./движок, js/реестр)', len(re.findall(r'<script[^>]*\bsrc="(?!https?:|//|\./|js/)', т)) == 0)
ок('только локальный trystero-бандл дома', т.count("import('./БИБЛИОТЕКИ/trystero-nostr.bundle.mjs')") == 1)

# 9. Версия модуля честно поднята
ок('v1.1 в шапке модуля', 'v1.1' in т)
ок('крюки K23 рассказывают про круг', "версия: '1.1.0'" in т and 'свойкруг: function()' in т)

# 10. UI: панель и переключатель доступны
ок('панель СВОЙ КРУГ в ЗВОНКАХ', 'id="свкПанель"' in т and 'id="свкГальо"' in т)
ok_a11y = 'aria-labelledby="свкЗагл"' in т and 'role="switch"' in т
ок('переключатель круга — честный switch (aria)', ok_a11y)
ок('заметка про пение и честность транспорта', 'говорить и петь можно всем сразу' in т.lower() and 'IP нигде не записывается' in т)

print()
print(f'СВОЙ КРУГ ·23 (латка С130): прошло {прошло}, провалов {len(провалы)}')
sys.exit(1 if провалы else 0)
