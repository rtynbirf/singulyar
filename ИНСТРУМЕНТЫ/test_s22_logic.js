#!/usr/bin/env node
/* Тест логики ·22 СВЯЗЬ. Ядро извлекается ИЗ ОТГРУЖЕННОГО файла (маркеры
   S22:CORE-BEGIN/END) и исполняется в песочнице — проверяется ровно тот
   код, который получит человек. Запуск: node ИНСТРУМЕНТЫ/test_s22_logic.js */
'use strict';
const fs = require('fs');
const vm = require('vm');
const path = require('path');

const ФАЙЛ = path.join(__dirname, '..', 'СИНГУЛЯР_22_СВЯЗЬ.html');
const html = fs.readFileSync(ФАЙЛ, 'utf8');

let прошло = 0, всего = 0;
function ок(имя, условие) {
  всего++;
  if (условие) { прошло++; console.log('  ✓ ' + имя); }
  else { console.error('  ✗ ПРОВАЛ: ' + имя); }
}
function раздел(т) { console.log('\n— ' + т); }

/* ── извлечение ядра ── */
раздел('извлечение ядра из отгруженного файла');
const начало = html.indexOf('/* S22:CORE-BEGIN */');
const конец = html.indexOf('/* S22:CORE-END */');
ок('маркеры найдены и в правильном порядке', начало >= 0 && конец > начало);
const ядро = html.slice(начало, конец + '/* S22:CORE-END */'.length);
const песочница = {};
vm.createContext(песочница);
vm.runInContext(ядро + '\nthis.S22 = S22;', песочница);
const S22 = песочница.S22;
ок('S22 определён', !!S22 && typeof S22 === 'object');
ок('версия 1.1.0', S22.VERSION === '1.1.0');
ок('протокол = 1', S22.PROTO === 1);
ок('ключ профиля singulyar.svyaz.v1', S22.STORE_KEY === 'singulyar.svyaz.v1');

/* ── реестр каналов ── */
раздел('реестр каналов');
const идентификаторы = Object.keys(S22.CHANNELS);
ок('девять каналов', идентификаторы.length === 9);
ок('каналы из ТЗ присутствуют', ['text', 'file', 'captions', 'voice', 'tts', 'callAudio', 'callVideo', 'screen', 'activity'].every(к => идентификаторы.includes(к)));
ок('имена человеческие и неповторяются', new Set(идентификаторы.map(к => S22.CHANNELS[к].имя)).size === 9 && идентификаторы.every(к => S22.CHANNELS[к].имя.length > 1));
ок('требования перечислены массивом', идентификаторы.every(к => Array.isArray(S22.CHANNELS[к].треб)));
ок('у каждого канала есть строка графа FALLBACK', идентификаторы.every(к => Array.isArray(S22.FALLBACK[к])));

/* ── граф fallback: терминальность и беззацикленность ── */
раздел('граф fallback');
function путьДо(id, глубина) {
  if (id === 'text') return true;
  if (глубина > 10) return false;
  const алт = S22.FALLBACK[id] || [];
  if (!алт.includes('text')) return false;         /* каждый список кончается базой */
  return алт.every(а => идентификаторы.includes(а) && путьДо(а, глубина + 1));
}
ок('все пути ведут к «Текст», зацикливаний нет', идентификаторы.every(к => путьДо(к, 0)));
ок('text — базовый канал без требований', S22.CHANNELS.text.треб.length === 0 && S22.FALLBACK.text.length === 0);

/* ── доступность и причины ── */
раздел('доступность и причины');
const ПУСТО = S22.возможности({});
ок('пустое устройство: всё false', Object.keys(ПУСТО).every(к => ПУСТО[к] === false));
ок('text доступен всегда', S22.доступен('text', ПУСТО));
ок('voice недоступен без микрофона', !S22.доступен('voice', ПУСТО));
ок('voice доступен с микрофоном', S22.доступен('voice', { микрофон: true }));
ок('причина voice без микрофона: «нужен микрофон»', S22.причина('voice', ПУСТО).indexOf('нужен микрофон') === 0);
ок('у доступного канала причины нет', S22.причина('voice', { микрофон: true }) === '');
ок('callVideo требует микрофон, камеру и сеть', S22.CHANNELS.callVideo.треб.length === 3);
ок('неизвестный канал: «такого канала нет»', S22.причина('абракадабра', ПУСТО) === 'такого канала нет');

/* ── маршрутизация ── */
раздел('маршрутизация');
const м1 = S22.маршрут('voice', ПУСТО);
ок('voice без микрофона → text, путь [voice, text]', м1.канал === 'text' && JSON.stringify(м1.путь) === JSON.stringify(['voice', 'text']));
const м2 = S22.маршрут('callVideo', { микрофон: true, камера: false, дисплей: false, синтезРечи: false, распознаваниеРечи: false, вибрация: false, сеть: true });
ок('видеозвонок без камеры → аудиозвонок', м2.канал === 'callAudio' && JSON.stringify(м2.путь) === JSON.stringify(['callVideo', 'callAudio']));
const м3 = S22.маршрут('callVideo', ПУСТО);
ок('видеозвонок без всего → text через граф', м3.канал === 'text' && м3.путь[0] === 'callVideo' && м3.путь[м3.путь.length - 1] === 'text');
const м4 = S22.маршрут('screen', { микрофон: false, камера: false, дисплей: true, синтезРечи: false, распознаваниеРечи: false, вибрация: false, сеть: false });
ок('экран без сети → субтитры', м4.канал === 'captions' && м4.путь[0] === 'screen');
const м5 = S22.маршрут('text', ПУСТО);
ок('доступный канал: путь из одного звена, причина «доступен»', м5.канал === 'text' && м5.путь.length === 1 && м5.причина === 'доступен');
ок('желаемый неизвестен → text, а не падение', S22.маршрут('чушь', ПУСТО).канал === 'text');

/* ── железобетон: все 128 комбинаций возможностей × 9 каналов ── */
раздел('перебор 128 комбинаций возможностей × 9 каналов');
const ключиКап = ['микрофон', 'камера', 'дисплей', 'синтезРечи', 'распознаваниеРечи', 'вибрация', 'сеть'];
let тупиков = 0, недоступныйТекст = 0;
for (let маска = 0; маска < 128; маска++) {
  const кап = {};
  ключиКап.forEach((к, i) => { кап[к] = !!(маска & (1 << i)); });
  if (!S22.доступен('text', кап)) недоступныйТекст++;
  for (const ж of идентификаторы) {
    const м = S22.маршрут(ж, кап);
    if (!м || !S22.доступен(м.канал, кап)) тупиков++;
    if (м.путь[0] !== ж) тупиков++;                 /* путь начинается с желаемого */
  }
}
ок('ни один маршрут не кончается недоступным каналом', тупиков === 0);
ок('text доступен во всех 128 мирах', недоступныйТекст === 0);

/* ── выбор человека (override) ── */
раздел('выбор человека');
const в1 = S22.выборЧеловека('voice', { микрофон: true });
ок('доступный выбор: канал сохраняется, override=true', в1 && в1.канал === 'voice' && в1.override === true);
const в2 = S22.выборЧеловека('callVideo', ПУСТО);
ок('недоступный выбор: не подменяется молча, канал null + причина', в2 && в2.канал === null && в2.override === true && в2.причина.indexOf('твой выбор') === 0);
ок('мусорный выбор → null', S22.выборЧеловека('чушь', ПУСТО) === null && S22.выборЧеловека(null, ПУСТО) === null);

/* ── профиль ── */
раздел('профиль способов общения');
const чистый = S22.профильОк({ override: 'voice', текст: false, звук: 'да', субтитры: 1, озвучка: true, вибро: false, движение: true, крупные: false });
ок('валидный профиль читается', чистый.override === 'voice' && чистый.текст === false && чистый.озвучка === true);
ок('мусорные булевы сбрасываются к умолчанию', чистый.звук === false && чистый.субтитры === true);
ок('мусорный override стирается', S22.профильОк({ override: 'чушь' }).override === null);
ок('мусорный профиль → пустой', S22.профильОк('мусор').override === null && S22.профильОк(null).субтитры === true);
ок('пустой профиль: субтитры и текст включены по умолчанию', (() => { const п = S22.профильПустой(); return п.текст === true && п.субтитры === true && п.озвучка === false; })());

/* ── мост адаптации ·19 ── */
раздел('мост адаптации ·19');
const а1 = S22.адаптация19('{}');
ок('нет решений: автоматика по умолчанию (крупные цели — да)', а1.крупныеЦели === true && а1.вибрация === null && а1.уведомления === null && а1.движениеМеньше === null);
const а2 = S22.адаптация19('{"haptic": false, "largeTargets": false, "notifications": true, "reducedMotion": true}');
ок('решения человека в ·19 уважаются', а2.вибрация === false && а2.крупныеЦели === false && а2.уведомления === true && а2.движениеМеньше === true);
ок('мусор вместо JSON → умолчания', S22.адаптация19('не-json').крупныеЦели === true);

/* ── контракт ── */
раздел('контракт');
const правила = Object.values(S22.КОНТРАКТ);
ок('пять правил контракта', правила.length === 5);
ок('правила говорят о неравенстве ролей', правила.every(п => /[≠≥]/.test(п)));
ок('зал ≠ аккаунт сформулирован', S22.КОНТРАКТ.зал === 'зал ≠ аккаунт');
ок('выбор человека ≥ автоматика сформулирован', S22.КОНТРАКТ.выбор === 'выбор человека ≥ автоматика');

/* ── гигиена отгруженного файла ── */
раздел('гигиена отгруженного файла');
ок('innerHTML не употребляется', !/\.innerHTML\s*=/.test(html));
ok_doc();

function ok_doc() {
  ок('доктайп один', (html.match(/<!doctype html>/gi) || []).length === 1);
  ок('маркеры ядра — ровно по одному', (html.match(/\/\* S22:CORE-BEGIN \*\//g) || []).length === 1 && (html.match(/\/\* S22:CORE-END \*\//g) || []).length === 1);
  ок('нет чужих сервисов в коде (fetch/XMLHttpRequest/WebSocket)', !/fetch\(|XMLHttpRequest|new WebSocket/.test(html));
  ок('нет телеметрии и аналитики', !/gtag|analytics|beacon|sentry/i.test(html));
  /* все id, к которым обращается скрипт, существуют в разметке */
  const обращения = new Set([...html.matchAll(/\$\('([A-Za-z0-9_]+)'\)/g)].map(m => m[1]));
  const идшники = new Set([...html.matchAll(/id="([A-Za-z0-9_]+)"/g)].map(m => m[1]));
  const нет = [...обращения].filter(и => !идшники.has(и));
  ок('каждое обращение к элементам находит их в разметке (' + обращения.size + ' id)', нет.length === 0);
}

console.log('\n════════════════════════════════');
console.log('ИТОГ: ' + прошло + '/' + всего);
process.exit(прошло === всего ? 0 : 1);
