function ok_doc() {
  ок('доктайп один', (html.match(/<!doctype html>/gi) || []).length === 1);
  ок('маркеры ядра — ровно по одному', (html.match(/\/\* S22:CORE-BEGIN \*\//g) || []).length === 1 && (html.match(/\/\* S22:CORE-END \*\//g) || []).length === 1);
  ок('нет чужих сервисов в коде (fetch/XMLHttpRequest/WebSocket)', !/fetch\(|XMLHttpRequest|new WebSocket/.test(html));
  ок('нет телеметрии и аналитики', !/gtag|analytics|beacon|sentry/i.test(html));
  /* все id, к которым обращается скрипт, существуют в разметке */
  const обращения = new Set([...html.matchAll(/\$\('([A-Za-z0-9_]+)'\)/g)].map(m => m[1]));
  const идшники = new Set([...html.matchAll(/id="([A-Za-z0-9_]+)"/g)].map(m => m[1]));
  const нет = [...обращения].filter(и => !идшники.has(и));
  ок('каждое обращение к элементам находит их в разметке (' + обращения.size + ' id)', нет.length === 0);
}

