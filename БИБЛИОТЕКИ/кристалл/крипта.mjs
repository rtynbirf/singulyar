/* ── канонические байты: детерминированная сериализация факта ──
   Ключи объектов сортируются на ВСЕХ уровнях, порядок массивов
   сохраняется (массив — это порядок, объект — множество). Одна и та
   же логическая структура = одни и те же байты на любом устройстве
   и в любом порядке вставки ключей — иначе подписи разъезжаются. */
export function канонБайты(значение) {
  return КОДЕР.encode(канонJSON(значение));
}
function канонJSON(з) {
  if (з === null || typeof з === 'number' || typeof з === 'boolean') return JSON.stringify(з);
  if (typeof з === 'string') return JSON.stringify(з);
  if (typeof з === 'undefined') return 'null';
  if (Array.isArray(з)) return '[' + з.map(канонJSON).join(',') + ']';
  if (typeof з === 'object') {
    const кл = Object.keys(з).filter(function (к) { return typeof з[к] !== 'function'; }).sort();
    return '{' + кл.map(function (к) { return JSON.stringify(к) + ':' + канонJSON(з[к]); }).join(',') + '}';
  }
  throw new Error('КРИПТА: канонизация не осилила тип ' + typeof з);
}

/* ── подпись ФАКТА (верификация ·19): ECDSA над канонБайты ──
   факт — любой JSON-совместимый объект; подпись — base64 (для провода).
   Ключ подписи — приватный ECDSA личности ·19 (non-extractable). */
