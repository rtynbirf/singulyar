export const COMPOSITION = Object.freeze({ name: 'singulyar-composition', version: '0.1.0' });

/* ── РЕЕСТР ПРИМИТИВОВ (Capability Registry, ТЗ §20) ──
   Примитив — строительный блок среды, а не модуль и не сервис.
   Декларация: имя · требует (способности среды) · даёт (что вносит
   в пространство) · представления · транспорты · разрешения ·
   расширяет (намерения, которым примитив может предложить себя). */
const РЕЕСТР = new Map();

function чисто(х) { return String(х == null ? '' : х).trim(); }

export function объявиПримитив(декларация) {
  const имя = чисто(декларация && декларация.имя);
  if (имя.length < 2) return { ok: false, причина: 'ИМЯ_ПУСТО' };
  const требует = Array.isArray(декларация.требует) ? декларация.требует.map(чисто).filter(Boolean) : [];
  const даёт = Array.isArray(декларация.даёт) ? декларация.даёт.map(чисто).filter(Boolean) : [];
  const представления = Array.isArray(декларация.представления) ? декларация.представления.map(чисто).filter(Boolean) : [];
  const транспорты = Array.isArray(декларация.транспорты) ? декларация.транспорты.map(чисто).filter(Boolean) : [];
  const разрешения = (декларация.разрешения && typeof декларация.разрешения === 'object')
    ? Object.freeze({ ...декларация.разрешения }) : Object.freeze({});
  const расширяет = Array.isArray(декларация.расширяет) ? декларация.расширяет.map(чисто).filter(Boolean) : [];
  РЕЕСТР.set(имя, Object.freeze({ имя, требует, даёт, представления, транспорты, разрешения, расширяет }));
  return { ok: true, имя };
}

export function реестр() { return [...РЕЕСТР.values()]; }
export function примитив(имя) { return РЕЕСТР.get(чисто(имя)) || null; }
export function сбросьРеестр() { РЕЕСТР.clear(); }   /* только для тестов и пересборки */

/* ── КЛЮЧЕВЫЕ НАМЕРЕНИЯ ДОМА ──
   Намерение произносит ЧЕЛОВЕК; машина знает лишь, какие примитивы
   нужны, чтобы среда возникла. Ни один ключ здесь не «модуль дома» —
   это слова деятельности: поговорить, споём, посмотрим, сохранить… */
const НАМЕРЕНИЯ = Object.freeze({
  'поговорить':  ['люди', 'присутствие', 'смысл', 'представление', 'доставка'],
  'споём':       ['люди', 'аудио', 'синхронизация', 'слова', 'запись', 'память'],
  'посмотрим':   ['люди', 'экран', 'синхронизация', 'чат'],
  'сохранить':   ['память'],
  'обменяемся':  ['люди', 'файлы', 'доставка'],
  'созвонимся':  ['люди', 'аудио', 'присутствие', 'доставка']
});
/* расширения словаря объявляются честно (объявиНамерение), база не правится: */
const НАМЕРЕНИЯ_ПЛЮС = new Map();
function словарьНамерений() { return Object.assign(Object.create(null), НАМЕРЕНИЯ, Object.fromEntries(НАМЕРЕНИЯ_ПЛЮС)); }

export function намерения() { return [...Object.keys(НАМЕРЕНИЯ), ...НАМЕРЕНИЯ_ПЛЮС.keys()]; }
export function объявиНамерение(слово, примитивы) {
  const с = чисто(слово);
  if (с.length < 2 || !Array.isArray(примитивы) || !примитивы.length) return { ok: false, причина: 'НАМЕРЕНИЕ_НЕПОЛНОЕ' };
  НАМЕРЕНИЯ_ПЛЮС.set(с, [...примитивы]);   /* расширение без правки ядра движка */
  return { ok: true, слово: с };
}

/* ── ПРОВЕРКА СПОСОБНОСТЕЙ СРЕДЫ ──
   требуемое примитива должно присутствовать в контексте.возможности.
   Отсутствие — не ошибка, а ЧЕСТНАЯ ОТМЕТКА на варианте (I-04). */
function нехватает(пр, возможности) {
  return (пр.требует || []).filter(function (т) { return !возможности.has(т); });
}

/* ── КОМПОЗИЦИЯ ПРОСТРАНСТВА (Space Manifest, ТЗ §13–§14) ──
   Вход:
     кто         — id человека (не профиль);
     сКем        — участники отношения (дома — люди, не аккаунты);
     намерение   — СЛОВО ЧЕЛОВЕКА (не enumerate функций);
     контекст    — { возможности: [..], сеть: bool, … };
     выбор       — решения человека: { примитивы?, память?, запретить?, транспорт? }.
   Выход:
     { ок, причина?, варианты: [SpaceManifest…], след } —
     машина предлагает, человек решает; каждый вариант несёт след. */
export function compose({ кто, сКем = [], намерение, контекст = {}, выбор = {} }) {
  const след = { движок: COMPOSITION.version, намерение: чисто(намерение), шаги: [] };
  if (!кто || !чисто(намерение)) {
    return { ок: false, причина: 'НЕТ_ЧЕЛОВЕКА_ИЛИ_НАМЕРЕНИЯ', варианты: [], след };
  }
  /* выбор человека высшего ранга: явный список примитивов перекрывает словарь */
  const слово = чисто(намерение).toLowerCase();
  const явные = Array.isArray(выбор.примитивы) && выбор.примитивы.length
    ? выбор.примитивы.map(чисто)
    : словарьНамерений()[слово];
  if (!явные) {
    /* I-09: неизвестное слово — честный отказ, без выдумок */
    return { ок: false, причина: 'НАМЕРЕНИЕ_НЕИЗВЕСТНО', варианты: [], след };
  }
  const запрет = new Set(Array.isArray(выбор.запретить) ? выбор.запретить.map(чисто) : []);
  const возможности = new Set(Array.isArray(контекст.возможности) ? контекст.возможности.map(чисто) : []);

  const нужно = явные.filter(function (имя) { return !запрет.has(имя); });
  if (!нужно.length) {
    return { ок: false, причина: 'ЧЕЛОВЕК_ЗАПРЕТИЛ_ВСЁ', варианты: [], след };
  }
  след.шаги.push({ шаг: 'примитивы', отобрано: [...нужно], запрещено: [...запрет] });

  /* примитивы, которых нет в реестре, честно записываются недостающими —
     «определить, какого универсального примитива не хватает» (ТЗ §36) */
  const недостающиеПримитивы = нужно.filter(function (имя) { return !РЕЕСТР.has(имя); });

  const доступные = [], упавшие = [];
  нужно.forEach(function (имя) {
    const пр = РЕЕСТР.get(имя);
    if (!пр) return;                       /* незнакомое — уже в недостающих */
    const не = нехватает(пр, возможности);
    if (не.length) упавшие.push({ имя: имя, нехватает: не });
    else доступные.push(пр);
  });
  след.шаги.push({ шаг: 'способности', упали: упавшие });

  if (!доступные.length && !недостающиеПримитивы.length) {
    return { ок: false, причина: 'СРЕДА_НЕВОЗМОЖНА', варианты: [], след };
  }

  /* память: машина НЕ имеет права ставить persistent сама (I-06).
     persistent — только явный выбор человека выбор.память='вечное'. */
  const памятьЧеловека = чисто(выбор.память).toLowerCase();
  const память = памятьЧеловека === 'вечное'
    ? { retention: 'persistent', ttl: null, решениеЧеловека: true }
    : { retention: 'temporary', ttl: (выбор.ttl == null ? null : Number(выбор.ttl)), решениеЧеловека: false };
  след.шаги.push({ шаг: 'память', ...память });

  const представления = [...new Set(доступные.flatMap(function (пр) { return пр.представления; }))];
  const транспортыЧеловека = чисто(выбор.транспорт);
  const транспорты = транспортыЧеловека
    ? [транспортыЧеловека]
    : [...new Set(доступные.flatMap(function (пр) { return пр.транспорты; }))];
  const разрешения = {};
  доступные.forEach(function (пр) {
    Object.keys(пр.разрешения || {}).forEach(function (р) { разрешения[р] = пр.разрешения[р]; });
  });

  const fallback = упавшие.length > 0 || недостающиеПримитивы.length > 0;
  const причина = недостающиеПримитивы.length
    ? 'НЕДОСТАЮЩИЕ_ПРИМИТИВЫ: ' + недостающиеПримитивы.join(', ')
    : (упавшие.length ? 'СРЕДА_УРЕЗАНА: ' + упавшие.map(function (у) { return у.имя; }).join(', ') : null);

  /* ЭМЕРДЖЕНТНОСТЬ БЕЗ ПРАВКИ ЯДРА (ТЗ §37): новые примитивы, объявившие
     расширяет: [намерение], ПОДКЛАДЫВАЮТСЯ в расширения[] — машина только
     предлагает, включить их в среду решает человек (выбор.примитивы). */
  const взяты = new Set(доступные.map(function (пр) { return пр.имя; }));
  const расширения = [];
  РЕЕСТР.forEach(function (пр, имя) {
    if (взяты.has(имя) || запрет.has(имя)) return;
    if (!(пр.расширяет || []).includes(слово)) return;
    if (нехватает(пр, возможности).length) return;
    расширения.push(имя);
  });

  const манифест = {
    ver: COMPOSITION.version,
    type: 'space.manifest',
    id: 'space_' + (globalThis.crypto && crypto.randomUUID ? crypto.randomUUID() : Date.now() + '-' + Math.random()),
    intent: слово,
    участники: Object.freeze([чисто(кто), ...сКем.map(чисто).filter(Boolean)]),
    примитивы: Object.freeze(доступные.map(function (пр) { return пр.имя; })),
    недостающиеПримитивы: Object.freeze(недостающиеПримитивы),
    расширения: Object.freeze(расширения),
    представления: Object.freeze(представления),
    транспорты: Object.freeze(транспорты),
    разрешения: Object.freeze(разрешения),
    память: Object.freeze(память),
    состояние: 'предложено',              /* жить средой решает человек (I-01) */
    fallback: fallback,
    причина: причина,
    revision: 1
  };
  след.шаги.push({ шаг: 'манифест', собран: манифест.примитивы.length, fallback: fallback });
  return { ок: true, варианты: [Object.freeze(манифест)], след };
}

/* ── ВАЛИДАЦИЯ МАНИФЕСТА (структурная, без зависимостей) ──
   Полная схема — рядом: space.schema.json (черновик 0.1, НЕ норматив).
   Здесь — обязательный минимум, достаточный тестам и мостам. */
export function validate(м) {
  if (!м || typeof м !== 'object') return { ok: false, причина: 'НЕ_ОБЪЕКТ' };
  if (м.type !== 'space.manifest') return { ok: false, причина: 'НЕ_МАНИФЕСТ' };
  if (typeof м.id !== 'string' || м.id.length < 8) return { ok: false, причина: 'ПЛОХОЙ_ID' };
  if (typeof м.intent !== 'string' || м.intent.length < 2) return { ok: false, причина: 'ПЛОХОЕ_НАМЕРЕНИЕ' };
  if (!Array.isArray(м.участники) || м.участники.length < 1) return { ok: false, причина: 'НЕТ_УЧАСТНИКОВ' };
  if (!Array.isArray(м.примитивы)) return { ok: false, причина: 'НЕТ_ПРИМИТИВОВ' };
  if (!м.память || !['temporary', 'persistent'].includes(м.память.retention)) return { ok: false, причина: 'ПЛОХАЯ_ПАМЯТЬ' };
  if (м.память.retention === 'persistent' && м.память.решениеЧеловека !== true) {
    return { ok: false, причина: 'ВЕЧНОЕ_БЕЗ_ЧЕЛОВЕКА' };   /* I-06 железно */
  }
  if (м.состояние !== 'предложено') return { ok: false, причина: 'МАШИНА_ПРИКАЗАЛА' };
  return { ok: true };
}

/* ── ПРОСВЕТ: сколько новых сценариев выражается без правки ядра ──
   Критерий успеха дома (ТЗ §37): EMERGENCE = NEW HUMAN MODE WITHOUT NEW CORE. */
export function просвет() {
  return { движок: COMPOSITION.version, примитивов: РЕЕСТР.size, намерений: Object.keys(НАМЕРЕНИЯ).length + НАМЕРЕНИЯ_ПЛЮС.size };
}
