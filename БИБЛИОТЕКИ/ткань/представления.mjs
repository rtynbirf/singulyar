/* Жёсткие требования — пишутся строками, проверяются фактом представления:
   'язык:ru'        — репрезентация обязана уметь язык
   'субтитры'       — обязана уметь субтитры
   'крупный-текст'  — обязана поддерживать крупный текст
   'аудиоописание'  — обязана уметь аудиоописание
   'только-аудио'   — обязана иметь аудиорежим                                   */

export const ПОРЯДОК_РЕШЕНИЯ = [
  'явный-выбор-человека', 'жёсткие-требования', 'безопасность-политика',
  'возможности-устройства', 'доступность', 'сеть-транспорт',
  'мягкие-предпочтения', 'ранжирование'
];

function языкИз(требование) {
  const м = /^язык:(.+)$/.exec(требование);
  return м ? м[1] : null;
}

function жёсткоеНарушено(реп, требование) {
  const яз = языкИз(требование);
  if (яз) return !(реп.языки || []).includes(яз);
  if (требование === 'субтитры') return !реп.субтитры;
  if (требование === 'крупный-текст') return !реп.крупныйТекст;
  if (требование === 'аудиоописание') return !реп.аудиоописание;
  if (требование === 'только-аудио') return !реп.толькоАудио;
  return false; /* незнакомое требование — не притворяемся, что проверили */
}

/* выбрать(объект, настройка) → решение.
   объект.представления: [{id, вид, медиаТип, языки:[], субтитры, крупныйТекст,
     аудиоописание, толькоАудио, качество}]
   настройка: {
     выборЧеловека: id представления | null   — явный override (первый в порядке ТЗ)
     требования: ['субтитры', 'язык:ru', ...]  — hard requirements
     профиль: {язык}                            — мягкое предпочтение
     возможности: {медиаТипы:[...]}             — что устройство/провод умеет
   }
   Решение: {статус:'выбрано'|'недоступно'|'неизвестно', представление?, причины:[],
             путь:['итог'], выборЧеловека:bool}                                  */
export function выбрать(объект, настройка) {
  const н = настройка || {};
  const требования = н.требования || [];
  const причины = [];
  const реп = (объект && объект.представления) || [];
  if (!реп.length) return { статус: 'неизвестно', причины: ['у объекта нет представлений'], путь: ['итог'], выборЧеловека: false };

  /* 1. явный выбор человека — уважается прежде ранжинга, НО жёсткие
        требования остаются железом: человек не просит машину навредить ему */
  if (н.выборЧеловека) {
    const своя = реп.find(function (р) { return р.id === н.выборЧеловека; });
    if (!своя) return { статус: 'неизвестно', причины: ['человек назвал представление, которого у объекта нет: ' + н.выборЧеловека], путь: ['явный-выбор'], выборЧеловека: true };
    const нарушенные = требования.filter(function (т) { return жёсткоеНарушено(своя, т); });
    if (нарушенные.length) {
      return { статус: 'недоступно', причины: ['явный выбор «' + н.выборЧеловека + '» нарушает жёсткие требования: ' + нарушенные.join(', ') + ' — жёсткое требование сильнее балла (ТЗ §6)'], путь: ['явный-выбор'], выборЧеловека: true };
    }
    return { статус: 'выбрано', представление: своя, причины: ['явный выбор человека (первый в порядке ТЗ §6)'], путь: ['явный-выбор'], выборЧеловека: true };
  }

  /* 2. жёсткие требования — фильтр, не баллы */
  const годные = реп.filter(function (р) {
    return !требования.some(function (т) { return жёсткоеНарушено(р, т); });
  });
  if (!годные.length) {
    return { статус: 'недоступно', причины: ['ни одно представление не проходит жёсткие требования: ' + требования.join(', ')], путь: ['жёсткие-требования'], выборЧеловека: false };
  }

  /* 3. возможности устройства/провода — отсеивает, что физически не доехать */
  const умеет = н.возможности && н.возможности.медиаТипы ? н.возможности.медиаТипы : null;
  const досягаемые = умеет ? годные.filter(function (р) { return умеет.includes(р.медиаТип); }) : годные;
  if (умеет && !досягаемые.length) {
    return { статус: 'недоступно', причины: ['жёстко годные представления не доезжают возможностями устройства: ' + годные.map(function (р) { return р.медиаТип; }).join(', ')], путь: ['возможности-устройства'], выборЧеловека: false };
  }

  /* 4. мягкие предпочтения — честный ранжинг с объяснимыми причинами */
  let лучший = null, лучшийБалл = -1;
  for (const р of досягаемые) {
    let балл = 0;
    if (н.профиль && н.профиль.язык && (р.языки || []).includes(н.профиль.язык)) { балл += 40; }
    if (р.качество === 'высокое') балл += 5;
    if (балл > лучшийБалл) { лучшийБалл = балл; лучший = р; }
  }
  if (н.профиль && н.профиль.язык) {
    причины.push('язык профиля «' + н.профиль.язык + '» учтён мягким баллом, жёсткие требования уже выполнены');
  }
  причины.push('выбрано ' + лучшийБалл + ' баллов объяснимого ранжинга');
  return { статус: 'выбрано', представление: лучший, причины: причины, путь: ['ранжирование'], выборЧеловека: false };
}

/* честное «неизвестно» — когда данных нет, статус не выдумывается */
export function неизвестно(причина) {
  return { статус: 'неизвестно', причины: [причина || 'данных недостаточно'], путь: ['итог'], выборЧеловека: false };
}
