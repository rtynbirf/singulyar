export const ИНТЕРФЕЙС = ['подключить', 'отключить', 'послатьУправляющее', 'послатьЧанк',
                          'наУправляющее', 'наЧанк', 'состояние', 'возможности', 'закрыть'];

/* создатьЛокальныйТранспорт({канал, шина}) — шина: {postMessage, onmessage}
   для тестов; в браузере — настоящий BroadcastChannel.
   Сообщение шины — конверт {вид:'управляющее'|'чанк', кому?, тело}:
   транспорт проверяет ТОЛЬКО вид конверта, никогда — содержание. */
export function создатьЛокальныйТранспорт(настройка) {
  const н = настройка || {};
  const каналИмя = н.канал || 'singulyar-ткань-v1';
  /* шина: фабрика (тесты — своя шина каждому узлу) | готовый экземпляр | BroadcastChannel */
  const Шина = typeof н.шина === 'function' ? н.шина()
    : (н.шина || (typeof BroadcastChannel !== 'undefined' ? new BroadcastChannel(каналИмя) : null));
  if (!Шина) return null;

  const узел = { id: 't-' + Math.random().toString(36).slice(2, 10) };
  let живой = false;
  const слушателиУправляющих = [];
  const слушателиЧанков = [];

  Шина.onmessage = function (событие) {
    /* транспорт заглядывает в конверт только чтобы выбрать очередь слушателей:
       вид конверта — часть провода; тело конверта транспорт не трогает */
    const конверт = событие && событие.data;
    if (!конверт || !конверт.вид || конверт.от === узел.id) return;
    if (конверт.вид === 'управляющее') слушателиУправляющих.forEach(function (ф) { ф(конверт.тело, конверт.от); });
    else if (конверт.вид === 'чанк') слушателиЧанков.forEach(function (ф) { ф(конверт.тело, конверт.от); });
  };

  function послать(вид, тело) {
    Шина.postMessage({ вид: вид, тело: тело, от: узел.id });
  }

  return {
    id: узел.id,
    вид: 'локальный',
    подключить() { живой = true; },
    отключить() { живой = false; },
    послатьУправляющее(сообщение) { if (!живой) throw new Error('транспорт не подключён'); послать('управляющее', сообщение); },
    послатьЧанк(сообщение) { if (!живой) throw new Error('транспорт не подключён'); послать('чанк', сообщение); },
    наУправляющее(ф) { слушателиУправляющих.push(ф); },
    наЧанк(ф) { слушателиЧанков.push(ф); },
    состояние() { return живой ? 'живой' : 'спит'; },
    возможности() { return { чанки: true, порядок: true, сквозной: false, сеть: false }; },
    закрыть() { живой = false; try { Шина.close && Шина.close(); } catch (е) { /* уже закрыта */ } }
  };
}

/* связано(а, б) → проверка, что два транспорта одной шины слышат друг друга
   (используется комнатой при подъёме пары вкладок и тестом в node). */
export function связаны(а, б) {
  return !!(а && б && а.вид === б.вид && а.состояние() === 'живой' && б.состояние() === 'живой');
}
