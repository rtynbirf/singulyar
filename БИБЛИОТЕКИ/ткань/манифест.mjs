import { ВЕРСИЯ, ошибка, ОШИБКИ } from './протокол.mjs';
import { дайджест, байты, objectIdИз } from './целостность.mjs';

export const ЧАНК_РАЗМЕР = 262144; /* 256 КБ — стартовый размер ТЗ §9 */

export const ВИДЫ = ['текст', 'образ', 'голос', 'звук', 'файл', 'документ', 'память', 'другое'];

/* число чанков из размера — O-03: вычисляется, а не обещается */
export function число_чанков(размер, чанкРазмер) {
  const чр = чанкРазмер || ЧАНК_РАЗМЕР;
  return Math.max(1, Math.ceil((размер || 0) / чр));
}

/* создатьМанифест({имя, вид, медиаТип, содержимое, от, кому, политика})
   → Promise<манифест>. Содержимое уходит ТОЛЬКО в дайджест — в манифесте
   его нет (O-02). */
export async function создатьМанифест(заявка) {
  const з = заявка || {};
  const б = байты(з.содержимое == null ? '' : з.содержимое);
  const д = await дайджест(б);
  const вид = ВИДЫ.indexOf(з.вид) !== -1 ? з.вид : 'другое';
  const политика = Object.assign({ переправка: false, кэш: true, память: 'спросить' }, з.политика || {});
  return {
    протокол: ВЕРСИЯ,
    objectId: objectIdИз(д),
    вид: вид,
    имя: String(з.имя || 'объект').slice(0, 200),
    размер: б.length,
    createdAt: Date.now(),
    от: з.от || null,
    кому: з.кому || null,
    представление: { медиаТип: String(з.медиаТип || 'text/plain') },
    чанкРазмер: ЧАНК_РАЗМЕР,
    чанков: число_чанков(б.length, ЧАНК_РАЗМЕР),
    целостность: { алгоритм: 'SHA-256', дайджест: д },
    политика: политика
  };
}

/* проверитьМанифест(м) → {ok, причины:[]} — никаких бросков: вердикт вернётся
   списком честных причин. Инварианты O-01..O-04, O-06. */
export function проверитьМанифест(м) {
  const причины = [];
  if (!м || typeof м !== 'object') return { ok: false, причины: ['манифест не объект'] };
  if (м.протокол !== ВЕРСИЯ) причины.push('протокол не ' + ВЕРСИЯ + ': ' + м.протокол);
  if (!/^sgo:sha256:[0-9a-f]{64}$/.test(String(м.objectId || ''))) {
    причины.push('objectId не формата sgo:sha256:<64hex> (O-01)');
  }
  const чр = м.чанкРазмер || ЧАНК_РАЗМЕР;
  if (!Number.isInteger(м.размер) || м.размер < 0) причины.push('размер не честное число');
  if (м.чанков !== число_чанков(м.размер, чр)) причины.push('чанков не сходится с размером (O-03)');
  if (!м.целостность || м.целостность.алгоритм !== 'SHA-256') причины.push('алгоритм целостности не SHA-256');
  if (!м.целостность || !/^[0-9a-f]{64}$/.test(String(м.целостность.дайджест || ''))) {
    причины.push('дайджест не 64 hex-символа');
  }
  if (м.целостность && /^sgo:sha256:/.test(String(м.objectId || '')) &&
      м.objectId !== objectIdИз(м.целостность.дайджест || '')) {
    причины.push('objectId не совпадает с дайджестом (O-04)');
  }
  if ('содержимое' in (м || {})) причины.push('манифест несёт содержимое — запрещено (O-02, O-06)');
  return { ok: причины.length === 0, причины: причины };
}

/* резать(содержимое, чанкРазмер) → массив Uint8Array — честная резка байтов */
export function резать(содержимое, чанкРазмер) {
  const б = байты(содержимое == null ? '' : содержимое);
  const чр = чанкРазмер || ЧАНК_РАЗМЕР;
  const куски = [];
  for (let i = 0; i < б.length; i += чр) куски.push(б.slice(i, i + чр));
  if (куски.length === 0) куски.push(new Uint8Array(0)); /* пустой объект — один честный чанк */
  return куски;
}

/* собрать(манифест, [Uint8Array]) → Promise<Uint8Array> — но приёмник обязан
   сам проверить дайджест через верь(); сборщик только складывает. */
export function собрать(куски) {
  let сумма = 0;
  for (const к of куски) сумма += к.length;
  const вых = new Uint8Array(сумма);
  let сдвиг = 0;
  for (const к of куски) { вых.set(к, сдвиг); сдвиг += к.length; }
  return вых;
}

/* честный отказ: манифест не прошёл проверку — приёмнику вернётся причина */
export function отказать(м) {
  const вердикт = проверитьМанифест(м);
  if (!вердикт.ok) throw ошибка(ОШИБКИ.ФОРМА, 'манифест не принят: ' + вердикт.причины.join('; '));
  return true;
}
