/* ═══════════════════════════════════════════════════════════════════════
   ТКАНЬ · ОТНОШЕНИЯ (такт v1.41.0) — слой 2 ТЗ: RelationshipStore.
   ───────────────────────────────────────────────────────────────────────
   ТЗ §4 R-01..R-07:
   R-01 отношение живёт без обязательного аккаунта (личность = отпечаток ключа);
   R-02 принятие — явное действие человека;
   R-03 блок закрывает доставку;
   R-04 удаление не уничтожает историческую личность другого;
   R-05 склад локален — сервер не источник истины (складу всё равно, есть ли сеть);
   R-06 изменения журналируются semantic-событиями (append-only);
   R-07 повтор события не создаёт дубликат.
   Складу injecting-ся адаптер хранения: в комнате — localStorage/IndexedDB,
   в тестах — память. Сам склад не знает про сеть вообще (R-05).
   ═══════════════════════════════════════════════════════════════════════ */

export const СОСТОЯНИЯ = ['предложено', 'принято', 'блок', 'удалено'];

export function памятьСклад() { /* адаптер для тестов и демо */
  const кэш = new Map();
  return {
    async получить(ключ) { return кэш.has(ключ) ? кэш.get(ключ) : null; },
    async положить(ключ, значение) { кэш.set(ключ, значение); return значение; },
    async список(префикс) {
      return [...кэш.keys()].filter(function (к) { return к.indexOf(префикс) === 0; })
        .map(function (к) { return кэш.get(к); });
    }
  };
}

/* создатьСклад(адаптер?) — адаптер: {получить, положить, список} */
export function создатьСклад(адаптер) {
  const ск = адаптер || памятьСклад();
  const ЛЮДИ = 'ткань:люди:', ОТН = 'ткань:отношения:', ЖУРНАЛ = 'ткань:журнал';

  async function событие(тип, данные, eventId) {
    const ид = eventId || (тип + ':' + (данные && данные.id || '') + ':' + Date.now() + ':' + Math.random().toString(36).slice(2, 8));
    const список = (await ск.список(ЖУРНАЛ));
    /* R-07: дедуп по eventId — повтор не создаёт дубликат */
    for (const эв of список) if (эв.eventId === ид) return { ок: true, дубль: true, eventId: ид };
    const эв = { eventId: ид, тип: тип, данные: данные, ts: Date.now() };
    await ск.положить(ЖУРНАЛ + ':' + ид, эв);
    return { ок: true, дубль: false, eventId: ид, событие: эв };
  }

  return {
    /* человек = отпечаток ключа + имя — НЕ аккаунт (R-01) */
    async добавитьЧеловека(_a) {
      const ч = { id: 'person:' + String(_a.id || Math.random().toString(36).slice(2, 10)),
                  имя: String(_a.имя || 'человек').slice(0, 80),
                  отпечаток: String(_a.отпечаток || ''), createdAt: Date.now() };
      await ск.положить(ЛЮДИ + ч.id, ч);
      await событие('person.added', { id: ч.id, имя: ч.имя });
      return ч;
    },
    async человек(id) { return ск.получить(ЛЮДИ + id); },
    async люди() { return (await ск.список(ЛЮДИ)); },

    /* отношение создаётся в состоянии «предложено» — принимает ЧЕЛОВЕК (R-02) */
    async создатьОтношение(personId, peerPersonId, права) {
      if (!personId || !peerPersonId) throw new Error('отношение требует двух людей');
      if (personId === peerPersonId) throw new Error('отношение к самому себе — не ткань');
      const п = { id: 'rel:' + Math.random().toString(36).slice(2, 10),
                  personId: personId, peerPersonId: peerPersonId,
                  state: 'предложено', createdAt: Date.now(), updatedAt: Date.now(),
                  права: Object.assign({ отправка: true, приём: true, переправка: false, кэш: true }, права || {}) };
      await ск.положить(ОТН + п.id, п);
      await событие('relationship.created', { id: п.id, state: п.state });
      return п;
    },
    async отношение(id) { return ск.получить(ОТН + id); },
    async отношения() { return (await ск.список(ОТН)); },

    async сменитьСостояние(id, состояние, типСобытия) {
      const п = await ск.получить(ОТН + id);
      if (!п) return { ok: false, причина: 'отношение не найдено' };
      if (СОСТОЯНИЯ.indexOf(состояние) === -1) return { ok: false, причина: 'чужое состояние: ' + состояние };
      if (п.state === 'удалено' && состояние !== 'удалено') {
        return { ok: false, причина: 'удалённое отношение не воскрешается — история честна (R-04)' };
      }
      п.state = состояние; п.updatedAt = Date.now();
      await ск.положить(ОТН + id, п);
      await событие(типСобытия || 'relationship.changed', { id: id, state: состояние });
      return { ok: true, отношение: п };
    },

    /* R-02: принять может только явное действие человека — это и есть функция */
    async принятьОтношение(id) { return this.сменитьСостояние(id, 'принято', 'relationship.accepted'); },
    /* R-03: блок — и доставку закрывает (см. разрешитьДоставку) */
    async блокироватьОтношение(id) { return this.сменитьСостояние(id, 'блок', 'relationship.blocked'); },
    /* R-04: удаление оставляет журнал и личность другого в покое — состояние
       лишь помечается;_peerPersonId никогда не вычищается */
    async удалитьОтношение(id) { return this.сменитьСостояние(id, 'удалено', 'relationship.removed'); },

    /* R-03: доставка разрешена только в «принято» и по правам направления */
    разрешитьДоставку(отношение, направление) {
      if (!отношение) return false;
      if (отношение.state !== 'принято') return false;
      if (направление === 'отправка') return !!отношение.права.отправка;
      if (направление === 'приём') return !!отношение.права.приём;
      return false;
    },

    /* R-06/R-07: журнал append-only, дедуп по eventId */
    событие: событие,
    async журнал() { return (await ск.список(ЖУРНАЛ)); }
  };
}
