export const ВЕРСИЯ = 'SNG-P2P/1';

export const ТИПЫ = {
  ОФФЕР: 'object.offer',
  ПРИНЯТЬ: 'object.accept',
  ОТКАЗ: 'object.reject',
  ЧАНК: 'object.chunk',
  ЗАВЕРШИТЬ: 'object.complete',
  ОТПЕЧАТОК: 'object.ack'
};

export const ОШИБКИ = {
  ФОРМА: 'protocol:форма',       /* не объект / нет полей */
  ТИП: 'protocol:тип',           /* неизвестный тип конверта */
  ВЕРСИЯ: 'protocol:версия',     /* чужой протокол */
  ПОРЯДОК: 'protocol:порядок'    /* поля конверта не согласованы (индексы и т.п.) */
};

export function ошибка(код, причина) {
  const е = new Error(причина || код);
  е.код = код;
  return е;
}

/* Порядок обмена — для честной подписи под капотом комнаты */
export const ПОРЯДОК_ОБМЕНА = [
  'object.offer',
  'object.accept | object.reject',
  'object.chunk × N',
  'object.complete',
  'object.ack'
];

/* проверитьСообщение(с) → с (та же ссылка) или бросает честную ошибку.
   Проверяется форма конверта, но НЕ содержимое: содержимое — не дело протокола. */
export function проверитьСообщение(с) {
  if (!с || typeof с !== 'object' || Array.isArray(с)) throw ошибка(ОШИБКИ.ФОРМА, 'сообщение не объект');
  if (typeof с.тип !== 'string') throw ошибка(ОШИБКИ.ФОРМА, 'нет поля «тип»');
  const типы = Object.values(ТИПЫ);
  if (типы.indexOf(с.тип) === -1) throw ошибка(ОШИБКИ.ТИП, 'неизвестный тип: ' + с.тип);
  if (с.тип !== ТИПЫ.ОФФЕР && typeof с.objectId !== 'string') {
    throw ошибка(ОШИБКИ.ФОРМА, 'конверт «' + с.тип + '» без objectId');
  }
  if (с.тип === ТИПЫ.ЧАНК) {
    if (!Number.isInteger(с.индекс) || с.индекс < 0) throw ошибка(ОШИБКИ.ПОРЯДОК, 'чанк без честного индекса');
    if (!Number.isInteger(с.изСкольких) || с.изСкольких < 1) throw ошибка(ОШИБКИ.ПОРЯДОК, 'чанк без числа частей');
    if (с.индекс >= с.изСкольких) throw ошибка(ОШИБКИ.ПОРЯДОК, 'индекс чанка за пределом');
    if (typeof с.байты !== 'string') throw ошибка(ОШИБКИ.ФОРМА, 'чанк без байтов (base64)');
  }
  if (с.тип === ТИПЫ.ЗАВЕРШИТЬ && !с.дайджест) throw ошибка(ОШИБКИ.ФОРМА, 'complete без дайджеста');
  if (с.тип === ТИПЫ.ОТПЕЧАТОК && typeof с.верено !== 'boolean') {
    throw ошибка(ОШИБКИ.ФОРМА, 'ack без честного вердикта верено:true|false');
  }
  return с;
}

/* канонЧанка(индекс, изСкольких) — конверт части; байты кладёт отправитель base64 */
export function канонЧанка(индекс, изСкольких, байты64) {
  return проверитьСообщение({ тип: ТИПЫ.ЧАНК, индекс: индекс, изСкольких: изСкольких, байты: байты64 });
}

/* base64 ↔ байты — свой конвейер, 0 зависимостей (работает и в node, и в браузере) */
const АЗБУКА = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
export function вBase64(байтыДанные) {
  const б = байтыДанные instanceof Uint8Array ? байтыДанные : new Uint8Array(байтыДанные);
  let вых = '';
  for (let i = 0; i < б.length; i += 3) {
    const б1 = б[i], б2 = б[i + 1], б3 = б[i + 2];
    вых += АЗБУКА[б1 >> 2];
    вых += АЗБУКА[((б1 & 3) << 4) | (б2 === undefined ? 0 : б2 >> 4)];
    вых += б2 === undefined ? '=' : АЗБУКА[((б2 & 15) << 2) | (б3 === undefined ? 0 : б3 >> 6)];
    вых += б3 === undefined ? '=' : АЗБУКА[б3 & 63];
  }
  return вых;
}
export function изBase64(строка) {
  const с = String(строка || '').replace(/[^A-Za-z0-9+/]/g, '');
  let длина = с.length;
  while (длина > 0 && с[длина - 1] === '=') длина--;
  const вых = new Uint8Array(Math.floor(длина * 3 / 4));
  let сч = 0, буфер = 0, бит = 0;
  for (let i = 0; i < длина; i++) {
    буфер = (буфер << 6) | АЗБУКА.indexOf(с[i]);
    бит += 6;
    if (бит >= 8) {
      бит -= 8;
      вых[сч++] = (буфер >> бит) & 255;
    }
  }
  return вых;
}
