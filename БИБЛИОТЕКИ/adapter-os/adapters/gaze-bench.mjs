// gaze-bench.mjs — СИНГУЛЯР·ADAPTER-OS, такт v10.98 «ВЗГЛЯД» (С74), строка А3:
// бенчмарк локального gaze — евклидова ошибка черты против размеченного корпуса.
//
// Требование карты А3: «бенчмарки (ledger трека)». Родня speech-bench.mjs
// (WER/CER текста) и ocr-bench.mjs (CER + точность строк) мерит СЛОВА — взору
// свои честные мерила, геометрические: евклидово расстояние между чертой
// движка и эталонной точкой (в нормализованных единицах кадра) + доля точек
// в названном допуске (по умолчанию 0.05 — пять сотых кадра, допуск назван
// запускающим, не выдуман домом).
//
// Честные границы:
//   - метрики считаются ТОЛЬКО по размеченному корпусу владельца; мок бегать
//     может, но протокол честно помечает отказы — выдуманной ошибки нет;
//   - меряется ЧЕРТА движка (кадр → точка взора) — качество калибровки дом
//     называет отдельно (остаток в аффинноеСоответствие: ошибка_средняя/
//     ошибка_макс); две меры не подменяют друг друга;
//   - тайминги устройства измеряет запускающий снаружи; внутри 0 часов;
//   - протокол детерминирован байт-в-байт: один прогон → один JSON.
//
// Экспорт: только ESM; импортов нет (самодостаточен, 0 зависимостей; мерила
// геометрические — текстовые мерила speech-bench сюда не тянутся).

export const ver = 'gaze-bench/0.1';
export const LEDGER_SCHEMA = 'adapter-os.gaze.bench.v1';

// Евклидово расстояние между двумя точками. Чистая функция, без часов.
export function евклид(a, b) {
  if (!a || typeof a !== 'object' || !b || typeof b !== 'object') {
    throw new TypeError('gaze-bench: евклид — точки ожидаются объектами { x, y }');
  }
  if (typeof a.x !== 'number' || !Number.isFinite(a.x) || typeof a.y !== 'number' || !Number.isFinite(a.y) ||
      typeof b.x !== 'number' || !Number.isFinite(b.x) || typeof b.y !== 'number' || !Number.isFinite(b.y)) {
    throw new TypeError('gaze-bench: евклид — координаты ожидаются конечными числами');
  }
  return Math.sqrt((a.x - b.x) ** 2 + (a.y - b.y) ** 2);
}

// Черта ответа runner'а. Отказ → null (точка уходит с отказом, ошибка не
// выдумывается).
export function чертаОтветаGaze(ответ) {
  if (!ответ || typeof ответ !== 'object' || Array.isArray(ответ)) return null;
  if (typeof ответ.отказ === 'string' && ответ.отказ) return null;
  const черта = ответ.черта;
  if (!черта || typeof черта !== 'object' || Array.isArray(черта)) return null;
  if (typeof черта.x !== 'number' || !Number.isFinite(черта.x)) return null;
  if (typeof черта.y !== 'number' || !Number.isFinite(черта.y)) return null;
  return { x: черта.x, y: черта.y };
}

// ---------------------------------------------------------------------------
// ПРОГОН БЕНЧМАРКА GAZE. Корпус: [{ id, эталон: {x, y}, задание }]; runner —
// контракт gaze.mjs. Допуск — named-параметр запускающего (по умолчанию 0.05).
// Протокол детерминирован байт-в-байт.
// ---------------------------------------------------------------------------
export function прогонБенчмаркаGaze(runner, корпус, параметры) {
  if (typeof runner !== 'function') {
    throw new TypeError('gaze-bench: прогонБенчмаркаGaze — runner ожидается функцией');
  }
  if (!Array.isArray(корпус) || корпус.length === 0) {
    throw new TypeError('gaze-bench: прогонБенчмаркаGaze — корпус ожидается непустым массивом записей { id, эталон, задание }');
  }
  const п = параметры && typeof параметры === 'object' && !Array.isArray(параметры) ? параметры : {};
  const допуск = п.допуск === undefined ? 0.05 : п.допуск;
  if (typeof допуск !== 'number' || !Number.isFinite(допуск) || допуск <= 0) {
    throw new TypeError('gaze-bench: прогонБенчмаркаGaze — допуск ожидается положительным конечным числом');
  }
  const строки = [];
  let сумма = 0, макс = 0, в_допуске = 0, счёт_метрик = 0, счёт_отказов = 0;
  for (let i = 0; i < корпус.length; i++) {
    const запись = корпус[i];
    const где = `корпус[${i}]`;
    if (!запись || typeof запись !== 'object' || Array.isArray(запись)) {
      throw new TypeError(`gaze-bench: ${где} ожидается объектом`);
    }
    if (typeof запись.id !== 'string' || !запись.id) {
      throw new TypeError(`gaze-bench: ${где}.id ожидается непустой строкой`);
    }
    const эталон = запись.эталон;
    if (!эталон || typeof эталон !== 'object' || Array.isArray(эталон) ||
        typeof эталон.x !== 'number' || !Number.isFinite(эталон.x) ||
        typeof эталон.y !== 'number' || !Number.isFinite(эталон.y)) {
      throw new TypeError(`gaze-bench: ${где}.эталон ожидается точкой { x, y } с конечными числами`);
    }
    let ответ;
    try {
      ответ = runner(запись.задание);
    } catch (ошибка) {
      ответ = { отказ: ошибка && ошибка.message ? ошибка.message : String(ошибка) };
    }
    const черта = чертаОтветаGaze(ответ);
    if (черта === null) {
      счёт_отказов += 1;
      const причина = ответ && typeof ответ.отказ === 'string' ? ответ.отказ : 'ответ runner\'а не разобран (не конверт)';
      строки.push({ id: запись.id, эталон, черта: null, ошибка: null, в_допуске: null, отказ: причина });
      continue;
    }
    const ошибка = евклид(эталон, черта);
    const попадание = ошибка <= допуск;
    сумма += ошибка; if (ошибка > макс) макс = ошибка; if (попадание) в_допуске += 1;
    счёт_метрик += 1;
    строки.push({ id: запись.id, эталон, черта, ошибка, в_допуске: попадание, отказ: null });
  }
  return {
    схема: LEDGER_SCHEMA,
    допуск,
    точек_в_корпусе: корпус.length,
    точек_с_метрикой: счёт_метрик,
    точек_с_отказом: счёт_отказов,
    точек_в_допуске: в_допуске,
    ошибка_средняя: счёт_метрик === 0 ? null : сумма / счёт_метрик,
    ошибка_максимальная: счёт_метрик === 0 ? null : макс,
    доля_в_допуске: счёт_метрик === 0 ? null : в_допуске / счёт_метрик,
    пометка: счёт_отказов === корпус.length
      ? 'ВСЕ ТОЧКИ С ОТКАЗОМ: метрик нет — это прогон мока/недоставленной модели, не мера качества (честно)'
      : 'метрики только по точкам с распознанной чертой; мерила геометрические (евклид в нормализованных единицах кадра), качество калибровки мерится отдельно (остаток аффинного соответствия)',
    строки,
  };
}
