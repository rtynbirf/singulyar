// ЧЕСТНОЕ РАЗДЕЛЕНИЕ ТРУДА (контракт: input 'text' → output 'unicode-braille'):
//   - ТАБЛИЦЫ — канон ячеек: латиница grade 1 (a–z), знаки пунктуации,
//     знак заглавной (точка 6) и знак цифр (точки 3-4-5-6), цифры 1–0 через
//     a–j. Встроенная таблица latin-g1 живёт в доме и закреплена тестами;
//     таблицы других языков добавляет владелец (ЛЮК_ТАБЛИЦ_БРАЙЛЬ.md,
//     Закон о языках: rus → srp → kaz → deu).
//   - ДВЕРЬ — перевод посимвольно, без часов, без сети, байт-в-байт
//     детерминизм; незнакомый символ — честный отказ (строгий режим) или
//     пустая ячейка с названной позицией (режим с_заглушками) — молча ничего
//     не теряется.
//
// ЧЕСТНЫЕ ГРАНИЦЫ:
//   - Unicode Braille — ТОЛЬКО представление; физический дисплей (WebHID/OS
//     accessibility) — hardware 'optional' по контракту, вне адаптера;
//   - grade 1 (посимвольная запись): сокращений grade 2 в доме нет — и это
//     названо, а не скрыто;
//   - числовая механика упрощена: знак цифр ставится перед каждой группой
//     цифр; терминатора чисел (как в UEB) дом не пишет — буквенный хвост
//     сразу после цифр (без разделителя) читатель может прочесть как цифры;
//     граница названа;
//   - пробел и перевод строки проходят как есть (структура текста сохраняется)
//     — канон дома, таблицей не подменяются;
//   - таблица НЕ может переопределить пробел и перевод строки (структура не
//     товар для торга);
//   - символы, уже лежащие в Unicode-Брайле (U+2800–U+28FF), на входе не
//     проходят мимо таблицы — сквозной пропуск был бы подменой гарантий.
//
// Экспорт: только ESM; импорт — ровно один, канон дома: ../src/core.mjs (STATUS).

import { STATUS } from '../src/core.mjs';

export const ver = 'braille-adapter/0.1';
export const LEDGER_SCHEMA = 'adapter-os.braille.v1';
export const ADAPTER_ID = 'output.braille';
export const ПРИОРИТЕТ = 50;

const ПАТТЕРН_ID = /^[\p{L}\p{N}][\p{L}\p{N}._-]*$/u;

// Канон службы дома: пробел и перевод строки — структура, не таблица.
export const СЛУЖЕБНЫЕ = Object.freeze(['\u0020', '\n']);
// Знаки службы: заглавная — точка 6; цифр — точки 3-4-5-6.
export const ЗНАК_ЗАГЛАВНОЙ = Object.freeze([6]);
export const ЗНАК_ЦИФР = Object.freeze([3, 4, 5, 6]);
// Цифры 1–0 через буквы a–j (канон Брайля).
const ЦИФРА_К_БУКВЕ = Object.freeze({ '1': 'a', '2': 'b', '3': 'c', '4': 'd', '5': 'e', '6': 'f', '7': 'g', '8': 'h', '9': 'i', '0': 'j' });

// Ячейка Брайля из точек: маска точек 1..8 → U+2800 + маска.
// Точка 1 = 0x01, 2 = 0x02, 3 = 0x04, 4 = 0x08, 5 = 0x10, 6 = 0x20, 7 = 0x40, 8 = 0x80.
export function ячейка(точки) {
  if (!Array.isArray(точки) || точки.length === 0) {
    throw new TypeError('braille-adapter: ячейка — ожидается непустой массив точек');
  }
  let маска = 0;
  const виденные = new Set();
  for (const т of точки) {
    if (!Number.isInteger(т) || т < 1 || т > 8) {
      throw new TypeError(`braille-adapter: ячейка — точка ожидается целым числом 1..8, получено ${JSON.stringify(т ?? null)}`);
    }
    if (виденные.has(т)) {
      throw new TypeError(`braille-adapter: ячейка — дубликат точки ${т}`);
    }
    виденные.add(т);
    маска |= 1 << (т - 1);
  }
  return String.fromCharCode(0x2800 + маска);
}

// ---------------------------------------------------------------------------
// ВСТРОЕННАЯ ТАБЛИЦА latin-g1: латиница grade 1 (a–z) + четыре знака
// пунктуации (запятая 2, точка 2-5-6, апостроф 3, дефис 3-6). Канон Луи
// Брайля/UEB grade 1, закреплён тестами байт-в-байт. Пробел и перевод строки
// — служебные, в таблицу не входят.
// ---------------------------------------------------------------------------
export const ТАБЛИЦА_LATIN_G1 = Object.freeze({
  'a': [1], 'b': [1, 2], 'c': [1, 4], 'd': [1, 4, 5], 'e': [1, 5],
  'f': [1, 2, 4], 'g': [1, 2, 4, 5], 'h': [1, 2, 5], 'i': [2, 4], 'j': [2, 4, 5],
  'k': [1, 3], 'l': [1, 2, 3], 'm': [1, 3, 4], 'n': [1, 3, 4, 5], 'o': [1, 3, 5],
  'p': [1, 2, 3, 4], 'q': [1, 2, 3, 4, 5], 'r': [1, 2, 3, 5], 's': [2, 3, 4], 't': [2, 3, 4, 5],
  'u': [1, 3, 6], 'v': [1, 2, 3, 6], 'w': [2, 4, 5, 6], 'x': [1, 3, 4, 6], 'y': [1, 3, 4, 5, 6], 'z': [1, 3, 5, 6],
  ',': [2], '.': [2, 5, 6], "'": [3], '-': [3, 6],
});

// ---------------------------------------------------------------------------
// LEDGER ТАБЛИЦ. На импорте — ровно одна, встроенная latin-g1 (она дома).
// Регистрации моделей у Брайля нет: таблицы — явные данные, проверенные
// структурно; весов нет — пин не нужен.
// ---------------------------------------------------------------------------
const ledger = new Map();
ledger.set('latin-g1', { имя: 'braille/latin-g1', таблица: ТАБЛИЦА_LATIN_G1, встроенная: true });

// ВАЛИДАЦИЯ ТАБЛИЦЫ. Строгая, структурная: каждый ключ — ровно один символ,
// каждая точка — целое 1..8 без дубликатов; пробел и перевод строки таблицей
// не подменяются (канон дома). Возвращает { ok, причина }.
export function валидироватьТаблицу(таблица) {
  if (!таблица || typeof таблица !== 'object' || Array.isArray(таблица)) {
    return { ok: false, причина: 'таблица ожидается объектом { символ: [точки] }' };
  }
  const ключи = Object.keys(таблица);
  if (ключи.length === 0) {
    return { ok: false, причина: 'таблица пуста — переводить нечем, честный отказ' };
  }
  for (const ключ of ключи) {
    if (typeof ключ !== 'string' || [...ключ].length !== 1) {
      return { ok: false, причина: `ключ "${ключ}" ожидается ровно одним символом` };
    }
    if (СЛУЖЕБНЫЕ.includes(ключ)) {
      return { ok: false, причина: `ключ "${JSON.stringify(ключ)}" — служебный символ дома (пробел/перевод строки), таблицей не подменяется` };
    }
    const точки = таблица[ключ];
    if (!Array.isArray(точки) || точки.length === 0 || точки.length > 8) {
      return { ok: false, причина: `таблица["${ключ}"] ожидается непустым массивом точек (1..8)` };
    }
    const виденные = new Set();
    for (const т of точки) {
      if (!Number.isInteger(т) || т < 1 || т > 8) {
        return { ok: false, причина: `таблица["${ключ}"] — точка ожидается целым числом 1..8, получено ${JSON.stringify(т ?? null)}` };
      }
      if (виденные.has(т)) {
        return { ok: false, причина: `таблица["${ключ}"] — дубликат точки ${т}` };
      }
      виденные.add(т);
    }
  }
  return { ok: true };
}

// Регистрация таблицы: честный true/false. Структура проверяется до входа в
// ledger; дубликат id — false.
export function registerBrailleTable(описание) {
  if (!описание || typeof описание !== 'object' || Array.isArray(описание)) return false;
  const { id, таблица } = описание;
  if (!id || typeof id !== 'string' || !ПАТТЕРН_ID.test(id)) return false;
  if (ledger.has(id)) return false; // дубликат id — честный false
  const проверка = валидироватьТаблицу(таблица);
  if (!проверка.ok) return false;
  // Копия: вход владельца не шарится (мутация после регистрации не меняет дом).
  const копия = {};
  for (const ключ of Object.keys(таблица)) копия[ключ] = [...таблица[ключ]];
  ledger.set(id, { имя: `braille/${id}`, таблица: копия, встроенная: false });
  return true;
}

export function списокТаблиц() {
  return [...ledger.keys()].sort().map((id) => {
    const запись = ledger.get(id);
    return {
      id,
      имя: запись.имя,
      символов: Object.keys(запись.таблица).length,
      встроенная: запись.встроенная,
      статус: запись.встроенная
        ? 'встроенная таблица дома, закреплена тестами байт-в-байт'
        : 'таблица владельца: структура проверена домом (символы и точки 1..8), соответствие стандарту языка — за владельцем',
    };
  });
}

// ---------------------------------------------------------------------------
// ВАЛИДАЦИЯ ЗАДАНИЯ. Текст — строка (пустая — честная пустота, как чистый
// лист у OCR); режим — 'строгий' | 'с_заглушками' (по умолчанию 'строгий').
// ---------------------------------------------------------------------------
export const РЕЖИМЫ = Object.freeze(['строгий', 'с_заглушками']);

export function валидироватьЗадание(задание) {
  if (!задание || typeof задание !== 'object' || Array.isArray(задание)) {
    return { ok: false, причина: 'задание ожидается объектом' };
  }
  if (typeof задание.текст !== 'string') {
    return { ok: false, причина: `задание.текст ожидается строкой, получено ${задание.текст === null ? 'null' : typeof задание.текст}` };
  }
  if (задание.режим !== undefined && !РЕЖИМЫ.includes(задание.режим)) {
    return { ok: false, причина: `задание.режим ожидается одним из [${РЕЖИМЫ.join(', ')}], получено ${JSON.stringify(задание.режим ?? null)}` };
  }
  return { ok: true };
}

// ---------------------------------------------------------------------------
// ДВЕРЬ БРАЙЛЯ (синхронная, чистая). Порядок честный и детерминированный:
// валидация → ledger → посимвольный перевод (знаки службы, заглавные, группы
// цифр, таблица) → отчёт. Одна таблица — она по умолчанию... В доме ВСЕГДА
// есть встроенная latin-g1, поэтому без id — она; несколько таблиц — id
// обязателен (дом не выбирает язык за человека). Дверь никогда не бросает.
// ---------------------------------------------------------------------------
export function брайль(задание, idТаблицы) {
  const проверка = валидироватьЗадание(задание);
  if (!проверка.ok) return { отказ: проверка.причина };
  if (ledger.size > 1 && idТаблицы === undefined) {
    return { отказ: `в ledger ${ledger.size} таблиц — назовите id честно, дом не выбирает язык за человека` };
  }
  const id = idТаблицы === undefined ? [...ledger.keys()][0] : idТаблицы;
  const запись = ledger.get(id);
  if (!запись) return { отказ: `таблица "${id}" не зарегистрирована` };

  const текст = задание.текст;
  if (текст === '') {
    return {
      ячейки: '',
      пусто: true,
      режим: задание.режим === undefined ? 'строгий' : задание.режим,
      таблица: id,
      символов: 0,
      ячеек: 0,
      знаков_цифр: 0,
      знаков_заглавных: 0,
    };
  }

  const режим = задание.режим === undefined ? 'строгий' : задание.режим;
  const символы = [...текст]; // посимвольно, кодовые точки (не суррогатные половины)
  const итог = [];
  const заглушки = [];
  let знаков_цифр = 0;
  let знаков_заглавных = 0;
  let предыдущая_цифра = false;

  for (let i = 0; i < символы.length; i++) {
    const символ = символы[i];
    if (СЛУЖЕБНЫЕ.includes(символ)) {
      итог.push(символ);
      предыдущая_цифра = false;
      continue;
    }
    if (символ >= '0' && символ <= '9') {
      const буква = ЦИФРА_К_БУКВЕ[символ];
      if (!Object.prototype.hasOwnProperty.call(запись.таблица, буква)) {
        if (режим === 'с_заглушками') {
          итог.push('\u2800'); // незаполненная ячейка — потеря названа в отчёте
          заглушки.push({ позиция: i, символ });
          предыдущая_цифра = true;
          continue;
        }
        return { отказ: `строгий режим: цифра "${символ}" на позиции ${i} требует ячейку буквы "${буква}" — в таблице "${id}" её нет; дом не выдумывает ячейки (режим "с_заглушками" назовёт потери явно)` };
      }
      if (!предыдущая_цифра) {
        итог.push(ячейка(ЗНАК_ЦИФР));
        знаков_цифр += 1;
      }
      итог.push(ячейка(запись.таблица[буква]));
      предыдущая_цифра = true;
      continue;
    }
    предыдущая_цифра = false;
    if (Object.prototype.hasOwnProperty.call(запись.таблица, символ)) {
      итог.push(ячейка(запись.таблица[символ]));
      continue;
    }
    const нижний = символ.toLowerCase();
    if (нижний !== символ && Object.prototype.hasOwnProperty.call(запись.таблица, нижний)) {
      итог.push(ячейка(ЗНАК_ЗАГЛАВНОЙ));
      знаков_заглавных += 1;
      итог.push(ячейка(запись.таблица[нижний]));
      continue;
    }
    if (режим === 'с_заглушками') {
      итог.push('\u2800'); // незаполненная ячейка — потеря названа в отчёте
      заглушки.push({ позиция: i, символ });
      continue;
    }
    let код = '';
    const ч = символ.codePointAt(0);
    if (ч !== undefined) код = `U+${ч.toString(16).toUpperCase().padStart(4, '0')}`;
    return { отказ: `строгий режим: символ "${символ}" (${код}) на позиции ${i} — в таблице "${id}" его нет; дом не выдумывает ячейки (режим "с_заглушками" назовёт потери явно)` };
  }

  const отчёт = {
    ячейки: итог.join(''),
    пусто: false,
    режим,
    таблица: id,
    символов: символы.length,
    ячеек: итог.length,
    знаков_цифр,
    знаков_заглавных,
  };
  if (заглушки.length > 0) отчёт.заглушки = заглушки;
  return отчёт;
}

// ---------------------------------------------------------------------------
// АДАПТЕР ДЛЯ РЕЕСТРА (AdapterRegistry). Тот же id, что у контрактной заглушки
// ('output.braille'); статус — READY честно: контракт требует output
// 'unicode-braille', дом делает ровно это, таблица закреплена тестами;
// физический дисплей — hardware 'optional', вне контракта, названо. privacy
// local — 0 сети, перевод локален.
// ---------------------------------------------------------------------------
export function createBrailleAdapter() {
  return {
    id: ADAPTER_ID,
    kind: 'output',
    priority: ПРИОРИТЕТ,
    status() {
      const таблицы = списокТаблиц();
      return {
        state: STATUS.READY,
        privacy: 'local',
        reason: `Unicode Braille only (contract output): детерминированный перевод, таблицы [${таблицы.map((т) => т.id).join(', ')}]; физический дисплей — hardware optional, вне контракта`,
      };
    },
    брайль(задание, id) { return брайль(задание, id); },
  };
}
