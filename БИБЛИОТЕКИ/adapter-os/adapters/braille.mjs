// перевод текста в Unicode-Брайль — детерминированная математика ячеек
// U+2800–U+28FF, а не нейросеть. Склейка частей, SHA-256-пин и честный мок
// четырёх предыдущих дверей сюда не тянутся — вместо них таблицы, закреплённые
