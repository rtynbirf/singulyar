// ocr.mjs — СИНГУЛЯР·ADAPTER-OS, такт v10.95 «ЧТЕНИЕ» (С71), строка А3, шаг 2.
//
// ПРИОРИТЕТ ВЛАДЕЛЬЦА (2026-10-13): «1) локальный Whisper (речь — ядро), 2) OCR,
// 3) gaze, 4) Demucs, 5) Брайль — последним». Шаг 1 сделан тактом v10.94
// «ГОЛОС» (speech.mjs). Этот файл — ШАГ 2: контракт input.ocr из contracts.mjs
// получает реализацию-дверь: ledger с пиннинтом модели (tesseract traineddata),
// строгий разбор результата, честный мок и дверь распознавания. Чтение текста
// с картинки — глаз дома: изображение не покидает устройство, 0 сети — закон
// приватности, не украшение.
//
// ЗАКОН ЧЕСТНОСТИ (родня speech.mjs): модели OCR в доме нет (правда платформы:
// файл ≤100 МБ) — адаптер не тащит, не качает и не запускает модель. Модель
// живёт ЛОКАЛЬНО у владельца (люк: docs — ЛЮК_ВЕСОВ_OCR.md, tesseract
// traineddata кладётся в репу весов singulyar-llm → OCR/) и приходит в адаптер
// готовой — через runner по контракту ниже. До pinned-хэша статус модели —
// EXPERIMENTAL, честно (критерий А3: «модель пинится и проходит контрактные
// тесты»).
//
// КОНТРАКТ RUNNER (синхронный, чистый; async-рантаймы приносят замороженный ответ):
//   runner(задание) → { текст: строка, строки: [строк]? , язык: строка }
//                   | { отказ: причина }
//   задание = { изображение: { данные: Uint8Array, формат: 'png'|'jpeg'|'bmp'
//                              |'gif'|'webp'|'tiff' },
//               язык: строка|'auto', параметры: объект }
//   - детерминированный: одна картинка → один ответ, байт-в-байт;
//   - 0 сети: runner ничего не качает — модель уже локальна;
//   - асинхронные рантаймы (Tesseract.js-воркер в веб-воркере, локальный
//     сервер вывода) гоняются ЗА пределами синхронного цикла и приносят
//     «замороженный ответ» (родня speech.mjs, срез 4 llm.mjs).
//   Нет runner'а — нет модели: адаптер не выдумывает текст за OCR.
//
// ПОДПИСЬ ФАЙЛА (честность входа): адаптер не верит названному формату —
// сверяет его с магическими байтами картинки (PNG \x89PNG…, JPEG \xFF\xD8\xFF,
// BMP 'BM', GIF 'GIF8…', WEBP 'RIFF…WEBP', TIFF 'II*\0'/'MM\0*'). Расхождение —
// честный отказ: картинка не подменяется и не «чинится» молча.
//
// Честные границы:
//   - ПУСТОЙ текст — валидный ответ (чистый лист честно распознаётся пустотой),
//     в отличие от речи: там пустая реплика — отказ; здесь пустота — факт;
//   - адаптер не бинаризует, не поворачивает и не улучшает картинку молча:
//     предобработка — дело владельца картинки, не адаптера;
//   - язык приходит как назвал runner: дом не угадывает язык за моделью;
//   - мок (mockRunner) НЕ притворяется чтением: всегда честный отказ;
//   - склейка частей и пин — та же механика, что speech.mjs; копия
//     сознательна (самодостаточность адаптера), расхождение ловят тесты
//     (обе копии держат вектор SHA-256("abc")).
//
// Экспорт: только ESM; импорт — ровно один, канон дома: ../src/core.mjs (STATUS).

import { STATUS } from '../src/core.mjs';

export const ver = 'ocr-adapter/0.1';
export const LEDGER_SCHEMA = 'adapter-os.ocr.v1';
export const ADAPTER_ID = 'input.ocr';

const ПАТТЕРН_ID = /^[\p{L}\p{N}][\p{L}\p{N}._-]*$/u;
const ПАТТЕРН_ХЭША = /^[0-9a-f]{64}$/i;
const ПАТТЕРН_ЯЗЫКА = /^[\p{L}\p{N}]{2,8}(-[\p{L}\p{N}]{2,8})*$/u;
// Честная граница объёма: строк не больше МАКС_СТРОК, символов текста не
// больше МАКС_СИМВОЛОВ (книга на картинке проходит; многотомье — повод
// честно отказать).
export const МАКС_СТРОК = 4096;
export const МАКС_СИМВОЛОВ = 1_000_000;

// Подписи форматов: [формат, функция проверки первых байтов]. Проверка требует
// достаточно длинного буфера — короткие данные честно не проходят.
export const ПОДПИСИ = {
  png: (б) => б.length >= 8 && б[0] === 0x89 && б[1] === 0x50 && б[2] === 0x4e && б[3] === 0x47 && б[4] === 0x0d && б[5] === 0x0a && б[6] === 0x1a && б[7] === 0x0a,
  jpeg: (б) => б.length >= 3 && б[0] === 0xff && б[1] === 0xd8 && б[2] === 0xff,
  bmp: (б) => б.length >= 2 && б[0] === 0x42 && б[1] === 0x4d,
  gif: (б) => б.length >= 6 && б[0] === 0x47 && б[1] === 0x49 && б[2] === 0x46 && б[3] === 0x38 && (б[4] === 0x37 || б[4] === 0x39) && б[5] === 0x61,
  webp: (б) => б.length >= 12 && б[0] === 0x52 && б[1] === 0x49 && б[2] === 0x46 && б[3] === 0x46 && б[8] === 0x57 && б[9] === 0x45 && б[10] === 0x42 && б[11] === 0x50,
  tiff: (б) => б.length >= 4 && ((б[0] === 0x49 && б[1] === 0x49 && б[2] === 0x2a && б[3] === 0x00) || (б[0] === 0x4d && б[1] === 0x4d && б[2] === 0x00 && б[3] === 0x2a)),
};
export const ФОРМАТЫ = Object.keys(ПОДПИСИ);

// ---------------------------------------------------------------------------
// LEDGER моделей. На импорте пуст — моделей в доме нет, и это честно.
// ---------------------------------------------------------------------------
const ledger = new Map();

export function списокМоделей() {
  return [...ledger.keys()].sort().map((id) => {
    const запись = ledger.get(id);
    const веса = запись.веса;
    return {
      id,
      имя: запись.имя,
      движок: запись.движок,
      веса: веса
        ? { имя: веса.имя, sha256: веса.sha256.toLowerCase(), байт: веса.байт, частей: веса.частей }
        : null,
      статус: веса
        ? `pinned sha256:${веса.sha256.toLowerCase()}`
        : 'EXPERIMENTAL: без pinned-хэша — модель владельца, дом не проверял веса',
    };
  });
}

// ---------------------------------------------------------------------------
// ВАЛИДАЦИЯ ЗАДАНИЯ. Картинка — Uint8Array с живой подписью, согласованной с
// названным форматом. Вход не мутируется: создатьЗадание отдаёт копию данных.
// ---------------------------------------------------------------------------
export function валидироватьЗадание(задание) {
  if (!задание || typeof задание !== 'object' || Array.isArray(задание)) {
    return { ok: false, причина: 'задание ожидается объектом' };
  }
  const картинка = задание.изображение;
  if (!картинка || typeof картинка !== 'object' || Array.isArray(картинка)) {
    return { ok: false, причина: 'задание.изображение ожидается объектом' };
  }
  const данные = картинка.данные;
  const тип = Object.prototype.toString.call(данные);
  if (тип !== '[object Uint8Array]') {
    return { ok: false, причина: `изображение.данные ожидаются Uint8Array, получено ${тип}` };
  }
  if (данные.length === 0) {
    return { ok: false, причина: 'изображение.данные пусты — читать нечего, честный отказ' };
  }
  const формат = картинка.формат;
  if (typeof формат !== 'string' || !ФОРМАТЫ.includes(формат)) {
    return { ok: false, причина: `изображение.формат ожидается одним из [${ФОРМАТЫ.join(', ')}], получено ${JSON.stringify(формат ?? null)}` };
  }
  if (!ПОДПИСИ[формат](данные)) {
    return { ok: false, причина: `подпись файла не сошлась с названным форматом "${формат}" — картинка не подменяется молча` };
  }
  const язык = задание.язык === undefined ? 'auto' : задание.язык;
  if (язык !== 'auto' && (typeof язык !== 'string' || !ПАТТЕРН_ЯЗЫКА.test(язык))) {
    return { ok: false, причина: `язык "${String(язык)}" не читается (паттерн ${ПАТТЕРН_ЯЗЫКА} или 'auto')` };
  }
  if (задание.параметры !== undefined && (typeof задание.параметры !== 'object' || задание.параметры === null || Array.isArray(задание.параметры))) {
    return { ok: false, причина: 'задание.параметры ожидается объектом или отсутствовать' };
  }
  return { ok: true };
}

// Готовит конверт задания: валидация + копия данных (вход не шарится).
export function создатьЗадание({ данные, формат, язык = 'auto', параметры = {} }) {
  const проверка = валидироватьЗадание({ изображение: { данные, формат }, язык, параметры });
  if (!проверка.ok) throw new TypeError(`ocr-adapter: создатьЗадание — ${проверка.причина}`);
  return {
    изображение: { данные: данные.slice(), формат },
    язык,
    параметры: JSON.parse(JSON.stringify(параметры)),
  };
}

// ---------------------------------------------------------------------------
// РАЗБОР ОТВЕТА МОДЕЛИ. Строгий. Пустой текст — ВАЛИДЕН (чистый лист честно
// распознаётся пустотой, в отличие от речи). Границы объёма названы.
// ---------------------------------------------------------------------------
export function разобратьОтвет(ответ) {
  if (!ответ || typeof ответ !== 'object' || Array.isArray(ответ)) {
    throw new TypeError(`ocr-adapter: разобратьОтвет — ответ ожидается конвертом, получено ${JSON.stringify(ответ ?? null)}`);
  }
  if (typeof ответ.отказ === 'string' && ответ.отказ) {
    throw new TypeError(`ocr-adapter: модель отказалась — ${ответ.отказ}`);
  }
  if (typeof ответ.текст !== 'string') {
    throw new TypeError(`ocr-adapter: в конверте нет строки «текст» (пустой текст — валиден, отсутствие — нет)`);
  }
  if (ответ.текст.length > МАКС_СИМВОЛОВ) {
    throw new TypeError(`ocr-adapter: текст ${ответ.текст.length} символов — больше ${МАКС_СИМВОЛОВ}`);
  }
  if (ответ.строки !== undefined) {
    if (!Array.isArray(ответ.строки)) {
      throw new TypeError('ocr-adapter: «строки» ожидается массивом строк или отсутствовать');
    }
    if (ответ.строки.length > МАКС_СТРОК) {
      throw new TypeError(`ocr-adapter: строк ${ответ.строки.length} — больше ${МАКС_СТРОК}`);
    }
    for (let i = 0; i < ответ.строки.length; i++) {
      if (typeof ответ.строки[i] !== 'string') {
        throw new TypeError(`ocr-adapter: строки[${i}] ожидается строкой`);
      }
    }
  }
  const язык = ответ.язык === undefined ? 'auto' : ответ.язык;
  if (язык !== 'auto' && (typeof язык !== 'string' || !ПАТТЕРН_ЯЗЫКА.test(язык))) {
    throw new TypeError(`ocr-adapter: язык ответа "${String(язык)}" не читается`);
  }
  return {
    текст: ответ.текст,
    строки: ответ.строки === undefined ? null : ответ.строки,
    язык,
  };
}

// ---------------------------------------------------------------------------
// РЕГИСТРАЦИЯ МОДЕЛИ. Честный true/false; веса — all-or-nothing.
// ---------------------------------------------------------------------------
export function registerOcrModel(описание) {
  if (!описание || typeof описание !== 'object' || Array.isArray(описание)) return false;
  const { id, runner, веса, движок } = описание;
  if (!id || typeof id !== 'string' || !ПАТТЕРН_ID.test(id)) return false;
  if (typeof runner !== 'function') return false;
  if (движок !== undefined && (typeof движок !== 'string' || !движок)) return false;

  let пин = null;
  if (веса !== undefined) {
    if (!веса || typeof веса !== 'object' || Array.isArray(веса)) return false;
    if (typeof веса.имя !== 'string' || !веса.имя) return false;
    if (typeof веса.sha256 !== 'string' || !ПАТТЕРН_ХЭША.test(веса.sha256)) return false;
    if (typeof веса.байт !== 'number' || !Number.isInteger(веса.байт) || веса.байт <= 0) return false;
    if (typeof веса.частей !== 'number' || !Number.isInteger(веса.частей) || веса.частей <= 0) return false;
    пин = { имя: веса.имя, sha256: веса.sha256.toLowerCase(), байт: веса.байт, частей: веса.частей };
  }

  if (ledger.has(id)) return false; // дубликат id — честный false
  ledger.set(id, {
    имя: `ocr/${id}`,
    runner,
    веса: пин,
    движок: движок === undefined ? 'не назван (EXPERIMENTAL)' : движок,
  });
  return true;
}

// ---------------------------------------------------------------------------
// СКЛЕЙКА ЧАСТЕЙ И ПИН. Та же механика, что speech.mjs (копия сознательна —
// самодостаточность адаптера; вектор SHA-256("abc") держат обе копии).
// crypto.subtle асинхронен — это фаза приведения двигателя, ВНЕ синхронного
// контрактного цикла.
// ---------------------------------------------------------------------------
export async function склеитьЧасти(части) {
  if (!Array.isArray(части) || части.length === 0) {
    throw new TypeError('ocr-adapter: склеитьЧасти — ожидается непустой массив частей');
  }
  let всего = 0;
  for (const ч of части) {
    const тип = Object.prototype.toString.call(ч);
    if (тип !== '[object Uint8Array]') {
      throw new TypeError(`ocr-adapter: склеитьЧасти — часть ожидается Uint8Array, получено ${тип}`);
    }
    if (ч.length === 0) {
      throw new TypeError('ocr-adapter: склеитьЧасти — часть пуста (0 байт): раскрой не может давать пустые части, честный отказ');
    }
    всего += ч.length;
  }
  const цельное = new Uint8Array(всего);
  let офсет = 0;
  for (const ч of части) { цельное.set(ч, офсет); офсет += ч.length; }
  const хэш = await crypto.subtle.digest('SHA-256', цельное);
  const hex = [...new Uint8Array(хэш)].map((б) => б.toString(16).padStart(2, '0')).join('');
  return { данные: цельное, sha256: hex, байт: всего };
}

export async function сверитьПин(id, части) {
  const запись = ledger.get(id);
  if (!запись) return { ok: false, причина: `модель "${id}" не зарегистрирована` };
  if (!запись.веса) return { ok: false, причина: `модель "${id}" без pinned-хэша — сверять нечем (честно EXPERIMENTAL)` };
  let склейка;
  try {
    склейка = await склеитьЧасти(части);
  } catch (ошибка) {
    return { ok: false, причина: `склейка не сошлась — ${ошибка && ошибка.message ? ошибка.message : String(ошибка)}` };
  }
  if (склейка.sha256 !== запись.веса.sha256) {
    return { ok: false, причина: `SHA-256 частей (${склейка.sha256.slice(0, 12)}…) не сошёлся с пином (${запись.веса.sha256.slice(0, 12)}…) — данные не выдаются` };
  }
  return { ok: true, данные: склейка.данные, sha256: склейка.sha256, байт: склейка.байт };
}

// ---------------------------------------------------------------------------
// ЧЕСТНЫЙ МОК. Всегда отказ с названной причиной; детерминизм даже в отказе.
// ---------------------------------------------------------------------------
export const ПРИЧИНА_МОКА = 'МОК ocr: модели нет в доме — мок не притворяется читать картинки (закон честности)';
export function mockRunner() {
  return function mockOcr() { return { отказ: ПРИЧИНА_МОКА }; };
}

// ---------------------------------------------------------------------------
// ДВЕРЬ РАСПОЗНАВАНИЯ (синхронная, над замороженным ответом). Одна модель в
// ledger — она; несколько — id обязателен; бросок runner'а — отказ в конверте.
// ---------------------------------------------------------------------------
export function распознать(задание, idМодели) {
  const проверка = валидироватьЗадание(задание);
  if (!проверка.ok) return { отказ: проверка.причина };
  if (ledger.size === 0) {
    return { отказ: 'в ledger нет ни одной модели — сначала registerOcrModel (модель у владельца, ЛЮК_ВЕСОВ_OCR.md)' };
  }
  if (idМодели === undefined && ledger.size > 1) {
    return { отказ: `в ledger ${ledger.size} моделей — назовите id честно, дом не выбирает за человека` };
  }
  const id = idМодели === undefined ? [...ledger.keys()][0] : idМодели;
  const запись = ledger.get(id);
  if (!запись) return { отказ: `модель "${id}" не зарегистрирована` };
  try {
    const конверт = создатьЗадание({
      данные: задание.изображение.данные,
      формат: задание.изображение.формат,
      язык: задание.язык,
      параметры: задание.параметры,
    });
    const ответ = запись.runner(конверт);
    return разобратьОтвет(ответ);
  } catch (ошибка) {
    const текст = ошибка && ошибка.message ? ошибка.message : String(ошибка);
    return { отказ: текст };
  }
}

// ---------------------------------------------------------------------------
// АДАПТЕР ДЛЯ РЕЕСТРА (AdapterRegistry). Тот же id, что у контрактной заглушки
// ('input.ocr'); статус живёт по ledger: пусто/без пина — EXPERIMENTAL честно,
// есть пин — READY. privacy local — картинка не покидает устройство.
// ---------------------------------------------------------------------------
export function createOcrAdapter() {
  return {
    id: ADAPTER_ID,
    kind: 'input',
    priority: 30,
    status() {
      const модели = списокМоделей();
      if (модели.length === 0) {
        return {
          state: STATUS.EXPERIMENTAL,
          privacy: 'local',
          reason: 'contract present, no model registered: модель у владельца (ЛЮК_ВЕСОВ_OCR.md), до пина честно EXPERIMENTAL',
        };
      }
      const запиненные = модели.filter((м) => м.веса);
      if (запиненные.length > 0) {
        return {
          state: STATUS.READY,
          privacy: 'local',
          reason: `pinned: ${запиненные.map((м) => м.id).join(', ')}`,
        };
      }
      return {
        state: STATUS.EXPERIMENTAL,
        privacy: 'local',
        reason: `модели без пина: ${модели.map((м) => м.id).join(', ')} — честно EXPERIMENTAL`,
      };
    },
    распознать(задание, id) { return распознать(задание, id); },
  };
}
