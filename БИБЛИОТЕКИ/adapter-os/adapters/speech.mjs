// speech.mjs — СИНГУЛЯР·ADAPTER-OS, такт v10.94 «ГОЛОС» (С70), строка А3, шаг 1.
//
// ПРИОРИТЕТ ВЛАДЕЛЬЦА (2026-10-13): «1) локальный Whisper (речь — ядро), 2) OCR,
// 3) gaze, 4) Demucs, 5) Брайль — последним: аудитория узкая, а работы много».
// Этот файл — ШАГ 1: контракт input.whisper-local из contracts.mjs получает
// реализацию-дверь: ledger с пиннинтом весов, строгий разбор сегментов,
// честный мок и дверь распознавания. Голос — ядро дома: речь клиента не
// покидает устройство, 0 сети — закон приватности, не украшение.
//
// ЗАКОН ЧЕСТНОСТИ (родня open-model-adapter.mjs): весов Whisper в доме нет
// (правда платформы: файл ≤100 МБ, Pages ≤1 ГБ) — адаптер не тащит, не качает
// и не запускает веса. Модель живёт ЛОКАЛЬНО у владельца (лук весов:
// docs — ЛЮК_ВЕСОВ_WHISPER.md, части ≤100 МБ кладутся в репу весов
// singulyar-llm) и приходит в адаптер готовой — через runner по контракту
// ниже. До pinned-хэша статус модели — EXPERIMENTAL, честно (критерий А3:
// «модель пинится и проходит контрактные тесты»; слова «проверено» без пина
// не существует).
//
// КОНТРАКТ RUNNER (синхронный, чистый; тот же дух, что ladom.open-model.v1):
//   runner(задание) → { сегменты: [{начало, конец, текст}…], язык: строка }
//                   | { отказ: причина }
//   задание = { аудио: { данные: Float32Array|Int16Array, частота: число },
//               язык: строка|'auto', параметры: объект }
//   - детерминированный: одно аудио → один ответ, байт-в-байт;
//   - 0 сети: runner ничего не качает — веса уже локальны;
//   - асинхронные рантаймы (whisper.cpp→wasm, transformers.js, локальный
//     сервер вывода) гоняются ЗА пределами синхронного цикла и приносят
//     «замороженный ответ»: runner = () => ({ сегменты: …, язык: … }).
//   Нет runner'а — нет модели: адаптер не выдумывает текст за Whisper.
//
// ПИН ВЕСОВ (закрытие А3 «модель пинится»): владелец раскраивает ggml-файл
// на части ≤100 МБ (tools/раскрой_весов.py), SHA-256 целого файла входит в
// ledger при registerWhisperModel({ веса: { sha256, байт, частей, имя } }).
// Загрузчик склеивает части и сверит SHA-256 через crypto.subtle: расхождение
// — честный отказ, склейка не выдаётся. crypto.subtle асинхронен по природе
// платформы — пин живёт в загрузчике (фаза приведения двигателя), синхронный
// контракт runner'а не ломается.
//
// Честные границы:
//   - адаптер не калибрует тайминги и не чинит их молча: сегменты с бедой —
//     честный отказ парсера (ничего не «улучшается» на лету);
//   - язык приходит как назвал runner: дом не угадывает язык за моделью;
//   - мок (mockRunner) НЕ притворяется распознаванием: всегда честный отказ
//     с названной причиной — дверь тестируема, совесть цела;
//   - возвращённые из ledger записи — копии: снаружи ledger не подменить.
//
// Экспорт: только ESM; импорт — ровно один, канон дома: ../src/core.mjs (STATUS).

import { STATUS } from '../src/core.mjs';

export const ver = 'speech-adapter/0.1';
export const LEDGER_SCHEMA = 'adapter-os.speech.v1';
export const ADAPTER_ID = 'input.whisper-local';

// Паттерн id модели: буквы/цифры Unicode (дом говорит и по-русски) плюс точка,
// подчёркивание, дефис — имя 'whisper/<id>' читается однозначно.
const ПАТТЕРН_ID = /^[\p{L}\p{N}][\p{L}\p{N}._-]*$/u;
// pinned-хэш — sha256 в шестнадцатеричном виде (64 знака); обещание пиннинга
// обязано быть проверяемой строкой, а не словом.
const ПАТТЕРН_ХЭША = /^[0-9a-f]{64}$/i;
// Язык распознавания: буквы/цифры Юникода, возможно с одним дефисом-составом
// (ru, sr, kk, de, zh-Hans, sr-Latn) — дом не ограничивает хозяина языка.
const ПАТТЕРН_ЯЗЫКА = /^[\p{L}\p{N}]{2,8}(-[\p{L}\p{N}]{2,8})*$/u;
// Честная граница объёма: сегментов не больше МАКС_СЕГМЕНТОВ (час аудиокниги
// с плотными репликами укладывается; больше — повод честно отказать и спросить,
// зачем в доме полчаса тишины подряд).
export const МАКС_СЕГМЕНТОВ = 4096;

// ---------------------------------------------------------------------------
// LEDGER моделей. На импорте пуст — моделей в доме нет, и это честно.
// ---------------------------------------------------------------------------
const ledger = new Map();

export function списокМоделей() {
  return [...ledger.keys()].sort().map((id) => {
    const запись = ledger.get(id);
    const веса = запись.веса;
    return {
      id,
      имя: запись.имя,
      движок: запись.движок,
      веса: веса
        ? { имя: веса.имя, sha256: веса.sha256.toLowerCase(), байт: веса.байт, частей: веса.частей }
        : null,
      статус: веса
        ? `pinned sha256:${веса.sha256.toLowerCase()}`
        : 'EXPERIMENTAL: без pinned-хэша — модель владельца, дом не проверял веса',
    };
  });
}

// ---------------------------------------------------------------------------
// ВАЛИДАЦИЯ ЗАДАНИЯ. Аудио — typed array (Float32/Int16), частота — конечное
// положительное число, язык — по паттерну или 'auto'. Вход не мутируется:
// создатьЗадание отдаёт копию данных (slice), наружу TypedArray не живёт.
// ---------------------------------------------------------------------------
export function валидироватьЗадание(задание) {
  if (!задание || typeof задание !== 'object' || Array.isArray(задание)) {
    return { ok: false, причина: 'задание ожидается объектом' };
  }
  const аудио = задание.аудио;
  if (!аудио || typeof аудио !== 'object' || Array.isArray(аудио)) {
    return { ok: false, причина: 'задание.аудио ожидается объектом' };
  }
  const данные = аудио.данные;
  const тип = Object.prototype.toString.call(данные);
  if (тип !== '[object Float32Array]' && тип !== '[object Int16Array]') {
    return { ok: false, причина: `аудио.данные ожидаются Float32Array|Int16Array, получено ${тип}` };
  }
  if (данные.length === 0) {
    return { ok: false, причина: 'аудио.данные пусты — распознавать нечего, честный отказ' };
  }
  const частота = аудио.частота;
  if (typeof частота !== 'number' || !Number.isFinite(частота) || частота <= 0) {
    return { ok: false, причина: 'аудио.частота ожидается конечным положительным числом' };
  }
  const язык = задание.язык === undefined ? 'auto' : задание.язык;
  if (язык !== 'auto' && (typeof язык !== 'string' || !ПАТТЕРН_ЯЗЫКА.test(язык))) {
    return { ok: false, причина: `язык "${String(язык)}" не читается (паттерн ${ПАТТЕРН_ЯЗЫКА} или 'auto')` };
  }
  if (задание.параметры !== undefined && (typeof задание.параметры !== 'object' || задание.параметры === null || Array.isArray(задание.параметры))) {
    return { ok: false, причина: 'задание.параметры ожидается объектом или отсутствовать' };
  }
  return { ok: true };
}

// Готовит конверт задания для runner'а: валидация + копия данных (вход не
// мутируется и не шарится). Детерминирован по построению.
export function создатьЗадание({ данные, частота, язык = 'auto', параметры = {} }) {
  const проверка = валидироватьЗадание({ аудио: { данные, частота }, язык, параметры });
  if (!проверка.ok) throw new TypeError(`speech-adapter: создатьЗадание — ${проверка.причина}`);
  return {
    аудио: { данные: данные.slice(), частота },
    язык,
    параметры: JSON.parse(JSON.stringify(параметры)),
  };
}

// ---------------------------------------------------------------------------
// РАЗБОР ОТВЕТА МОДЕЛИ. Строгий: один формат, никакого угадывания, ничего
// не чинится молча. Сегменты обязаны идти по времени строго вверх, без
// наложений; пустые реплики — отказ (runner не должен их слать).
// Беда — честный TypeError (дверь распознавания завернёт в отказ).
// ---------------------------------------------------------------------------
export function разобратьОтвет(ответ) {
  if (!ответ || typeof ответ !== 'object' || Array.isArray(ответ)) {
    throw new TypeError(`speech-adapter: разобратьОтвет — ответ ожидается конвертом, получено ${JSON.stringify(ответ ?? null)}`);
  }
  if (typeof ответ.отказ === 'string' && ответ.отказ) {
    throw new TypeError(`speech-adapter: модель отказалась — ${ответ.отказ}`);
  }
  if (!Array.isArray(ответ.сегменты)) {
    throw new TypeError('speech-adapter: в конверте нет массива «сегменты»');
  }
  if (ответ.сегменты.length > МАКС_СЕГМЕНТОВ) {
    throw new TypeError(`speech-adapter: сегментов ${ответ.сегменты.length} — больше ${МАКС_СЕГМЕНТОВ}`);
  }
  const язык = ответ.язык === undefined ? 'auto' : ответ.язык;
  if (язык !== 'auto' && (typeof язык !== 'string' || !ПАТТЕРН_ЯЗЫКА.test(язык))) {
    throw new TypeError(`speech-adapter: язык ответа "${String(язык)}" не читается`);
  }
  const сегменты = [];
  let прежнийКонец = -1;
  for (let i = 0; i < ответ.сегменты.length; i++) {
    const s = ответ.сегменты[i];
    const где = `сегменты[${i}]`;
    if (!s || typeof s !== 'object' || Array.isArray(s)) {
      throw new TypeError(`speech-adapter: ${где} ожидается объектом`);
    }
    const { начало, конец, текст } = s;
    if (typeof начало !== 'number' || !Number.isFinite(начало) || начало < 0) {
      throw new TypeError(`speech-adapter: ${где}.начало ожидается неотрицательным числом`);
    }
    if (typeof конец !== 'number' || !Number.isFinite(конец) || конец <= начало) {
      throw new TypeError(`speech-adapter: ${где}.конец ожидается числом больше начала`);
    }
    if (typeof текст !== 'string' || текст.trim() === '') {
      throw new TypeError(`speech-adapter: ${где}.текст ожидается непустой строкой`);
    }
    if (начало < прежнийКонец) {
      throw new TypeError(`speech-adapter: ${где} наложился на предыдущий (начало ${начало} < конец ${прежнийКонец}) — время не чинится молча`);
    }
    // Порядок «строго вверх» отдельной веткой не проверяется: при enforced
    // конец>начало наложение выше полностью покрывает нарушение порядка —
    // мёртвой ветки в доме не держим (доказано тестом).
    прежнийКонец = конец;
    сегменты.push({ начало, конец, текст });
  }
  return { сегменты, язык };
}

// ---------------------------------------------------------------------------
// РЕГИСТРАЦИЯ МОДЕЛИ. Честный true/false, не бросок (как registerOpenModel).
// веса — all-or-nothing: частичная запись пина (хэш без размера и т.п.)
// отклоняется целиком, полупиннинг запрещён.
// ---------------------------------------------------------------------------
export function registerWhisperModel(описание) {
  if (!описание || typeof описание !== 'object' || Array.isArray(описание)) return false;
  const { id, runner, веса, движок } = описание;
  if (!id || typeof id !== 'string' || !ПАТТЕРН_ID.test(id)) return false;
  if (typeof runner !== 'function') return false;
  if (движок !== undefined && (typeof движок !== 'string' || !движок)) return false;

  let пин = null;
  if (веса !== undefined) {
    if (!веса || typeof веса !== 'object' || Array.isArray(веса)) return false;
    if (typeof веса.имя !== 'string' || !веса.имя) return false;
    if (typeof веса.sha256 !== 'string' || !ПАТТЕРН_ХЭША.test(веса.sha256)) return false;
    if (typeof веса.байт !== 'number' || !Number.isInteger(веса.байт) || веса.байт <= 0) return false;
    if (typeof веса.частей !== 'number' || !Number.isInteger(веса.частей) || веса.частей <= 0) return false;
    пин = { имя: веса.имя, sha256: веса.sha256.toLowerCase(), байт: веса.байт, частей: веса.частей };
  }

  if (ledger.has(id)) return false; // дубликат id — честный false
  ledger.set(id, {
    имя: `whisper/${id}`,
    runner,
    веса: пин,
    движок: движок === undefined ? 'не назван (EXPERIMENTAL)' : движок,
  });
  return true;
}

// ---------------------------------------------------------------------------
// СКЛЕЙКА ЧАСТЕЙ И ПИН. crypto.subtle асинхронен — это фаза приведения
// двигателя (грузим части из кеша браузера/репы весов, склеиваем, сверим
// хэш), ВНЕ синхронного контрактного цикла. Расхождение хэша — честный
// отказ: склейка не выдаётся даже на байт.
// ---------------------------------------------------------------------------
export async function склеитьЧасти(части) {
  if (!Array.isArray(части) || части.length === 0) {
    throw new TypeError('speech-adapter: склеитьЧасти — ожидается непустой массив частей');
  }
  let всего = 0;
  for (const ч of части) {
    const тип = Object.prototype.toString.call(ч);
    if (тип !== '[object Uint8Array]') {
      throw new TypeError(`speech-adapter: склеитьЧасти — часть ожидается Uint8Array, получено ${тип}`);
    }
    if (ч.length === 0) {
      throw new TypeError('speech-adapter: склеитьЧасти — часть пуста (0 байт): раскрой не может давать пустые части, честный отказ');
    }
    всего += ч.length;
  }
  const цельное = new Uint8Array(всего);
  let офсет = 0;
  for (const ч of части) { цельное.set(ч, офсет); офсет += ч.length; }
  const хэш = await crypto.subtle.digest('SHA-256', цельное);
  const hex = [...new Uint8Array(хэш)].map((б) => б.toString(16).padStart(2, '0')).join('');
  return { данные: цельное, sha256: hex, байт: всего };
}

// Пин по id из ledger: склеить, сверить, отдать данные только при схождении.
export async function сверитьПин(id, части) {
  const запись = ledger.get(id);
  if (!запись) return { ok: false, причина: `модель "${id}" не зарегистрирована` };
  if (!запись.веса) return { ok: false, причина: `модель "${id}" без pinned-хэша — сверять нечем (честно EXPERIMENTAL)` };
  let склейка;
  try {
    склейка = await склеитьЧасти(части);
  } catch (ошибка) {
    return { ok: false, причина: `склейка не сошлась — ${ошибка && ошибка.message ? ошибка.message : String(ошибка)}` };
  }
  if (склейка.sha256 !== запись.веса.sha256) {
    return { ok: false, причина: `SHA-256 частей (${склейка.sha256.slice(0, 12)}…) не сошёлся с пином (${запись.веса.sha256.slice(0, 12)}…) — данные не выдаются` };
  }
  return { ok: true, данные: склейка.данные, sha256: склейка.sha256, байт: склейка.байт };
}

// ---------------------------------------------------------------------------
// ЧЕСТНЫЙ МОК. Всегда отказ с названной причиной: мок не распознаёт голос
// и не делает вид. Причина — константа: детерминизм даже в отказе.
// ---------------------------------------------------------------------------
export const ПРИЧИНА_МОКА = 'МОК whisper: весов нет в доме — мок не притворяется распознавать голос (закон честности)';
export function mockRunner() {
  return function mockWhisper() { return { отказ: ПРИЧИНА_МОКА }; };
}

// ---------------------------------------------------------------------------
// ДВЕРЬ РАСПОЗНАВАНИЯ (синхронная, над замороженным ответом). Валидирует
// задание, зовёт runner модели (одна в ledger — она; несколько — id обязателен:
// дом не выбирает за человека), строго разбирает ответ. Никогда не бросает
// наружу: беда — честный отказ в конверте { отказ }.
// ---------------------------------------------------------------------------
export function распознать(задание, idМодели) {
  const проверка = валидироватьЗадание(задание);
  if (!проверка.ok) return { отказ: проверка.причина };
  if (ledger.size === 0) {
    return { отказ: 'в ledger нет ни одной модели — сначала registerWhisperModel (веса у владельца, ЛЮК_ВЕСОВ_WHISPER.md)' };
  }
  if (idМодели === undefined && ledger.size > 1) {
    return { отказ: `в ledger ${ledger.size} моделей — назовите id честно, дом не выбирает за человека` };
  }
  const id = idМодели === undefined ? [...ledger.keys()][0] : idМодели;
  const запись = ledger.get(id);
  if (!запись) return { отказ: `модель "${id}" не зарегистрирована` };
  try {
    const конверт = создатьЗадание({
      данные: задание.аудио.данные,
      частота: задание.аудио.частота,
      язык: задание.язык,
      параметры: задание.параметры,
    });
    const ответ = запись.runner(конверт);
    return разобратьОтвет(ответ);
  } catch (ошибка) {
    const текст = ошибка && ошибка.message ? ошибка.message : String(ошибка);
    return { отказ: текст };
  }
}

// ---------------------------------------------------------------------------
// АДАПТЕР ДЛЯ РЕЕСТРА (AdapterRegistry). Тот же id, что у контрактной заглушки
// из contracts.mjs ('input.whisper-local'), но статус живёт по ledger: есть
// пин — READY+pinned, есть модель без пина — EXPERIMENTAL честно, пусто —
// EXPERIMENTAL честно. Реестр дома получает одну правду вместо двух.
// ---------------------------------------------------------------------------
export function createSpeechAdapter() {
  return {
    id: ADAPTER_ID,
    kind: 'input',
    priority: 30,
    status() {
      const модели = списокМоделей();
      if (модели.length === 0) {
        return {
          state: STATUS.EXPERIMENTAL,
          privacy: 'local',
          reason: 'contract present, no model registered: веса у владельца (ЛЮК_ВЕСОВ_WHISPER.md), до пина честно EXPERIMENTAL',
        };
      }
      const запиненные = модели.filter((м) => м.веса);
      if (запиненные.length > 0) {
        return {
          state: STATUS.READY,
          privacy: 'local',
          reason: `pinned: ${запиненные.map((м) => м.id).join(', ')}`,
        };
      }
      return {
        state: STATUS.EXPERIMENTAL,
        privacy: 'local',
        reason: `модели без пина: ${модели.map((м) => м.id).join(', ')} — честно EXPERIMENTAL`,
      };
    },
    распознать(задание, id) { return распознать(задание, id); },
  };
}
