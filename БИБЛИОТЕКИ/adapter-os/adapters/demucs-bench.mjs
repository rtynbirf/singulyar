// demucs-bench.mjs — СИНГУЛЯР·ADAPTER-OS, такт v10.99 «МИНУС» (С75), строка А3:
// бенчмарк локального Demucs — SDR стемов против размеченного корпуса.
//
// Требование карты А3: «бенчмарки (ledger трека)». Родня speech-bench.mjs
// (WER/CER текста), ocr-bench.mjs (CER + точность строк) и gaze-bench.mjs
// (евклид + допуск) мерит СВОЁ — разделению звука честная мера одна: SDR,
// signal-to-distortion ratio: 10·log10(||эталон||² / ||эталон − оценка||²).
// Здесь — классический SDR БЕЗ выравнивания (bss_eval делает выравнивание
// фильтра; мы его не делаем — граница названа честно, протокол детерминирован).
//
// Честные границы:
//   - метрики считаются ТОЛЬКО по корпусу с эталонными стемами владельца;
//     мок бегать может, но протокол честно помечает отказы — SDR не
//     выдумывается;
//   - идеальная сходимость (оценка = эталону) НЕ пишется как Infinity:
//     JSON.stringify(Infinity) молча дал бы null — грех подмены; честно
//     названо полем сходимость, число не выдумывается;
//   - тишина в эталоне (||эталон||² = 0) — SDR не определён, честно названо
//     «не мера», а не выдуманное число;
//   - рмс/пик оценок считаются независимо от SDR — энергопрофиль назван
//     даже там, где SDR не мера;
//   - тайминги устройства измеряет запускающий снаружи; внутри 0 часов;
//   - протокол детерминирован байт-в-байт: один прогон → один JSON.
//
// Экспорт: только ESM; импортов нет (самодостаточен, 0 зависимостей; канон
// стемов продублирован сознательно — расхождение копий ловят тесты).

export const ver = 'demucs-bench/0.1';
export const LEDGER_SCHEMA = 'adapter-os.demucs.bench.v1';
export const СТЕМЫ = Object.freeze(['vocals', 'drums', 'bass', 'other']);

// Нормализация отсчётов: Float32Array | массив конечных чисел → Float32Array,
// иначе причина отказа строкой (своя копия дисциплины demucs.mjs).
function нормализовать(имя, значение) {
  const тип = Object.prototype.toString.call(значение);
  if (тип === '[object Float32Array]') {
    if (значение.length === 0) return `${имя} пуст (0 отсчётов)`;
    for (let i = 0; i < значение.length; i++) {
      if (!Number.isFinite(значение[i])) return `${имя}[${i}] — не конечное число`;
    }
    return new Float32Array(значение);
  }
  if (Array.isArray(значение)) {
    if (значение.length === 0) return `${имя} пуст (0 отсчётов)`;
    const копия = new Float32Array(значение.length);
    for (let i = 0; i < значение.length; i++) {
      if (!Number.isFinite(значение[i])) return `${имя}[${i}] — не конечное число`;
      копия[i] = значение[i];
    }
    return копия;
  }
  return `${имя} ожидается Float32Array или массивом конечных чисел, получено ${тип}`;
}

// ||x||² — сумма квадратов. Чисто, без часов.
export function энергия(отсчёты) {
  const норма = нормализовать('энергия', отсчёты);
  if (typeof норма === 'string') throw new TypeError(`demucs-bench: энергия — ${норма}`);
  let с = 0;
  for (let i = 0; i < норма.length; i++) с += норма[i] * норма[i];
  return с;
}

// RMS. Чисто, без часов.
export function рмс(отсчёты) {
  const норма = нормализовать('рмс', отсчёты);
  if (typeof норма === 'string') throw new TypeError(`demucs-bench: рмс — ${норма}`);
  let с = 0;
  for (let i = 0; i < норма.length; i++) с += норма[i] * норма[i];
  return Math.sqrt(с / норма.length);
}

// SDR без выравнивания: 10·log10(||эталон||² / ||эталон − оценка||²).
// Идеальная сходимость и тишина эталона НЕ дают выдуманных чисел: поля
// sdr_дБ = null + названная сходимость/причина.
export function sdrБезВыравнивания(эталон, оценка) {
  const э = нормализовать('эталон', эталон);
  if (typeof э === 'string') throw new TypeError(`demucs-bench: sdrБезВыравнивания — ${э}`);
  const о = нормализовать('оценка', оценка);
  if (typeof о === 'string') throw new TypeError(`demucs-bench: sdrБезВыравнивания — ${о}`);
  if (о.length !== э.length) {
    throw new TypeError(`demucs-bench: sdrБезВыравнивания — длины не сошлись (эталон ${э.length}, оценка ${о.length})`);
  }
  let эталон2 = 0, ошибка2 = 0;
  for (let i = 0; i < э.length; i++) {
    эталон2 += э[i] * э[i];
    const разность = о[i] - э[i];
    ошибка2 += разность * разность;
  }
  if (ошибка2 === 0) {
    return { sdr_дБ: null, сходимость: эталон2 === 0 ? 'идеальная: обе тишины' : 'идеальная: оценка = эталону (0 искажений)' };
  }
  if (эталон2 === 0) {
    return { sdr_дБ: null, причина_не_меры: 'тишина в эталоне: SDR от тишины не считается честно' };
  }
  return { sdr_дБ: 10 * Math.log10(эталон2 / ошибка2), сходимость: null, причина_не_меры: null };
}

// Стем из ответа runner'а. Отказ/мусор → null (с причиной, ошибка не
// выдумывается).
export function стемОтветаDemucs(ответ, имяСтема) {
  if (!ответ || typeof ответ !== 'object' || Array.isArray(ответ)) return { стем: null, причина: 'ответ не конверт' };
  if (typeof ответ.отказ === 'string' && ответ.отказ) return { стем: null, причина: ответ.отказ };
  const стемы = ответ.стемы;
  if (!стемы || typeof стемы !== 'object' || Array.isArray(стемы)) return { стем: null, причина: 'в конверте нет объекта «стемы»' };
  if (!(имяСтема in стемы)) return { стем: null, причина: `нет стема "${имяСтема}" в ответе` };
  const норма = нормализовать(`стемы.${имяСтема}`, стемы[имяСтема]);
  if (typeof норма === 'string') return { стем: null, причина: норма };
  return { стем: норма, причина: null };
}

// ---------------------------------------------------------------------------
// ПРОГОН БЕНЧМАРКА DEMUCS. Корпус: [{ id, эталоны: { vocals?, drums?, bass?,
// other? }, задание }]; runner — контракт demucs.mjs. Стемы без эталона
// честно помечены «не мера». Протокол детерминирован байт-в-байт (стемы идут
// по канону).
// ---------------------------------------------------------------------------
export function прогонБенчмаркаDemucs(runner, корпус) {
  if (typeof runner !== 'function') {
    throw new TypeError('demucs-bench: прогонБенчмаркаDemucs — runner ожидается функцией');
  }
  if (!Array.isArray(корпус) || корпус.length === 0) {
    throw new TypeError('demucs-bench: прогонБенчмаркаDemucs — корпус ожидается непустым массивом записей { id, эталоны, задание }');
  }
  const строки = [];
  let с_метрикой = 0, с_отказом = 0, без_эталона = 0, идеальных = 0;
  const sdrЧисла = [];
  for (let i = 0; i < корпус.length; i++) {
    const запись = корпус[i];
    const где = `корпус[${i}]`;
    if (!запись || typeof запись !== 'object' || Array.isArray(запись)) {
      throw new TypeError(`demucs-bench: ${где} ожидается объектом`);
    }
    if (typeof запись.id !== 'string' || !запись.id) {
      throw new TypeError(`demucs-bench: ${где}.id ожидается непустой строкой`);
    }
    const эталоны = запись.эталоны;
    if (!эталоны || typeof эталоны !== 'object' || Array.isArray(эталоны)) {
      throw new TypeError(`demucs-bench: ${где}.эталоны ожидается объектом { vocals, drums, bass, other }`);
    }
    let ответ;
    try {
      ответ = runner(запись.задание);
    } catch (ошибка) {
      ответ = { отказ: ошибка && ошибка.message ? ошибка.message : String(ошибка) };
    }
    for (const имя of СТЕМЫ) {
      const эталон = эталоны[имя];
      const нормаЭталона = эталон === undefined || эталон === null
        ? null
        : нормализовать(`эталоны.${имя}`, эталон);
      if (нормаЭталона === null || typeof нормаЭталона === 'string') {
        без_эталона += 1;
        const { стем } = стемОтветаDemucs(ответ, имя);
        const рмсОценки = стем ? рмс(стем) : null;
        строки.push({
          id: запись.id, стем: имя,
          sdr_дБ: null, сходимость: null,
          причина_не_меры: нормаЭталона === null ? 'эталон не назван владельцем' : нормаЭталона,
          отказ: null, рмс_оценки: рмсОценки,
        });
        continue;
      }
      const { стем, причина } = стемОтветаDemucs(ответ, имя);
      if (стем === null) {
        с_отказом += 1;
        строки.push({
          id: запись.id, стем: имя,
          sdr_дБ: null, сходимость: null,
          причина_не_меры: null,
          отказ: причина, рмс_оценки: null,
        });
        continue;
      }
      if (стем.length !== нормаЭталона.length) {
        с_отказом += 1;
        строки.push({
          id: запись.id, стем: имя,
          sdr_дБ: null, сходимость: null,
          причина_не_меры: `длины не сошлись (эталон ${нормаЭталона.length}, стем ${стем.length})`,
          отказ: null, рмс_оценки: рмс(стем),
        });
        continue;
      }
      const мера = sdrБезВыравнивания(нормаЭталона, стем);
      if (мера.sdr_дБ === null && мера.сходимость !== null) идеальных += 1;
      if (мера.sdr_дБ !== null) {
        с_метрикой += 1;
        sdrЧисла.push(мера.sdr_дБ);
      }
      строки.push({
        id: запись.id, стем: имя,
        sdr_дБ: мера.sdr_дБ,
        сходимость: мера.сходимость,
        причина_не_меры: мера.причина_не_меры,
        отказ: null, рмс_оценки: рмс(стем),
      });
    }
  }
  const отсечено = с_отказом + без_эталона;
  return {
    схема: LEDGER_SCHEMA,
    выравнивание: 'нет (SDR без выравнивания; bss_eval не притворяется)',
    записей: корпус.length,
    стемов_в_корпусе: корпус.length * 4,
    стемов_с_метрикой: с_метрикой,
    стемов_идеальных: идеальных,
    стемов_с_отказом: с_отказом,
    стемов_без_эталона: без_эталона,
    sdr_средний_дБ: с_метрикой === 0 ? null : sdrЧисла.reduce((a, b) => a + b, 0) / sdrЧисла.length,
    sdr_мин_дБ: с_метрикой === 0 ? null : Math.min(...sdrЧисла),
    sdr_макс_дБ: с_метрикой === 0 ? null : Math.max(...sdrЧисла),
    пометка: отсечено === корпус.length * 4
      ? 'ВСЕ СТЕМЫ БЕЗ МЕТРИК: это прогон мока/недоставленной модели, не мера качества (честно)'
      : 'метрики только по стемам с эталоном и разобранным ответом; SDR без выравнивания — граница названа; идеальная сходимость не пишется числом (Infinity в JSON — грех подмены)',
    строки,
  };
}
