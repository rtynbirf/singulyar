// speech-bench.mjs — СИНГУЛЯР·ADAPTER-OS, такт v10.94 «ГОЛОС» (С70), строка А3:
// бенчмарк локального Whisper — WER/CER против размеченного корпуса.
//
// КРИТЕРИЙ А3: «модель пинится и проходит контрактные тесты» + карта требует
// «бенчмарки (ledger трека)». Этот файл — измеритель: прогоняет runner по
// корпусу (id, эталон, задание), считает WER (по словам) и CER (по символам)
// и отдаёт детерминированный протокол без часов и случайности.
//
// Честные границы:
//   - метрики считаются ТОЛЬКО по размеченному корпусу владельца; мок бегать
//     по бенчмарку может, но протокол честно помечает, что распознанного
//     текста нет (отказ) — строка уходит с отказом, а не с выдуманным WER;
//   - тайминги устройства (мс на сегмент) измеряет запускающий снаружи
//     (performance.now) — внутрь протокола он пишет их сам; бенчмарк внутри
//     0 часов: один и тот же прогон — байт-в-байт один протокол;
//   - нормализация для метрик названа честно: нижний регистр, ё→е, пунктуация
//     прочь, сжатие пробелов; это договор мерила, а не подгонка ответа.
//
// Экспорт: только ESM; импортов нет (самодостаточен, 0 зависимостей).

export const ver = 'speech-bench/0.1';
export const LEDGER_SCHEMA = 'adapter-os.speech.bench.v1';

// ---------------------------------------------------------------------------
// НОРМАЛИЗАЦИЯ (договор мерила). Вход — строка, выход — массив слов.
// ---------------------------------------------------------------------------
export function нормализоватьСлова(текст) {
  if (typeof текст !== 'string') return [];
  const чисто = текст
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^\p{L}\p{N}\s]+/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  return чисто === '' ? [] : чисто.split(' ');
}

// Левенштейн по массивам токенов (слова или символы), DP без часов и мутаций
// входа. Классика: расстояние редактирования вставка/удаление/замена.
export function левенштейн(a, b) {
  const m = a.length, n = b.length;
  if (m === 0) return n;
  if (n === 0) return m;
  let прежний = new Array(n + 1);
  let текущий = new Array(n + 1);
  for (let j = 0; j <= n; j++) прежний[j] = j;
  for (let i = 1; i <= m; i++) {
    текущий[0] = i;
    for (let j = 1; j <= n; j++) {
      const цена = a[i - 1] === b[j - 1] ? 0 : 1;
      текущий[j] = Math.min(прежний[j] + 1, текущий[j - 1] + 1, прежний[j - 1] + цена);
    }
    [прежний, текущий] = [текущий, прежний];
  }
  return прежний[n];
}

// WER строки: редактор/слов эталона. Эталон пуст и получено пусто → 0.
// Эталон пуст, получено не пусто → 1 (названо честно, не деление на ноль).
export function верСтрока(эталон, получено) {
  const а = нормализоватьСлова(эталон);
  const б = нормализоватьСлова(получено);
  if (а.length === 0) return б.length === 0 ? 0 : 1;
  return левенштейн(а, б) / а.length;
}

// CER строки: то же по символам нормализованного текста.
export function церСтрока(эталон, получено) {
  const а = нормализоватьСлова(эталон).join(' ');
  const б = нормализоватьСлова(получено).join(' ');
  if (а.length === 0) return б.length === 0 ? 0 : 1;
  return левенштейн([...а], [...б]) / [...а].length;
}

// Текст ответа runner'а: склейка сегментов пробелом в порядке времени.
// Отказ → null (строка уходит с отказом, WER не выдумывается).
export function текстОтвета(ответ) {
  if (!ответ || typeof ответ !== 'object' || Array.isArray(ответ)) return null;
  if (typeof ответ.отказ === 'string' && ответ.отказ) return null;
  if (!Array.isArray(ответ.сегменты)) return null;
  const части = [];
  for (const s of ответ.сегменты) {
    if (!s || typeof s.текст !== 'string') return null;
    части.push(s.текст);
  }
  return части.join(' ');
}

// ---------------------------------------------------------------------------
// ПРОГОН БЕНЧМАРКА. Корпус: массив записей { id, эталон, задание } (задание —
// конверт для runner'а). Runner — тот же контракт, что у speech-adapter.
// Протокол детерминирован: один прогон — байт-в-байт один JSON.
// ---------------------------------------------------------------------------
export function прогонБенчмарка(runner, корпус) {
  if (typeof runner !== 'function') {
    throw new TypeError('speech-bench: прогонБенчмарка — runner ожидается функцией');
  }
  if (!Array.isArray(корпус) || корпус.length === 0) {
    throw new TypeError('speech-bench: прогонБенчмарка — корпус ожидается непустым массивом записей { id, эталон, задание }');
  }
  const строки = [];
  let сумма_вер = 0, сумма_цер = 0, счёт_метрик = 0, счёт_отказов = 0;
  for (let i = 0; i < корпус.length; i++) {
    const запись = корпус[i];
    const где = `корпус[${i}]`;
    if (!запись || typeof запись !== 'object' || Array.isArray(запись)) {
      throw new TypeError(`speech-bench: ${где} ожидается объектом`);
    }
    if (typeof запись.id !== 'string' || !запись.id) {
      throw new TypeError(`speech-bench: ${где}.id ожидается непустой строкой`);
    }
    if (typeof запись.эталон !== 'string') {
      throw new TypeError(`speech-bench: ${где}.эталон ожидается строкой (пустая — честный ноль)`);
    }
    let ответ;
    try {
      ответ = runner(запись.задание);
    } catch (ошибка) {
      ответ = { отказ: ошибка && ошибка.message ? ошибка.message : String(ошибка) };
    }
    const текст = текстОтвета(ответ);
    if (текст === null) {
      счёт_отказов += 1;
      const причина = ответ && typeof ответ.отказ === 'string' ? ответ.отказ : 'ответ runner\'а не разобран (не конверт)';
      строки.push({ id: запись.id, эталон: запись.эталон, распознано: null, вер: null, цер: null, отказ: причина });
      continue;
    }
    const вер = верСтрока(запись.эталон, текст);
    const цер = церСтрока(запись.эталон, текст);
    сумма_вер += вер; сумма_цер += цер; счёт_метрик += 1;
    строки.push({ id: запись.id, эталон: запись.эталон, распознано: текст, вер, цер, отказ: null });
  }
  return {
    схема: LEDGER_SCHEMA,
    строк_в_корпусе: корпус.length,
    строк_с_метрикой: счёт_метрик,
    строк_с_отказом: счёт_отказов,
    вер_среднее: счёт_метрик === 0 ? null : сумма_вер / счёт_метрик,
    цер_среднее: счёт_метрик === 0 ? null : сумма_цер / счёт_метрик,
    пометка: счёт_отказов === корпус.length
      ? 'ВСЕ СТРОКИ С ОТКАЗОМ: метрик нет — это прогон мока/недоставленных весов, не мера качества (честно)'
      : 'метрики только по строкам с распознанным текстом',
    строки,
  };
}
