// ---------------------------------------------------------------------------
// ДВЕРЬ ВЗГЛЯДА (синхронная, над замороженным ответом). Порядок честный и
// детерминированный: валидация входа → калибровка (обязательна — причина
// контракта) → соответствие (вырожденность ловится ДО вызова двигателя —
// не будим модель под заведомо мёртвой картой) → ledger → runner → разбор →
// проекция. Одна модель в ledger — она; несколько — id обязателен; бросок
// runner'а — отказ в конверте. Выход за экран — не отказ: честный флаг
// в_границах.
// ---------------------------------------------------------------------------
export function взгляд(задание, idМодели) {
  const проверка = валидироватьЗадание(задание);
  if (!проверка.ok) return { отказ: проверка.причина };
  if (задание.калибровка === undefined) {
    return { отказ: 'нет калибровки — черта кадра не является указателем экрана (контракт input.gaze: landmarks не calibrated gaze; соберите калибровку gaze-calib-affine/0.1)' };
  }
  let соответствие;
  try {
    соответствие = аффинноеСоответствие(задание.калибровка.точки);
  } catch (ошибка) {
    const текст = ошибка && ошибка.message ? ошибка.message : String(ошибка);
    return { отказ: текст };
  }
  if (ledger.size === 0) {
    return { отказ: 'в ledger нет ни одной модели — сначала registerGazeModel (модель у владельца, ЛЮК_ВЕСОВ_GAZE.md)' };
  }
  if (idМодели === undefined && ledger.size > 1) {
    return { отказ: `в ledger ${ledger.size} моделей — назовите id честно, дом не выбирает за человека` };
  }
  const id = idМодели === undefined ? [...ledger.keys()][0] : idМодели;
  const запись = ledger.get(id);
  if (!запись) return { отказ: `модель "${id}" не зарегистрирована` };
  let черта;
  try {
    const конверт = создатьЗадание({
      данные: задание.кадр.данные,
      формат: задание.кадр.формат,
      калибровка: задание.калибровка,
      параметры: задание.параметры,
    });
    const ответ = запись.runner(конверт);
    черта = разобратьОтвет(ответ);
  } catch (ошибка) {
    const текст = ошибка && ошибка.message ? ошибка.message : String(ошибка);
    return { отказ: текст };
  }
  const проекция = спроецироватьТочку(соответствие, черта.x, черта.y);
  return {
    указатель: { x: проекция.x, y: проекция.y, уверенность: черта.уверенность, в_границах: проекция.в_границах },
    черта,
    калибровка: { ошибка_средняя: соответствие.ошибка_средняя, ошибка_макс: соответствие.ошибка_макс, точек: соответствие.точек },
  };
}

// ---------------------------------------------------------------------------
// АДАПТЕР ДЛЯ РЕЕСТРА (AdapterRegistry). Тот же id, что у контрактной заглушки
// ('input.gaze'); статус живёт по ledger: пусто/без пина — EXPERIMENTAL честно,
// есть пин — READY. privacy local — камера не покидает устройство.
// ---------------------------------------------------------------------------
export function createGazeAdapter() {
  return {
    id: ADAPTER_ID,
    kind: 'input',
    priority: 5,
    status() {
      const модели = списокМоделей();
      if (модели.length === 0) {
        return {
          state: STATUS.EXPERIMENTAL,
          privacy: 'local',
          reason: 'contract present, no model registered: модель у владельца (ЛЮК_ВЕСОВ_GAZE.md), до пина честно EXPERIMENTAL',
        };
      }
      const запиненные = модели.filter((м) => м.веса);
      if (запиненные.length > 0) {
        return {
          state: STATUS.READY,
          privacy: 'local',
          reason: `pinned: ${запиненные.map((м) => м.id).join(', ')}`,
        };
      }
      return {
        state: STATUS.EXPERIMENTAL,
        privacy: 'local',
        reason: `модели без пина: ${модели.map((м) => м.id).join(', ')} — честно EXPERIMENTAL`,
      };
    },
    взгляд(задание, id) { return взгляд(задание, id); },
    событияDwell(траектория, параметры) { return событияDwell(траектория, параметры); },
  };
}
