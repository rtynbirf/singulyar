const ПАТТЕРН_ID = /^[\p{L}\p{N}][\p{L}\p{N}._-]*$/u;
const ПАТТЕРН_ХЭША = /^[0-9a-f]{64}$/i;
// Честная граница объёма: точек калибровки не больше МАКС_ТОЧЕК (сеанс
// калибровки — десятки точек; многотысячный список — повод честно отказать).
export const МАКС_ТОЧЕК = 4096;

// Подписи форматов: [формат, функция проверки первых байтов]. Копия таблицы
// ocr.mjs (кадр камеры — та же картинка); проверка требует достаточно
// длинного буфера — короткие данные честно не проходят.
export const ПОДПИСИ = {
  png: (б) => б.length >= 8 && б[0] === 0x89 && б[1] === 0x50 && б[2] === 0x4e && б[3] === 0x47 && б[4] === 0x0d && б[5] === 0x0a && б[6] === 0x1a && б[7] === 0x0a,
  jpeg: (б) => б.length >= 3 && б[0] === 0xff && б[1] === 0xd8 && б[2] === 0xff,
  bmp: (б) => б.length >= 2 && б[0] === 0x42 && б[1] === 0x4d,
  gif: (б) => б.length >= 6 && б[0] === 0x47 && б[1] === 0x49 && б[2] === 0x46 && б[3] === 0x38 && (б[4] === 0x37 || б[4] === 0x39) && б[5] === 0x61,
  webp: (б) => б.length >= 12 && б[0] === 0x52 && б[1] === 0x49 && б[2] === 0x46 && б[3] === 0x46 && б[8] === 0x57 && б[9] === 0x45 && б[10] === 0x42 && б[11] === 0x50,
  tiff: (б) => б.length >= 4 && ((б[0] === 0x49 && б[1] === 0x49 && б[2] === 0x2a && б[3] === 0x00) || (б[0] === 0x4d && б[1] === 0x4d && б[2] === 0x00 && б[3] === 0x2a)),
};
export const ФОРМАТЫ = Object.keys(ПОДПИСИ);

// ---------------------------------------------------------------------------
// ЧИСЛОВАЯ ЧЕСТНОСТЬ. Конечное число — не NaN, не ∞, не строка. Одна проверка
// на весь файл: границы называются там, где они есть (уверенность [0,1],
// экран [0,1]), остальное — мусор данных.
// ---------------------------------------------------------------------------
function конечное(значение) {
  return typeof значение === 'number' && Number.isFinite(значение);
}

// ---------------------------------------------------------------------------
// ВАЛИДАЦИЯ КАЛИБРОВКИ. Схема названа, точек ≥3 (аффинное соответствие —
// 6 параметров), каждая пара — конечные числа. Пары читаются только на подбор
// соответствия — вход не мутируется.
// ---------------------------------------------------------------------------
export function валидироватьКалибровку(калибровка) {
  if (!калибровка || typeof калибровка !== 'object' || Array.isArray(калибровка)) {
    return { ok: false, причина: 'калибровка ожидается объектом' };
  }
  if (калибровка.схема !== СХЕМА_КАЛИБРОВКИ) {
    return { ok: false, причина: `калибровка.схема ожидается "${СХЕМА_КАЛИБРОВКИ}", получено ${JSON.stringify(калибровка.схема ?? null)}` };
  }
  const точки = калибровка.точки;
  if (!Array.isArray(точки)) {
    return { ok: false, причина: 'калибровка.точки ожидается массивом пар' };
  }
  if (точки.length < 3) {
    return { ok: false, причина: `точек калибровки ${точки.length} — аффинному соответствию нужно минимум 3` };
  }
  if (точки.length > МАКС_ТОЧЕК) {
    return { ok: false, причина: `точек калибровки ${точки.length} — больше ${МАКС_ТОЧЕК}` };
  }
  for (let i = 0; i < точки.length; i++) {
    const пара = точки[i];
    if (!пара || typeof пара !== 'object' || Array.isArray(пара)) {
      return { ok: false, причина: `калибровка.точки[${i}] ожидается парой { кадр, экран }` };
    }
    for (const имя of ['кадр', 'экран']) {
      const точка = пара[имя];
      if (!точка || typeof точка !== 'object' || Array.isArray(точка)) {
        return { ok: false, причина: `калибровка.точки[${i}].${имя} ожидается точкой { x, y }` };
      }
      if (!конечное(точка.x) || !конечное(точка.y)) {
        return { ok: false, причина: `калибровка.точки[${i}].${имя}.x/y ожидаются конечными числами` };
      }
    }
  }
  return { ok: true };
}

// ---------------------------------------------------------------------------
// АФФИННОЕ СООТВЕТСТВИЕ (mapping, часть 1 — подбор). Наименьшие квадраты по
// нормальным уравнениям: экран_x = a11·u + a12·v + b1, экран_y = a21·u +
// a22·v + b2, где (u, v) — точка кадра. Нормальная матрица
//   M = [[Σu², Σuv, Σu], [Σuv, Σv², Σv], [Σu, Σv, n]]
// решается правилом Крамера отдельно для правых частей x и y — без библиотек,
// без часов, байт-в-байт детерминизм. Вырожденность (точки кадра на одной
// прямой, совпадающие точки) — честный отказ: через коллинеарные точки
// плоскость не натянуть.
// ---------------------------------------------------------------------------
export function аффинноеСоответствие(точки) {
  if (!Array.isArray(точки) || точки.length < 3) {
    throw new TypeError('gaze-adapter: аффинноеСоответствие — ожидается массив минимум из 3 пар');
  }
  let suu = 0, suv = 0, svv = 0, su = 0, sv = 0, n = 0;
  let sux = 0, svx = 0, sx = 0;
  let suy = 0, svy = 0, sy = 0;
  for (const пара of точки) {
    const u = пара.кадр.x, v = пара.кадр.y;
    const x = пара.экран.x, y = пара.экран.y;
    suu += u * u; suv += u * v; svv += v * v;
    su += u; sv += v; n += 1;
    sux += u * x; svx += v * x; sx += x;
    suy += u * y; svy += v * y; sy += y;
  }
  const дет =
    suu * (svv * n - sv * sv) -
    suv * (suv * n - sv * su) +
    su * (suv * sv - svv * su);
  if (!Number.isFinite(дет) || Math.abs(дет) <= 1e-12) {
    throw new TypeError(`gaze-adapter: аффинноеСоответствие — калибровка вырождена (определитель ${дет}): точки кадра лежат на одной прямой или совпадают, плоскость экрана не натянуть`);
  }
  // Крамер, x-строка: правая часть [sux, svx, sx] — по очереди заменяет
  // первый, второй и третий столбец нормальной матрицы.
  const дет_a = sux * (svv * n - sv * sv) - suv * (svx * n - sv * sx) + su * (svx * sv - svv * sx);
  const дет_b = suu * (svx * n - sv * sx) - sux * (suv * n - sv * su) + su * (suv * sx - svx * su);
  const дет_c = suu * (svv * sx - svx * sv) - suv * (suv * sx - svx * su) + sux * (suv * sv - svv * su);
  // Крамер, y-строка: правая часть [suy, svy, sy].
  const дет_a2 = suy * (svv * n - sv * sv) - suv * (svy * n - sv * sy) + su * (svy * sv - svv * sy);
  const дет_b2 = suu * (svy * n - sv * sy) - suy * (suv * n - sv * su) + su * (suv * sy - svy * su);
  const дет_c2 = suu * (svv * sy - svy * sv) - suv * (suv * sy - svy * su) + suy * (suv * sv - svv * su);
  const соответствие = {
    a11: дет_a / дет,
    a12: дет_b / дет,
    b1: дет_c / дет,
    a21: дет_a2 / дет,
    a22: дет_b2 / дет,
    b2: дет_c2 / дет,
  };
  // Остаток калибровки — назван честно: качество сеанса владельца видно
  // числами, а не обещаниями.
  const ошибки = [];
  for (const пара of точки) {
    const прогноз = спроецироватьТочку(соответствие, пара.кадр.x, пара.кадр.y);
    const dx = прогноз.x - пара.экран.x;
    const dy = прогноз.y - пара.экран.y;
    ошибки.push(Math.sqrt(dx * dx + dy * dy));
  }
  const сумма = ошибки.reduce((a, b) => a + b, 0);
  соответствие.ошибка_средняя = сумма / ошибки.length;
  соответствие.ошибка_макс = ошибки.reduce((a, b) => (b > a ? b : a), 0);
  соответствие.точек = точки.length;
  return соответствие;
}

// ---------------------------------------------------------------------------
// ПРОЕКЦИЯ (mapping, часть 2 — применение). Чиста, без часов. Выход за экран
// НЕ поджимается: честный флаг в_границах (данные не подменяются молча).
// ---------------------------------------------------------------------------
export function спроецироватьТочку(соответствие, u, v) {
  if (!соответствие || typeof соответствие !== 'object') {
    throw new TypeError('gaze-adapter: спроецироватьТочку — соответствие ожидается объектом');
  }
  if (!конечное(u) || !конечное(v)) {
    throw new TypeError('gaze-adapter: спроецироватьТочку — координаты ожидаются конечными числами');
  }
  const x = соответствие.a11 * u + соответствие.a12 * v + соответствие.b1;
  const y = соответствие.a21 * u + соответствие.a22 * v + соответствие.b2;
  if (!Number.isFinite(x) || !Number.isFinite(y)) {
    throw new TypeError('gaze-adapter: проекция дала не конечные числа — соответствие сломано, честный отказ');
  }
  const в_границах = x >= 0 && x <= 1 && y >= 0 && y <= 1;
  return { x, y, в_границах };
}

// ---------------------------------------------------------------------------
// DWELL-SELECTION (редюсер выдержки). Чистая функция над траекторией:
// точки внутри радиуса вокруг якоря копят выдержку; выход за радиус+гистерезис
// сбрасывает; накопил выдержку — событие «выбор», и до выхода из радиуса
// повторного выбора в той же точке не будет (нет пулемёта кликов). Часы —
// ВНЕШНИЕ (t приносит запускающий); монотонность проверяется честно.
// Параметры: радиус (доля экрана), выдержка (мс), выход (гистерезис ≥
// радиуса), порог_уверенности (точки ниже — пропущены, названо честно).
// ---------------------------------------------------------------------------
export const DWELL_ПО_УМОЛЧАНИЮ = Object.freeze({ радиус: 0.04, выдержка: 600, выход: 0.08, порог_уверенности: 0 });

export function событияDwell(траектория, параметры) {
  if (!Array.isArray(траектория)) {
    throw new TypeError('gaze-adapter: событияDwell — траектория ожидается массивом точек { x, y, t }');
  }
  const п = { ...DWELL_ПО_УМОЛЧАНИЮ, ...(параметры && typeof параметры === 'object' && !Array.isArray(параметры) ? параметры : {}) };
  if (!конечное(п.радиус) || п.радиус <= 0 || п.радиус > 1) {
    throw new TypeError('gaze-adapter: событияDwell — радиус ожидается числом из (0, 1]');
  }
  if (!конечное(п.выход) || п.выход < п.радиус) {
    throw new TypeError('gaze-adapter: событияDwell — выход (гистерезис) ожидается числом ≥ радиуса: гистерезис меньше радиуса мёртв');
  }
  if (!конечное(п.выдержка) || п.выдержка <= 0) {
    throw new TypeError('gaze-adapter: событияDwell — выдержка ожидается положительным числом (мс, внешние часы)');
  }
  if (!конечное(п.порог_уверенности) || п.порог_уверенности < 0 || п.порог_уверенности > 1) {
    throw new TypeError('gaze-adapter: событияDwell — порог_уверенности ожидается числом в [0, 1]');
  }
  const события = [];
  let якорь = null;  // точка, вокруг которой копится выдержка
  let старт = 0;     // внешнее время начала накопления
  let замок = null;  // точка последнего события: до честного выхода из её радиуса повторного выбора не будет
  const дистанция = (a, b) => Math.sqrt((a.x - b.x) ** 2 + (a.y - b.y) ** 2);
  for (let i = 0; i < траектория.length; i++) {
    const точка = траектория[i];
    if (!точка || typeof точка !== 'object' || Array.isArray(точка)) {
      throw new TypeError(`gaze-adapter: событияDwell — траектория[${i}] ожидается точкой { x, y, t }`);
    }
    if (!конечное(точка.x) || !конечное(точка.y) || !конечное(точка.t)) {
      throw new TypeError(`gaze-adapter: событияDwell — траектория[${i}].x/y/t ожидаются конечными числами`);
    }
    if (i > 0 && точка.t < траектория[i - 1].t) {
      throw new TypeError(`gaze-adapter: событияDwell — время траектории не монотонно (траектория[${i}].t назад): внешние часы текут назад, честный отказ`);
    }
    if (точка.уверенность !== undefined) {
      if (!конечное(точка.уверенность) || точка.уверенность < 0 || точка.уверенность > 1) {
        throw new TypeError(`gaze-adapter: событияDwell — траектория[${i}].уверенность ожидается числом в [0, 1]`);
      }
      if (точка.уверенность < п.порог_уверенности) continue; // названный порог: точка пропущена
    }
    if (замок !== null) {
      if (дистанция(точка, замок) > п.радиус) замок = null; // взгляд честно вышел — замок снят
      else continue; // ещё в радиусе события — ждём выхода, пулемёта кликов нет
    }
    if (якорь === null) {
      якорь = { x: точка.x, y: точка.y };
      старт = точка.t;
      continue;
    }
    if (дистанция(точка, якорь) > п.выход) {
      якорь = { x: точка.x, y: точка.y }; // ушла за гистерезис — накопление честно забыто, якорь переносится
      старт = точка.t;
      continue;
    }
    if (точка.t - старт >= п.выдержка) {
      события.push({ тип: 'выбор', x: якорь.x, y: якорь.y, t0: старт, t1: точка.t, выдержка_мс: точка.t - старт });
      замок = { x: якорь.x, y: якорь.y };
      якорь = null;
    }
  }
  return события;
}

