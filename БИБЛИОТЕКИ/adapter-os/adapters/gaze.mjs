const ledger = new Map();

export function списокМоделей() {
  return [...ledger.keys()].sort().map((id) => {
    const запись = ledger.get(id);
    const веса = запись.веса;
    return {
      id,
      имя: запись.имя,
      движок: запись.движок,
      веса: веса
        ? { имя: веса.имя, sha256: веса.sha256.toLowerCase(), байт: веса.байт, частей: веса.частей }
        : null,
      статус: веса
        ? `pinned sha256:${веса.sha256.toLowerCase()}`
        : 'EXPERIMENTAL: без pinned-хэша — модель владельца, дом не проверял веса',
    };
  });
}

// ---------------------------------------------------------------------------
// ВАЛИДАЦИЯ ЗАДАНИЯ. Кадр — Uint8Array с живой подписью, согласованной с
// названным форматом; калибровка — опциональна для валидации (дверь без неё
// честно откажет); параметры — объект или отсутствие. Вход не мутируется:
// создатьЗадание отдаёт копию данных.
// ---------------------------------------------------------------------------
export function валидироватьЗадание(задание) {
  if (!задание || typeof задание !== 'object' || Array.isArray(задание)) {
    return { ok: false, причина: 'задание ожидается объектом' };
  }
  const кадр = задание.кадр;
  if (!кадр || typeof кадр !== 'object' || Array.isArray(кадр)) {
    return { ok: false, причина: 'задание.кадр ожидается объектом' };
  }
  const данные = кадр.данные;
  const тип = Object.prototype.toString.call(данные);
  if (тип !== '[object Uint8Array]') {
    return { ok: false, причина: `кадр.данные ожидаются Uint8Array, получено ${тип}` };
  }
  if (данные.length === 0) {
    return { ok: false, причина: 'кадр.данные пусты — смотреть не на что, честный отказ' };
  }
  const формат = кадр.формат;
  if (typeof формат !== 'string' || !ФОРМАТЫ.includes(формат)) {
    return { ok: false, причина: `кадр.формат ожидается одним из [${ФОРМАТЫ.join(', ')}], получено ${JSON.stringify(формат ?? null)}` };
  }
  if (!ПОДПИСИ[формат](данные)) {
    return { ok: false, причина: `подпись файла не сошлась с названным форматом "${формат}" — кадр не подменяется молча` };
  }
  if (задание.калибровка !== undefined) {
    const проверкаК = валидироватьКалибровку(задание.калибровка);
    if (!проверкаК.ok) return { ok: false, причина: проверкаК.причина };
  }
  if (задание.параметры !== undefined && (typeof задание.параметры !== 'object' || задание.параметры === null || Array.isArray(задание.параметры))) {
    return { ok: false, причина: 'задание.параметры ожидается объектом или отсутствовать' };
  }
  return { ok: true };
}

// Готовит конверт задания: валидация + копия данных кадра (вход не шарится).
export function создатьЗадание({ данные, формат, калибровка, параметры = {} }) {
  const проверка = валидироватьЗадание({ кадр: { данные, формат }, калибровка, параметры });
  if (!проверка.ok) throw new TypeError(`gaze-adapter: создатьЗадание — ${проверка.причина}`);
  return {
    кадр: { данные: данные.slice(), формат },
    калибровка,
    параметры: JSON.parse(JSON.stringify(параметры)),
  };
}

// ---------------------------------------------------------------------------
// РАЗБОР ОТВЕТА МОДЕЛИ. Строгий. Черта — { x, y, уверенность }: конечные
// числа; уверенность — в [0,1]. Диапазона на x/y НЕТ (кадр живёт своей
// системой координат, границы ставит проекция).
// ---------------------------------------------------------------------------
export function разобратьОтвет(ответ) {
  if (!ответ || typeof ответ !== 'object' || Array.isArray(ответ)) {
    throw new TypeError(`gaze-adapter: разобратьОтвет — ответ ожидается конвертом, получено ${JSON.stringify(ответ ?? null)}`);
  }
  if (typeof ответ.отказ === 'string' && ответ.отказ) {
    throw new TypeError(`gaze-adapter: модель отказалась — ${ответ.отказ}`);
  }
  const черта = ответ.черта;
  if (!черта || typeof черта !== 'object' || Array.isArray(черта)) {
    throw new TypeError('gaze-adapter: в конверте нет объекта «черта» { x, y, уверенность }');
  }
  if (!конечное(черта.x)) {
    throw new TypeError(`gaze-adapter: черта.x ожидается конечным числом, получено ${JSON.stringify(черта.x ?? null)}`);
  }
  if (!конечное(черта.y)) {
    throw new TypeError(`gaze-adapter: черта.y ожидается конечным числом, получено ${JSON.stringify(черта.y ?? null)}`);
  }
  if (!конечное(черта.уверенность) || черта.уверенность < 0 || черта.уверенность > 1) {
    throw new TypeError(`gaze-adapter: черта.уверенность ожидается числом в [0, 1], получено ${JSON.stringify(черта.уверенность ?? null)}`);
  }
  return { x: черта.x, y: черта.y, уверенность: черта.уверенность };
}

// ---------------------------------------------------------------------------
// РЕГИСТРАЦИЯ МОДЕЛИ. Честный true/false; веса — all-or-nothing.
// ---------------------------------------------------------------------------
export function registerGazeModel(описание) {
  if (!описание || typeof описание !== 'object' || Array.isArray(описание)) return false;
  const { id, runner, веса, движок } = описание;
  if (!id || typeof id !== 'string' || !ПАТТЕРН_ID.test(id)) return false;
  if (typeof runner !== 'function') return false;
  if (движок !== undefined && (typeof движок !== 'string' || !движок)) return false;

  let пин = null;
  if (веса !== undefined) {
    if (!веса || typeof веса !== 'object' || Array.isArray(веса)) return false;
    if (typeof веса.имя !== 'string' || !веса.имя) return false;
    if (typeof веса.sha256 !== 'string' || !ПАТТЕРН_ХЭША.test(веса.sha256)) return false;
    if (typeof веса.байт !== 'number' || !Number.isInteger(веса.байт) || веса.байт <= 0) return false;
    if (typeof веса.частей !== 'number' || !Number.isInteger(веса.частей) || веса.частей <= 0) return false;
    пин = { имя: веса.имя, sha256: веса.sha256.toLowerCase(), байт: веса.байт, частей: веса.частей };
  }

  if (ledger.has(id)) return false; // дубликат id — честный false
  ledger.set(id, {
    имя: `gaze/${id}`,
    runner,
    веса: пин,
    движок: движок === undefined ? 'не назван (EXPERIMENTAL)' : движок,
  });
  return true;
}

// ---------------------------------------------------------------------------
// СКЛЕЙКА ЧАСТЕЙ И ПИН. Та же механика, что speech.mjs/ocr.mjs (копия
// сознательна — самодостаточность адаптера; вектор SHA-256("abc") держат все
// копии). crypto.subtle асинхронен — это фаза приведения двигателя, ВНЕ
// синхронного контрактного цикла.
// ---------------------------------------------------------------------------
export async function склеитьЧасти(части) {
  if (!Array.isArray(части) || части.length === 0) {
    throw new TypeError('gaze-adapter: склеитьЧасти — ожидается непустой массив частей');
  }
  let всего = 0;
  for (const ч of части) {
    const тип = Object.prototype.toString.call(ч);
    if (тип !== '[object Uint8Array]') {
      throw new TypeError(`gaze-adapter: склеитьЧасти — часть ожидается Uint8Array, получено ${тип}`);
    }
    if (ч.length === 0) {
      throw new TypeError('gaze-adapter: склеитьЧасти — часть пуста (0 байт): раскрой не может давать пустые части, честный отказ');
    }
    всего += ч.length;
  }
  const цельное = new Uint8Array(всего);
  let офсет = 0;
  for (const ч of части) { цельное.set(ч, офсет); офсет += ч.length; }
  const хэш = await crypto.subtle.digest('SHA-256', цельное);
  const hex = [...new Uint8Array(хэш)].map((б) => б.toString(16).padStart(2, '0')).join('');
  return { данные: цельное, sha256: hex, байт: всего };
}

export async function сверитьПин(id, части) {
  const запись = ledger.get(id);
  if (!запись) return { ok: false, причина: `модель "${id}" не зарегистрирована` };
  if (!запись.веса) return { ok: false, причина: `модель "${id}" без pinned-хэша — сверять нечем (честно EXPERIMENTAL)` };
  let склейка;
  try {
    склейка = await склеитьЧасти(части);
  } catch (ошибка) {
    return { ok: false, причина: `склейка не сошлась — ${ошибка && ошибка.message ? ошибка.message : String(ошибка)}` };
  }
  if (склейка.sha256 !== запись.веса.sha256) {
    return { ok: false, причина: `SHA-256 частей (${склейка.sha256.slice(0, 12)}…) не сошёлся с пином (${запись.веса.sha256.slice(0, 12)}…) — данные не выдаются` };
  }
  return { ok: true, данные: склейка.данные, sha256: склейка.sha256, байт: склейка.байт };
}

