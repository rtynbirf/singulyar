export const ver = 'demucs-adapter/0.1';
export const LEDGER_SCHEMA = 'adapter-os.demucs.v1';
export const ADAPTER_ID = 'tool.demucs';

// Канон стемов — ровно как контракт contracts.mjs (output-массив), порядок
// канона фиксирован: доли мощности и бенчмарк идут по нему — детерминизм.
export const СТЕМЫ = Object.freeze(['vocals', 'drums', 'bass', 'other']);

const ПАТТЕРН_ID = /^[\p{L}\p{N}][\p{L}\p{N}._-]*$/u;
const ПАТТЕРН_ХЭША = /^[0-9a-f]{64}$/i;

// Подписи аудио-форматов: [формат, функция проверки первых байтов].
//   wav  — RIFF....WAVE (52 49 46 46 … 57 41 56 45 на 8..11);
//   mp3  — ID3-тег (49 44 33) ИЛИ frame sync (FF, второй байт 111xxxxx);
//   ogg  — OggS (4f 67 67 53);
//   flac — fLaC (66 4c 61 43);
//   m4a  — размер + 'ftyp' (66 74 79 70 на 4..7).
// Проверка требует достаточно длинного буфера — короткие данные честно
// не проходят.
export const ПОДПИСИ = {
  wav: (б) => б.length >= 12 && б[0] === 0x52 && б[1] === 0x49 && б[2] === 0x46 && б[3] === 0x46 && б[8] === 0x57 && б[9] === 0x41 && б[10] === 0x56 && б[11] === 0x45,
  mp3: (б) => б.length >= 3 && ((б[0] === 0x49 && б[1] === 0x44 && б[2] === 0x33) || (б.length >= 2 && б[0] === 0xff && (б[1] & 0xe0) === 0xe0)),
  ogg: (б) => б.length >= 4 && б[0] === 0x4f && б[1] === 0x67 && б[2] === 0x67 && б[3] === 0x53,
  flac: (б) => б.length >= 4 && б[0] === 0x66 && б[1] === 0x4c && б[2] === 0x61 && б[3] === 0x43,
  m4a: (б) => б.length >= 8 && б[4] === 0x66 && б[5] === 0x74 && б[6] === 0x79 && б[7] === 0x70,
};
export const ФОРМАТЫ = Object.keys(ПОДПИСИ);

// ---------------------------------------------------------------------------
// ЧИСЛОВАЯ ЧЕСТНОСТЬ. Конечное число — не NaN, не ∞, не строка. Одна проверка
// на весь файл: границы называются там, где они есть (частота > 0, доля
// мощности [0,1]), остальное — мусор данных.
// ---------------------------------------------------------------------------
function конечное(значение) {
  return typeof значение === 'number' && Number.isFinite(значение);
}

// Числовой массив отсчётов: Float32Array или массив конечных чисел, длина > 0.
// Возвращает (нормализует к) Float32Array или причину отказа — строкой.
function нормализоватьОтсчёты(имя, значение) {
  const тип = Object.prototype.toString.call(значение);
  if (тип === '[object Float32Array]') {
    if (значение.length === 0) return `${имя} пуст (0 отсчётов) — разделение не о чем, честный отказ`;
    for (let i = 0; i < значение.length; i++) {
      if (!Number.isFinite(значение[i])) return `${имя}[${i}] — не конечное число (${JSON.stringify(значение[i] ?? null)}), мусор данных`;
    }
    return new Float32Array(значение); // копия: ответ движка не шарится
  }
  if (Array.isArray(значение)) {
    if (значение.length === 0) return `${имя} пуст (0 отсчётов) — разделение не о чем, честный отказ`;
    const копия = new Float32Array(значение.length);
    for (let i = 0; i < значение.length; i++) {
      if (!конечное(значение[i])) return `${имя}[${i}] — не конечное число (${JSON.stringify(значение[i] ?? null)}), мусор данных`;
      копия[i] = значение[i];
    }
    return копия;
  }
  return `${имя} ожидается Float32Array или массивом конечных чисел, получено ${тип}`;
}

// ---------------------------------------------------------------------------
// ВАЛИДАЦИЯ ЗАДАНИЯ. Аудио — Uint8Array с живой подписью, согласованной с
// названным форматом; параметры — объект или отсутствие. Вход не мутируется:
// создатьЗадание отдаёт копию данных.
// ---------------------------------------------------------------------------
export function валидироватьЗадание(задание) {
  if (!задание || typeof задание !== 'object' || Array.isArray(задание)) {
    return { ok: false, причина: 'задание ожидается объектом' };
  }
  const аудио = задание.аудио;
  if (!аудио || typeof аудио !== 'object' || Array.isArray(аудио)) {
    return { ok: false, причина: 'задание.аудио ожидается объектом' };
  }
  const данные = аудио.данные;
  const тип = Object.prototype.toString.call(данные);
  if (тип !== '[object Uint8Array]') {
    return { ok: false, причина: `аудио.данные ожидаются Uint8Array, получено ${тип}` };
  }
  if (данные.length === 0) {
    return { ok: false, причина: 'аудио.данные пусты — разделять нечего, честный отказ' };
  }
  const формат = аудио.формат;
  if (typeof формат !== 'string' || !ФОРМАТЫ.includes(формат)) {
    return { ok: false, причина: `аудио.формат ожидается одним из [${ФОРМАТЫ.join(', ')}], получено ${JSON.stringify(формат ?? null)}` };
  }
  if (!ПОДПИСИ[формат](данные)) {
    return { ok: false, причина: `подпись файла не сошлась с названным форматом "${формат}" — звук не подменяется молча` };
  }
  if (задание.параметры !== undefined && (typeof задание.параметры !== 'object' || задание.параметры === null || Array.isArray(задание.параметры))) {
    return { ok: false, причина: 'задание.параметры ожидается объектом или отсутствовать' };
  }
  return { ok: true };
}

// Готовит конверт задания: валидация + копия данных аудио (вход не шарится).
export function создатьЗадание({ данные, формат, параметры = {} }) {
  const проверка = валидироватьЗадание({ аудио: { данные, формат }, параметры });
  if (!проверка.ok) throw new TypeError(`demucs-adapter: создатьЗадание — ${проверка.причина}`);
  return {
    аудио: { данные: данные.slice(), формат },
    параметры: JSON.parse(JSON.stringify(параметры)),
  };
}

// ---------------------------------------------------------------------------
// РАЗБОР ОТВЕТА МОДЕЛИ. Строгий. Ровно четыре канонических стема (лишний
// ключ — мусор, недостающий — отказ), каждый — Float32Array конечных
// отсчётов, все длины равны. Смесь (если названа) — той же длины. Частота
// дискретизации (если названа) — конечное число > 0. Диапазона на отсчётах
// НЕТ — конечность требует разбор, поджатие не делаем.
// ---------------------------------------------------------------------------
export function разобратьОтвет(ответ) {
  if (!ответ || typeof ответ !== 'object' || Array.isArray(ответ)) {
    throw new TypeError(`demucs-adapter: разобратьОтвет — ответ ожидается конвертом, получено ${JSON.stringify(ответ ?? null)}`);
  }
  if (typeof ответ.отказ === 'string' && ответ.отказ) {
    throw new TypeError(`demucs-adapter: модель отказалась — ${ответ.отказ}`);
  }
  const стемы = ответ.стемы;
  if (!стемы || typeof стемы !== 'object' || Array.isArray(стемы)) {
    throw new TypeError('demucs-adapter: в конверте нет объекта «стемы» { vocals, drums, bass, other }');
  }
  for (const ключ of Object.keys(стемы)) {
    if (!СТЕМЫ.includes(ключ)) {
      throw new TypeError(`demucs-adapter: лишний стем "${ключ}" — контракт требует ровно [${СТЕМЫ.join(', ')}], мусор не выбрасывается молча`);
    }
  }
  const разобранные = {};
  let длина = null;
  for (const имя of СТЕМЫ) {
    if (!(имя in стемы)) {
      throw new TypeError(`demucs-adapter: нет стема "${имя}" — контракт требует ровно [${СТЕМЫ.join(', ')}]`);
    }
    const норма = нормализоватьОтсчёты(`стемы.${имя}`, стемы[имя]);
    if (typeof норма === 'string') throw new TypeError(`demucs-adapter: ${норма}`);
    if (длина === null) длина = норма.length;
    else if (норма.length !== длина) {
      throw new TypeError(`demucs-adapter: длины стемов не сошлись (${имя}: ${норма.length} против ${длина}) — стемы это каналы одного микса`);
    }
    разобранные[имя] = норма;
  }
  let смесь;
  if (ответ.смесь !== undefined && ответ.смесь !== null) {
    const нормаСмеси = нормализоватьОтсчёты('смесь', ответ.смесь);
    if (typeof нормаСмеси === 'string') throw new TypeError(`demucs-adapter: ${нормаСмеси}`);
    if (нормаСмеси.length !== длина) {
      throw new TypeError(`demucs-adapter: длина смеси (${нормаСмеси.length}) не сходится со стемами (${длина}) — одна система координат`);
    }
    смесь = нормаСмеси;
  }
  let частота;
  if (ответ.частота_дискретизации !== undefined && ответ.частота_дискретизации !== null) {
    if (!конечное(ответ.частота_дискретизации) || ответ.частота_дискретизации <= 0) {
      throw new TypeError(`demucs-adapter: частота_дискретизации ожидается конечным числом > 0, получено ${JSON.stringify(ответ.частота_дискретизации ?? null)}`);
    }
    частота = ответ.частота_дискретизации;
  }
  return { стемы: разобранные, смесь, частота_дискретизации: частота, длина };
}

// ---------------------------------------------------------------------------
// ЧЕСТНЫЕ ЧИСЛА СТЕМОВ. Рмс = sqrt(mean(x²)), пик = max|x|, громкость_дБ =
// 20·log10(рмс) — тишина (рмс 0) названа честно, −∞ не выдумывается; доля
// мощности = mean(x²)/Σmean(x²) — сумма долей математически 1 (один
// знаменатель), у полной тишины доли не выдумываются. Чисто, без часов.
// ---------------------------------------------------------------------------
export function числаСтемов(стемы) {
  if (!стемы || typeof стемы !== 'object' || Array.isArray(стемы)) {
    throw new TypeError('demucs-adapter: числаСтемов — стемы ожидаются объектом { vocals, drums, bass, other }');
  }
  const мощности = {};
  const числа = {};
  for (const имя of СТЕМЫ) {
    const стем = стемы[имя];
    if (!стем || (Object.prototype.toString.call(стем) !== '[object Float32Array]' && !Array.isArray(стем))) {
      throw new TypeError(`demucs-adapter: числаСтемов — стем "${имя}" ожидается Float32Array или массивом`);
    }
    let сумма2 = 0;
    let пик = 0;
    for (let i = 0; i < стем.length; i++) {
      const x = стем[i];
      if (!Number.isFinite(x)) throw new TypeError(`demucs-adapter: числаСтемов — стем "${имя}"[${i}] не конечное число`);
      сумма2 += x * x;
      const абс = Math.abs(x);
      if (абс > пик) пик = абс;
    }
    const мощность = сумма2 / стем.length;
    const рмс = Math.sqrt(мощность);
    мощности[имя] = мощность;
    числа[имя] = {
      пик,
      рмс,
      громкость_дБ: рмс === 0 ? null : 20 * Math.log10(рмс),
      тишина: рмс === 0,
      мощность,
    };
  }
  const полнаяМощность = СТЕМЫ.reduce((с, имя) => с + мощности[имя], 0);
  if (полнаяМощность > 0) {
    for (const имя of СТЕМЫ) числа[имя].доля_мощности = мощности[имя] / полнаяМощность;
  } else {
    for (const имя of СТЕМЫ) числа[имя].доля_мощности = null; // полная тишина — доли не выдумываются
  }
  return числа;
}

// ---------------------------------------------------------------------------
// ОСТАТОК МИКСА. Смесь − сумма стемов, по отсчётам. Честность как у остатка
// калибровки gaze.mjs: расхождение названо числами (рмс_остатка и
// против_смеси_дБ), а не скрыто обещанием идеального разделения. Полная
// сходимость (остаток — тишина) названа словами, число не выдумывается.
// ---------------------------------------------------------------------------
export function остатокМикса(смесь, стемы) {
  const нормаСмеси = нормализоватьОтсчёты('смесь', смесь);
  if (typeof нормаСмеси === 'string') throw new TypeError(`demucs-adapter: остатокМикса — ${нормаСмеси}`);
  const разобранные = {};
  for (const имя of СТЕМЫ) {
    if (!(имя in (стемы || {}))) throw new TypeError(`demucs-adapter: остатокМикса — нет стема "${имя}"`);
    const норма = нормализоватьОтсчёты(`стемы.${имя}`, стемы[имя]);
    if (typeof норма === 'string') throw new TypeError(`demucs-adapter: остатокМикса — ${норма}`);
    if (норма.length !== нормаСмеси.length) {
      throw new TypeError(`demucs-adapter: остатокМикса — длина стема "${имя}" (${норма.length}) не сходится со смесью (${нормаСмеси.length})`);
    }
    разобранные[имя] = норма;
  }
  let сумма2Остатка = 0;
  for (let i = 0; i < нормаСмеси.length; i++) {
    const разность = нормаСмеси[i] - (разобранные.vocals[i] + разобранные.drums[i] + разобранные.bass[i] + разобранные.other[i]);
    сумма2Остатка += разность * разность;
  }
  const рмсОстатка = Math.sqrt(сумма2Остатка / нормаСмеси.length);
  let сумма2Смеси = 0;
  for (let i = 0; i < нормаСмеси.length; i++) сумма2Смеси += нормаСмеси[i] * нормаСмеси[i];
  const рмсСмеси = Math.sqrt(сумма2Смеси / нормаСмеси.length);
  const ответ = { рмс_остатка: рмсОстатка, рмс_смеси: рмсСмеси, против_смеси_дБ: null, сходимость: null };
  if (рмсОстатка === 0) {
    ответ.сходимость = 'полная: сумма стемов — тишина остатка';
  } else if (рмсСмеси === 0) {
    ответ.сходимость = 'смесь — тишина: остаток назван рмс_остатка, отношение честно не определено';
  } else {
    ответ.против_смеси_дБ = 20 * Math.log10(рмсОстатка / рмсСмеси);
  }
  return ответ;
}

// ---------------------------------------------------------------------------
// LEDGER моделей. На импорте пуст — моделей в доме нет, и это честно.
// ---------------------------------------------------------------------------
const ledger = new Map();

export function списокМоделей() {
  return [...ledger.keys()].sort().map((id) => {
    const запись = ledger.get(id);
    const веса = запись.веса;
    return {
      id,
      имя: запись.имя,
      движок: запись.движок,
      веса: веса
        ? { имя: веса.имя, sha256: веса.sha256.toLowerCase(), байт: веса.байт, частей: веса.частей }
        : null,
      статус: веса
        ? `pinned sha256:${веса.sha256.toLowerCase()}`
        : 'EXPERIMENTAL: без pinned-хэша — модель владельца, дом не проверял веса',
    };
  });
}

// ---------------------------------------------------------------------------
// РЕГИСТРАЦИЯ МОДЕЛИ. Честный true/false; веса — all-or-nothing.
// ---------------------------------------------------------------------------
export function registerDemucsModel(описание) {
  if (!описание || typeof описание !== 'object' || Array.isArray(описание)) return false;
  const { id, runner, веса, движок } = описание;
  if (!id || typeof id !== 'string' || !ПАТТЕРН_ID.test(id)) return false;
  if (typeof runner !== 'function') return false;
  if (движок !== undefined && (typeof движок !== 'string' || !движок)) return false;

  let пин = null;
  if (веса !== undefined) {
    if (!веса || typeof веса !== 'object' || Array.isArray(веса)) return false;
    if (typeof веса.имя !== 'string' || !веса.имя) return false;
    if (typeof веса.sha256 !== 'string' || !ПАТТЕРН_ХЭША.test(веса.sha256)) return false;
    if (typeof веса.байт !== 'number' || !Number.isInteger(веса.байт) || веса.байт <= 0) return false;
    if (typeof веса.частей !== 'number' || !Number.isInteger(веса.частей) || веса.частей <= 0) return false;
    пин = { имя: веса.имя, sha256: веса.sha256.toLowerCase(), байт: веса.байт, частей: веса.частей };
  }

  if (ledger.has(id)) return false; // дубликат id — честный false
  ledger.set(id, {
    имя: `demucs/${id}`,
    runner,
    веса: пин,
    движок: движок === undefined ? 'не назван (EXPERIMENTAL)' : движок,
  });
  return true;
}

// ---------------------------------------------------------------------------
// СКЛЕЙКА ЧАСТЕЙ И ПИН. Та же механика, что speech.mjs/ocr.mjs/gaze.mjs (копия
// сознательна — самодостаточность адаптера; вектор SHA-256("abc") держат все
// четыре копии). crypto.subtle асинхронен — это фаза приведения двигателя, ВНЕ
// синхронного контрактного цикла.
// ---------------------------------------------------------------------------
export async function склеитьЧасти(части) {
  if (!Array.isArray(части) || части.length === 0) {
    throw new TypeError('demucs-adapter: склеитьЧасти — ожидается непустой массив частей');
  }
  let всего = 0;
  for (const ч of части) {
    const тип = Object.prototype.toString.call(ч);
    if (тип !== '[object Uint8Array]') {
      throw new TypeError(`demucs-adapter: склеитьЧасти — часть ожидается Uint8Array, получено ${тип}`);
    }
    if (ч.length === 0) {
      throw new TypeError('demucs-adapter: склеитьЧасти — часть пуста (0 байт): раскрой не может давать пустые части, честный отказ');
    }
    всего += ч.length;
  }
  const цельное = new Uint8Array(всего);
  let офсет = 0;
  for (const ч of части) { цельное.set(ч, офсет); офсет += ч.length; }
  const хэш = await crypto.subtle.digest('SHA-256', цельное);
  const hex = [...new Uint8Array(хэш)].map((б) => б.toString(16).padStart(2, '0')).join('');
  return { данные: цельное, sha256: hex, байт: всего };
}

export async function сверитьПин(id, части) {
  const запись = ledger.get(id);
  if (!запись) return { ok: false, причина: `модель "${id}" не зарегистрирована` };
  if (!запись.веса) return { ok: false, причина: `модель "${id}" без pinned-хэша — сверять нечем (честно EXPERIMENTAL)` };
  let склейка;
  try {
    склейка = await склеитьЧасти(части);
  } catch (ошибка) {
    return { ok: false, причина: `склейка не сошлась — ${ошибка && ошибка.message ? ошибка.message : String(ошибка)}` };
  }
  if (склейка.sha256 !== запись.веса.sha256) {
    return { ok: false, причина: `SHA-256 частей (${склейка.sha256.slice(0, 12)}…) не сошёлся с пином (${запись.веса.sha256.slice(0, 12)}…) — данные не выдаются` };
  }
  return { ok: true, данные: склейка.данные, sha256: склейка.sha256, байт: склейка.байт };
}

