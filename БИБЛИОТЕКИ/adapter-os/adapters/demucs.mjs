//
// ПРИОРИТЕТ ВЛАДЕЛЬЦА (2026-10-13): «1) локальный Whisper (речь — ядро), 2) OCR,
// 3) gaze, 4) Demucs, 5) Брайль — последним». Шаг 1 сделан тактом v10.94
// «ГОЛОС» (speech.mjs), шаг 2 — тактом v10.95 «ЧТЕНИЕ» (ocr.mjs), шаг 3 —
// тактом v10.98 «ВЗГЛЯД» (gaze.mjs). Этот файл — ШАГ 4: контракт tool.demucs
// из contracts.mjs получает реализацию-дверь.
// Demucs — разделение звука на четыре стема: vocals / drums / bass / other.
// Для караоке-дома это честный путь к минусу: голос отделяется от остального —
// человек поёт, дом держит музыку. Звук не покидает устройство, 0 сети —
// закон приватности, не украшение.
//
// ЧЕСТНОЕ РАЗДЕЛЕНИЕ ТРУДА (контракт: input 'audio' → output
// ['vocals','drums','bass','other']):
//   - ДВИЖОК — рантайм владельца (Demucs WASM / локальный сервер вывода):
//     аудио-файл → четыре стема. Дом не тащит и не запускает веса (правда
//     платформы: файл ≤100 МБ; веса htdemucs крупнее — раскрой через
//     tools/раскрой_весов.py, люк ЛЮК_ВЕСОВ_DEMUCS.md).
//   - ПОДПИСЬ АУДИО — дом: магические байты (5 форматов: wav/mp3/ogg/flac/
//     m4a); «названо wav, лежит ogg» — честный отказ, звук не подменяется
//     молча.
//   - СТРОГИЙ РАЗБОР — дом: ровно четыре канонических стема, равные длины,
//     конечные отсчёты; диапазона на отсчётах НЕТ — поджимать не смеем.
//   - ЧЕСТНЫЕ ЧИСЛА — дом: рмс/пик/доля мощности по стемам (кто главнее в
//     миксе — видно числами, а не обещаниями); остаток микса назван, если
//     смесь названа движком; тишина стема названа честно (не выдуманный −∞).
//
// КОНТРАКТ RUNNER (синхронный, чистый; async-рантаймы приносят замороженный
// ответ):
//   runner(задание) → { стемы: { vocals, drums, bass, other },
//                       смесь?, частота_дискретизации? } | { отказ: причина }
//   задание = { аудио: { данные: Uint8Array, формат: 'wav'|'mp3'|'ogg'
//                       |'flac'|'m4a' }, параметры?: объект }
//   - детерминированный: одно аудио → один ответ, байт-в-байт;
//   - 0 сети: runner ничего не качает — модель уже локальна;
//   - асинхронные рантаймы (wasm-воркер, локальный сервер вывода) гоняются
//     ЗА пределами синхронного цикла и приносят «замороженный ответ»
//     (родня speech.mjs / ocr.mjs / gaze.mjs, срез 4 llm.mjs).
//   Нет runner'а — нет модели: адаптер не выдумывает стемы за движок.
//
// ПОДПИСЬ ФАЙЛА (честность входа): магические байты сверяются с названным
// форматом (RIFF/WAVE, ID3|frame-sync, OggS, fLaC, ftyp). Копия дисциплины
// подписи ПОДПИСЕЙ сознательна (самодостаточность адаптера, как у gaze.mjs —
// копия таблицы ocr.mjs); расхождение копий ловят тесты.
//
// ЧЕСТНЫЕ ЧИСЛА (почему они у дома, а не у движка): движок отдаёт отсчёты —
// дом обязан говорить о них правду: RMS/пик/доли мощности считаются здесь,
// чисто, без часов и библиотек. Остаток микса (смесь − сумма стемов) — та же
// честность, что остаток калибровки у gaze.mjs: расхождение видимо числами,
// а не скрыто обещанием «идеального разделения».
//
// Честные границы:
//   - дом не проверяет КАЧЕСТВО разделения — он называет числа (рмс, пик,
//     доли, остаток); качество против эталонных стемов мерит
//     demucs-bench.mjs (SDR без выравнивания) по корпусу владельца;
//   - диапазона на отсчётах НЕТ: конечность — требование, поджатие — грех
//     подмены данных;
//   - тишина стема — честно названа (рмс 0 → громкость не выдумывается);
//   - мок (mockRunner) НЕ притворяется разделять звук: всегда честный отказ;
//   - склейка частей и пин — та же механика, что speech.mjs/ocr.mjs/gaze.mjs;
//     копия сознательна (самодостаточность), вектор SHA-256("abc") держат все
//     четыре копии.
//
// Экспорт: только ESM; импорт — ровно один, канон дома: ../src/core.mjs (STATUS).

