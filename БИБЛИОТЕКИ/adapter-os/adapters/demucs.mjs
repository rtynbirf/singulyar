// ---------------------------------------------------------------------------
// ДВЕРЬ РАЗДЕЛЕНИЯ (синхронная, над замороженным ответом). Порядок честный и
// детерминированный: валидация входа → ledger → runner → строгий разбор →
// честные числа (→ остаток, если смесь названа). Одна модель в ledger — она;
// несколько — id обязателен; бросок runner'а — отказ в конверте. Дверь
// никогда не бросает.
// ---------------------------------------------------------------------------
export function разделить(задание, idМодели) {
  const проверка = валидироватьЗадание(задание);
  if (!проверка.ok) return { отказ: проверка.причина };
  if (ledger.size === 0) {
    return { отказ: 'в ledger нет ни одной модели — сначала registerDemucsModel (модель у владельца, ЛЮК_ВЕСОВ_DEMUCS.md)' };
  }
  if (idМодели === undefined && ledger.size > 1) {
    return { отказ: `в ledger ${ledger.size} моделей — назовите id честно, дом не выбирает за человека` };
  }
  const id = idМодели === undefined ? [...ledger.keys()][0] : idМодели;
  const запись = ledger.get(id);
  if (!запись) return { отказ: `модель "${id}" не зарегистрирована` };
  let разобранный;
  try {
    const конверт = создатьЗадание({
      данные: задание.аудио.данные,
      формат: задание.аудио.формат,
      параметры: задание.параметры,
    });
    const ответ = запись.runner(конверт);
    разобранный = разобратьОтвет(ответ);
  } catch (ошибка) {
    const текст = ошибка && ошибка.message ? ошибка.message : String(ошибка);
    return { отказ: текст };
  }
  const числа = числаСтемов(разобранный.стемы);
  const результат = {
    стемы: разобранный.стемы,
    числа,
    длина: разобранный.длина,
    байт_аудио: задание.аудио.данные.length,
  };
  if (разобранный.смесь) результат.остаток = остатокМикса(разобранный.смесь, разобранный.стемы);
  if (разобранный.частота_дискретизации !== undefined) результат.частота_дискретизации = разобранный.частота_дискретизации;
  return результат;
}

// ---------------------------------------------------------------------------
// АДАПТЕР ДЛЯ РЕЕСТРА (AdapterRegistry). Тот же id, что у контрактной заглушки
// ('tool.demucs'); статус живёт по ledger: пусто/без пина — EXPERIMENTAL
// честно, есть пин — READY. privacy local — звук не покидает устройство.
// ---------------------------------------------------------------------------
export function createDemucsAdapter() {
  return {
    id: ADAPTER_ID,
    kind: 'tool',
    priority: 0,
    status() {
      const модели = списокМоделей();
      if (модели.length === 0) {
        return {
          state: STATUS.EXPERIMENTAL,
          privacy: 'local',
          reason: 'contract present, no model registered: модель у владельца (ЛЮК_ВЕСОВ_DEMUCS.md), до пина честно EXPERIMENTAL',
        };
      }
      const запиненные = модели.filter((м) => м.веса);
      if (запиненные.length > 0) {
        return {
          state: STATUS.READY,
          privacy: 'local',
          reason: `pinned: ${запиненные.map((м) => м.id).join(', ')}`,
        };
      }
      return {
        state: STATUS.EXPERIMENTAL,
        privacy: 'local',
        reason: `модели без пина: ${модели.map((м) => м.id).join(', ')} — честно EXPERIMENTAL`,
      };
    },
    разделить(задание, id) { return разделить(задание, id); },
  };
}
