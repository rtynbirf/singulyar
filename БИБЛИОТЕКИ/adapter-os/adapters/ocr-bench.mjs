// ocr-bench.mjs — СИНГУЛЯР·ADAPTER-OS, такт v10.95 «ЧТЕНИЕ» (С71), строка А3:
// бенчмарк локального OCR — CER/WER против размеченного корпуса.
//
// Требование карты А3: «бенчмарки (ledger трека)». Шаг 1 (speech) принёс
// протокол бенчмарка; шаг 2 переиспользует ОБЩИЕ МЕРИЛА дома — нормализация,
// Левенштейн, WER/CER импортируются из speech-bench.mjs (мерила не должны
// разъезжаться между адаптерами: одна нормализация на дом).
//
// Честные границы:
//   - метрики считаются ТОЛЬКО по размеченному корпусу владельца; мок бегать
//     может, но протокол честно помечает отказы — выдуманного WER нет;
//   - ПУСТОЙ распознанный текст — валидный результат (чистый лист), мерила
//     считают его честно: против непустого эталона это 1.0, против пустого — 0;
//   - тайминги устройства измеряет запускающий снаружи; внутри 0 часов;
//   - протокол детерминирован байт-в-байт: один прогон → один JSON.
//
// Экспорт: только ESM; импорт — ровно один: ./speech-bench.mjs (общие мерила).

import { нормализоватьСлова, левенштейн, верСтрока, церСтрока } from './speech-bench.mjs';

export { нормализоватьСлова, левенштейн, верСтрока, церСтрока }; // те же мерила, названное имя

export const ver = 'ocr-bench/0.1';
export const LEDGER_SCHEMA = 'adapter-os.ocr.bench.v1';

// Точность строки: нормализованная строка распознанного совпала с эталоном
// байт-в-байт (после договора мерила). Классическая «line accuracy» OCR.
export function точнаяСтрока(эталон, получено) {
  return нормализоватьСлова(эталон).join(' ') === нормализоватьСлова(получено).join(' ');
}

// Текст ответа runner'а. Отказ → null (строка уходит с отказом, метрика не
// выдумывается). строки (если пришли) склеиваются переводом строки — они
// построчный разрез того же текста.
export function текстОтветаOcr(ответ) {
  if (!ответ || typeof ответ !== 'object' || Array.isArray(ответ)) return null;
  if (typeof ответ.отказ === 'string' && ответ.отказ) return null;
  if (typeof ответ.текст !== 'string') return null;
  return ответ.текст;
}

// ---------------------------------------------------------------------------
// ПРОГОН БЕНЧМАРКА OCR. Корпус: [{ id, эталон, задание }]; runner — контракт
// ocr.mjs. Протокол детерминирован байт-в-байт.
// ---------------------------------------------------------------------------
export function прогонБенчмаркаOcr(runner, корпус) {
  if (typeof runner !== 'function') {
    throw new TypeError('ocr-bench: прогонБенчмаркаOcr — runner ожидается функцией');
  }
  if (!Array.isArray(корпус) || корпус.length === 0) {
    throw new TypeError('ocr-bench: прогонБенчмаркаOcr — корпус ожидается непустым массивом записей { id, эталон, задание }');
  }
  const строки = [];
  let сумма_вер = 0, сумма_цер = 0, точных = 0, счёт_метрик = 0, счёт_отказов = 0;
  for (let i = 0; i < корпус.length; i++) {
    const запись = корпус[i];
    const где = `корпус[${i}]`;
    if (!запись || typeof запись !== 'object' || Array.isArray(запись)) {
      throw new TypeError(`ocr-bench: ${где} ожидается объектом`);
    }
    if (typeof запись.id !== 'string' || !запись.id) {
      throw new TypeError(`ocr-bench: ${где}.id ожидается непустой строкой`);
    }
    if (typeof запись.эталон !== 'string') {
      throw new TypeError(`ocr-bench: ${где}.эталон ожидается строкой (пустая — честный ноль)`);
    }
    let ответ;
    try {
      ответ = runner(запись.задание);
    } catch (ошибка) {
      ответ = { отказ: ошибка && ошибка.message ? ошибка.message : String(ошибка) };
    }
    const текст = текстОтветаOcr(ответ);
    if (текст === null) {
      счёт_отказов += 1;
      const причина = ответ && typeof ответ.отказ === 'string' ? ответ.отказ : 'ответ runner\'а не разобран (не конверт)';
      строки.push({ id: запись.id, эталон: запись.эталон, распознано: null, вер: null, цер: null, точная: null, отказ: причина });
      continue;
    }
    const вер = верСтрока(запись.эталон, текст);
    const цер = церСтрока(запись.эталон, текст);
    const точная = точнаяСтрока(запись.эталон, текст);
    сумма_вер += вер; сумма_цер += цер; if (точная) точных += 1;
    счёт_метрик += 1;
    строки.push({ id: запись.id, эталон: запись.эталон, распознано: текст, вер, цер, точная, отказ: null });
  }
  return {
    схема: LEDGER_SCHEMA,
    строк_в_корпусе: корпус.length,
    строк_с_метрикой: счёт_метрик,
    строк_с_отказом: счёт_отказов,
    строк_точных: точных,
    вер_среднее: счёт_метрик === 0 ? null : сумма_вер / счёт_метрик,
    цер_среднее: счёт_метрик === 0 ? null : сумма_цер / счёт_метрик,
    доля_точных_строк: счёт_метрик === 0 ? null : точных / счёт_метрик,
    пометка: счёт_отказов === корпус.length
      ? 'ВСЕ СТРОКИ С ОТКАЗОМ: метрик нет — это прогон мока/недоставленной модели, не мера качества (честно)'
      : 'метрики только по строкам с распознанным текстом; мерила общие с speech-bench (одна нормализация на дом)',
    строки,
  };
}
