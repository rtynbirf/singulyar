#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
раскрой_весов.py — СИНГУЛЯР·ADAPTER-OS, такт v10.94 «ГОЛОС» (С70), строка А3.

Инструмент владельца для люка весов Whisper: берёт локальный ggml-файл модели
(например ggml-tiny.bin из whisper.cpp), раскраивает на части ≤ лимита git
(100 МБ), считает SHA-256 целого файла и каждой части, печатает готовый
фрагмент манифеста репы весов (rtynbirf/singulyar-llm → WHISPER/) и команды
выкладки. Ничего не качает и никуда не ходит по сети — только локальный файл.

Использование:
    python3 раскрой_весов.py ПУТЬ_К_МОДЕЛИ.ggml [--лимит 100000000] [--вых WHISPER]

Результат:
    <вых>/<имя>.part-01-of-NN.bin …   — части
    <вых>/МАНИФЕСТ_ФРАГМЕНТ.txt       — готовый блок для МАНИФЕСТа репы весов
    печатный свод: размер целого, SHA-256 целого, части с их SHA-256

Закон дома: пин фиксируется только по факту скачки файла — дом не называет
SHA-256 публичных моделей по памяти.
"""

import argparse
import hashlib
import os
import sys

ГРАНИЦ_ГИТ = 100_000_000          # честный запас: лимит git 100 МБ = 104 857 600
БЛОК = 4 * 1024 * 1024            # чтение кусками 4 МБ


def sha256_файла(путь):
    х = hashlib.sha256()
    with open(путь, "rb") as f:
        while True:
            кусок = f.read(БЛОК)
            if not кусок:
                break
            х.update(кусок)
    return х.hexdigest()


def главное():
    парсер = argparse.ArgumentParser(description="Раскрой ggml-модели Whisper на части ≤ лимита git")
    парсер.add_argument("модель", help="путь к локальному ggml-файлу (веса Whisper)")
    парсер.add_argument("--лимит", type=int, default=ГРАНИЦ_ГИТ, help="максимальный размер части в байтах")
    парсер.add_argument("--вых", default="WHISPER", help="каталог для частей (по умолчанию WHISPER/)")
    арг = парсер.parse_args()

    путь = арг.модель
    if not os.path.isfile(путь):
        print(f"ОТКАЗ: файл не найден: {путь}", file=sys.stderr)
        return 1
    if лимит_низкий(арг.лимит):
        print(f"ОТКАЗ: лимит части {арг.лимит} байт слишком мал (нужно ≥ 1 МБ)", file=sys.stderr)
        return 1

    имя = os.path.basename(путь)
    размер = os.path.getsize(путь)
    print(f"Файл:     {имя}")
    print(f"Размер:   {размер:,} байт".replace(",", " "))
    print("Считаю SHA-256 целого…")
    хэш_целого = sha256_файла(путь)
    print(f"SHA-256:  {хэш_целого}")

    частей = (размер + арг.лимит - 1) // арг.лимит
    print(f"Частей:   {частей} (лимит части {арг.лимит:,} байт)".replace(",", " "))

    os.makedirs(арг.вых, exist_ok=True)
    свод = [
        "ФРАГМЕНТ МАНИФЕСТА — singulyar-llm → WHISPER/",
        "=" * 60,
        "",
        "ЦЕЛОЕ ФАЙЛА",
        f"Файл:     WHISPER/{имя}",
        f"Размер:   {размер} байт",
        f"SHA-256:  {хэш_целого}",
        "",
        "ЧАСТИ (по порядку, имя — размер — SHA-256)",
    ]
    офсет = 0
    счёт = 0
    with open(путь, "rb") as источник:
        while офсет < размер:
            счёт += 1
            длина = min(арг.лимит, размер - офсет)
            часть_имя = f"{имя}.part-{счёт:02d}-of-{частей:02d}.bin"
            часть_путь = os.path.join(арг.вых, часть_имя)
            х = hashlib.sha256()
            записано = 0
            with open(часть_путь, "wb") as приёмник:
                while записано < длина:
                    кусок = источник.read(min(БЛОК, длина - записано))
                    if not кусок:
                        break
                    приёмник.write(кусок)
                    х.update(кусок)
                    записано += len(кусок)
            if записано != длина:
                print(f"ОТКАЗ: файл короче, чем обещал размер каталога ({записано} < {длина})", file=sys.stderr)
                return 1
            хэш_части = х.hexdigest()
            свод.append(f"WHISPER/{часть_имя}  {записано}  {хэш_части}")
            print(f"  часть {счёт:02d}/{частей:02d}: {часть_имя} ({записано:,} байт)".replace(",", " "))
            офсет += длина

    свод += [
        "",
        "КАК ПРОВЕРИТЬ ПОСЛЕ ВЫКЛАДКИ",
        "  sha256sum WHISPER/*.bin   — сверить с этим фрагментом построчно",
        f"  cat WHISPER/{имя}.part-*-of-{частей:02d}.bin > /tmp/{имя} && sha256sum /tmp/{имя}",
        f"      → должен совпасть с {хэш_целого}",
        "",
        "ПИН В ДОМЕ (после выкладки частей в репу весов):",
        "  registerWhisperModel({",
        f"    id: '<имя-модели>',",
        "    runner: <двигатель whisper.cpp/wasm, замороженный ответ>,",
        "    движок: 'whisper.cpp/wasm',",
        "    веса: {",
        f"      имя: '{имя}',",
        f"      sha256: '{хэш_целого}',",
        f"      байт: {размер},",
        f"      частей: {частей},",
        "    },",
        "  });",
    ]
    фрагмент = os.path.join(арг.вых, "МАНИФЕСТ_ФРАГМЕНТ.txt")
    with open(фрагмент, "w", encoding="utf-8") as f:
        f.write("\n".join(свод) + "\n")
    print(f"\nГотово. Фрагмент манифеста: {фрагмент}")
    print("Дальше — по ЛЮК_ВЕСОВ_WHISPER.md (выкладка в rtynbirf/singulyar-llm → WHISPER/).")
    return 0


def лимит_низкий(лимит):
    return лимит < 1_000_000


if __name__ == "__main__":
    sys.exit(главное())
