// test-speech.mjs — СИНГУЛЯР·ADAPTER-OS, такт v10.94 «ГОЛОС» (С70):
// контрактные тесты speech.mjs + speech-bench.mjs (строка А3, шаг 1).
// Запуск: node БИБЛИОТЕКИ/adapter-os/tests/test-speech.mjs
// Правило дома: RED против живых файлов, честный PASS-счёт, без подтирок.

import assert from 'node:assert/strict';
import { AdapterRegistry, STATUS } from '../src/core.mjs';
import {
  ADAPTER_ID, LEDGER_SCHEMA, МАКС_СЕГМЕНТОВ, ПРИЧИНА_МОКА,
  mockRunner, создатьЗадание, валидироватьЗадание, разобратьОтвет,
  registerWhisperModel, списокМоделей, склеитьЧасти, сверитьПин,
  распознать, createSpeechAdapter,
} from '../adapters/speech.mjs';
import {
  нормализоватьСлова, левенштейн, верСтрока, церСтрока,
  текстОтвета, прогонБенчмарка,
} from '../adapters/speech-bench.mjs';

let счёт = 0;
function ок(имя) { счёт += 1; console.log(`  ✓ ${имя}`); }

// Детерминированный «замороженный» runner: честная модель теста — одно аудио
// → один ответ; аудио не читается умнее, чем нужно тесту (длина + первый байт
// через функцию), никакого шума и часов.
function замороженныйRunner(сегменты, язык = 'ru') {
  return function () { return { сегменты, язык }; };
}

// Правильное ЗАДАНИЕ по контракту: аудио в обёртке {аудио: {данные, частота}}.
const ЦЕЛ_ЗАДАНИЕ = { аудио: { данные: new Float32Array([0.1, -0.2, 0.3]), частота: 16000 } };

async function main() {
  // --- 1. Ledger пуст на импорте — честно --------------------------------
  assert.deepEqual(списокМоделей(), [], 'ledger пуст на импорте');
  assert.ok(распознать({ аудио: { данные: new Float32Array([0.1]), частота: 16000 } }).отказ.includes('нет ни одной модели'), 'пустой ledger — честный отказ');
  ок('ledger пуст на импорте — моделей в доме нет, дверь честно отказывает');

  // --- 2. Честный мок ----------------------------------------------------
  const мок = mockRunner();
  const ответМока = мок({});
  assert.ok(typeof ответМока.отказ === 'string' && ответМока.отказ.includes('МОК'), 'мок отказывается честно');
  assert.deepEqual(мок({}), ответМока, 'мок детерминирован');
  assert.equal(мок({}).отказ, ПРИЧИНА_МОКА);
  ок('мок: честный отказ с названной причиной, байт-в-байт детерминизм');

  // --- 3. Регистрация: честные true/false --------------------------------
  assert.equal(registerWhisperModel(null), false, 'null — false');
  assert.equal(registerWhisperModel({ id: 'тест', runner: 'не функция' }), false, 'runner не функция — false');
  assert.equal(registerWhisperModel({ id: 'плохой id!', runner: мок }), false, 'плохой id — false');
  assert.equal(registerWhisperModel({ id: 'тест', runner: мок, веса: { имя: 'w', sha256: 'НЕТХЭША', байт: 1, частей: 1 } }), false, 'плохой хэш — false');
  assert.equal(registerWhisperModel({ id: 'тест', runner: мок, веса: { имя: 'w', sha256: 'a'.repeat(64), байт: 1 } }), false, 'полупин без частей — false');
  assert.equal(registerWhisperModel({ id: 'тест', runner: мок }), true, 'валидная регистрация — true');
  assert.equal(registerWhisperModel({ id: 'тест', runner: мок }), false, 'дубликат id — false');
  ок('регистрация: true/false честные, полупиннинг запрещён, дубликат — false');

  // --- 4. Список моделей: EXPERIMENTAL честно ----------------------------
  const список = списокМоделей();
  assert.equal(список.length, 1);
  assert.equal(список[0].имя, 'whisper/тест', 'имя = whisper/<id>');
  assert.ok(список[0].статус.startsWith('EXPERIMENTAL'), 'без пина — EXPERIMENTAL');
  assert.equal(список[0].веса, null);
  ок('список моделей: статус EXPERIMENTAL назван честно, весов нет');

  // --- 4-б. Статус адаптера ДО пинов: EXPERIMENTAL честно -----------------
  const адаптерРано = createSpeechAdapter();
  const раноСт = адаптерРано.status();
  assert.equal(раноСт.state, STATUS.EXPERIMENTAL, 'непиненные модели — EXPERIMENTAL');
  assert.ok(раноСт.reason.includes('честно EXPERIMENTAL'), 'причина названа');
  assert.equal(раноСт.privacy, 'local', 'приватность local');
  ок('статус адаптера до пинов: EXPERIMENTAL честно, privacy local');

  // --- 5. Валидация задания ---------------------------------------------
  assert.equal(валидироватьЗадание(null).ok, false);
  assert.equal(валидироватьЗадание({}).ok, false, 'без аудио — беда');
  assert.equal(валидироватьЗадание({ аудио: { данные: [1, 2], частота: 16000 } }).ok, false, 'массив — не typed array');
  assert.equal(валидироватьЗадание({ аудио: { данные: new Float32Array(0), частота: 16000 } }).ok, false, 'пустое аудио — честный отказ');
  assert.equal(валидироватьЗадание({ аудио: { данные: new Int16Array(4), частота: 0 } }).ok, false, 'частота 0 — беда');
  assert.equal(валидироватьЗадание({ аудио: { данные: new Float32Array(4), частота: 16000 }, язык: 'ru!' }).ok, false, 'язык ru! — беда');
  assert.equal(валидироватьЗадание({ аудио: { данные: new Float32Array(4), частота: 16000 }, язык: 'auto' }).ok, true);
  assert.equal(валидироватьЗадание({ аудио: { данные: new Float32Array(4), частота: 16000 }, язык: 'zh-Hans' }).ok, true, 'zh-Hans читается');
  assert.equal(валидироватьЗадание({ аудио: { данные: new Float32Array(4), частота: 16000 }, параметры: null }).ok, false, 'параметры null — беда');
  ок('валидация задания: typed array, частота, язык (ru/kk/sr/zh-Hans/auto), параметры');

  // --- 6. создатьЗадание: вход не мутируется ----------------------------
  const сырьё = new Float32Array([0.5, 0.25]);
  const конверт = создатьЗадание({ данные: сырьё, частота: 16000, язык: 'ru' });
  сырьё[0] = 9.9; // мутация источника после создания
  assert.equal(конверт.аудио.данные[0], 0.5, 'копия защитила конверт');
  ок('создатьЗадание: копия данных — вход не шарится и не мутируется');

  // --- 7. Разбор ответа: строгий, ничего не чинится молча ----------------
  const добрый = { сегменты: [{ начало: 0, конец: 1.5, текст: 'привет' }, { начало: 1.5, конец: 2.5, текст: 'дом' }], язык: 'ru' };
  assert.equal(разобратьОтвет(добрый).сегменты.length, 2);
  assert.throws(() => разобратьОтвет(null), TypeError);
  assert.throws(() => разобратьОтвет({ отказ: 'модель отказалась' }), /отказалась/);
  assert.throws(() => разобратьОтвет({ язык: 'ru' }), /сегменты/);
  assert.throws(() => разобратьОтвет({ сегменты: [{ начало: -1, конец: 1, текст: 'х' }] }), /начало/);
  assert.throws(() => разобратьОтвет({ сегменты: [{ начало: 2, конец: 2, текст: 'х' }] }), /конец/);
  assert.throws(() => разобратьОтвет({ сегменты: [{ начало: 0, конец: 1, текст: '  ' }] }), /текст/);
  assert.throws(() => разобратьОтвет({ сегменты: [{ начало: 0, конец: 2, текст: 'а' }, { начало: 1, конец: 3, текст: 'б' }] }), /наложился/);
  assert.throws(() => разобратьОтвет({ сегменты: [{ начало: 2, конец: 3, текст: 'б' }, { начало: 0, конец: 1, текст: 'а' }] }), /наложился/, 'назад по времени поймается как наложение');
  assert.throws(() => разобратьОтвет({ сегменты: [{ начало: 0, конец: 1, текст: 'х' }], язык: 'ru!!' }), /язык/);
  assert.throws(() => разобратьОтвет({ сегменты: new Array(МАКС_СЕГМЕНТОВ + 1).fill(0).map((_, i) => ({ начало: i, конец: i + 1, текст: 'х' })) }), /больше/);
  ок('разбор ответа: 9 честных отказов (наложение — в том числе ход назад, пустой текст, граница объёма…)');

  // --- 8. Дверь распознавания -------------------------------------------
  const мокОтказ = распознать(ЦЕЛ_ЗАДАНИЕ); // в ledger «тест» — мок
  assert.ok(мокОтказ.отказ.includes('МОК'), 'мок в ledger — честный отказ через дверь');
  registerWhisperModel({ id: 'одна', runner: замороженныйRunner([{ начало: 0, конец: 1, текст: 'голос' }]) });
  const хорошо = распознать(ЦЕЛ_ЗАДАНИЕ, 'одна');
  assert.equal(хорошо.сегменты[0].текст, 'голос');
  assert.equal(хорошо.язык, 'ru');
  registerWhisperModel({ id: 'вторая', runner: замороженныйRunner([]) });
  const спор = распознать(ЦЕЛ_ЗАДАНИЕ);
  assert.ok(спор.отказ.includes('назовите id'), 'несколько моделей — дом не выбирает за человека');
  assert.ok(распознать(ЦЕЛ_ЗАДАНИЕ, 'нет-такой').отказ.includes('не зарегистрирована'));
  const бросок = registerWhisperModel({ id: 'бросок', runner: () => { throw new Error('двигатель упал'); } });
  assert.equal(бросок, true);
  assert.ok(распознать(ЦЕЛ_ЗАДАНИЕ, 'бросок').отказ.includes('двигатель упал'), 'бросок runner\'а — честный отказ в конверте');
  ок('дверь распознавания: пусто/одна/несколько/чужой id/бросок — все отказы названы');

  // --- 9. Детерминизм двери ---------------------------------------------
  const снова = распознать(ЦЕЛ_ЗАДАНИЕ, 'одна');
  assert.equal(JSON.stringify(хорошо), JSON.stringify(снова), 'один вход → один выход');
  ок('детерминизм: одно аудио → один ответ, байт-в-байт');

  // --- 10. Склейка частей и пин ------------------------------------------
  const байты = new TextEncoder().encode('abc');
  const склейка = await склеитьЧасти([байты]);
  assert.equal(склейка.sha256, 'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad', 'известный вектор SHA-256("abc")');
  assert.equal(склейка.байт, 3);
  const части = [байты.slice(0, 1), байты.slice(1, 2), байты.slice(2, 3)];
  const склейка2 = await склеитьЧасти(части);
  assert.equal(склейка2.sha256, склейка.sha256, 'части 1+1+1 склеиваются в тот же хэш');
  await assert.rejects(() => склеитьЧасти([]), TypeError, 'пустой массив частей — беда');
  await assert.rejects(() => склеитьЧасти(['не Uint8Array']), TypeError);
  ок('склейка частей: вектор SHA-256, порядок частей, честные отказы');

  // --- 11. сверитьПин: все ветки ----------------------------------------
  assert.equal((await сверитьПин('нет-такой', части)).ok, false, 'нет модели');
  assert.equal((await сверитьПин('тесст'.slice(0, 0) + 'одна', части)).ok, false, 'модель без пина — сверять нечем');
  const ХЭШ_ABC = склейка.sha256;
  registerWhisperModel({ id: 'пин-модель', runner: мок, веса: { имя: 'ggml/tiny.bin', sha256: ХЭШ_ABC, байт: 3, частей: 3 }, движок: 'whisper.cpp/wasm' });
  const пинОк = await сверитьПин('пин-модель', части);
  assert.equal(пинОк.ok, true, 'сошлось — данные выдаются');
  assert.deepEqual([...пинОк.данные], [...байты]);
  const кривые = [байты.slice(1), байты.slice(0, 1)]; // другой КОНТЕНТ (bca) — раскрой тех же байт дал бы тот же хэш (это и есть суть частей)
  const пинПлохой = await сверитьПин('пин-модель', кривые);
  assert.equal(пинПлохой.ok, false, 'расхождение хэша — отказ');
  assert.ok(пинПлохой.причина.includes('не сошёлся'), 'причина названа');
  const пустаяЧасть = await сверитьПин('пин-модель', [new Uint8Array(0)]);
  assert.equal(пустаяЧасть.ok, false, 'пустая часть — честный отказ склейки');
  ок('пин: сошлось/не сошлось/нет модели/нет пина/пустая часть — склейка не выдаётся при расхождении');

  // --- 12. Статус адаптера ПОСЛЕ пина: READY, реестр принимает ------------
  const адаптер = createSpeechAdapter();
  assert.equal(адаптер.id, ADAPTER_ID);
  assert.equal(адаптер.kind, 'input');
  assert.ok(адаптер.priority > 0);
  const реестр = new AdapterRegistry();
  реестр.register(адаптер);
  const ст = адаптер.status();
  assert.equal(ст.state, STATUS.READY, 'есть пин (пин-модель) — READY');
  assert.ok(ст.reason.includes('пин-модель'), 'имя пиненой названо');
  registerWhisperModel({ id: 'готовая', runner: мок, веса: { имя: 'ggml/base.bin', sha256: 'b'.repeat(64), байт: 142000000, частей: 2 } });
  assert.ok(адаптер.status().reason.includes('готовая'));
  const статусы = реестр.statuses();
  assert.ok(статусы.some((s) => s.id === ADAPTER_ID && s.state === STATUS.READY));
  ок('статус адаптера после пина: READY честно, реестр дома принимает');

  // --- 13. Бенчмарк: нормализация и метрики ------------------------------
  assert.deepEqual(нормализоватьСлова('Ёлка, ТЫГЫДЫМ!'), ['елка', 'тыгыдым']);
  assert.equal(левенштейн(['а', 'б'], ['а', 'в']), 1);
  assert.equal(левенштейн([], ['а']), 1);
  assert.equal(верСтрока('я люблю тебя', 'я люблю тебя'), 0, 'идеал — 0');
  assert.ok(Math.abs(верСтрока('я люблю тебя', 'я люблю вас') - 1 / 3) < 1e-12, 'замена одного слова из трёх = 1/3');
  assert.equal(верСтрока('', ''), 0);
  assert.equal(верСтрока('', 'лишнее'), 1, 'эталон пуст — честная единица, не деление на ноль');
  assert.equal(церСтрока('дом', 'дон'), 1 / 3, 'CER по символам');
  ок('метрики: WER/CER, нормализация (регистр, ё→е, пунктуация), деление на ноль названо');

  // --- 14. Бенчмарк: прогон ---------------------------------------------
  const корпус = [
    { id: 'строка-1', эталон: 'я люблю тебя', задание: ЦЕЛ_ЗАДАНИЕ },
    { id: 'строка-2', эталон: 'дом', задание: ЦЕЛ_ЗАДАНИЕ },
  ];
  const протокол = прогонБенчмарка(замороженныйRunner([{ начало: 0, конец: 1, текст: 'дом' }]), корпус);
  assert.equal(протокол.схема, 'adapter-os.speech.bench.v1');
  assert.equal(протокол.строк_в_корпусе, 2);
  assert.equal(протокол.строк_с_метрикой, 2);
  assert.equal(протокол.строк_с_отказом, 0);
  assert.ok(Math.abs(протокол.вер_среднее - 0.5) < 1e-12, 'строка-1 WER=1 (3/3), строка-2 WER=0 → среднее 0.5');
  const протоколМока = прогонБенчмарка(мок, корпус);
  assert.equal(протоколМока.строк_с_отказом, 2);
  assert.equal(протоколМока.вер_среднее, null, 'отказы не превращаются в выдуманный WER');
  assert.ok(протоколМока.пометка.includes('не мера качества'), 'мок честно помечен');
  const байт1 = JSON.stringify(протоколМока);
  const байт2 = JSON.stringify(прогонБенчмарка(мок, корпус));
  assert.equal(байт1, байт2, 'протокол детерминирован байт-в-байт');
  assert.throws(() => прогонБенчмарка(мок, []), TypeError, 'пустой корпус — беда');
  assert.throws(() => прогонБенчмарка('не функция', корпус), TypeError);
  assert.equal(текстОтвета({ отказ: 'х' }), null);
  assert.equal(текстОтвета({ сегменты: [{ начало: 0, конец: 1, текст: 'а' }, { начало: 1, конец: 2, текст: 'б' }] }), 'а б');
  ок('прогон: протокол без часов, отказы честные, детерминизм байт-в-байт, пустой корпус — отказ');

  // --- 15. Схемы ---------------------------------------------------------
  assert.equal(LEDGER_SCHEMA, 'adapter-os.speech.v1');
  ок('схемы ledger названы: adapter-os.speech.v1 / .bench.v1');

  console.log(`PASS speech ${счёт}/16`);
}

main().catch((ошибка) => { console.error('FAIL', ошибка); process.exit(1); });
