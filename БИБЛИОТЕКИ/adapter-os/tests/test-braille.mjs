// test-braille.mjs — СИНГУЛЯР·ADAPTER-OS, такт v11.00 «БРАЙЛЬ» (С76):
// контрактные тесты braille.mjs (строка А3, шаг 5 — последний).
// Запуск: node БИБЛИОТЕКИ/adapter-os/tests/test-braille.mjs

import assert from 'node:assert/strict';
import { AdapterRegistry, STATUS } from '../src/core.mjs';
import { brailleContract } from '../adapters/contracts.mjs';
import {
  ADAPTER_ID, LEDGER_SCHEMA, ver, ПРИОРИТЕТ, СЛУЖЕБНЫЕ, ЗНАК_ЗАГЛАВНОЙ, ЗНАК_ЦИФР,
  ТАБЛИЦА_LATIN_G1, РЕЖИМЫ, ячейка, валидироватьТаблицу, registerBrailleTable,
  списокТаблиц, валидироватьЗадание, брайль, createBrailleAdapter,
} from '../adapters/braille.mjs';

let счёт = 0;
function ок(имя) { счёт += 1; console.log(`  ✓ ${имя}`); }

// Канон ячеек a–z (Луи Брайль/UEB grade 1) — своя копия в тесте: расхождение
// копий ловится здесь, а не живёт молча.
const КАНОН_A_Z = ['⠁','⠃','⠉','⠙','⠑','⠋','⠛','⠓','⠊','⠚','⠅','⠇','⠍','⠝','⠕','⠏','⠟','⠗','⠎','⠞','⠥','⠧','⠺','⠭','⠽','⠵'];

async function main() {
  // --- 1. Встроенная таблица дома -----------------------------------------
  const список = списокТаблиц();
  assert.equal(список.length, 1, 'на импорте в доме ровно одна таблица');
  assert.equal(список[0].id, 'latin-g1');
  assert.equal(список[0].встроенная, true);
  assert.equal(список[0].символов, 30, '26 букв + 4 знака пунктуации');
  assert.ok(список[0].статус.includes('закреплена тестами'));
  ок('встроенная таблица latin-g1 при импорте — канон дома, закреплён тестами');

  // --- 2. Алфавит a–z: точные коды ячеек -----------------------------------
  const алфавит = брайль({ текст: 'abcdefghijklmnopqrstuvwxyz' });
  assert.equal(алфавит.ячейки, КАНОН_A_Z.join(''), 'a–z байт-в-байт по канону');
  assert.equal(алфавит.знаков_цифр, 0);
  assert.equal(алфавит.знаков_заглавных, 0);
  ок('алфавит a–z: ячейки U+2800-блока точны, сравнение с независимой копией канона');

  // --- 3. Знак заглавной (точка 6) -----------------------------------------
  assert.equal(ячейка(ЗНАК_ЗАГЛАВНОЙ), '⠠', 'знак заглавной = U+2820');
  assert.equal(брайль({ текст: 'A' }).ячейки, '⠠⠁', 'A = знак заглавной + ячейка a');
  assert.equal(брайль({ текст: 'Ab' }).ячейки, '⠠⠁⠃');
  assert.equal(брайль({ текст: 'ABC' }).ячейки, '⠠⠁⠠⠃⠠⠉', 'знак перед КАЖДОЙ заглавной');
  ок('знак заглавной: точка 6 перед каждой заглавной, названо');

  // --- 4. Цифры и группы ----------------------------------------------------
  assert.equal(ячейка(ЗНАК_ЦИФР), '⠼', 'знак цифр = U+283C (точки 3-4-5-6)');
  assert.equal(брайль({ текст: '1' }).ячейки, '⠼⠁', '1 = a');
  assert.equal(брайль({ текст: '31' }).ячейки, '⠼⠉⠁', '31 — знак один раз на группу');
  assert.equal(брайль({ текст: '10.88' }).ячейки, '⠼⠁⠚⠲⠼⠓⠓', '10.88 — две группы, точка между');
  assert.equal(брайль({ текст: '0' }).ячейки, '⠼⠚', '0 = j');
  ок('цифры 1–0 через a–j: знак цифр перед каждой группой, механика названа');

  // --- 5. Пунктуация ---------------------------------------------------------
  assert.equal(брайль({ текст: ',' }).ячейки, '⠂', 'запятая = точка 2');
  assert.equal(брайль({ текст: '.' }).ячейки, '⠲', 'точка = 2-5-6');
  assert.equal(брайль({ текст: "'" }).ячейки, '⠄', 'апостроф = точка 3');
  assert.equal(брайль({ текст: '-' }).ячейки, '⠤', 'дефис = 3-6');
  ок('пунктуация: запятая/точка/апостроф/дефис — канон Луи Брайля');

  // --- 6. Строка целиком -------------------------------------------------------
  const строка = брайль({ текст: 'Abc 31,' });
  assert.equal(строка.ячейки, '⠠⠁⠃⠉ ⠼⠉⠁⠂', 'заглавная+строчные+пробел+группа цифр+запятая');
  assert.equal(строка.символов, 7);
  assert.equal(строка.ячеек, 9);
  assert.equal(строка.знаков_цифр, 1);
  assert.equal(строка.знаков_заглавных, 1);
  assert.equal(строка.таблица, 'latin-g1');
  assert.equal(строка.режим, 'строгий', 'режим по умолчанию назван');
  ок('строка целиком: отчёт честный (символов/ячеек/знаки/таблица/режим)');

  // --- 7. Валидация задания ----------------------------------------------------
  function валид(з) { return валидироватьЗадание(з).ok; }
  assert.equal(валид(null), false);
  assert.equal(валид('текст'), false, 'строка вместо задания — беда');
  assert.equal(валид({ текст: 42 }), false, 'текст не строка — беда');
  assert.equal(валид({ текст: null }), false);
  assert.equal(валид({ текст: 'ок', режим: 'махарайон' }), false, 'режим не из списка — беда');
  assert.equal(валид({ текст: 'ок', режим: 'с_заглушками' }), true);
  assert.deepEqual([...РЕЖИМЫ], ['строгий', 'с_заглушками'], 'два режима, названы');
  ок('валидация задания: строка, режим из двух названных, честные отказы');

  // --- 8. Пустой текст — честная пустота --------------------------------------
  const пусто = брайль({ текст: '' });
  assert.equal(пусто.ячейки, '');
  assert.equal(пусто.пусто, true, 'честная пустота названа (как чистый лист у OCR)');
  assert.equal(пусто.символов, 0);
  ок('пустой текст — честная пустота, ничего не выдумано');

  // --- 9. Строгий режим: незнакомый символ — честный отказ ---------------------
  const отказ = брайль({ текст: 'привет' }); // кириллица не в latin-g1
  assert.ok(отказ.отказ.includes('позиции 0'), 'позиция названа');
  assert.ok(отказ.отказ.includes('U+043F'), 'код символа назван');
  assert.ok(отказ.отказ.includes('не выдумывает'), 'дом не выдумывает ячейки');
  const отказСередина = брайль({ текст: 'abЖd' });
  assert.ok(отказСередина.отказ.includes('позиции 2'), 'позиция в середине названа');
  const отказТаб = брайль({ текст: 'a\tb' });
  assert.ok(отказТаб.отказ.includes('U+0009'), 'табуляция — тоже честный отказ');
  ок('строгий режим: незнакомый символ — отказ с позицией и кодом, ячейки не выдуманы');

  // --- 10. Режим с_заглушками: потеря названа -----------------------------------
  const заглушки = брайль({ текст: 'aЖb', режим: 'с_заглушками' });
  assert.equal(заглушки.ячейки, '⠁\u2800⠃', 'незаполненная ячейка U+2800 на месте неизвестного');
  assert.deepEqual(заглушки.заглушки, [{ позиция: 1, символ: 'Ж' }], 'потеря названа посимвольно');
  const заглушкиЦифры = брайль({ текст: '1', режим: 'с_заглушками' }); // latin-g1 имеет a — цифра переводится
  assert.equal(заглушкиЦифры.ячейки, '⠼⠁');
  ок('режим с_заглушками: пустая ячейка + список потерь — ничего не теряется молча');

  // --- 11. Регистрация таблиц: честные true/false -------------------------------
  assert.equal(registerBrailleTable(null), false);
  assert.equal(registerBrailleTable('таблица'), false);
  assert.equal(registerBrailleTable({ id: 'плохой id!', таблица: { 'ж': [1] } }), false);
  assert.equal(registerBrailleTable({ id: 'тест' }), false, 'без таблицы — false');
  assert.equal(registerBrailleTable({ id: 'тест', таблица: {} }), false, 'пустая таблица — false');
  assert.equal(registerBrailleTable({ id: 'тест', таблица: { 'аб': [1] } }), false, 'ключ — ровно один символ');
  assert.equal(registerBrailleTable({ id: 'тест', таблица: { '\u0020': [1] } }), false, 'пробел таблицей не подменяется');
  assert.equal(registerBrailleTable({ id: 'тест', таблица: { '\n': [1] } }), false, 'перевод строки таблицей не подменяется');
  assert.equal(registerBrailleTable({ id: 'тест', таблица: { 'ж': 'да' } }), false, 'значение не массив — false');
  assert.equal(registerBrailleTable({ id: 'тест', таблица: { 'ж': [] } }), false, 'пустые точки — false');
  assert.equal(registerBrailleTable({ id: 'тест', таблица: { 'ж': [0] } }), false, 'точка 0 — беда');
  assert.equal(registerBrailleTable({ id: 'тест', таблица: { 'ж': [9] } }), false, 'точка 9 — беда');
  assert.equal(registerBrailleTable({ id: 'тест', таблица: { 'ж': [1.5] } }), false, 'дробная точка — беда');
  assert.equal(registerBrailleTable({ id: 'тест', таблица: { 'ж': [1, 1] } }), false, 'дубликат точки — беда');
  assert.equal(registerBrailleTable({ id: 'тест', таблица: { 'ж': [1, 2, 3] } }), true, 'валидная — true');
  assert.equal(registerBrailleTable({ id: 'тест', таблица: { 'ж': [4] } }), false, 'дубликат id — false');
  ок('регистрация таблиц: структурная строгость, 13 провалов названы, дубликат — false');

  // --- 12. Несколько таблиц — id обязателен; своя таблица работает ---------------
  assert.ok(брайль({ текст: 'a' }).отказ.includes('назовите id'), 'после регистрации дом не выбирает таблицу за человека');
  assert.ok(брайль({ текст: 'a', режим: 'строгий' }).отказ.includes('назовите id'), 'режим не спасает — id обязателен');
  assert.ok(брайль({ текст: 'a' }, 'нет-такой').отказ.includes('не зарегистрирована'));
  const своя = брайль({ текст: 'ж' }, 'тест');
  assert.equal(своя.ячейки, '⠇', 'своя таблица: ж = точки 1-2-3 = U+2807');
  assert.ok(брайль({ текст: 'я' }, 'latin-g1').отказ.includes('U+044F'), 'в latin-g1 кириллицы нет — честный отказ');
  // Копия: мутация входа после регистрации не меняет дом.
  const сырьё = { 'ч': [1, 4] };
  registerBrailleTable({ id: 'копия', таблица: сырьё });
  сырьё['ч'] = [2];
  assert.equal(брайль({ текст: 'ч' }, 'копия').ячейки, '⠉', 'вход не шарится — дом защитил таблицу');
  assert.equal(списокТаблиц().length, 3, 'в ledger три таблицы');
  ок('свойства таблиц: id обязателен, своя таблица работает, вход защищён копией');

  // --- 13. Валидация таблицы напрямую и ячейка() ---------------------------------
  assert.equal(валидироватьТаблицу(null).ok, false);
  assert.equal(валидироватьТаблицу([]).ok, false, 'массив — не таблица');
  assert.equal(валидироватьТаблицу(ТАБЛИЦА_LATIN_G1).ok, true, 'встроенная таблица структурно чиста');
  assert.throws(() => ячейка([]), TypeError, 'пустые точки — беда');
  assert.throws(() => ячейка([0]), TypeError);
  assert.throws(() => ячейка([9]), TypeError);
  assert.throws(() => ячейка([1, 1]), TypeError, 'дубликат точки — беда');
  assert.equal(ячейка([1, 2, 4, 5]), '⠛', 'g = 1-2-4-5');
  assert.deepEqual([...СЛУЖЕБНЫЕ], ['\u0020', '\n'], 'служебные названы');
  ок('валидироватьТаблицу/ячейка: границы точек 1..8, дубликаты, служебные — названы');

  // --- 14. Пробел, перевод строки, детерминизм ------------------------------------
  const многострочный = брайль({ текст: 'a\nb' }, 'latin-g1');
  assert.equal(многострочный.ячейки, '⠁\n⠃', 'структура текста сохранена');
  const снова = брайль({ текст: 'Abc 31,' }, 'latin-g1');
  assert.equal(JSON.stringify(брайль({ текст: 'Abc 31,' }, 'latin-g1')), JSON.stringify(снова), 'один вход → один выход, байт-в-байт');
  const однобайт = брайль({ текст: 'Abc 31,', режим: 'с_заглушками' }, 'latin-g1');
  assert.equal(JSON.stringify(брайль({ текст: 'Abc 31,', режим: 'с_заглушками' }, 'latin-g1')), JSON.stringify(однобайт), 'детерминизм в обоих режимах');
  ок('пробел/перевод строки — как есть; детерминизм байт-в-байт в двух режимах');

  // --- 15. Статус адаптера: READY честно, реестр дома принимает --------------------
  const адаптер = createBrailleAdapter();
  assert.equal(адаптер.id, ADAPTER_ID);
  assert.equal(адаптер.kind, 'output');
  assert.equal(адаптер.priority, 50, 'приоритет контракта output.braille — 50');
  const ст = адаптер.status();
  assert.equal(ст.state, STATUS.READY, 'перевод детерминирован и проверен — READY честно');
  assert.equal(ст.privacy, 'local', '0 сети');
  assert.ok(ст.reason.includes('Unicode Braille only'), 'граница Unicode-only названа');
  assert.ok(ст.reason.includes('hardware optional'), 'отсутствие дисплея названо');
  const реестр = new AdapterRegistry();
  реестр.register(адаптер);
  const статусы = реестр.statuses();
  assert.ok(статусы.some((s) => s.id === ADAPTER_ID && s.state === STATUS.READY));
  assert.equal(адаптер.брайль({ текст: 'a' }, 'latin-g1').ячейки, '⠁', 'дверь через адаптер работает');
  ок('статус адаптера: READY честно (контракт = unicode-braille), границы названы, реестр принимает');

  // --- 16. Схемы, канон, контракт не тронут -----------------------------------------
  assert.equal(ver, 'braille-adapter/0.1');
  assert.equal(LEDGER_SCHEMA, 'adapter-os.braille.v1');
  assert.equal(ADAPTER_ID, 'output.braille');
  assert.equal(ПРИОРИТЕТ, 50);
  assert.equal(brailleContract.id, ADAPTER_ID, 'id совпадает с контрактной заглушкой');
  assert.equal(brailleContract.contract.output, 'unicode-braille', 'контракт требует unicode-braille');
  assert.equal(brailleContract.status().state, STATUS.EXPERIMENTAL, 'заглушка contracts.mjs не тронута (байт-в-байт)');
  ок('схемы и канон названы: braille.v1 / output.braille / приоритет 50 / контракт цел');

  console.log(`PASS braille ${счёт}/16`);
}

main().catch((ошибка) => { console.error('FAIL', ошибка); process.exit(1); });
