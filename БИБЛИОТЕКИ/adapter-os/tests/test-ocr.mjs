// test-ocr.mjs — СИНГУЛЯР·ADAPTER-OS, такт v10.95 «ЧТЕНИЕ» (С71):
// контрактные тесты ocr.mjs + ocr-bench.mjs (строка А3, шаг 2).
// Запуск: node БИБЛИОТЕКИ/adapter-os/tests/test-ocr.mjs

import assert from 'node:assert/strict';
import { AdapterRegistry, STATUS } from '../src/core.mjs';
import {
  ADAPTER_ID, LEDGER_SCHEMA, МАКС_СТРОК, МАКС_СИМВОЛОВ, ФОРМАТЫ, ПРИЧИНА_МОКА,
  mockRunner, создатьЗадание, валидироватьЗадание, разобратьОтвет,
  registerOcrModel, списокМоделей, склеитьЧасти, сверитьПин,
  распознать, createOcrAdapter, ПОДПИСИ,
} from '../adapters/ocr.mjs';
import { точнаяСтрока, текстОтветаOcr, прогонБенчмаркаOcr } from '../adapters/ocr-bench.mjs';

let счёт = 0;
function ок(имя) { счёт += 1; console.log(`  ✓ ${имя}`); }

function замороженныйRunner(конверт) {
  return function () { return конверт; };
}

// Настоящая PNG-подпись (8 байт) + полезная нагрузка.
const PNG_ГОЛОВА = new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 1, 2, 3]);
const JPEG_ГОЛОВА = new Uint8Array([0xff, 0xd8, 0xff, 0xe0, 1, 2, 3]);
const ЦЕЛ_ЗАДАНИЕ = { изображение: { данные: PNG_ГОЛОВА, формат: 'png' }, язык: 'ru' };

async function main() {
  // --- 1. Ledger пуст на импорте — честно --------------------------------
  assert.deepEqual(списокМоделей(), [], 'ledger пуст на импорте');
  assert.ok(распознать(ЦЕЛ_ЗАДАНИЕ).отказ.includes('нет ни одной модели'), 'пустой ledger — честный отказ');
  ок('ledger пуст на импорте — моделей в доме нет, дверь честно отказывает');

  // --- 2. Честный мок ----------------------------------------------------
  const мок = mockRunner();
  assert.ok(typeof мок({}).отказ === 'string' && мок({}).отказ.includes('МОК'));
  assert.deepEqual(мок({}), мок({}), 'мок детерминирован');
  assert.equal(мок({}).отказ, ПРИЧИНА_МОКА);
  ок('мок: честный отказ с названной причиной, байт-в-байт детерминизм');

  // --- 3. Регистрация: честные true/false --------------------------------
  assert.equal(registerOcrModel(null), false);
  assert.equal(registerOcrModel({ id: 'тест', runner: 'не функция' }), false);
  assert.equal(registerOcrModel({ id: 'плохой id!', runner: мок }), false);
  assert.equal(registerOcrModel({ id: 'тест', runner: мок, веса: { имя: 'm', sha256: 'НЕТ', байт: 1, частей: 1 } }), false, 'плохой хэш — false');
  assert.equal(registerOcrModel({ id: 'тест', runner: мок, веса: { имя: 'm', sha256: 'a'.repeat(64), байт: 1 } }), false, 'полупин без частей — false');
  assert.equal(registerOcrModel({ id: 'тест', runner: мок }), true, 'валидная регистрация — true');
  assert.equal(registerOcrModel({ id: 'тест', runner: мок }), false, 'дубликат id — false');
  ок('регистрация: true/false честные, полупиннинг запрещён, дубликат — false');

  // --- 4. Список моделей: EXPERIMENTAL честно ----------------------------
  const список = списокМоделей();
  assert.equal(список.length, 1);
  assert.equal(список[0].имя, 'ocr/тест', 'имя = ocr/<id>');
  assert.ok(список[0].статус.startsWith('EXPERIMENTAL'));
  assert.equal(список[0].веса, null);

  // --- 4-б. Статус адаптера ДО пинов: EXPERIMENTAL честно -----------------
  const адаптерРано = createOcrAdapter();
  const раноСт = адаптерРано.status();
  assert.equal(раноСт.state, STATUS.EXPERIMENTAL);
  assert.ok(раноСт.reason.includes('честно EXPERIMENTAL'));
  assert.equal(раноСт.privacy, 'local');
  ок('статус адаптера до пинов: EXPERIMENTAL честно, privacy local');

  // --- 5. Валидация задания и ПОДПИСИ БАЙТОВ -----------------------------
  assert.equal(валидироватьЗадание(null).ok, false);
  assert.equal(валидироватьЗадание({}).ok, false, 'без картинки — беда');
  assert.equal(валидироватьЗадание({ изображение: { данные: [1, 2], формат: 'png' } }).ok, false, 'массив — не Uint8Array');
  assert.equal(валидироватьЗадание({ изображение: { данные: new Uint8Array(0), формат: 'png' } }).ok, false, 'пустые данные — честный отказ');
  assert.equal(валидироватьЗадание({ изображение: { данные: PNG_ГОЛОВА, формат: 'jpeg' } }).ok, false, 'назван jpeg, байты png — подпись не сошлась');
  assert.equal(валидироватьЗадание({ изображение: { данные: PNG_ГОЛОВА, формат: 'exe' } }).ok, false, 'формат не из списка');
  assert.equal(валидироватьЗадание({ изображение: { данные: PNG_ГОЛОВА, формат: 'png' } }).ok, true, 'png по подписи');
  assert.equal(валидироватьЗадание({ изображение: { данные: JPEG_ГОЛОВА, формат: 'jpeg' } }).ok, true, 'jpeg по подписи');
  assert.equal(валидироватьЗадание({ изображение: { данные: new TextEncoder().encode('BMФайл'), формат: 'bmp' } }).ok, true, 'bmp по подписи');
  assert.equal(валидироватьЗадание({ изображение: { данные: new TextEncoder().encode('GIF89a…'), формат: 'gif' } }).ok, true, 'gif по подписи');
  assert.equal(валидироватьЗадание({ изображение: { данные: new TextEncoder().encode('II*\u0000x'), формат: 'tiff' } }).ok, true, 'tiff (II) по подписи');
  assert.equal(валидироватьЗадание({ изображение: { данные: new Uint8Array([0x52, 0x49, 0x46, 0x46, 0, 0, 0, 0, 0x57, 0x45, 0x42, 0x50, 1]), формат: 'webp' } }).ok, true, 'webp по подписи');
  assert.equal(валидироватьЗадание({ изображение: { данные: PNG_ГОЛОВА, формат: 'png' }, язык: 'ru!' }).ok, false, 'язык ru! — беда');
  assert.equal(валидироватьЗадание({ изображение: { данные: PNG_ГОЛОВА, формат: 'png' }, язык: 'sr-Latn' }).ok, true, 'sr-Latn читается');
  assert.equal(валидироватьЗадание({ изображение: { данные: PNG_ГОЛОВА, формат: 'png' }, параметры: null }).ok, false, 'параметры null — беда');
  ок(`валидация: Uint8Array, 6 форматов по магическим байтам (не по ярлыку), язык (ru/sr-Latn/kk/de/auto)`);

  // --- 6. создатьЗадание: вход не мутируется -----------------------------
  const сырьё = new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 9]);
  const конверт = создатьЗадание({ данные: сырьё, формат: 'png', язык: 'ru' });
  сырьё[8] = 77; // мутация источника после создания
  assert.equal(конверт.изображение.данные[8], 9, 'копия защитила конверт');
  ок('создатьЗадание: копия данных — вход не шарится и не мутируется');

  // --- 7. Разбор ответа: строгий; пустой текст ВАЛИДЕН -------------------
  const добрый = { текст: 'привет дом', строки: ['привет', 'дом'], язык: 'ru' };
  const разбор = разобратьОтвет(добрый);
  assert.equal(разбор.текст, 'привет дом');
  assert.equal(разбор.строки.length, 2);
  assert.equal(разобратьОтвет({ текст: '', язык: 'ru' }).текст, '', 'пустой текст — валиден (чистый лист)');
  assert.equal(разобратьОтвет({ текст: 'х' }).строки, null, 'строки отсутствуют → null');
  assert.throws(() => разобратьОтвет(null), TypeError);
  assert.throws(() => разобратьОтвет({ отказ: 'модель отказалась' }), /отказалась/);
  assert.throws(() => разобратьОтвет({}), /текст/, 'нет строки «текст» — отказ');
  assert.throws(() => разобратьОтвет({ текст: 42 }), /текст/);
  assert.throws(() => разобратьОтвет({ текст: 'х', строки: 'не массив' }), /строки/);
  assert.throws(() => разобратьОтвет({ текст: 'х', строки: [1, 2] }), /строк/);
  assert.throws(() => разобратьОтвет({ текст: 'х', строки: new Array(МАКС_СТРОК + 1).fill('х') }), /больше/);
  assert.throws(() => разобратьОтвет({ текст: 'х'.repeat(МАКС_СИМВОЛОВ + 1) }), /символов/);
  assert.throws(() => разобратьОтвет({ текст: 'х', язык: 'ru!!' }), /язык/);
  ок('разбор ответа: пустота — факт, отсутствие текста — отказ, границы честные (9 провалов названы)');

  // --- 8. Дверь распознавания -------------------------------------------
  const мокОтказ = распознать(ЦЕЛ_ЗАДАНИЕ); // в ledger «тест» — мок
  assert.ok(мокОтказ.отказ.includes('МОК'), 'мок в ledger — честный отказ через дверь');
  registerOcrModel({ id: 'одна', runner: замороженныйRunner({ текст: 'привет' }) });
  const хорошо = распознать(ЦЕЛ_ЗАДАНИЕ, 'одна');
  assert.equal(хорошо.текст, 'привет');
  assert.equal(хорошо.язык, 'auto');
  registerOcrModel({ id: 'вторая', runner: замороженныйRunner({ текст: 'вторая' }) });
  const спор = распознать(ЦЕЛ_ЗАДАНИЕ);
  assert.ok(спор.отказ.includes('назовите id'), 'несколько моделей — дом не выбирает за человека');
  assert.ok(распознать(ЦЕЛ_ЗАДАНИЕ, 'нет-такой').отказ.includes('не зарегистрирована'));
  registerOcrModel({ id: 'бросок', runner: () => { throw new Error('двигатель упал'); } });
  assert.ok(распознать(ЦЕЛ_ЗАДАНИЕ, 'бросок').отказ.includes('двигатель упал'), 'бросок runner\'а — честный отказ в конверте');
  ок('дверь распознавания: мок/одна/несколько/чужой id/бросок — все отказы названы');

  // --- 9. Детерминизм двери ---------------------------------------------
  const снова = распознать(ЦЕЛ_ЗАДАНИЕ, 'одна');
  assert.equal(JSON.stringify(хорошо), JSON.stringify(снова), 'один вход → один выход');
  ок('детерминизм: одна картинка → один ответ, байт-в-байт');

  // --- 10. Склейка частей и пин ------------------------------------------
  const байты = new TextEncoder().encode('abc');
  const склейка = await склеитьЧасти([байты]);
  assert.equal(склейка.sha256, 'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad', 'вектор SHA-256("abc")');
  const склейка2 = await склеитьЧасти([байты.slice(0, 1), байты.slice(1, 2), байты.slice(2, 3)]);
  assert.equal(склейка2.sha256, склейка.sha256, 'части склеиваются в тот же хэш');
  await assert.rejects(() => склеитьЧасти([]), TypeError);
  await assert.rejects(() => склеитьЧасти([new Uint8Array(0)]), /пуста/);
  ок('склейка частей: вектор SHA-256, честные отказы (пустой массив, пустая часть)');

  // --- 11. сверитьПин: все ветки ----------------------------------------
  assert.equal((await сверитьПин('нет-такой', [байты])).ok, false, 'нет модели');
  assert.equal((await сверитьПин('одна', [байты])).ok, false, 'модель без пина — сверять нечем');
  registerOcrModel({ id: 'пин-модель', runner: мок, веса: { имя: 'rus.traineddata', sha256: склейка.sha256, байт: 3, частей: 3 }, движок: 'tesseract.js/wasm' });
  const пинОк = await сверитьПин('пин-модель', [байты.slice(0, 1), байты.slice(1, 2), байты.slice(2, 3)]);
  assert.equal(пинОк.ok, true, 'сошлось — данные выдаются');
  const кривые = [байты.slice(1), байты.slice(0, 1)]; // другой контент (bca)
  const пинПлохой = await сверитьПин('пин-модель', кривые);
  assert.equal(пинПлохой.ok, false, 'расхождение хэша — отказ');
  assert.ok(пинПлохой.причина.includes('не сошёлся'), 'причина названа');
  ок('пин: сошлось/не сошлось/нет модели/нет пина — склейка не выдаётся при расхождении');

  // --- 12. Статус адаптера ПОСЛЕ пина: READY, реестр принимает ------------
  const адаптер = createOcrAdapter();
  assert.equal(адаптер.id, ADAPTER_ID);
  assert.equal(адаптер.kind, 'input');
  assert.ok(адаптер.priority > 0);
  const реестр = new AdapterRegistry();
  реестр.register(адаптер);
  const ст = адаптер.status();
  assert.equal(ст.state, STATUS.READY, 'есть пин (пин-модель) — READY');
  assert.ok(ст.reason.includes('пин-модель'));
  registerOcrModel({ id: 'готовая', runner: мок, веса: { имя: 'eng.traineddata', sha256: 'b'.repeat(64), байт: 15000000, частей: 1 } });
  assert.ok(адаптер.status().reason.includes('готовая'));
  const статусы = реестр.statuses();
  assert.ok(статусы.some((s) => s.id === ADAPTER_ID && s.state === STATUS.READY));
  ок('статус адаптера после пина: READY честно, реестр дома принимает');

  // --- 13. Бенчмарк OCR ---------------------------------------------------
  assert.equal(точнаяСтрока('Привет, ДОМ!', 'привет дом'), true, 'нормализация делает строку точной');
  assert.equal(точнаяСтрока('дом', 'дон'), false);
  assert.equal(текстОтветаOcr({ отказ: 'х' }), null);
  assert.equal(текстОтветаOcr({ текст: '' }), '', 'пустой текст — не отказ');
  const корпус = [
    { id: 'строка-1', эталон: 'я вижу текст', задание: ЦЕЛ_ЗАДАНИЕ },
    { id: 'строка-2', эталон: 'дом', задание: ЦЕЛ_ЗАДАНИЕ },
  ];
  const протокол = прогонБенчмаркаOcr(замороженныйRunner({ текст: 'дом', язык: 'ru' }), корпус);
  assert.equal(протокол.схема, 'adapter-os.ocr.bench.v1');
  assert.equal(протокол.строк_с_метрикой, 2);
  assert.ok(Math.abs(протокол.вер_среднее - 0.5) < 1e-12, 'строка-1 WER=1 (3/3), строка-2 WER=0 → 0.5');
  assert.equal(протокол.строк_точных, 1, 'вторая строка точна');
  const протоколМока = прогонБенчмаркаOcr(мок, корпус);
  assert.equal(протоколМока.строк_с_отказом, 2);
  assert.equal(протоколМока.вер_среднее, null, 'отказы не превращаются в выдуманный WER');
  assert.ok(протоколМока.пометка.includes('не мера качества'), 'мок честно помечен');
  assert.equal(JSON.stringify(протоколМока), JSON.stringify(прогонБенчмаркаOcr(мок, корпус)), 'протокол детерминирован байт-в-байт');
  assert.throws(() => прогонБенчмаркаOcr(мок, []), TypeError, 'пустой корпус — беда');
  assert.throws(() => прогонБенчмаркаOcr('не функция', корпус), TypeError);
  ок('прогон OCR: общие мерила с speech-bench, точность строк, детерминизм, отказы честные');

  // --- 14. Схемы ---------------------------------------------------------
  assert.equal(LEDGER_SCHEMA, 'adapter-os.ocr.v1');
  assert.deepEqual([...ФОРМАТЫ].sort(), ['bmp', 'gif', 'jpeg', 'png', 'tiff', 'webp']);
  ок('схемы ledger и форматы названы: adapter-os.ocr.v1 / .bench.v1, 6 форматов');

  console.log(`PASS ocr ${счёт}/14`);
}

main().catch((ошибка) => { console.error('FAIL', ошибка); process.exit(1); });
