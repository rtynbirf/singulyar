/* Нормализация живой речи: регистр, ё→е, пробелы, концевые знаки.
   Запятые НЕ режутся: Chrome вкладывает пунктуацию в транскрипт, и
   payload «отправь: …» должен доходить без потерь. Нормализуем только
   хвост и кавычки — фраза с мусором в начале («ё… прочитай журнал»)
   командой не становится. */
export function нормализовать(фраза) {
  let s = String(фраза == null ? '' : фраза).toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();
  s = s.replace(/[.,!?;:…]+$/, '').replace(/^[«"']+/, '').replace(/[»"']+$/, '').trim();
  return s;
}

/* Командная форма: запятые живой темпоральной речи — пробелы.
   Нужна только для сверки с префиксами и картой («открой, пожалуйста, зал»);
   извлечённый payload остаётся из нормализованной строки с запятыми. */
function командно(s) {
  return s.replace(/,/g, ' ').replace(/\s+/g, ' ').trim();
}

