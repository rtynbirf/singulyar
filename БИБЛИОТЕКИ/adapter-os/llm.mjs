export function решитьСтраницу(цель) {
  const s = нормализовать(цель);
  if (!s) return null;
  for (const п of СТРАНИЦЫ) {
    for (const т of п.стем) {
      if (s.indexOf(т) !== -1) return { имя: п.имя, файл: п.файл };
    }
  }
  return null;
}

/* разобрать(фраза) → {намерение, текст?} | null.
   null — это честное «не команда»: фраза уйдёт модели или вернёт
   «модель не загружена». Никаких угадываний.
   Префикс/карта сверяются в командной форме (запятые — пробелы),
   но если сверка удалась на сырой нормализованной строке — payload
   берётся из неё (запятые сохранены). */
export function разобрать(фраза) {
  const s = нормализовать(фраза);
  if (!s) return null;
  const ск = командно(s);
  for (const p of ПРЕФИКСЫ) {
    if (s.startsWith(p.префикс)) {
      const хвост = s.slice(p.префикс.length).trim();
      if (!хвост) return { намерение: p.намерение, текст: '' };
      return { намерение: p.намерение, текст: хвост };
    }
  }
  for (const p of ПРЕФИКСЫ) {
    if (ск.startsWith(p.префикс)) {
      const хвост = ск.slice(p.префикс.length).trim();
      if (!хвост) return { намерение: p.намерение, текст: '' };
      return { намерение: p.намерение, текст: хвост };
    }
  }
  const намерение = карта().get(ск) || карта().get(s);
  return намерение ? { намерение: намерение } : null;
}

/* Правило-слой: исполняет команды словаря через исполнитель страницы.
   Работает БЕЗ модели — платформа управляема всегда. */
export function создатьПравилоСлой(исполнитель) {
  return {
    разобрать: разобрать,
    async исполнить(фраза) {
      const r = разобрать(фраза);
      if (!r) return null;
      let ответ;
      switch (r.намерение) {
        case 'send': ответ = await исполнитель.send(r.текст || ''); break;
        case 'read': ответ = await исполнитель.read(); break;
        case 'clear': ответ = await исполнитель.clear(); break;
        case 'clear_field': ответ = await исполнитель.clearField(); break;
        case 'read_log': ответ = await исполнитель.readLog(); break;
        case 'status': ответ = await исполнитель.status(); break;
        case 'help': ответ = await исполнитель.help(); break;
        case 'stop': ответ = await исполнитель.stop(); break;
        case 'load_model': ответ = await исполнитель.loadModel(); break;
        case 'open': ответ = await исполнитель.open(r.текст || ''); break;
        case 'repeat': ответ = await исполнитель.repeat(r.текст || ''); break;
        case 'ping': ответ = await исполнитель.ping(); break;
        case 'count': ответ = await исполнитель.count(); break;
        case 'identity': ответ = await исполнитель.identity(); break;
        default: return null;
      }
      return { намерение: r.намерение, текст: r.текст || '', ответ: ответ == null ? '' : String(ответ) };
    }
  };
}

/* ── Адаптер llm.local: веса из репы singulyar-llm → wllama в браузере ── */
const ЧАСТЬ_РАЗМЕРЫ = [81900005, 81900005, 81900005, 81900005, 81900005, 81900007];
const ИМЯ_ФАЙЛА = 'qwen2.5-0.5b-instruct-q4_k_m.part-0N-of-06.bin';
const КЭШ_ЧАСТЕЙ = 'singular-llm-parts-v1';
const КЭШ_ПРАВИЛ = 'singular-llm-rules-v1';

export function создатьLlmАдаптер(opts) {
  opts = opts || {};
  /* база весов: opts.baseUrl > SINGULAR_LLM_BASE (тест/дев) > репа singulyar-llm.
     Аналогично правила: SINGULAR_LLM_RULES — локальная копия обучающего слоя. */
  const база = opts.baseUrl || (typeof globalThis !== 'undefined' && globalThis.SINGULAR_LLM_BASE) || ('https://raw.githubusercontent.com/' + LLM_РЕПО + '/main/MODELS/');
  const правилаUrl = opts.rulesUrl || (typeof globalThis !== 'undefined' && globalThis.SINGULAR_LLM_RULES) || ('https://raw.githubusercontent.com/' + LLM_РЕПО + '/main/' + encodeURIComponent('ОБУЧЕНИЕ/ПРАВИЛА_СИНГУЛЯРА.txt'));
  let состояние = 'UNAVAILABLE';           /* честно: весов нет */
  let причина = 'веса не загружены — скажи «загрузи модель» или нажми кнопку на панели МОЗГ';
  let wllama = null;                        /* инстанс после загрузки */
  let правила = ПРАВИЛА_ТЕКСТ;              /* офлайн-копия; освежается при загрузке */
  let загрузка = null;                      /* обещание текущей загрузки */
  let прервано = false;

  async function взять(url) {
    /* кеш браузера (Cache API): первый запуск качает ~469 МБ, дальше — локально */
    try {
      if (typeof caches !== 'undefined') {
        const кэш = await caches.open(КЭШ_ЧАСТЕЙ);
        const изКэша = await кэш.match(url);
        if (изКэша) return изКэша;
        const ответ = await fetch(url);
        if (!ответ.ok) throw new Error('HTTP ' + ответ.status + ' для ' + url);
        try { await кэш.put(url, ответ.clone()); } catch (e) { /* приватный режим — живём без кеша */ }
        return ответ;
      }
    } catch (e) { /* падение кеша — честный fetch мимо */ }
    const ответ = await fetch(url);
    if (!ответ.ok) throw new Error('HTTP ' + ответ.status + ' для ' + url);
    return ответ;
  }

  async function освежитьПравила() {
    try {
      const к = await fetch(правилаUrl);
      if (к.ok) {
        const т = await к.text();
        if (т && т.length > 200 && /^\d+\./m.test(т)) {
          правила = т;
          try { localStorage.setItem(КЭШ_ПРАВИЛ, т); } catch (e) { /* приватный режим */ }
        }
      }
    } catch (e) { /* офлайн — остаётся вшитая копия */ }
  }

  const адаптер = {
    id: 'llm.local',
    kind: 'llm',
    priority: 50,
    status() {
      return { state: состояние, privacy: 'local', reason: причина };
    },
    /* Загрузка: 6 частей → один Blob → wllama. onProgress({loaded,total,faza}) */
    load(onProgress) {
      if (состояние === 'READY') return Promise.resolve('READY');
      if (загрузка) return загрузка;
      прервано = false;
      const общий = ЧАСТЬ_РАЗМЕРЫ.reduce(function (a, b) { return a + b; }, 0);
      причина = 'загрузка весов… 0%';
      загрузка = (async function () {
        try {
          const куски = [];
          let скачано = 0;
          for (let i = 1; i <= 6; i++) {
            const url = база + ИМЯ_ФАЙЛА.replace('part-0N-of-06', 'part-0' + i + '-of-06');
            const ответ = await взять(url);
            const буфер = await ответ.arrayBuffer();
            куски.push(буфер);
            скачано += буфер.byteLength;
            const процент = Math.min(99, Math.round(скачано * 100 / общий));
            причина = 'загрузка весов… ' + процент + '%';
            if (onProgress) { try { onProgress({ loaded: скачано, total: общий, faza: 'части ' + i + '/6', percent: процент }); } catch (e) {} }
          }
          if (onProgress) { try { onProgress({ loaded: скачано, total: общий, faza: 'склейка и запуск', percent: 100 }); } catch (e) {} }
          причина = 'склейка и запуск модели…';
          const блоб = new Blob(куски);
          const wllamaМодуль = await import(new URL('../wllama/index.js', import.meta.url).href);
          wllama = new wllamaМодуль.Wllama({ default: new URL('../wllama/wasm/wllama.wasm', import.meta.url).href });
          await wllama.loadModel([блоб], { n_ctx: 2048, progressCallback: function (д) {
            if (д && onProgress) { try { onProgress({ loaded: д.loaded || 0, total: д.total || общий, faza: 'модель в память', percent: (д.total ? Math.round((д.loaded || 0) * 100 / д.total) : 100) }); } catch (e) {} }
          } });
          await освежитьПравила();          /* обучающий слой — свежий из репы llm */
          состояние = 'READY';
          причина = 'готова: Qwen2.5-0.5B (q4_k_m), локально в браузере';
          return 'READY';
        } catch (e) {
          состояние = 'UNAVAILABLE';
          причина = 'загрузка не удалась: ' + String((e && e.message) || e).slice(0, 160);
          try { if (wllama && wllama.exit) await wllama.exit(); } catch (e2) {}
          wllama = null;
          throw e;
        } finally {
          загрузка = null;
        }
      })();
      return загрузка;
    },
    /* Свободная речь → ответ модели. До загрузки — честная ошибка. */
    async generate(текст, парам) {
      if (состояние !== 'READY' || !wllama) throw new Error('веса не загружены — скажи «загрузи модель»');
      парам = парам || {};
      прервано = false;
      const ответ = await wllama.createChatCompletion({
        messages: [
          { role: 'system', content: правила },
          { role: 'user', content: String(текст == null ? '' : текст).slice(0, 2000) }
        ],
        max_tokens: парам.maxTokens || 160,
        temperature: 0.6,
        top_k: 40,
        top_p: 0.9,
        onNewToken: function (токен, кусок, текущий) {
          if (прервано) return false;      /* «стоп» работает и для модели */
          if (парам.onToken && кусок) { try { парам.onToken(кусок, текущий); } catch (e) {} }
          return true;
        }
      });
      const содержимое = ответ && ответ.choices && ответ.choices[0] && ответ.choices[0].message && ответ.choices[0].message.content;
      return String(содержимое || '').trim();
    },
    abort() { прервано = true; },
    statusText() { return причина; }
  };
  return адаптер;
}

/* ── Адаптер input.speech: голосовой ввод через Web Speech API ──
   Честно: в Chrome звук распознавания уходит на серверы Google —
   это единственное облако во всей цепочке, и оно названо. */
export function создатьРечьАдаптер() {
  function класс() {
    try { return globalThis.SpeechRecognition || globalThis.webkitSpeechRecognition || null; }
    catch (e) { return null; }
  }
  return {
    id: 'input.speech',
    kind: 'input',
    priority: 60,
    status() {
      const к = класс();
      if (!к) return { state: 'UNAVAILABLE', privacy: 'cloud-input', reason: 'браузер не даёт Web Speech API — кнопка микрофона скрыта, текстовый ввод работает всегда' };
      return { state: 'BROWSER_DEPENDENT', privacy: 'cloud-input', reason: 'распознавание браузера; в Chrome звук уходит на серверы Google — сказано прямо' };
    },
    listen(парам) {
      парам = парам || {};
      const к = класс();
      if (!к) { if (парам.onError) парам.onError('Web Speech API недоступен в этом браузере'); return false; }
      let распознавание;
      try {
        распознавание = new к();
      } catch (e) { if (парам.onError) парам.onError('распознавание не стартовало: ' + String(e && e.message || e)); return false; }
      распознавание.lang = парам.lang || 'ru-RU';
      распознавание.interimResults = false;
      распознавание.maxAlternatives = 1;
      распознавание.onresult = function (событие) {
        const текст = событие && событие.results && событие.results[0] && событие.results[0][0] && событие.results[0][0].transcript || '';
        if (парам.onResult && текст) парам.onResult(текст);
      };
      распознавание.onerror = function (событие) {
        const ош = событие && событие.error ? String(событие.error) : 'ошибка распознавания';
        if (парам.onError) парам.onError(ош === 'not-allowed' ? 'микрофон запрещён — разрешение нужно дать вручную' : ош);
      };
      if (парам.onEnd) распознавание.onend = function () { парам.onEnd(); };
      try { распознавание.start(); return true; }
      catch (e) { if (парам.onError) парам.onError('распознавание не стартовало: ' + String(e && e.message || e)); return false; }
    }
  };
}
