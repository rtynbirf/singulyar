// локальный open-model адаптер.
//
// КРИТЕРИЙ СТРОКИ (Л5 из ЕДИНОЙ карты): P4.1 — «локальный open-model адаптер» —
// мост между локальной открытой моделью хоста и агентным циклом v10.85
// (src/repair-agent.mjs). Вкат в их реестр — ровно той дверью, которую они
// оставили: registerProposer (см. их ЗАКОН ЧЕСТНОСТИ v10.85).
//
// РАЗДЕЛЕНИЕ ВЛАСТИ (роль 9 из 09_ARCHITECTURE_BLUEPRINT_RU.md — Repair Planner
// «определяет, какую область исправить»): модель-планировщик отвечает на «ЧТО
// чинить» — выбирает маску регионов; «КАК чинить» остаётся канону дома:
// применение — их applyMaskedRepair с их baselineDerive (v10.81, не правится).
// Модель не двигает байты: план по её маске собирает их planMaskedRepair, и в
// плане стоит их generatedBy — честное авторство, без приписок.
//
// КОНТРАКТ ЛОКАЛЬНОЙ МОДЕЛИ (адаптируемый мир ladom.open-model-ask.v1):
//   модель(запрос) → { маска: [id, ...] } | { отказ: 'причина' }
//   - синхронная: реестр repair-agent синхронен; асинхронный инференс
//     (wllama/WebLLM/…) хост ведёт ВНЕ цикла агента и вкатывает готовый ответ
//     обёрткой-функцией — модуль это документирует, а не притворяется;
//   - детерминированная: один запрос → один ответ, байт-в-байт; часы и
//     случайность запрещены; проверить это модуль не может — честно сказано
//     здесь (как у их pickBest про scoreFn);
//   - 0 мутаций входа: запрос — копия мира, мутация модели не дойдёт ни до
//     проекта, ни до журнала (проверяется тестом);
//   - ВЕСА НЕ ВОЗЯТСЯ ЭТИМ МОДУЛЕМ: хост приносит модель сам. «Модель не
//     установлена» — честное состояние продукта: в проде (Pages) реестр пуст
//     от моделей, их listProposers().пометка верна; живую правду об
//     установленных адаптерах даёт списокАдаптеров() этого модуля.
//
// Что делает модуль:
//   составитьЗапрос(project, журнал)      — детерминированная сериализация мира
//                                           для модели: регионы по id (id/label/
//                                           prompt/bbox/locked/zIndex), пары
//                                           пересечений их bboxIoU (qa-metrics,
//                                           Л3) с пояснением, копия журнала
//                                           раундов, правило ответа;
//   проверитьОтветМодели(ответ, project)  — строгий гард: только {маска}|{отказ},
//                                           без лишних полей; id известны и не
//                                           locked; дубликаты съедаются (их
//                                           конвенция planMaskedRepair); мусор —
//                                           честный отказ, а не тихий пропуск;
//   makeOpenModelProposer({имя, модель})  — proposer контракта repair-agent/0.1:
//                                           (имя, снимок, журнал) → {план}|{маска:
//                                           []}|{отказ}; любой сбой модели — честный
//                                           отказ записью, не бросок;
//   registerOpenModel({имя, модель})      — вкат в их реестр через registerProposer;
//                                           дубликат имени/плохой вход — честный
//                                           false-отказ, их реестр не перезаписывается;
//   списокАдаптеров()                     — живая правда: какие адаптеры вкомканы
//                                           этим модулем в текущем процессе.
//
// Честные границы:
//   - 0 сети, 0 часов, 0 случайности: два прогона составитьЗапрос — байт-в-байт;
//   - вход не мутируется: проект и журнал читаются только через копии (тест);
//   - модель может врасть маской — дом от этого защищён: маска проходит их
//     planMaskedRepair (unknown/locked — отказ), применение — их гарды; модель
//     не может ни двигать удержанные, ни тронуть замки;
//   - их listProposers().пометка — их статический снимок v10.85 и в продукте
//     остаётся верной (реестр пуст от моделей); правка их канона не входит в
//     такт — их тест её защищает, а правда о моделях живёт в списокАдаптеров();
//   - счёт пересечений в запросе — их bboxIoU без порога (>0): модель видит те
//     же факты, что их planMaskFromOverlaps, но решает сама.
//
// Экспорт: только ESM; импорты — ровно три канона дома: ./masked-repair.mjs
// (их v10.81), ./qa-metrics.mjs (их Л3, v10.80), ./repair-agent.mjs (их v10.85).

import { REPAIR_SCHEMA, assertProjectShape, planMaskedRepair } from './masked-repair.mjs';
import { bboxIoU } from './qa-metrics.mjs';
import { registerProposer } from './repair-agent.mjs';

export const ver = 'open-model-adapter/0.1';
export const ASK_SCHEMA = 'ladom.open-model-ask.v1';

const round6 = (v) => Math.round(v * 1e6) / 1e6;
const глубокаяКопия = (x) => JSON.parse(JSON.stringify(x));
const текстОшибки = (ошибка) => (ошибка && ошибка.message ? ошибка.message : String(ошибка));

// Живая правда этого модуля: кто из моделей вкомкан в текущем процессе.
const адаптеры = new Map();

// ---------------------------------------------------------------------------
// ЗАПРОС МОДЕЛИ — мир, каким её видит модель. Детерминированный, копирующий.
// ---------------------------------------------------------------------------

export function составитьЗапрос(project, журнал = []) {
  assertProjectShape(project, 'project');
  if (!Array.isArray(журнал)) {
    throw new TypeError(`open-model-adapter: журнал — ожидается массив, получено ${typeof журнал}`);
  }
  const регионы = project.regions
    .map((r) => ({
      id: r.id,
      label: typeof r.label === 'string' ? r.label : '',
      prompt: typeof r.prompt === 'string' ? r.prompt : '',
      bbox: { x: r.bbox.x, y: r.bbox.y, width: r.bbox.width, height: r.bbox.height },
      locked: r.locked === true,
      zIndex: r.zIndex === undefined ? null : r.zIndex,
    }))
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const rs = project.regions;
  const пересечения = [];
  for (let i = 0; i < rs.length; i += 1) {
    for (let j = i + 1; j < rs.length; j += 1) {
      const iou = bboxIoU(rs[i].bbox, rs[j].bbox);
      if (iou <= 0) continue;
      const [a, b] = rs[i].id < rs[j].id ? [rs[i].id, rs[j].id] : [rs[j].id, rs[i].id];
      пересечения.push({ a, b, iou: round6(iou) });
    }
  }
  пересечения.sort((p, q) => (p.a < q.a ? -1 : p.a > q.a ? 1 : p.b < q.b ? -1 : p.b > q.b ? 1 : 0));
  return {
    schemaVersion: ASK_SCHEMA,
    задача: 'выбери маску регионов для адресного ремонта ladom.repair.v1: ответь строго {"маска":["id",...]} или {"отказ":"причина"}',
    title: project.title ?? '',
    regions: регионы,
    пересечения,
    журнал: глубокаяКопия(журнал),
    правило: {
      власть: 'модель выбирает ЧТО чинить (маску); КАК чинит дом — их applyMaskedRepair + baselineDerive (v10.81)',
      locked: 'locked=true не чинятся никогда — брать их в маску нельзя',
      пусто: 'пустая маска [] — валидный честный ответ «нечего чинить»',
      честность: 'один запрос → один ответ, байт-в-байт; 0 мутаций входа; часы и случайность запрещены',
    },
  };
}

// ---------------------------------------------------------------------------
// ГАРД ОТВЕТА — мусор не проходит молча: только {маска}|{отказ}.
// ---------------------------------------------------------------------------

export function проверитьОтветМодели(ответ, project) {
  assertProjectShape(project, 'project');
  if (!ответ || typeof ответ !== 'object' || Array.isArray(ответ)) {
    return { ок: false, причина: `ответ не объект-конверт: ${JSON.stringify(ответ ?? null)} — жду {"маска":[...]}|{"отказ":"..."}` };
  }
  const ключи = Object.keys(ответ).sort();
  if (ответ.отказ !== undefined) {
    if (ключи.length !== 1) {
      return { ок: false, причина: `отказ смешан с лишними полями ${JSON.stringify(ключи.filter((k) => k !== 'отказ'))} — отвечай либо {"отказ":...}, либо {"маска":[...]}` };
    }
    if (typeof ответ.отказ !== 'string' || !ответ.отказ) {
      return { ок: false, причина: `отказ не непустой строкой: ${JSON.stringify(ответ.отказ ?? null)}` };
    }
    return { ок: true, отказ: ответ.отказ };
  }
  if (ответ.маска === undefined) {
    return { ок: false, причина: 'нет ни маски, ни отказа — жду {"маска":[...]}|{"отказ":"..."}' };
  }
  if (!Array.isArray(ответ.маска)) {
    return { ок: false, причина: `маска не массив: ${JSON.stringify(ответ.маска ?? null)}` };
  }
  if (ключи.length !== 1) {
    return { ок: false, причина: `лишние поля рядом с маской: ${JSON.stringify(ключи.filter((k) => k !== 'маска'))} — только {"маска":[...]}` };
  }
  const byId = new Map(project.regions.map((r) => [r.id, r]));
  const seen = new Set();
  for (const id of ответ.маска) {
    if (typeof id !== 'string' || !id) {
      return { ок: false, причина: `id в маске не непустая строка: ${JSON.stringify(id ?? null)}` };
    }
    if (seen.has(id)) continue; // дубликаты съедаются — их конвенция planMaskedRepair
    seen.add(id);
    const регион = byId.get(id);
    if (!регион) {
      return { ок: false, причина: `в маске неизвестный id "${id}" — такого региона в проекте нет` };
    }
    if (регион.locked === true) {
      return { ок: false, причина: `в маске locked-регион "${id}" — заблокированное не чинится никогда` };
    }
  }
  return { ок: true, маска: [...seen] }; // порядок ответа модели сохранён (детерминизм)
}

// ---------------------------------------------------------------------------
// PROPOSER И РЕЕСТР — мост в их агентный цикл v10.85.
// ---------------------------------------------------------------------------

export function makeOpenModelProposer({ имя, модель, правило = '' } = {}) {
  if (typeof имя !== 'string' || !имя) {
    return { ок: false, причина: `имя — ожидается непустая строка, получено ${JSON.stringify(имя ?? null)}` };
  }
  if (typeof модель !== 'function') {
    return { ок: false, причина: `модель — ожидается синхронная функция (запрос → {"маска"}|{"отказ"}), получено ${typeof модель}` };
  }
  const proposer = (proposerИмя, project, журнал) => {
    try {
      const запрос = составитьЗапрос(project, журнал);
      const ответ = модель(запрос);
      const вердикт = проверитьОтветМодели(ответ, project);
      if (!вердикт.ок) return { отказ: `модель "${имя}": ${вердикт.причина}` };
      if (вердикт.отказ !== undefined) {
        return { отказ: `модель "${имя}" отказалась: ${вердикт.отказ}` };
      }
      if (вердикт.маска.length === 0) return { маска: [] };
      const план = planMaskedRepair(project, вердикт.маска, {
        reason: `open model "${имя}": маска модели${правило ? ` — ${String(правило)}` : ''}`,
      });
      return { план };
    } catch (ошибка) {
      return { отказ: `модель "${имя}" не дошла до плана: ${текстОшибки(ошибка)}` };
    }
  };
  return { ок: true, proposer, имя };
}

export function registerOpenModel({ имя, модель, правило = '' } = {}) {
  const сделан = makeOpenModelProposer({ имя, модель, правило });
  if (!сделан.ок) return { ок: false, причина: сделан.причина };
  const встал = registerProposer(имя, сделан.proposer); // их реестр; дубликат — честный false
  if (!встал) {
    return { ок: false, причина: `их реестр не принял "${имя}" — имя занято или неверно; их реестр не перезаписывается` };
  }
  адаптеры.set(имя, { ver, модель: 'функция хоста (веса у хоста)', правило: String(правило ?? '') });
  return { ок: true, имя };
}

export function списокАдаптеров() {
  return {
    ver,
    имена: [...адаптеры.keys()].sort(),
    пометка: 'модели вкомкиваются только через registerOpenModel (их registerProposer); весов в модуле нет — хост приносит модель сам; в продукте (Pages) реестр пуст от моделей — их listProposers().пометка верна',
  };
}

