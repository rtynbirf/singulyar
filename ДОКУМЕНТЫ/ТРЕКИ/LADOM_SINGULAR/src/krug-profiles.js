/* ═══ КАНОН трека LADOM_SINGULAR — «КРУГ СВОИХ» (P3.1, такт v10.84) ═══
   Локальные профили отношений и согласия. Критерий P3.1: «Повторный
   контакт без повторного QR» — первый контакт честно остаётся QR/кодом
   (физика air-gapped WebRTC: SDP свеж при каждой встрече), рукопожатие
   HELLO записывает ПРОФИЛЬ ОТНОШЕНИЙ; повторный контакт идёт по памяти
   круга через детерминированный рендеву (мост вкладок того же браузера —
   чистый офлайн; между устройствами — та же комната через Nostr-релеи,
   как звонки ·23), и только если обе стороны дали согласие.

   Один файл — одно место: зал ·17 грузит его классическим script-тегом
   (https и file://), тесты зовут через node:vm. Чистота как у
   sync-crdt.js: 0 сети · 0 document · 0 eval; хранилище передаётся
   снаружи адаптером (модуль не знает ни DOM, ни хранилища страницы).

   Закон согласия (одинаков на обеих сторонах):
     - незнакомец (профиля нет)     → повторный контакт = вопрос человеку;
     - «спрошено» (по умолчанию)    → повторный контакт = вопрос человеку;
     - «разрешено»                  → идёт без вопроса;
     - «запрещено»                  → честный отказ без вопроса (не молчание);
     - «забыть»                     → профиль удалён — снова незнакомец.
   Первый контакт (QR/код/рукопожатие) — сам по себе явный шаг человека,
   поэтому запись профиля не спрашивает; спрашивает только ПОВТОРНЫЙ.

   Детерминизм: список профилей сортируется по ключу; часы не участвуют
   в решениях — «первая/последняя встреча» это данные (передаются снаружи,
   тесты передают фиксированные), не логика. */
(function (root, factory) {
  var К = factory();
  if (typeof module !== 'undefined' && module.exports) module.exports = К;
  else root.КругПрофили = К;
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  var ВЕРСИЯ = 'krug-profiles/0.1';
  var ЛИМИТ_ПРОФИЛЕЙ = 64;               /* честный потолок локального круга */
  var РАЗРЕШЁННЫЕ = { 'спрошено': 1, 'разрешено': 1, 'запрещено': 1 };
  var ШЕСТНАДЦАТЬ = /^[0-9a-f]{32}$/;

  /* ── ключ устройства: 32 hex; ран — генератор случайности (по умолчанию
     Math.random; зал и тесты могут передать честный crypto-путь) ── */
  function новыйКлюч(ран) {
    var ген = typeof ран === 'function' ? ран : Math.random;
    var б = new Array(16);
    for (var i = 0; i < 16; i++) б[i] = Math.floor(ген() * 256) & 0xff;
    var с = '';
    for (var j = 0; j < 16; j++) с += ('0' + (б[j] & 0xff).toString(16)).slice(-2);
    if (!ШЕСТНАДЦАТЬ.test(с)) с = 'e3b0c44298fc1c149afbf4c8996fb924'; /* не должен случиться — гарды */
    return с;
  }

  /* ── устройство: постоянная личность устройства. Адаптер тот же,
     что у профилей: { load() → json|null, save(json) } — одно хранилище,
     модуль различает внутри поле «устройство» и профили. Без памяти
     адаптера ключ честно становится сессионным (профиль всё равно
     работает, просто не переживает перезагрузку — имитаций нет). ── */
  function устройство(адаптер, ран, tsМили) {
    var став = ставИз(адаптер);
    var у = став.устройство || null;
    if (!у || !ШЕСТНАДЦАТЬ.test(String(у.key || ''))) {
      у = { key: новыйКлюч(ран), имя: 'устройство', ts: (tsМили === undefined ? null : tsМили) };
      став.устройство = у;
      ставВ(адаптер, став);
    }
    return { key: String(у.key), имя: String(у.имя || 'устройство'), ts: у.ts === undefined ? null : у.ts };
  }

  /* ── став (хранилище профилей): { v:1, профили:[…] } — отсортирован по .key ── */
  function пустойСтав() { return { v: 1, профили: [] }; }

  function ставИз(адаптер) {
    var с = null;
    if (адаптер && typeof адаптер.load === 'function') {
      try { с = адаптер.load(); } catch (е) { с = null; }
    }
    var устройство_стар = (с && с.устройство && ШЕСТНАДЦАТЬ.test(String(с.устройство.key || '')))
      ? { key: String(с.устройство.key), имя: String(с.устройство.имя || 'устройство'),
          ts: с.устройство.ts === undefined ? null : с.устройство.ts }
      : null;
    if (!с || с.v !== 1 || !Array.isArray(с.профили)) с = пустойСтав();
    var чистый = [], видел = {}, i, п;
    for (i = 0; i < с.профили.length; i++) {
      п = с.профили[i];
      if (!п || !ШЕСТНАДЦАТЬ.test(String(п.key || '')) || видел[п.key]) continue;
      видел[п.key] = 1;
      чистый.push({ key: String(п.key), имя: String(п.имя || '').slice(0, 40),
        роль: String(п.роль || '').slice(0, 12),
        первая: п.первая === undefined ? null : п.первая,
        последняя: п.последняя === undefined ? null : п.последняя,
        встреч: (п.встреч | 0) < 1 ? 1 : (п.встреч | 0),
        согласие: РАЗРЕШЁННЫЕ[п.согласие] ? п.согласие : 'спрошено' });
    }
    чистый.sort(function (а, б) { return а.key < б.key ? -1 : (а.key > б.key ? 1 : 0); });
    var став = { v: 1, профили: чистый };
    if (устройство_стар) став.устройство = устройство_стар;
    return став;
  }

  function ставВ(адаптер, став) {
    if (адаптер && typeof адаптер.save === 'function') адаптер.save(став);
    return став;
  }

  function индекс(став, ключ) {
    for (var i = 0; i < став.профили.length; i++) if (став.профили[i].key === ключ) return i;
    return -1;
  }

  function проверьКлюч(ключ) {
    if (!ШЕСТНАДЦАТЬ.test(String(ключ || ''))) throw new Error('круг: ключ не по форме (32 hex) — ' + String(ключ).slice(0, 12));
    return String(ключ);
  }

  /* ── встреча: записать контакт. Первая встреча создаёт профиль
     (согласие «спрошено»), повторная обновляет счётчик и «последнюю».
     ts передаётся снаружи (тесты — фикс; зал — Date.now()). ── */
  function встреча(адаптер, кто, tsМили) {
    if (!кто || typeof кто !== 'object') throw new Error('круг: встреча без человека');
    проверьКлюч(кто.key);
    var став = ставИз(адаптер);
    var i = индекс(став, кто.key);
    var тс = (typeof tsМили === 'number' && isFinite(tsМили)) ? Math.floor(tsМили) : null;
    var первая = i === -1;
    if (первая) {
      if (став.профили.length >= ЛИМИТ_ПРОФИЛЕЙ) throw new Error('круг полон — ' + ЛИМИТ_ПРОФИЛЕЙ + ' профилей: забудь кого-нибудь');
      став.профили.push({ key: String(кто.key), имя: String(кто.имя || '').slice(0, 40),
        роль: String(кто.роль || '').slice(0, 12),
        первая: тс, последняя: тс, встреч: 1, согласие: 'спрошено' });
    } else {
      var п = став.профили[i];
      if (кто.имя) п.имя = String(кто.имя).slice(0, 40);
      if (кто.роль) п.роль = String(кто.роль).slice(0, 12);
      п.последняя = тс;
      п.встреч = п.встреч + 1;
    }
    став.профили.sort(function (а, б) { return а.key < б.key ? -1 : (а.key > б.key ? 1 : 0); });
    ставВ(адаптер, став);
    var п2 = став.профили[первая ? став.профили.length - 1 : индекс(став, кто.key)];
    return { первая: первая, профиль: { key: п2.key, имя: п2.имя, роль: п2.роль,
      первая: п2.первая, последняя: п2.последняя, встреч: п2.встреч, согласие: п2.согласие } };
  }

  /* ── согласие: назвать состояние вслух. Профиль должен существовать —
     согласие о незнакомце не выдумываем. ── */
  function согласие(адаптер, ключ, состояние) {
    проверьКлюч(ключ);
    if (!РАЗРЕШЁННЫЕ[состояние]) throw new Error('круг: нет такого согласия — ' + String(состояние));
    var став = ставИз(адаптер);
    var i = индекс(став, ключ);
    if (i === -1) throw new Error('круг: согласие о незнакомце не даётся — сначала встреча');
    став.профили[i].согласие = состояние;
    ставВ(адаптер, став);
    return став.профили[i].согласие;
  }

  /* ── забыть: настоящее удаление (закон дома: удаление настоящее) ── */
  function забыть(адаптер, ключ) {
    проверьКлюч(ключ);
    var став = ставИз(адаптер);
    var i = индекс(став, ключ);
    if (i === -1) return false;
    став.профили.splice(i, 1);
    ставВ(адаптер, став);
    return true;
  }

  /* ── список: детерминированный снимок (сорт по ключу — уже гарантирован) ── */
  function список(адаптер) {
    var став = ставИз(адаптер);
    return JSON.parse(JSON.stringify(став.профили));
  }

  function профиль(адаптер, ключ) {
    проверьКлюч(ключ);
    var став = ставИз(адаптер);
    var i = индекс(став, ключ);
    return i === -1 ? null : JSON.parse(JSON.stringify(став.профили[i]));
  }

  /* ── рендеву: детерминированное имя встречи круга по ключу хозяина.
     Имя одно и то же при каждой встрече — на нём стоит мост вкладок
     (тот же браузер) и комната релеев (между устройствами). ── */
  function рендеву(ключ) {
    проверьКлюч(ключ);
    return 'krug-' + ключ;
  }

  /* ── повторный контакт: ЗАКОН согласия. Решение — по локальному
     профилю; часы не участвуют; вопрос человеку возвращает флаг. ── */
  function повторныйКонтакт(адаптер, ключ) {
    проверьКлюч(ключ);
    var п = профиль(адаптер, ключ);
    if (!п) return { ok: false, причина: 'незнакомец', вопрос: true };
    if (п.согласие === 'разрешено') return { ok: true, рендеву: рендеву(ключ), профиль: п };
    if (п.согласие === 'спрошено') return { ok: false, причина: 'согласие не дано', вопрос: true, профиль: п };
    return { ok: false, причина: 'запрещено', вопрос: false, профиль: п };
  }

  return {
    ver: ВЕРСИЯ,
    лимит: ЛИМИТ_ПРОФИЛЕЙ,
    новыйКлюч: новыйКлюч,
    устройство: устройство,
    встреча: встреча,
    согласие: согласие,
    забыть: забыть,
    список: список,
    профиль: профиль,
    рендеву: рендеву,
    повторныйКонтакт: повторныйКонтакт
  };
});
