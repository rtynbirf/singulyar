/* ── 21–23: base64url и честные отказы канонизации ──────────────────────── */

test('21 · base64url: круговое равенство на векторах 0/1/255 байтов, известные векторы, детерминизм', () => {
  const векторы = [
    new Uint8Array(0),
    Uint8Array.of(0),
    Uint8Array.of(255),
    Uint8Array.of(255, 255),
    Uint8Array.of(255, 255, 255),
    Uint8Array.of(0, 255, 128, 7, 1, 2, 3),
    Uint8Array.of(0xde, 0xad, 0xbe, 0xef, 0x00, 0x42),
  ];
  for (const байты of векторы) {
    const строка = base64urlИзБайтов(байты);
    for (let i = 0; i < 100; i += 1) assert.equal(base64urlИзБайтов(байты), строка); // детерминизм
    assert.deepEqual(Array.from(байтыИзBase64url(строка)), Array.from(байты), 'вектор ' + строка);
  }
  assert.equal(base64urlИзБайтов(Uint8Array.of(0)), 'AA');
  assert.equal(base64urlИзБайтов(Uint8Array.of(255)), '_w');
  assert.equal(base64urlИзБайтов(Uint8Array.of(255, 255)), '__8');
  assert.equal(base64urlИзБайтов(Uint8Array.of(255, 255, 255)), '____');
});

test('22 · base64url: честные отказы на мусоре (RangeError/TypeError)', () => {
  assert.throws(() => байтыИзBase64url('!!!'), RangeError);
  assert.throws(() => байтыИзBase64url('a=b'), RangeError); // «=» запрещён
  assert.throws(() => байтыИзBase64url('abcde'), RangeError); // длина %4 == 1
  assert.throws(() => байтыИзBase64url('+/_'), RangeError); // это base64, а не base64url
  assert.throws(() => байтыИзBase64url(42), TypeError);
  assert.throws(() => base64urlИзБайтов('строка'), TypeError);
});

test('23 · канонизация: честные отказы на не-JSON значениях', () => {
  assert.throws(() => канонизировать(undefined), TypeError);
  assert.throws(() => канонизировать({ a: undefined }), TypeError);
  assert.throws(() => канонизировать(() => 1), TypeError);
  assert.throws(() => канонизировать(new Date(0)), TypeError);
  assert.throws(() => канонизировать(new Map([[1, 2]])), TypeError);
  assert.throws(() => канонизировать({ a: 1n }), TypeError);
  assert.throws(() => канонизировать({ a: NaN }), RangeError);
  assert.throws(() => канонизировать({ a: Infinity }), RangeError);
  const цикл = {};
  цикл.сам = цикл;
  assert.throws(() => канонизировать(цикл), RangeError); // переполнение стека — тоже честный отказ
});
