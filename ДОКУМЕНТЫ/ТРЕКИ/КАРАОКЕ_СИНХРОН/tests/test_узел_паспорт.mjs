//   а не байт-равенство (случайный k внутри WebCrypto по FIPS 186-5 канон
//   не контролирует — честная граница дома); вход не мутируется; честные
//   русские отказы; битые паспорта не бросают, а возвращают причины;
//   порт ≡ канон (vm-прогон, кросс-проверка паспортов, отпечатки байт в байт).
