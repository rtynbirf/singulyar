describe('д · три тренажёра-фабрики', () => {
  const диктант = fs6.создатьДиктант();
  const пропуски = fs6.создатьПропуски();
  const эхо = fs6.создатьЭхоПлан();

  it('типы разные и из реестра КС4; ключи по схеме «контур.тренажёры.<тип>.<ид>»', () => {
    assert.deepEqual([диктант.тип, пропуски.тип, эхо.тип], ['диктант', 'пропуски', 'эхо-план']);
    assert.deepEqual(fs6.ТРЕНАЖЁРЫ, ['диктант', 'пропуски', 'эхо-план']);
    const ключи = [диктант, пропуски, эхо].map((т) => т.ключХранилища('свет-1'));
    assert.deepEqual(ключи, [
      'контур.тренажёры.диктант.свет-1',
      'контур.тренажёры.пропуски.свет-1',
      'контур.тренажёры.эхо-план.свет-1',
    ]);
    assert.equal(new Set(ключи).size, 3, 'ключи различны');
    // хранилище отдельно от kv.контур: ни один ключ не начинается с kv.контур
    for (const к of ключи) assert.ok(!к.startsWith('kv.'), 'ключ тренажёра не в kv-пространстве КОНТУРа');
    assert.equal(fs6.ключХранилища('диктант', 'слово:5'), 'контур.тренажёры.диктант.слово:5');
  });

  it('диктант: правки/подсказка/быстро/чисто → опять/трудно/легко/хорошо; мусор → null', () => {
    const м = диктант.оценкаИзСобытия;
    assert.equal(м({ верно: false }), 'опять');
    assert.equal(м({ заменено: 1, пропущено: 0, лишнее: 2 }), 'опять');
    assert.equal(м({ верно: true, сПодсказкой: true }), 'трудно');
    assert.equal(м({ верно: true, быстро: true }), 'легко');
    assert.equal(м({ верно: true }), 'хорошо');
    assert.equal(м({}), null);
    assert.equal(м(null), null);
  });

  it('пропуски и эхо-план: свой маппинг, тот же честный отказ на пустом событии', () => {
    assert.equal(пропуски.оценкаИзСобытия({ ошибок: 2 }), 'опять');
    assert.equal(пропуски.оценкаИзСобытия({ верно: true, сПодсказкой: true }), 'трудно');
    assert.equal(пропуски.оценкаИзСобытия({ верно: true, быстро: true }), 'легко');
    assert.equal(пропуски.оценкаИзСобытия({ верно: true }), 'хорошо');
    assert.equal(пропуски.оценкаИзСобытия({}), null);
    assert.equal(эхо.оценкаИзСобытия({ совпало: false }), 'опять');
    assert.equal(эхо.оценкаИзСобытия({ совпало: true, сПодсказкой: true }), 'трудно');
    assert.equal(эхо.оценкаИзСобытия({ совпало: true, быстро: true }), 'легко');
    assert.equal(эхо.оценкаИзСобытия({ совпало: true }), 'хорошо');
    assert.equal(эхо.оценкаИзСобытия({}), null);
  });

  it('фабрика.оценить = маппинг + FSRS: результат совпадает с прямой оценкой', () => {
    const м = М0 + ДЕНЬ_МС;
    const черезФабрику = диктант.оценить(fs6.создатьКарточку('т-1', М0), { верно: true, быстро: true }, м);
    const напрямую = fs6.оценить(fs6.создатьКарточку('т-1', М0), 'легко', м);
    assert.deepEqual(черезФабрику, напрямую);
    assert.throws(() => диктант.оценить(fs6.создатьКарточку('т-2', М0), {}, м), /честный отказ/);
  });

  it('ключХранилища: честные отказы на пустых/с точкой/с пробелом', () => {
    assert.throws(() => fs6.ключХранилища('', 'ид'), /непустая/);
    assert.throws(() => fs6.ключХранилища('диктант', ''), /непустая/);
    assert.throws(() => fs6.ключХранилища('диктант', 'а.б'), /точку или пробел/);
    assert.throws(() => fs6.ключХранилища('эхо план', 'ид'), /точку или пробел/);
  });
});

