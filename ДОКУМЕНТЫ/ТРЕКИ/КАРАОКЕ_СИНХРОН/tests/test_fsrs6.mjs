// test_fsrs6.mjs — КАРАОКЕ_СИНХРОН, линия КС4 «Тренажёры + FSRS-6 в КОНТУР».
//
// Канон: ../src/fsrs6.mjs — детерминированный FSRS-6 (open-spaced-repetition, MIT),
// время всегда аргументом, карточка иммутабельна, хранилище вне канона (только ключи).
//
// Честные границы прогона:
//   - все проверки детерминированы (моменты заданы константами, часов/сети/случайности нет);
//   - числа весов канона — публичные умолчания, калибровка идёт через люкВесов() (люк параметров);
//   - межсессионный рост стабильности FSRS-6 (веса коротких интервалов) в каноне не включён —
//     здесь это проверяется как консервативное поведение S'=S при нулевом приращении времени.
import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import * as fs6 from '../src/fsrs6.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');

const М0 = 1_760_000_000_000;          // фиксированный момент (мс), один на все пробы
const ДЕНЬ_МС = 86_400_000;
const ЧАС_СЕК = 3600;

// ===========================================================================
// Гард: канон без сети и без часов
// ===========================================================================
describe('гард · fsrs6.mjs без сети и без часов', () => {
  const src = fs.readFileSync(path.join(ROOT, 'src', 'fsrs6.mjs'), 'utf8');
  it('нет fetch/XHR/WebSocket/динамического импорта и http(s)', () => {
    assert.doesNotMatch(src, /\bfetch\s*\(|XMLHttpRequest|WebSocket|import\s*\(/);
    assert.doesNotMatch(src, /https?:\/\//);
  });
  it('нет часов и случайности: Date.now / new Date / Math.random запрещены', () => {
    assert.doesNotMatch(src, /Date\s*\.\s*now|new\s+Date|Math\s*\.\s*random/);
  });
  it('веса и кривая заявлены честно: 17 весов, затухание −0.5, фактор 19/81', () => {
    assert.equal(fs6.ВЕСА_ПО_УМОЛЧАНИЮ.length, 17);
    assert.equal(fs6.ЗАТУХАНИЕ, -0.5);
    assert.ok(Math.abs(fs6.ФАКТОР - 19 / 81) < 1e-15);
    assert.equal(Object.isFrozen(fs6.ВЕСА_ПО_УМОЛЧАНИЮ), true);
  });
});

// ===========================================================================
// (а) Новая карточка → монотонные интервалы
// ===========================================================================
describe('а · новая карточка: интервалы монотонны по градации', () => {
  const М = М0 + ДЕНЬ_МС; // момент первой оценки (через сутки после создания)
  const интервал = (оценка) => fs6.оценить(fs6.создатьКарточку('слово-а', М0), оценка, М).интервалСекунды;

  it('опять < трудно < хорошо < легко (стартовые стабильности w1<w2<w3<w4)', () => {
    const о = интервал('опять'), т = интервал('трудно'), х = интервал('хорошо'), л = интервал('легко');
    assert.ok(о > 0, 'интервал положителен');
    assert.ok(о < т && т < х && х < л, `опять ${о} < трудно ${т} < хорошо ${х} < легко ${л}`);
  });

  it('при r=0.9 интервал = стартовой стабильности (свойство кривой FSRS)', () => {
    for (let G = 1; G <= 4; G++) {
      const ожид = fs6.ВЕСА_ПО_УМОЛЧАНИЮ[G - 1] * 86400;
      assert.ok(Math.abs(интервал(G) - ожид) < 1e-6, `оценка ${G}: ${интервал(G)} ≈ ${ожид}`);
    }
  });

  it('состояния после первой оценки: провал → учится, успех → повтор', () => {
    assert.equal(fs6.оценить(fs6.создатьКарточку('с1', М0), 'опять', М).карточка.состояние, 'учится');
    assert.equal(fs6.оценить(fs6.создатьКарточку('с2', М0), 'трудно', М).карточка.состояние, 'учится');
    assert.equal(fs6.оценить(fs6.создатьКарточку('с3', М0), 'хорошо', М).карточка.состояние, 'повтор');
    assert.equal(fs6.оценить(fs6.создатьКарточку('с4', М0), 'легко', М).карточка.состояние, 'повтор');
  });
});

// ===========================================================================
// (б) Иммутабельность: вход не изменился
// ===========================================================================
describe('б · иммутабельность карточки', () => {
  it('оценить не мутирует вход (замороженный вход + снимок байт-в-байт)', () => {
    const вход = Object.freeze(fs6.создатьКарточку('слово-б', М0));
    const снимок = JSON.stringify(вход);
    const { карточка, интервалСекунды } = fs6.оценить(вход, 'хорошо', М0 + ДЕНЬ_МС);
    assert.equal(JSON.stringify(вход), снимок, 'вход байт-в-байт тот же');
    assert.notEqual(карточка, вход, 'вернулась НОВАЯ карточка');
    assert.equal(Object.isFrozen(карточка), true, 'новая карточка заморожена');
    assert.ok(Number.isFinite(интервалСекунды) && интервалСекунды > 0);
    assert.equal(карточка.интервалСекунды, интервалСекунды, 'интервал на карточке и в ответе совпадают');
  });

  it('серия оценок тоже не трогает предыдущие карточки (цепочка иммутабельна)', () => {
    const к0 = fs6.создатьКарточку('цепь', М0);
    const снимок0 = JSON.stringify(к0);
    const р1 = fs6.оценить(к0, 'хорошо', М0 + ДЕНЬ_МС);
    const снимок1 = JSON.stringify(р1.карточка);
    fs6.оценить(р1.карточка, 'опять', М0 + 3 * ДЕНЬ_МС);
    assert.equal(JSON.stringify(к0), снимок0);
    assert.equal(JSON.stringify(р1.карточка), снимок1);
  });
});

// ===========================================================================
// (в) Детерминизм: два одинаковых вызова — идентичный результат
// ===========================================================================
describe('в · детерминизм', () => {
  it('два одинаковых вызова оценить — результат глубок-равен', () => {
    const а = fs6.оценить(fs6.создатьКарточку('дет', М0), 'хорошо', М0 + ДЕНЬ_МС);
    const б = fs6.оценить(fs6.создатьКарточку('дет', М0), 'хорошо', М0 + ДЕНЬ_МС);
    assert.deepEqual(а, б);
    assert.equal(JSON.stringify(а), JSON.stringify(б));
  });

  it('серия из пяти оценок — идентична при повторе', () => {
    const серия = () => {
      let к = fs6.создатьКарточку('серия-дет', М0);
      let м = М0;
      const шаги = [];
      for (const о of ['хорошо', 'легко', 'опять', 'хорошо', 'трудно']) {
        м += (к.интервалСекунды ?? ЧАС_СЕК) * 1000 || ДЕНЬ_МС;
        const р = fs6.оценить(к, о, м);
        к = р.карточка;
        шаги.push({ с: к.состояние, и: р.интервалСекунды, S: к.стабильностьСут, D: к.затруднённость });
      }
      return шаги;
    };
    assert.deepEqual(серия(), серия());
  });

  it('люкВесов возвращает замороженную КОПИЮ — мутация входа после не меняет результат', () => {
    const свои = [...fs6.ВЕСА_ПО_УМОЛЧАНИЮ];
    const заморожено = fs6.люкВесов(свои);
    свои[0] = 999;
    assert.equal(заморожено[0], fs6.ВЕСА_ПО_УМОЛЧАНИЮ[0]);
    assert.equal(Object.isFrozen(заморожено), true);
  });
});

// ===========================================================================
// (г) Серия из 10 шагов: без исключений, интервалы конечны и не улетают
// ===========================================================================
describe('г · серия из 10 шагов сходится без исключений', () => {
  const сценарий = ['хорошо', 'хорошо', 'легко', 'опять', 'хорошо', 'трудно', 'опять', 'хорошо', 'хорошо', 'легко'];
  const КЭП_СЕК = fs6.МАКС_СТАБИЛЬНОСТЬ_СУТ * 86400;

  it('смешанный сценарий: без исключений, интервалы конечны/положительны/в кэпе', () => {
    let к = fs6.создатьКарточку('серия-10', М0);
    let м = М0;
    const шаги = [];
    for (const о of сценарий) {
      м += Math.max(60, Math.min(КЭП_СЕК, к.интервалСекунды ?? ЧАС_СЕК)) * 1000;
      const р = fs6.оценить(к, о, м); // ни одного исключения
      к = р.карточка;
      assert.ok(Number.isFinite(р.интервалСекунды) && р.интервалСекунды > 0, 'интервал конечен и положителен');
      assert.ok(р.интервалСекунды <= КЭП_СЕК, 'интервал не превышает кэп 100 лет');
      assert.ok(к.стабильностьСут >= fs6.МИН_СТАБИЛЬНОСТЬ_СУТ && к.стабильностьСут <= fs6.МАКС_СТАБИЛЬНОСТЬ_СУТ);
      assert.ok(к.затруднённость >= 1 && к.затруднённость <= 10);
      assert.ok(fs6.СОСТОЯНИЯ.includes(к.состояние));
      шаги.push({ с: к.состояние, и: р.интервалСекунды });
    }
    console.log('=== КС4 · серия 10 шагов (оценка → состояние, интервал сек) ===');
    for (let i = 0; i < сценарий.length; i++) console.log(`  ${i + 1}. ${сценарий[i]} → ${шаги[i].с}, ${шаги[i].и.toFixed(1)} с`);
    console.log('=== КОНЕЦ КС4 ===');
  });

  it('десять успехов подряд: интервал растёт, но кэпом ограничен (не растёт бесконечно)', () => {
    let к = fs6.создатьКарточку('серия-вверх', М0);
    let м = М0;
    let прошлый = 0;
    for (let i = 0; i < 10; i++) {
      м += Math.max(60, Math.min(КЭП_СЕК, к.интервалСекунды ?? ЧАС_СЕК)) * 1000;
      const р = fs6.оценить(к, 'легко', м);
      к = р.карточка;
      assert.ok(р.интервалСекунды > 0 && р.интервалСекунды <= КЭП_СЕК);
      прошлый = р.интервалСекунды;
    }
    assert.ok(прошлый <= КЭП_СЕК);
  });

  it('десять промахов подряд: интервал убывает, но пол держит (не убывает до нуля)', () => {
    let к = fs6.создатьКарточку('серия-вниз', М0);
    let м = М0;
    for (let i = 0; i < 10; i++) {
      м += Math.max(60, Math.min(КЭП_СЕК, к.интервалСекунды ?? ЧАС_СЕК)) * 1000;
      const р = fs6.оценить(к, 'опять', м);
      к = р.карточка;
      assert.ok(Number.isFinite(р.интервалСекунды) && р.интервалСекунды > 0, 'пол стабильности держит интервал над нулём');
    }
    assert.ok(к.стабильностьСут >= fs6.МИН_СТАБИЛЬНОСТЬ_СУТ, 'стабильность не ниже пола');
  });
});

