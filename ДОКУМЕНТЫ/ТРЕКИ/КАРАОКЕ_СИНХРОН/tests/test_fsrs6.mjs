// (е) планПодтверждений: сортировка по времени, детерминизм, честные сроки
// ===========================================================================
describe('е · планПодтверждений сортирован по времени', () => {
  it('очередь по возрастанию момента; нова карточка — срок «сейчас»; ничья — по ид', () => {
    const м = М0 + ДЕНЬ_МС;
    const кПоздняя = fs6.оценить(fs6.создатьКарточку('б-слово', М0), 'хорошо', м).карточка;
    const кРанняя = fs6.оценить(fs6.создатьКарточку('а-слово', М0), 'опять', м).карточка;
    const кНовая = fs6.создатьКарточку('в-слово', М0);
    const план = fs6.планПодтверждений([кПоздняя, кРанняя, кНовая], м + ЧАС_СЕК * 1000);
    assert.equal(план.length, 3);
    for (let i = 1; i < план.length; i++) {
      assert.ok(план[i - 1].момент <= план[i].момент, 'сортировка по времени');
      if (план[i - 1].момент === план[i].момент) assert.ok(план[i - 1].ид < план[i].ид, 'ничья — по ид');
    }
    // сроки: в-слово (нова) = сейчас = м+1ч; а-слово («опять») ≈ м+11.7ч; б-слово («хорошо») ≈ м+3.7 сут
    assert.equal(план[0].ид, 'в-слово');
    assert.equal(план[1].ид, 'а-слово');
    assert.equal(план[2].ид, 'б-слово');
    const новая = план.find((п) => п.ид === 'в-слово');
    assert.equal(новая.состояние, 'нова');
    assert.equal(новая.момент, м + ЧАС_СЕК * 1000, 'нова — показ сейчас');
    assert.ok(новая.просроченоСек === 0);
  });

  it('просроченные карточки дают просроченоСек > 0 и идут первыми', () => {
    const м = М0 + ДЕНЬ_МС;
    const к = fs6.оценить(fs6.создатьКарточку('старое', М0), 'хорошо', м).карточка;
    const сейчас = к.моментПоследнего + (к.интервалСекунды + 500) * 1000;
    const план = fs6.планПодтверждений([к], сейчас);
    assert.equal(план.length, 1);
    assert.ok(план[0].просроченоСек === 500, 'просрочена ровно на 500 с');
    assert.equal(план[0].момент, к.моментПоследнего + к.интервалСекунды * 1000);
  });

  it('детерминизм плана: два одинаковых вызова — идентичный результат', () => {
    const м = М0 + ДЕНЬ_МС;
    const карточки = [
      fs6.оценить(fs6.создатьКарточку('п-1', М0), 'хорошо', м).карточка,
      fs6.оценить(fs6.создатьКарточку('п-2', М0), 'опять', м).карточка,
      fs6.создатьКарточку('п-3', М0),
    ];
    assert.deepEqual(fs6.планПодтверждений(карточки, м), fs6.планПодтверждений(карточки, м));
  });
});

