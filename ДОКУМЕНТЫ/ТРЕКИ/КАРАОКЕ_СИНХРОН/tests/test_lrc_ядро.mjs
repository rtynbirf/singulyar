import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import vm from 'node:vm';

import { разобрать, собратьLRC, версия } from '../src/lrc-ядро.mjs';

test('версия()', () => { assert.equal(версия(), 'lrc-ядро/0.1'); });

/* ── базовый разбор ──────────────────────────────────────────────────────── */
test('разобрать: простой LRC с метками и сортировкой', () => {
  const р = разобрать('[00:03.00]Второй\n[00:01.00]Первый\n[01:02.50]Хвост');
  assert.deepEqual(р.строки.map((с) => с.времяМс), [1000, 3000, 62500]);
  assert.deepEqual(р.строки.map((с) => с.текст), ['Первый', 'Второй', 'Хвост']);
  assert.equal(р.слова, null);
  assert.equal(р.версия, 'lrc-ядро/0.1');
});

test('разобрать: дробь позиционная — .5 = 500 мс, .05 = 50 мс, .500 = 500 мс', () => {
  const р = разобрать('[00:01.5]а\n[00:02.05]б\n[00:03.500]в');
  assert.deepEqual(р.строки.map((с) => с.времяМс), [1500, 2050, 3500]);
});

test('разобрать: множественные метки на строке — две записи', () => {
  const р = разобрать('[00:01.0][00:05.0]Припев');
  assert.equal(р.строки.length, 2);
  assert.deepEqual(р.строки.map((с) => с.времяМс), [1000, 5000]);
  assert.deepEqual(р.строки.map((с) => с.текст), ['Припев', 'Припев']);
});

test('разобрать: теги читаются, offset применяется (+1500 и −500)', () => {
  const плюс = разобрать('[ti:Песня]\n[ar:Автор]\n[offset:1500]\n[00:01.00]Строка');
  assert.deepEqual(плюс.теги, { ti: 'Песня', ar: 'Автор', offset: '1500' });
  assert.equal(плюс.строки[0].времяМс, 2500);
  const минус = разобрать('[offset:-500]\n[00:01.00]Строка');
  assert.equal(минус.строки[0].времяМс, 500);
});

test('разобрать: enhanced ELRC — слова с абсолютным временем', () => {
  const р = разобрать('[00:10.00]<00:10.00>Слово <00:10.50>второе <00:11.00>третье');
  assert.ok(р.слова, 'слова должны быть');
  assert.deepEqual(р.слова.map((с) => с.времяМс), [10000, 10500, 11000]);
  assert.deepEqual(р.слова.map((с) => с.слово), ['Слово', 'второе', 'третье']);
  assert.equal(р.строки[0].текст, 'Слово второе третье');
});

test('разобрать: offset учитывается и в словах', () => {
  const р = разобрать('[offset:1000]\n[00:05.00]<00:05.00>Да');
  assert.equal(р.слова[0].времяМс, 6000); /* 5000 + офсет 1000, один раз */
});

test('разобрать: строки без меток игнорируются; пустые тоже', () => {
  const р = разобрать('мусор без меток\n\n[00:01.00]Живая');
  assert.equal(р.строки.length, 1);
  assert.equal(р.строки[0].текст, 'Живая');
});

test('разобрать: CRLF и CR переводы строк', () => {
  const р = разобрать('[00:01.00]А\r\n[00:02.00]Б\r[00:03.00]В');
  assert.equal(р.строки.length, 3);
});

/* ── честные отказы ──────────────────────────────────────────────────────── */
test('разобрать: не строка — TypeError', () => {
  assert.throws(() => разобрать(42), TypeError);
  assert.throws(() => разобрать(null), TypeError);
});

test('разобрать: нет меток — RangeError «это не LRC»', () => {
  assert.throws(() => разобрать('просто текст'), RangeError);
  assert.throws(() => разобрать(''), RangeError);
});

test('разобрать: секунд больше 59 — RangeError', () => {
  assert.throws(() => разобрать('[00:99.00]Странно'), RangeError);
});

test('разобрать: offset не число — RangeError; двойной offset — RangeError', () => {
  assert.throws(() => разобрать('[offset:позже]\n[00:01.00]х'), RangeError);
  assert.throws(() => разобрать('[offset:100]\n[offset:200]\n[00:01.00]х'), RangeError);
});

/* ── немутация, детерминизм ──────────────────────────────────────────────── */
test('разобрать: вход не мутируется; двойной вызов байт-в-байт', () => {
  const текст = '[ti:х]\n[00:01.00]Строка <00:01.50>со словами';
  const копия = текст.slice();
  const а = JSON.stringify(разобрать(текст));
  const б = JSON.stringify(разобрать(текст));
  assert.equal(текст, копия);
  assert.equal(а, б);
});

test('разобрать: стабильность при равных метках — исходный порядок', () => {
  const р = разобрать('[00:05.00]Первая\n[00:05.00]Вторая');
  assert.deepEqual(р.строки.map((с) => с.текст), ['Первая', 'Вторая']);
});

/* ── обратная сборка ─────────────────────────────────────────────────────── */
test('собратьLRC → разобрать: круговая на выборке', () => {
  const исходные = [
    { времяМс: 1000, текст: 'Первый' },
    { времяМс: 1500, текст: 'Второй' },
    { времяМс: 62500, текст: 'Хвост' },
  ];
  const собрано = собратьLRC(исходные);
  assert.ok(собрано.includes('[00:01.000]Первый'));
  const р = разобрать(собрано);
  assert.deepEqual(р.строки, исходные);
});

test('собратьLRC: отказы', () => {
  assert.throws(() => собратьLRC('не массив'), TypeError);
  assert.throws(() => собратьLRC([42]), TypeError);
  assert.throws(() => собратьLRC([{ времяМс: -1, текст: 'х' }]), RangeError);
});

/* ── Порт ≡ канон (vm) ───────────────────────────────────────────────────── */
test('порт lrc-core.js ≡ канон', async () => {
  const кодПорта = await readFile(join(dirname(fileURLToPath(import.meta.url)), '../../../../js/lrc-core.js'), 'utf8');
  const песочница = { window: {}, console };
  vm.createContext(песочница);
  vm.runInContext(кодПорта, песочница, { filename: '../../../../js/lrc-core.js' });
  const порт = песочница.window.__ЛРЦ;
  assert.ok(порт, 'порт не поставил __ЛРЦ');

  const векторы = [
    '[00:01.00]Простая\n[00:02.00]Вторая',
    '[ti:Песня]\n[ar:Автор]\n[offset:-500]\n[00:01.0][00:04.0]Двойная',
    '[00:10.00]<00:10.00>Слово <00:10.50>второе',
    '[00:01.5]Дробь .5\n[00:02.05]Дробь .05',
    'мусор\n[00:03.00]Живая',
  ];
  for (const в of векторы) {
    assert.equal(JSON.stringify(порт.разобрать(в)), JSON.stringify(разобрать(в)), 'расхождение на: ' + в);
  }
  const отказы = ['', 'просто текст', 42, '[00:99.00]х', '[offset:x]\n[00:01.00]х'];
  for (const о of отказы) {
    let оКан = null, оПор = null;
    try { разобрать(о); } catch (е) { оКан = е; }
    try { порт.разобрать(о); } catch (е) { оПор = е; }
    assert.ok(оКан && оПор, 'оба должны отказать на: ' + JSON.stringify(о));
    assert.equal(оПор.name, оКан.name);
    assert.equal(оПор.message, оКан.message);
  }
  assert.equal(порт.собратьLRC([{ времяМс: 1000, текст: 'х' }]), собратьLRC([{ времяМс: 1000, текст: 'х' }]));
  // идиомпотентность
  assert.equal(JSON.stringify(порт.разобрать(векторы[0])), JSON.stringify(порт.разобрать(векторы[0])));
});
