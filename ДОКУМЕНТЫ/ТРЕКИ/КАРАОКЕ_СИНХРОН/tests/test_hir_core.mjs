test('16 · альтернативы: ≤3, по убыванию оценок, без победителя и без нулей', () => {
  const дом = создатьДомашний();
  for (const фраза of ['открой зал', 'что здесь делать', 'включи караоке', 'расскажи обо мне']) {
    const р = дом.распознать(фраза);
    assert.ok(р.альтернативы.length <= 3, 'больше трёх альтернатив у «' + фраза + '»');
    assert.ok(!р.альтернативы.some((а) => а.намерение === р.намерение), 'победитель попал в альтернативы');
    for (let i = 0; i < р.альтернативы.length; i += 1) {
      assert.ok(р.альтернативы[i].оценка > 0, 'нулевая альтернатива у «' + фраза + '»');
      if (i > 0) {
        assert.ok(
          р.альтернативы[i - 1].оценка >= р.альтернативы[i].оценка,
          'порядок нарушен у «' + фраза + '»'
        );
      }
    }
  }
  // нулевые классы честно не попадают в альтернативы
  const к = создатьКлассификатор([
    { текст: 'первый класс текст', намерение: 'а' },
    { текст: 'второй род слов', намерение: 'б' },
  ]);
  const р = к.распознать('первый');
  assert.equal(р.намерение, 'а');
  assert.ok(!р.альтернативы.some((а) => а.намерение === 'б'), 'нулевой класс «б» выдуман в альтернативах');
});

