/* Загрузка порта в песочницу с фейковым window (порт ищет window). */
function загрузитьПорт(дополнение = {}) {
  const окно = {};
  const песочница = { window: окно, ...дополнение };
  const контекст = vm.createContext(песочница);
  vm.runInContext(КОД_ПОРТА, контекст, { filename: '../../../../js/hir-core.js' });
  return { окно, песочница };
}

/* Независимая реализация сравнения строк по кодовым точкам — для поверки сортировки. */
function поКодовымТочкам(а, б) {
  const нитиА = Array.from(а);
  const нитиБ = Array.from(б);
  for (let i = 0; i < Math.min(нитиА.length, нитиБ.length); i += 1) {
    const па = нитиА[i].codePointAt(0);
    const пб = нитиБ[i].codePointAt(0);
    if (па !== пб) return па - пб;
  }
  return нитиА.length - нитиБ.length;
}

/* Исход «фразы»: либо JSON-результат, либо имя+сообщение отказа. */
function исход(действие) {
  try {
    return { ок: JSON.stringify(действие()) };
  } catch (ошибка) {
    return { отказ: ошибка.name + ': ' + ошибка.message };
  }
}

