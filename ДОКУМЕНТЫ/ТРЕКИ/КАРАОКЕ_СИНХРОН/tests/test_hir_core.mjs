test('19 · РЕЕСТР_НАМЕРЕНИЙ: 12 намерений × 6 живых фраз, заморожен, без повторов', () => {
  assert.equal(Object.isFrozen(РЕЕСТР_НАМЕРЕНИЙ), true);
  assert.equal(РЕЕСТР_НАМЕРЕНИЙ.length, 72);
  const классы = new Map();
  const виденные = new Set();
  for (const пример of РЕЕСТР_НАМЕРЕНИЙ) {
    assert.equal(Object.isFrozen(пример), true);
    assert.equal(typeof пример.текст, 'string');
    assert.equal(typeof пример.намерение, 'string');
    assert.ok(пример.текст.length > 0);
    const слов = пример.текст.split(' ').length;
    assert.ok(слов >= 2 && слов <= 6, 'слов ' + слов + ' у «' + пример.текст + '»');
    assert.ok(!виденные.has(пример.текст), 'повтор фразы «' + пример.текст + '»');
    виденные.add(пример.текст);
    if (!классы.has(пример.намерение)) классы.set(пример.намерение, 0);
    классы.set(пример.намерение, классы.get(пример.намерение) + 1);
  }
  assert.equal(классы.size, 12);
  for (const число of классы.values()) assert.equal(число, 6);
});

