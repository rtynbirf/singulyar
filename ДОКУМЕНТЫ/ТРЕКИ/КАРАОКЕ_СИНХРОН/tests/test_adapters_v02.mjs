// «Универсальный прототип v0.1 — 6 контрактов адаптеров — основа адаптеров Ж4».
//
// Канон такта: src/adapters-v02.mjs (karaoke-adapters/0.2) — шесть контрактов
// адаптеров из прототипа Singulyar_Universal_Karaoke_Prototype_v0_1
// (docs/TECHNICAL_SPEC_RU.md §6) КАК ВАЛИДАТОРЫ/ФАБРИКИ: форма объекта-адаптера,
// типы, подписи функций, вердикт {годен, причины[]}.
//
// Проверяемые честные границы:
//   - для КАЖДОГО из 6 контрактов: годен; нарушено обязательное поле; нарушен
//     тип; нарушена подпись (минимум 3 пробы — здесь по 6 на контракт);
//   - чистота входа: валидатор не мутирует объект (замороженный адаптер +
//     байтовый снапшот до/после);
//   - детерминизм: два подряд вызова дают идентичный вердикт (байт-в-байт);
//   - дверь никогда не бросает: любой вход → честный вердикт по-русски; бросает
//     только фабрика на структурную ошибку вызова (чужое/нестроковое имя);
//   - статика источника канона: 0 сети, 0 часов, 0 случайности, 0 eval,
//     импортов ноль — канон чист.
import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import {
  ver, КОНТРАКТЫ, ИМЕНА_КОНТРАКТОВ,
  создатьВалидаторКонтракта,
  создатьВалидаторАср, создатьВалидаторПеревода, создатьВалидаторВыравнивания,
  создатьВалидаторВокальнойГенерации, создатьВалидаторВоротКачества,
  создатьВалидаторТранспорта,
} from '../src/adapters-v02.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = readFileSync(join(HERE, '..', 'src', 'adapters-v02.mjs'), 'utf8');

const j = (x) => JSON.stringify(x);

// Контрактная функция каждого контракта (из реестра канона, 1-в-1).
const имяФункции = (имяКонтракта) => КОНТРАКТЫ[имяКонтракта].функции[0].имя;

// Годный адаптер-фикстура для контракта: все общие поля + функция с нужной подписью.
function годныйАдаптер(имяКонтракта) {
  const функции = {
    ASRAdapter: { распознать: (аудиофрагмент, язык, метаданныеВремени) => ({ текст: '', меткиСлов: [], confidence: null }) },
    TranslationAdapter: { перевести: (текст, исходныйЯзык, целевойЯзык) => ({ кандидаты: [], confidence: null }) },
    SingingAlignmentAdapter: { выровнять: (вокал, текст, ноты) => ({ тайминг: [], confidence: null }) },
    VocalGenerationAdapter: { сгенерировать: (перевод, разметка, мелодическийТаймлайн, профильГолоса) => ({ аудио: null, ограничения: [] }) },
    QualityGate: { проверить: (результат, требования) => ({ пропустить: true }) },
    TransportAdapter: { передать: (дорожка, метаданные) => ({ sequence: 0 }) },
  };
  return {
    контракт: имяКонтракта,
    версия: `${имяКонтракта}/0.1`,
    таймАутМс: 5000,
    метрики: () => ({ модуль: имяКонтракта }),
    ...функции[имяКонтракта],
  };
}

// Какое обязательное поле ломает каждый контракт в пробе T02 (покрыть ВСЕ общие
// поля и обе функции по разным контрактам — шире, чем одинаковая проба ×6).
const ПРОБЫ_НЕДОСТАЮЩЕГО_ПОЛЯ = {
  ASRAdapter: { поле: 'версия', фрагмент: 'поле «версия»: отсутствует' },
  TranslationAdapter: { поле: 'таймАутМс', фрагмент: 'поле «таймАутМс»: отсутствует' },
  SingingAlignmentAdapter: { поле: 'метрики', фрагмент: 'поле «метрики»: отсутствует' },
  VocalGenerationAdapter: { поле: 'контракт', фрагмент: 'поле «контракт»: отсутствует' },
  QualityGate: { поле: 'проверить', фрагмент: 'функция «проверить»: отсутствует' },
  TransportAdapter: { поле: 'передать', фрагмент: 'функция «передать»: отсутствует' },
};

const ФАБРИКИ_ПО_ИМЕНИ = [
  ['создатьВалидаторАср', 'ASRAdapter'],
  ['создатьВалидаторПеревода', 'TranslationAdapter'],
  ['создатьВалидаторВыравнивания', 'SingingAlignmentAdapter'],
  ['создатьВалидаторВокальнойГенерации', 'VocalGenerationAdapter'],
  ['создатьВалидаторВоротКачества', 'QualityGate'],
  ['создатьВалидаторТранспорта', 'TransportAdapter'],
];

const ФАБРИКИ = {
  создатьВалидаторАср,
  создатьВалидаторПеревода,
  создатьВалидаторВыравнивания,
  создатьВалидаторВокальнойГенерации,
  создатьВалидаторВоротКачества,
  создатьВалидаторТранспорта,
};

// ---------------------------------------------------------------------------
// ШЕСТЬ КОНТРАКТОВ — по 6 проб на каждый (годен; поле; тип; подпись; чистота;
// детерминизм).
// ---------------------------------------------------------------------------
for (const имяКонтракта of ИМЕНА_КОНТРАКТОВ) {
  describe(`контракт ${имяКонтракта} — валидатор формы (ТЗ §6 прототипа)`, () => {
    const создать = () => создатьВалидаторКонтракта(имяКонтракта);
    const фн = имяФункции(имяКонтракта);

    it(`T01 годный адаптер — вердикт годен true, причин нет, форма {годен, причины}`, () => {
      const в = создать()(годныйАдаптер(имяКонтракта));
      assert.equal(в.годен, true);
      assert.deepEqual(в.причины, []);
      assert.deepEqual(Object.keys(в), ['годен', 'причины']);
      assert.equal(typeof в.годен, 'boolean');
      assert.ok(Array.isArray(в.причины));
    });

    it(`T02 нарушено обязательное поле «${ПРОБЫ_НЕДОСТАЮЩЕГО_ПОЛЯ[имяКонтракта].поле}» — честный отказ с точной причиной`, () => {
      const адаптер = годныйАдаптер(имяКонтракта);
      delete адаптер[ПРОБЫ_НЕДОСТАЮЩЕГО_ПОЛЯ[имяКонтракта].поле];
      const в = создать()(адаптер);
      assert.equal(в.годен, false);
      assert.equal(в.причины.length, 1, 'одна беда — одна причина');
      assert.ok(в.причины[0].includes(ПРОБЫ_НЕДОСТАЮЩЕГО_ПОЛЯ[имяКонтракта].фрагмент), в.причины[0]);
    });

    it(`T03 нарушен тип: «${фн}» не функция — честный отказ`, () => {
      const адаптер = { ...годныйАдаптер(имяКонтракта), [фн]: 'не функция, а строка' };
      const в = создать()(адаптер);
      assert.equal(в.годен, false);
      assert.equal(в.причины.length, 1);
      assert.ok(в.причины[0].includes(`функция «${фн}»`), в.причины[0]);
      assert.ok(в.причины[0].includes('ожидается функция'), в.причины[0]);
    });

    it(`T04 нарушена подпись: «${фн}» без обязательных параметров — честный отказ`, () => {
      const адаптер = { ...годныйАдаптер(имяКонтракта), [фн]: () => ({}) };
      const в = создать()(адаптер);
      assert.equal(в.годен, false);
      assert.equal(в.причины.length, 1);
      assert.ok(в.причины[0].includes('подпись не по контракту'), в.причины[0]);
      assert.ok(в.причины[0].includes('минимум'), в.причины[0]);
    });

    it('T05 чистота входа: замороженный годный адаптер проходит и не мутируется', () => {
      const адаптер = Object.freeze(годныйАдаптер(имяКонтракта));
      const до = j(адаптер);
      const ключиДо = Object.keys(адаптер).sort();
      const в = создать()(адаптер);
      assert.equal(в.годен, true, j(в.причины));
      assert.equal(j(адаптер), до, 'байты входа не изменились');
      assert.deepEqual(Object.keys(адаптер).sort(), ключиДо);
      assert.equal(Object.isFrozen(адаптер), true);
    });

    it('T06 два подряд вызова дают идентичный вердикт (байт-в-байт, без общего состояния)', () => {
      const валидатор = создать();
      const в1 = валидатор(годныйАдаптер(имяКонтракта));
      const в2 = валидатор(годныйАдаптер(имяКонтракта));
      assert.notEqual(в1, в2, 'вердикты свежие, а не один общий объект');
      assert.equal(j(в1), j(в2));
      assert.deepEqual(в1, в2);
    });

    it(`T07 общая фабрика и именованная согласованы: контракт «${имяКонтракта}»`, () => {
      const имяФабрики = ФАБРИКИ_ПО_ИМЕНИ.find(([, имя]) => имя === имяКонтракта)[0];
      const в1 = ФАБРИКИ[имяФабрики]()(годныйАдаптер(имяКонтракта));
      const в2 = создатьВалидаторКонтракта(имяКонтракта)(годныйАдаптер(имяКонтракта));
      assert.equal(j(в1), j(в2));
      assert.equal(в1.годен, true);
    });
  });
}

// ---------------------------------------------------------------------------
// ОБЩАЯ ФАБРИКА И РЕЕСТР: честный TypeError на структурную ошибку, каталог
// шести контрактов, полнота причин, типовые нарушения общих полей.
// ---------------------------------------------------------------------------
describe('общая фабрика создатьВалидаторКонтракта и реестр КОНТРАКТЫ', () => {
  it('G01 неизвестное имя контракта — честный TypeError с перечнем шести имён', () => {
    assert.throws(() => создатьВалидаторКонтракта('НеизвестныйАдаптер'), (о) =>
      о instanceof TypeError && о.message.includes('одним из шести') && о.message.includes('ASRAdapter'));
  });

  it('G02 имя-не-строка (null) — честный TypeError, значение названо', () => {
    assert.throws(() => создатьВалидаторКонтракта(null), (о) =>
      о instanceof TypeError && о.message.includes('получено null'));
  });

  it('G03 имя-число (42) — честный TypeError, значение названо', () => {
    assert.throws(() => создатьВалидаторКонтракта(42), (о) =>
      о instanceof TypeError && о.message.includes('получено число(42)'));
  });

  it('G04 шесть именованных фабрик: каждая создаёт валидатор своего контракта', () => {
    for (const [имяФабрики, имяКонтракта] of ФАБРИКИ_ПО_ИМЕНИ) {
      const валидатор = ФАБРИКИ[имяФабрики]();
      assert.equal(валидатор.контракт, имяКонтракта, имяФабрики);
      assert.equal(валидатор(годныйАдаптер(имяКонтракта)).годен, true, имяФабрики);
      const чужое = имяКонтракта === 'TransportAdapter' ? 'ASRAdapter' : 'TransportAdapter';
      assert.equal(валидатор(годныйАдаптер(чужое)).годен, false, 'чужой адаптер не проходит');
    }
  });

  it('G05 реестр КОНТРАКТЫ заморожен и держит ровно шесть английских имён (1-в-1 по ТЗ §6)', () => {
    assert.equal(Object.isFrozen(КОНТРАКТЫ), true);
    assert.deepEqual(Object.keys(КОНТРАКТЫ), [
      'ASRAdapter', 'TranslationAdapter', 'SingingAlignmentAdapter',
      'VocalGenerationAdapter', 'QualityGate', 'TransportAdapter',
    ]);
    assert.deepEqual([...ИМЕНА_КОНТРАКТОВ], Object.keys(КОНТРАКТЫ));
    assert.equal(Object.isFrozen(ИМЕНА_КОНТРАКТОВ), true);
  });

  it('G06 дверь никогда не бросает: null/undefined/массив/строка/число/функция — честный вердикт', () => {
    const валидатор = создатьВалидаторКонтракта('ASRAdapter');
    for (const плохой of [null, undefined, [], 'строка', 42, () => ({}), true]) {
      const в = валидатор(плохой);
      assert.equal(в.годен, false, j(плохой ?? 'null'));
      assert.equal(в.причины.length, 1, j(плохой ?? 'null'));
      assert.ok(в.причины[0].includes('ожидается объект'), в.причины[0]);
    }
  });

  it('G07 пустой объект — ВСЕ пять причин, порядок проверок фиксирован', () => {
    const в = создатьВалидаторКонтракта('ASRAdapter')({});
    assert.equal(в.годен, false);
    assert.equal(в.причины.length, 5);
    assert.ok(в.причины[0].includes('поле «контракт»'), в.причины[0]);
    assert.ok(в.причины[1].includes('поле «версия»'), в.причины[1]);
    assert.ok(в.причины[2].includes('поле «таймАутМс»'), в.причины[2]);
    assert.ok(в.причины[3].includes('поле «метрики»'), в.причины[3]);
    assert.ok(в.причины[4].includes('функция «распознать»'), в.причины[4]);
  });

  it('G08 таймАутМс: строка/0/отрицательное/NaN/Infinity/null/true — честный отказ каждый раз', () => {
    const валидатор = создатьВалидаторКонтракта('ASRAdapter');
    for (const плохой of ['5000', 0, -1, NaN, Infinity, null, true]) {
      const адаптер = { ...годныйАдаптер('ASRAdapter'), таймАутМс: плохой };
      const в = валидатор(адаптер);
      assert.equal(в.годен, false, String(плохой));
      assert.equal(в.причины.length, 1, String(плохой));
      assert.ok(в.причины[0].includes('«таймАутМс»'), в.причины[0]);
    }
  });

  it('G09 версия: пустая/пробельная/не-строка — честный отказ', () => {
    const валидатор = создатьВалидаторКонтракта('TranslationAdapter');
    for (const плохой of ['', '   ', 42, null]) {
      const адаптер = { ...годныйАдаптер('TranslationAdapter'), версия: плохой };
      const в = валидатор(адаптер);
      assert.equal(в.годен, false, j(плохой));
      assert.equal(в.причины.length, 1);
      assert.ok(в.причины[0].includes('«версия»'), в.причины[0]);
    }
  });

  it('G10 контракт-чужое-имя и контракт-не-строка — валидатор не путает формы', () => {
    const валидатор = создатьВалидаторКонтракта('ASRAdapter');
    const чужой = { ...годныйАдаптер('ASRAdapter'), контракт: 'TranslationAdapter' };
    const в1 = валидатор(чужой);
    assert.equal(в1.годен, false);
    assert.ok(в1.причины[0].includes('ожидалось «ASRAdapter»'), в1.причины[0]);
    assert.ok(в1.причины[0].includes('TranslationAdapter'), в1.причины[0]);
    const нестрока = { ...годныйАдаптер('ASRAdapter'), контракт: 42 };
    const в2 = валидатор(нестрока);
    assert.equal(в2.годен, false);
    assert.ok(в2.причины[0].includes('получено число(42)'), в2.причины[0]);
  });

  it('G11 метрики-не-функция — честный отказ (диагностические метрики обязательны, ARCHITECTURE §4)', () => {
    const адаптер = { ...годныйАдаптер('QualityGate'), метрики: 'отчёт строкой' };
    const в = создатьВалидаторКонтракта('QualityGate')(адаптер);
    assert.equal(в.годен, false);
    assert.equal(в.причины.length, 1);
    assert.ok(в.причины[0].includes('«метрики»') && в.причины[0].includes('ожидается функция'), в.причины[0]);
  });

  it('G12 вердикт заморожен: чужой код не перепишет причины и не добавит поля', () => {
    const в = создатьВалидаторКонтракта('ASRAdapter')({});
    assert.equal(Object.isFrozen(в), true);
    assert.equal(Object.isFrozen(в.причины), true);
    assert.throws(() => { 'use strict'; в.годен = true; }, TypeError);
    assert.throws(() => { 'use strict'; в.причины.push('внутренний'); }, TypeError);
  });

  it('G13 детерминизм на битом адаптере: два подряд вызова — один вердикт байт-в-байт', () => {
    const валидатор = создатьВалидаторКонтракта('SingingAlignmentAdapter');
    const в1 = валидатор({});
    const в2 = валидатор({});
    assert.equal(j(в1), j(в2));
    assert.deepEqual(в1, в2);
  });

  it('G14 замороженный битый адаптер — вердикт честный, вход не тронут', () => {
    const адаптер = Object.freeze({});
    const до = j(адаптер);
    const в = создатьВалидаторКонтракта('VocalGenerationAdapter')(адаптер);
    assert.equal(в.годен, false);
    assert.equal(в.причины.length, 5);
    assert.equal(j(адаптер), до);
  });

  it('G15 два валидатора одной фабрики независимы и согласованы по вердикту', () => {
    const фаб = создатьВалидаторТранспорта;
    const в1 = фаб();
    const в2 = фаб();
    assert.notEqual(в1, в2, 'фабрика каждый раз даёт свежего валидатора');
    const адаптер = годныйАдаптер('TransportAdapter');
    assert.equal(j(в1(адаптер)), j(в2(адаптер)));
    assert.equal(в1.контракт, 'TransportAdapter');
    assert.equal(в2.контракт, 'TransportAdapter');
  });
});

// ---------------------------------------------------------------------------
