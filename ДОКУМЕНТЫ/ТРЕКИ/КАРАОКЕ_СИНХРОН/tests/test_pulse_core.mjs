/* ── нормализоватьASR ─────────────────────────────────────────────────────── */

describe('нормализоватьASR', () => {
  it('базовая: регистр, пунктуация, пробелы, ё→е', () => {
    assert.deepEqual(
      нормализоватьASR('Мы, БЕЖИМ  по Ёлке-пальме!!'),
      ['мы', 'бежим', 'по', 'елкепальме']
    );
  });

  it('граничная: пусто и одиночка', () => {
    assert.deepEqual(нормализоватьASR(''), []);
    assert.deepEqual(нормализоватьASR(null), []);
    assert.deepEqual(нормализоватьASR(undefined), []);
    assert.deepEqual(нормализоватьASR('Один'), ['один']);
    assert.deepEqual(нормализоватьASR('  ...  '), []);   // одна пунктуация — не слова
  });

  it('инвариант детерминизма: два вызова идентичны байт-в-байт', () => {
    const вход = 'МЫ  божим, па  кругу!! Ветир  паёт у ушех...';
    assert.equal(байты(нормализоватьASR(вход)), байты(нормализоватьASR(вход)));
  });

  it('вход не мутируется', () => {
    const вход = [{ w: 'Мы', s: 100, e: 200 }, { word: 'бежим', start: 0.2, end: 0.5 }];
    const до = байты(вход);
    нормализоватьASR(вход);
    assert.equal(байты(вход), до);
  });

  it('честная ошибка: не строка и не массив', () => {
    assert.throws(() => нормализоватьASR(42), TypeError);
    assert.throws(() => нормализоватьASR({ w: 'мы' }), TypeError);
  });

  it('диалекты ядра-образца: секунды → мс, {w,s,e} — мс, segments', () => {
    assert.deepEqual(нормализоватьASR([{ word: 'Мы', start: 1.5, end: 1.75 }]), [{ w: 'мы', s: 1500, e: 1750 }]);
    assert.deepEqual(нормализоватьASR([{ text: 'хвост', timestamp: [2, 2.25] }]), [{ w: 'хвост', s: 2000, e: 2250 }]);
    assert.deepEqual(нормализоватьASR([{ w: 'у', s: 90, e: 120 }]), [{ w: 'у', s: 90, e: 120 }]);
    assert.deepEqual(
      нормализоватьASR([{ words: [{ word: 'мы', start: 0.1, end: 0.2 }] }]),
      [{ w: 'мы', s: 100, e: 200 }]
    );
  });

  it('слово без конечных времён остаётся текстовым {w}', () => {
    assert.deepEqual(нормализоватьASR([{ w: 'у', s: 'мусор' }]), [{ w: 'у' }]);
    assert.deepEqual(нормализоватьASR(['ХВОСТ!']), [{ w: 'хвост' }]);
  });
});

/* ── выровнять ────────────────────────────────────────────────────────────── */

describe('выровнять (Needleman–Wunsch)', () => {
  it('базовая: точные слова + одна ASR-ошибка проходит по порогу 0.6', () => {
    const р = выровнять(['мы', 'бежим', 'па', 'круге'], ['мы бежим по кругу']);
    assert.equal(р.всего, 4);
    assert.equal(р.совпало, 3);
    assert.equal(р.покрытие, 3 / 4);
    // «па»↔«по»: сходство 0.5 < 0.6 — не пара; «круге»↔«кругу»: 0.8 ≥ 0.6 — пара не точная
    assert.equal(р.пары.length, 3);
    assert.deepEqual(р.пары.map(п => п.слово), ['мы', 'бежим', 'кругу']);
    assert.deepEqual(р.пары.map(п => п.точно), [true, true, false]);
    assert.ok(Math.abs(р.пары[2].sim - 0.8) < 1e-12);
    assert.deepEqual(р.пропущено, [{ строка: 0, позиция: 2, слово: 'по' }]);
    assert.equal(р.лишнее.length, 1);
    assert.equal(р.лишнее[0].слово, 'па');
  });

  it('граничная: пусто с любой стороны — пар нет, покрытие 0 (честное «нечем мерить»)', () => {
    const безАс = выровнять([], ['раз два']);
    assert.deepEqual(безАс.пары, []);
    assert.equal(безАс.пропущено.length, 2);
    assert.deepEqual(безАс.лишнее, []);
    assert.equal(безАс.покрытие, 0);

    const безЭт = выровнять(['слово'], []);
    assert.deepEqual(безЭт.пары, []);
    assert.equal(безЭт.лишнее.length, 1);
    assert.equal(безЭт.всего, 0);
    assert.equal(безЭт.покрытие, 0);
  });

  it('граничная: одиночка — точная пара, покрытие 1', () => {
    const р = выровнять(['ХВОСТ!'], ['хвост']);
    assert.equal(р.совпало, 1);
    assert.equal(р.покрытие, 1);
    assert.equal(р.пары[0].точно, true);
    assert.equal(р.пары[0].sim, 1);
  });

  it('граничная: полное расхождение — ноль пар, гэпы выигрывают у неверных пар', () => {
    const р = выровнять(['четыре', 'пять'], ['раз два три']);
    assert.equal(р.совпало, 0);
    assert.equal(р.покрытие, 0);
    assert.equal(р.пропущено.length, 3);
    assert.equal(р.лишнее.length, 2);
    assert.ok(р.матрица.every(ряд => ряд.every(s => s < ПС_ПОРОГ_СХОДСТВА)));
  });

  it('инвариант детерминизма: два вызова на строфе идентичны байт-в-байт', () => {
    const а1 = выровнять(нормализоватьASR(АСР_СЛОВА), СТРОФА);
    const а2 = выровнять(нормализоватьASR(АСР_СЛОВА), СТРОФА);
    assert.equal(байты(а1), байты(а2));
  });

  it('вход не мутируется (строка-фикстура и слова ASR целы)', () => {
    const ас = нормализоватьASR(АСР_СЛОВА);
    const до = байты([СТРОФА, ас]);
    выровнять(ас, СТРОФА);
    assert.equal(байты([СТРОФА, ас]), до);
  });

  it('опц.штраф — это порог сходства (имя приказа, алиас опц.порог ядра)', () => {
    // 0.99: «круге»↔«кругу» (0.8) больше не пара
    const строгий = выровнять(['мы', 'бежим', 'па', 'круге'], ['мы бежим по кругу'], { штраф: 0.99 });
    assert.equal(строгий.совпало, 2);
    assert.equal(строгий.порог, 0.99);
    // валидация порога — честные ошибки
    assert.throws(() => выровнять(['мы'], ['мы'], { штраф: 2 }), TypeError);
    assert.throws(() => выровнять(['мы'], ['мы'], { штраф: 'ноль' }), TypeError);
    assert.throws(() => выровнять(['мы'], ['мы'], { штраф: NaN }), TypeError);
    // алиас ядра работает так же
    assert.equal(выровнять(['мы'], ['мы'], { порог: 1 }).совпало, 1);
  });

  it('честная симметричная матрица: строится целиком и симметрична', () => {
    const р = выровнять(['а', 'б', 'г'], ['а б в']);
    assert.equal(р.матрица.length, 3);
    р.матрица.forEach((ряд, i) => {
      assert.equal(ряд.length, 3);
      ряд.forEach((s, j) => assert.equal(s, сходство(норм('а б в'.split(' ')[i]), норм(['а', 'б', 'г'][j]))));
    });
    for (const [a, b] of [['кругу', 'круге'], ['ушех', 'ушах'], ['по', 'па']]) {
      assert.equal(сходство(a, b), сходство(b, a));
    }
  });

  it('времена проходят в пары (юнит ↔ ASR), честные ошибки аргументов', () => {
    const строка = { i: 0, t: 'мы бежим', units: [{ t: 'мы', s: 1000, e: 1200 }, { t: 'бежим', s: 1210, e: 1500 }] };
    const р = выровнять([{ w: 'мы', s: 1005, e: 1195 }, { w: 'бежим', s: 1210, e: 1495 }], [строка]);
    assert.equal(р.пары.length, 2);
    assert.equal(р.пары[0].юнит.s, 1000);
    assert.equal(р.пары[0].asr.s, 1005);

    assert.throws(() => выровнять('мы', ['мы']), TypeError);
    assert.throws(() => выровнять(['мы'], 'мы'), TypeError);
    assert.throws(() => выровнять([42], ['мы']), TypeError);
    assert.throws(() => выровнять(['мы'], [{ a: 1 }]), TypeError);   // строка без t и units
  });
});

/* ── сравнить ─────────────────────────────────────────────────────────────── */

describe('сравнить (метрики выравнивания)', () => {
  const строфа = () => сравнить(выровнять(нормализоватьASR(АСР_СЛОВА), СТРОФА));

  it('базовая: совпадения/расхождения/покрытие на строфе с ASR-ошибками', () => {
    const м = строфа();
    assert.equal(м.всего, 8);
    assert.equal(м.совпало, 6);          // мы, божим→бежим, кругу, ветир→ветер, пает→поёт, ушех→ушах
    assert.equal(м.точно, 2);            // мы, кругу
    assert.equal(м.приблизительно, 4);
    assert.equal(м.пропущено, 2);        // по, в
    assert.equal(м.лишнее, 2);           // па, у
    assert.equal(м.расхождения, 8);      // приблизительно + пропущено + лишнее
    assert.equal(м.покрытие, 6 / 8);
    assert.ok(Math.abs(м.точностьТекста - 2 / 8) < 1e-12);
  });

  it('дельты времён: среднее/медиана/p90 и доли по правилам 50 и 80 мс', () => {
    const строка = { i: 0, t: 'мы бежим', units: [{ t: 'мы', s: 1000, e: 1200 }, { t: 'бежим', s: 1210, e: 1500 }] };
    const м = сравнить(выровнять([{ w: 'мы', s: 1005, e: 1195 }, { w: 'бежим', s: 1210, e: 1495 }], [строка]));
    assert.equal(м.времена, true);
    assert.deepEqual(м.дельты, {
      n: 2,
      среднее_мс: 3,          // round(5/2)
      медиана_мс: 5,          // sorted[1] — как в ядре-образце
      p90_мс: 5,
      в50_мс_процент: 100,
      в80_мс_процент: 100,
    });
  });

  it('граничная: пусто и без времён — дельты null, «времена» false', () => {
    const пусто = сравнить(выровнять([], []));
    assert.equal(пусто.всего, 0);
    assert.equal(пусто.покрытие, 0);
    assert.equal(пусто.дельты, null);
    assert.equal(пусто.времена, false);

    const текстовый = сравнить(выровнять(нормализоватьASR(ТЕКСТ_ASR), СТРОФА));
    assert.equal(текстовый.времена, false);   // ASR без времён — честное «нет данных»
    assert.equal(текстовый.дельты, null);
    assert.equal(текстовый.совпало, 6);
  });

  it('инвариант детерминизма: два вызова идентичны байт-в-байт', () => {
    assert.equal(байты(строфа()), байты(строфа()));
  });

  it('вход не мутируется: дельтаМс появляется только в копии «деталь»', () => {
    const выр = выровнять(нормализоватьASR(АСР_СЛОВА), СТРОФА);
    const до = байты(выр);
    const м = сравнить(выр);
    assert.equal(байты(выр), до);
    assert.equal('дельтаМс' in выр.пары[0], false);
    assert.equal('дельтаМс' in м.деталь[0], true);
  });

  it('честная ошибка: мусор на входе', () => {
    assert.throws(() => сравнить(null), TypeError);
    assert.throws(() => сравнить({}), TypeError);
    assert.throws(() => сравнить([]), TypeError);
  });
});

/* ── вHarm ────────────────────────────────────────────────────────────────── */

describe('вHarm (вердикт гармонии строки)', () => {
  const метрикиВремена = () => сравнить(выровнять(нормализоватьASR(АСР_СЛОВА), СТРОФА));
  const метрикиТекст = () => сравнить(выровнять(нормализоватьASR(ТЕКСТ_ASR), СТРОФА));

  it('базовая: исправная строка — все три правила ok, гармония true', () => {
    const вердикт = вHarm(метрикиВремена(), СТРОФА[0]);
    assert.equal(вердикт.гармония, true);
    assert.equal(вердикт.причина, null);
    assert.equal(вердикт.строка, 0);
    assert.deepEqual(вердикт.правила.map(п => п.правило), ['покрытие', 'комфорт80мс', 'хвост']);
    assert.deepEqual(вердикт.правила.map(п => п.статус), ['ok', 'ok', 'ok']);
    assert.ok(Math.abs(вердикт.покрытие - 3 / 4) < 1e-12);
    assert.deepEqual(вердикт.правила[2].значение, [30, 30, 30]);   // хвосты в каноне 20–40 мс
  });

  it('вторая строка строфы тоже гармонична', () => {
    const вердикт = вHarm(метрикиВремена(), СТРОФА[1]);
    assert.equal(вердикт.гармония, true);
    assert.deepEqual(вердикт.правила.map(п => п.статус), ['ok', 'ok', 'ok']);
  });

  it('граничная: ASR без времён — правила времени «нет данных» и не валят вердикт', () => {
    const вердикт = вHarm(метрикиТекст(), СТРОФА[0]);
    assert.equal(вердикт.гармония, true);                          // текстовая гармония подтверждена
    assert.deepEqual(вердикт.правила.map(п => п.статус), ['ok', 'нет данных', 'нет данных']);
    assert.equal(вердикт.правила[1].причина.includes('нет пар'), true);
  });

  it('граничная: строка без слов — покрытие «нет данных»', () => {
    const вердикт = вHarm(метрикиВремена(), { i: 9, t: '   ' });
    assert.equal(вердикт.правила[0].статус, 'нет данных');
    assert.equal(вердикт.покрытие, 0);
  });

  it('полное расхождение → гармония false, причина по-русски про покрытие', () => {
    const м = сравнить(выровнять(['четыре', 'пять'], ['раз два три']));
    const вердикт = вHarm(м, { i: 0, t: 'раз два три' });
    assert.equal(вердикт.гармония, false);
    assert.equal(вердикт.правила[0].статус, 'отклонено');
    assert.equal(вердикт.причина.includes('покрытие'), true);
  });

  it('правило ≤80 мс: сдвиг старта на 90 валит только комфорт', () => {
    const ас = [
      { w: 'мама', s: 1000, e: 1130 },
      { w: 'мыла', s: 1250, e: 1330 },   // дельта |1250−1160| = 90 > 80; хвост 1350−1330 = 20 — в каноне
      { w: 'раму', s: 1360, e: 1530 },
    ];
    const вердикт = вHarm(сравнить(выровнять(ас, [строкаРаму])), строкаРаму);
    assert.equal(вердикт.гармония, false);
    assert.deepEqual(вердикт.правила.map(п => п.статус), ['ok', 'отклонено', 'ok']);
    assert.equal(вердикт.правила[1].значение, 90);
    assert.equal(вердикт.правила[1].порог, ПС_КОМФОРТ_МС);
    assert.equal(вердикт.причина.includes('комфорт80мс'), true);
  });

  it('правило хвоста: 10 мс — мал, 60 мс — велик (канон 20–40)', () => {
    const мал = [
      { w: 'мама', s: 1000, e: 1140 },   // хвост 1150−1140 = 10 < 20
      { w: 'мыла', s: 1160, e: 1340 },
      { w: 'раму', s: 1360, e: 1540 },
    ];
    const вердиктМал = вHarm(сравнить(выровнять(мал, [строкаРаму])), строкаРаму);
    assert.equal(вердиктМал.гармония, false);
    assert.deepEqual(вердиктМал.правила.map(п => п.статус), ['ok', 'ok', 'отклонено']);
    assert.deepEqual(вердиктМал.правила[2].диапазон, [ПС_ХВОСТ_МИН_МС, ПС_ХВОСТ_МАКС_МС]);

    const велик = [
      { w: 'мама', s: 1000, e: 1090 },   // хвост 1150−1090 = 60 > 40
      { w: 'мыла', s: 1160, e: 1290 },
      { w: 'раму', s: 1360, e: 1490 },
    ];
    const вердиктВелик = вHarm(сравнить(выровнять(велик, [строкаРаму])), строкаРаму);
    assert.equal(вердиктВелик.гармония, false);
    assert.deepEqual(вердиктВелик.правила.map(п => п.статус), ['ok', 'ok', 'отклонено']);
  });

  it('инвариант детерминизма: два вердикта идентичны байт-в-байт', () => {
    const м = метрикиВремена();
    assert.equal(байты(вHarm(м, СТРОФА[0])), байты(вHarm(м, СТРОФА[0])));
  });

  it('вход не мутируется (метрики и строка целы)', () => {
    const м = метрикиВремена();
    const строка = СТРОФА[0];
    const до = байты([м, строка]);
    вHarm(м, строка);
    assert.equal(байты([м, строка]), до);
  });

  it('честные ошибки: мусор вместо метрик/строки, опций', () => {
    const м = метрикиВремена();
    assert.throws(() => вHarm(null, СТРОФА[0]), TypeError);
    assert.throws(() => вHarm({}, СТРОФА[0]), TypeError);
    assert.throws(() => вHarm(м, {}), TypeError);                       // нет i
    assert.throws(() => вHarm(м, { i: 0 }), TypeError);                 // нет units и t
    assert.throws(() => вHarm(м, 'мы бежим'), TypeError);
    assert.throws(() => вHarm(м, { i: 0.5, t: 'мы бежим' }), TypeError); // i не целое
    assert.throws(() => вHarm(м, СТРОФА[0], { порогПокрытия: 'ноль' }), TypeError);
  });
});

/* ── сквозной конвейер ────────────────────────────────────────────────────── */

describe('сквозной конвейер: нормализоватьASR → выровнять → сравнить → вHarm', () => {
  const прогон = ас => {
    const слова = нормализоватьASR(ас);
    const выравнивание = выровнять(слова, СТРОФА);
    const метрики = сравнить(выравнивание);
    const вердикты = СТРОФА.map(с => вHarm(метрики, с));
    return { слова, выравнивание, метрики, вердикты };
  };

  it('строфа с ASR-ошибками и временами: покрытие 0.75, обе строки в гармонии', () => {
    const { слова, метрики, вердикты } = прогон(АСР_СЛОВА);
    // диалект {w,s,e}: текст норм(), времена целые мс; «паёт» → «пает» (норм ядра: ё→е)
    assert.deepEqual(слова.map(x => x.w), ['мы', 'божим', 'па', 'кругу', 'ветир', 'пает', 'у', 'ушех']);
    assert.deepEqual(слова[0], { w: 'мы', s: 10000, e: 10200 });
    assert.equal(метрики.совпало, 6);
    assert.equal(метрики.пропущено, 2);
    assert.equal(метрики.лишнее, 2);
    assert.deepEqual(метрики.дельты, {
      n: 6, среднее_мс: 0, медиана_мс: 0, p90_мс: 0, в50_мс_процент: 100, в80_мс_процент: 100,
    });
    assert.equal(вердикты.length, 2);
    assert.equal(вердикты[0].гармония, true);
    assert.equal(вердикты[1].гармония, true);
  });

  it('та же строфа голым текстом: ось без времён честно «нет данных»', () => {
    const { слова, метрики, вердикты } = прогон(ТЕКСТ_ASR);
    assert.deepEqual(слова, ['мы', 'божим', 'па', 'кругу', 'ветир', 'пает', 'у', 'ушех']);
    assert.equal(метрики.времена, false);
    assert.equal(вердикты[0].гармония, true);
    assert.deepEqual(вердикты[0].правила.map(п => п.статус), ['ok', 'нет данных', 'нет данных']);
  });

  it('инвариант детерминизма: полный прогон дважды — байт-в-байт', () => {
    assert.equal(байты(прогон(АСР_СЛОВА)), байты(прогон(АСР_СЛОВА)));
    assert.equal(байты(прогон(ТЕКСТ_ASR)), байты(прогон(ТЕКСТ_ASR)));
  });

  it('сквозной прогон не мутирует фикстуры', () => {
    const до = байты([СТРОФА, АСР_СЛОВА, ТЕКСТ_ASR]);
    прогон(АСР_СЛОВА);
    прогон(ТЕКСТ_ASR);
    assert.equal(байты([СТРОФА, АСР_СЛОВА, ТЕКСТ_ASR]), до);
  });
});
