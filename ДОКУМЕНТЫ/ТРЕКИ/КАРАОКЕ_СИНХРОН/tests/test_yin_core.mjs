test('детерминизм: тот же вход — тот же выход', () => {
  const x = тонСГармониками(146.83);
  const а = частота(x, СР);
  const б = частота(x, СР);
  assert.equal(а.частота, б.частота);
  assert.equal(а.чистота, б.чистота);
  assert.equal(а.фолбэк, б.фолбэк);
});

test('разность: d(0)=0, d монотонно определена, длина W+1', () => {
  const d = разность(тон(220), {});
  assert.equal(d.length, (ОКНО >> 1) + 1);
  assert.equal(d[0], 0);
  for (let τ = 1; τ < d.length; τ++) assert.ok(isFinite(d[τ]));
});

test('нормировка: c(0)=1, у истинного периода c < θ', () => {
  const x = тон(220);
  const c = нормировка(разность(x, {}));
  assert.equal(c[0], 1);
  const пер = Math.round(СР / 220); /* ≈ 200 сэмплов */
  assert.ok(c[пер] < 0.15, 'c(период)=' + c[пер].toFixed(3) + ' < θ=0.15');
  assert.ok(c[пер] < c[2], 'у периода глубже, чем вне периодов');
});

