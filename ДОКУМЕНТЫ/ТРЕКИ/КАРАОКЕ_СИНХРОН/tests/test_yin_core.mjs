import { test } from 'node:test';
import assert from 'node:assert/strict';
import { ИМЯ, разность, нормировка, период, частота, создатьЯдро } from '../src/yin-core.mjs';

const СР = 44100;
const ОКНО = 2048;

function тон(гц, ср = СР, окно = ОКНО, амплитуда = 0.4, фаза = 0) {
  const x = new Float32Array(окно);
  for (let i = 0; i < окно; i++) x[i] = амплитуда * Math.sin(2 * Math.PI * гц * (i / ср) + фаза);
  return x;
}

function тонСГармониками(гц, ср = СР, окно = ОКНО) {
  const x = new Float32Array(окно);
  for (let i = 0; i < окно; i++) {
    const t = i / ср;
    x[i] = 0.35 * Math.sin(2 * Math.PI * гц * t)
         + 0.18 * Math.sin(2 * Math.PI * 2 * гц * t)
         + 0.09 * Math.sin(2 * Math.PI * 3 * гц * t)
         + 0.05 * Math.sin(2 * Math.PI * 4 * гц * t);
  }
  return x;
}

function близко(а, б, доп = 1.0) {
  return Math.abs(а - б) <= доп;
}

test('имя канона', () => {
  assert.equal(ИМЯ, 'yin-core/0.1');
});

test('чистый тон ля4 440 Гц — точная высота, θ взят без фолбэка', () => {
  const р = частота(тон(440), СР);
  assert.ok(р.частота !== null, 'высота найдена');
  assert.ok(близко(р.частота, 440, 0.5), '440 ± 0.5 Гц, факт ' + р.частота.toFixed(2));
  assert.ok(р.чистота > 0.85, 'чистота > 0.85, факт ' + р.чистота.toFixed(3));
  assert.equal(р.фолбэк, false, 'порог θ взят честно');
});

