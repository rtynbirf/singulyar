test('тон вне голосового диапазона 2000 Гц — только реальный период (субгармоника), не выдумка', () => {
  const р = частота(тон(2000), СР);
  /* 2000 Гц вне 60–1100: канон ищет периоды только от τМин, поэтому
     честный ответ — ближайший РЕАЛЬНЫЙ период внутри диапазона:
     2-я кратность 1000 Гц (выдумывать 2000 канон не может по закону τМин) */
  assert.ok(р.частота !== null);
  assert.ok(близко(р.частота, 1000, 1.0), 'реальный суб-период 1000 ± 1 Гц, факт ' + р.частота.toFixed(2));
  assert.ok(близко(р.чистота, 1, 0.05), 'периодичность подлинная, чистота ' + р.чистота.toFixed(3));
});

