test('смена тона в кадре: октава вниз не рвёт честность ответа', () => {
  /* второй полукадр — октава ниже: канон отвечает одним периодом,
     главное — не выдумать высоту, которой нет ни в одной половине */
  const x = new Float32Array(ОКНО);
  for (let i = 0; i < ОКНО; i++) {
    const гц = i < ОКНО / 2 ? 440 : 220;
    x[i] = 0.4 * Math.sin(2 * Math.PI * гц * (i / СР));
  }
  const р = частота(x, СР);
  if (р.частота !== null) {
    const вЛя = [220, 440].some(г => близко(р.частота, г, 2));
    assert.ok(вЛя, 'ответ из реальных периодов: ' + р.частота.toFixed(2));
  }
});

/* ── БЕНЧМАРК ПРИЁМКИ ПВ2: бюджет кадра < 10 мс (честное измерение) ── */
test('бенчмарк: 40 кадров по 2048 — медиана < 10 мс', () => {
  const кадры = [];
  for (let k = 0; k < 40; k++) кадры.push(тон(110 + k * 17.3, СР, ОКНО, 0.3 + 0.1 * (k % 5)));
  const врем = [];
  for (let k = 0; k < 40; k++) {
    const t0 = process.hrtime.bigint();
    частота(кадры[k], СР);
    врем.push(Number(process.hrtime.bigint() - t0) / 1e6);
  }
  врем.sort((а, б) => а - б);
  const медиана = врем[20];
  const макс = врем[39];
  console.log('  [ЙИН] медиана кадра: ' + медиана.toFixed(2) + ' мс · максимум: ' + макс.toFixed(2) + ' мс (node ' + process.version + ')');
  assert.ok(медиана < 10, 'медиана ' + медиана.toFixed(2) + ' мс < 10 мс — приёмка ПВ2');
});
