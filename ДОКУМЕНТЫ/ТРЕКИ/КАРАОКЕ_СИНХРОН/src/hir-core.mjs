/* ── создание классификатора ────────────────────────────────────────────── */

export function создатьКлассификатор(примеры, опции = {}) {
  if (!Array.isArray(примеры)) {
    throw new TypeError('примеры должны быть массивом {текст, намерение}, а пришло: ' + честныйТип(примеры));
  }
  if (примеры.length === 0) {
    throw new RangeError('примеры пусты: классификатору нужен хотя бы один пример');
  }
  if (опции === null || typeof опции !== 'object' || Array.isArray(опции)) {
    throw new TypeError('опции должны быть объектом, а пришло: ' + честныйТип(опции));
  }
  const минимум = проверитьГраницу(опции.ngramМин, ГРАММ_МИН_ПО_УМОЛЧАНИЮ, 'ngramМин');
  const максимум = проверитьГраницу(опции.ngramМакс, ГРАММ_МАКС_ПО_УМОЛЧАНИЮ, 'ngramМакс');
  if (максимум < минимум) {
    throw new RangeError('ngramМакс (' + максимум + ') не может быть меньше ngramМин (' + минимум + ')');
  }

  // Честная проверка каждого примера (порядок — как в массиве).
  for (let номер = 0; номер < примеры.length; номер += 1) {
    const пример = примеры[номер];
    if (пример === null || typeof пример !== 'object' || Array.isArray(пример)) {
      throw new TypeError('пример №' + (номер + 1) + ' должен быть объектом {текст, намерение}, а пришло: ' + честныйТип(пример));
    }
    if (пример.текст === undefined) {
      throw new TypeError('у примера №' + (номер + 1) + ' нет текста: нужен {текст, намерение}');
    }
    if (пример.намерение === undefined) {
      throw new TypeError('у примера №' + (номер + 1) + ' нет намерения: нужен {текст, намерение}');
    }
    if (typeof пример.текст !== 'string') {
      throw new TypeError('текст примера №' + (номер + 1) + ' должен быть строкой, а пришло: ' + честныйТип(пример.текст));
    }
    if (typeof пример.намерение !== 'string') {
      throw new TypeError('намерение примера №' + (номер + 1) + ' должно быть строкой, а пришло: ' + честныйТип(пример.намерение));
    }
    if (пример.текст === '') {
      throw new RangeError('текст примера №' + (номер + 1) + ' пуст: классу нужен настоящий текст');
    }
    if (пример.намерение === '') {
      throw new RangeError('намерение примера №' + (номер + 1) + ' пусто: у класса должно быть имя');
    }
    const нормальныйТекст = нормализовать(пример.текст);
    if (нормальныйТекст === '') {
      throw new RangeError('текст примера №' + (номер + 1) + ' пуст после нормализации (одни пробелы): нет ни одного признака');
    }
    if (нормальныйТекст.length < минимум) {
      throw new RangeError('текст примера №' + (номер + 1) + ' короче минимальной n-граммы (' + минимум + '): у примера не будет ни одного признака');
    }
  }

  // Класс-векторы: сумма нормализованных векторов примеров класса, затем L2.
  const векторыКлассов = new Map();
  for (let номер = 0; номер < примеры.length; номер += 1) {
    const пример = примеры[номер];
    const нормальныйТекст = нормализовать(пример.текст);
    const векторПримера = нормализованныйВекторL2(частотыNграмм(нормальныйТекст, минимум, максимум));
    let ведро = векторыКлассов.get(пример.намерение);
    if (ведро === undefined) {
      ведро = new Map();
      векторыКлассов.set(пример.намерение, ведро);
    }
    for (const [грамма, вес] of векторПримера) {
      ведро.set(грамма, (ведро.get(грамма) || 0) + вес);
    }
  }
  for (const [имя, ведро] of векторыКлассов) {
    векторыКлассов.set(имя, нормализованныйВекторL2(ведро));
  }

  const имена = Array.from(векторыКлассов.keys());
  имена.sort(сравнитьПоКодовымТочкам); // детерминированный порядок обхода классов

  /* распознать: честный ответ по фразе */
  function распознать(текст) {
    if (typeof текст !== 'string') {
      throw new TypeError('текст для распознавания должен быть строкой, а пришло: ' + честныйТип(текст));
    }
    const нормальныйТекст = нормализовать(текст);
    if (нормальныйТекст === '') {
      throw new RangeError('текст пуст: нечего распознавать');
    }
    const векторЗапроса = нормализованныйВекторL2(частотыNграмм(нормальныйТекст, минимум, максимум));

    const оценки = [];
    for (let номер = 0; номер < имена.length; номер += 1) {
      const имя = имена[номер];
      const оценка = скалярноеПроизведение(векторЗапроса, векторыКлассов.get(имя));
      оценки.push({ имя, оценка });
    }
    // Оценка по убыванию, затем имя по возрастанию кодовых точек — детерминизм.
    оценки.sort(function (левая, правая) {
      if (правая.оценка !== левая.оценка) {
        return левая.оценка > правая.оценка ? -1 : 1;
      }
      return сравнитьПоКодовымТочкам(левая.имя, правая.имя);
    });

    const лучший = оценки[0];
    if (!(лучший.оценка > 0)) {
      // Честный отказ от выдумки: совпадения нет — намерения нет.
      return { намерение: null, уверенность: 0, альтернативы: [] };
    }
    const альтернативы = [];
    for (let номер = 1; номер < оценки.length && альтернативы.length < АЛЬТЕРНАТИВ_МАКСИМУМ; номер += 1) {
      if (оценки[номер].оценка > 0) {
        альтернативы.push({ намерение: оценки[номер].имя, оценка: оценки[номер].оценка });
      }
    }
    return { намерение: лучший.имя, уверенность: лучший.оценка, альтернативы };
  }

  /* двери: отсортированный список имён намерений */
  function двери() {
    return имена.slice();
  }

  function версия() {
    return ВЕРСИЯ_КАНОНА;
  }

  return Object.freeze({ распознать, двери, версия });
}

/* ── готовый классификатор дома для двери ·41 ───────────────────────────── */

export function создатьДомашний() {
  return создатьКлассификатор(РЕЕСТР_НАМЕРЕНИЙ);
}
