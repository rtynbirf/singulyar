/*
 * hir-core/0.1 — «Нить Ариадны как рантайм»: HIR-классификатор намерений на N-граммах.
 *
 * Назначение: дверь ·41 НАМЕРЕНИЕ. Канон превращает русскую фразу в вектор частот
 * символьных n-грамм, сравнивает его косинусной близостью с векторами классов-намерений
 * и честно называет лучшее намерение, уверенность и до трёх альтернатив. Ничего
 * не выдумывает: нет совпадения — нет намерения (null). Класс-вектор — сумма
 * L2-нормализованных векторов примеров класса, снова L2-нормализованная.
 *
 * Законы дома (нарушать нельзя — это шрамы прежних тактов):
 *   0 сети                — канон никогда не обращается в сеть (fetch/XHR/WebSocket под запретом);
 *   0 случайности         — одинаковый вход даёт одинаковый выход (порядок обхода и тай-брейки детерминированы);
 *   0 часов               — время не вызывается никогда (Date.now/performance.now запрещены; время — только аргументом);
 *   вход не мутируется    — канон не меняет свои аргументы;
 *   честные русские отказы — на неверный вход RangeError/TypeError/Error с русским сообщением,
 *                           никогда молчаливые undefined/null.
 *
 * такт v11.47 «ЗАКРЫТИЕ» (С125)
 */

const ВЕРСИЯ_КАНОНА = 'hir-core/0.1';
const ГРАММ_МИН_ПО_УМОЛЧАНИЮ = 2;
const ГРАММ_МАКС_ПО_УМОЛЧАНИЮ = 4;
const АЛЬТЕРНАТИВ_МАКСИМУМ = 3;

/* ── честные русские отказы ─────────────────────────────────────────────── */

function честныйТип(значение) {
  if (значение === null) return 'null';
  if (Array.isArray(значение)) return 'массив';
  const вид = typeof значение;
  if (вид === 'string') return 'строка';
  if (вид === 'number') return 'число';
  if (вид === 'boolean') return 'логическое значение';
  if (вид === 'undefined') return 'undefined';
  if (вид === 'function') return 'функция';
  if (вид === 'symbol') return 'символ';
  return 'объект';
}

/* ── нормализация и признаки ────────────────────────────────────────────── */

// Нормализация фразы: нижний регистр, ё→е, любые пробельные последовательности
// в один пробел, обрезка краёв. Детерминирована.
function нормализовать(текст) {
  return текст.toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();
}

// Сравнение строк по возрастанию кодовых точек (не кодовых единиц UTF-16) —
// детерминированный тай-брейк дома.
function сравнитьПоКодовымТочкам(левая, правая) {
  if (левая === правая) return 0;
  const нитиЛевой = Array.from(левая);
  const нитиПравой = Array.from(правая);
  const общаяДлина = Math.min(нитиЛевой.length, нитиПравой.length);
  for (let шаг = 0; шаг < общаяДлина; шаг += 1) {
    const точкаЛевой = нитиЛевой[шаг].codePointAt(0);
    const точкаПравой = нитиПравой[шаг].codePointAt(0);
    if (точкаЛевой !== точкаПравой) return точкаЛевой < точкаПравой ? -1 : 1;
  }
  if (нитиЛевой.length !== нитиПравой.length) {
    return нитиЛевой.length < нитиПравой.length ? -1 : 1;
  }
  return 0;
}

// Частоты символьных n-грамм длины минимум..максимум по строке как есть
// (пробелы — тоже символы): «включи тишину» даёт «вк»,«кл»,… и «и т»,« ти»…
function частотыNграмм(строка, минимум, максимум) {
  const частоты = new Map();
  for (let длина = минимум; длина <= максимум; длина += 1) {
    for (let старт = 0; старт + длина <= строка.length; старт += 1) {
      const грамма = строка.slice(старт, старт + длина);
      частоты.set(грамма, (частоты.get(грамма) || 0) + 1);
    }
  }
  return частоты;
}

// L2-нормализация вектора (карта «грамма → частота»). Нулевой вектор остаётся пустым.
function нормализованныйВекторL2(частоты) {
  let сумма = 0;
  for (const частота of частоты.values()) сумма += частота * частота;
  const норма = Math.sqrt(сумма);
  if (!(норма > 0)) return new Map();
  const вектор = new Map();
  for (const [грамма, частота] of частоты) вектор.set(грамма, частота / норма);
  return вектор;
}

// Скалярное произведение разреженных векторов (обход по меньшей карте — порядок
// суммирования фиксирован, детерминизм).
function скалярноеПроизведение(левый, правый) {
  let сумма = 0;
  const меньший = левый.size <= правый.size ? левый : правый;
  const больший = меньший === левый ? правый : левый;
  for (const [грамма, вес] of меньший) {
    const чужойВес = больший.get(грамма);
    if (чужойВес !== undefined) сумма += вес * чужойВес;
  }
  return сумма;
}

/* ── проверка границ n-грамм ────────────────────────────────────────────── */

function проверитьГраницу(значение, умолчание, имя) {
  if (значение === undefined) return умолчание;
  if (typeof значение !== 'number') {
    throw new TypeError(имя + ' должен быть числом, а пришло: ' + честныйТип(значение));
  }
  if (!Number.isInteger(значение) || значение < 1) {
    throw new RangeError(имя + ' должен быть целым числом не меньше 1, а пришло: ' + String(значение));
  }
  return значение;
}

