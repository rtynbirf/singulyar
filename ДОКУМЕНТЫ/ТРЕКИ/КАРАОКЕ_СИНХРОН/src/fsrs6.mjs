// fsrs6.mjs — КАРАОКЕ_СИНХРОН, линия КС4 «Тренажёры + FSRS-6 в КОНТУР (подготовка Ж4)».
//
// ЧТО ЭТО: детерминированный планировщик интервальных повторений FSRS-6 — канон для
// трёх тренажёров КС4 (диктант, пропуски, эхо-план). Алгоритм FSRS — ОТКРЫТЫЙ
// (open-spaced-repetition, лицензия MIT): свободен, платного ничего.
//
// ИСТОЧНИК ФОРМУЛ: публичное описание алгоритма FSRS-4.5 → FSRS-6
// (open-spaced-repetition/fsrs4anki wiki «The Algorithm»; py-fsrs / ts-fsrs — MIT).
// Ядро из 17 весов w1..w17 (в коде — индексы 0..16) от FSRS-4.5 к FSRS-6 не менялось;
// FSRS-6 поверх ядра добавляет: подгоняемое затухание кривой (умолчание −0.5 — вшито
// здесь) и веса коротких (межсессионных) интервалов w18..w21 — их в каноне НЕТ (см. границы).
//
// ФОРМУЛЫ (все честные, без упрощения до SM-2):
//   удерживаемость      R(t,S) = (1 + ФАКТОР·t/S)^ЗАТУХАНИЕ
//   интервал            I(r,S) = S/ФАКТОР·(r^(1/ЗАТУХАНИЕ) − 1)          — при r=0.9: I = S
//   старт. стабильность S0(G)  = w[G−1]
//   старт. затруднён.   D0(G)  = clamp(w5 − (G−3)·w6, 1, 10)
//   затруднённость      D' = clamp(D − w6·(G−3)·(10−D)/9, 1, 10)         — линейное демпфирование (уточнение FSRS-5/6; в FSRS-4.5 его не было)
//                       D''= clamp(w7·D0(4) + (1−w7)·D', 1, 10)          — возврат к среднему (mean reversion)
//   успех (G≥2)         S' = S·(1 + e^w8·(11−D)·S^(−w9)·(e^(w10·(1−R))−1)·штрафТрудно·бонусЛегко)
//                       штрафТрудно = w16 при G=2, иначе 1;  бонусЛегко = w17 при G=4, иначе 1
//   промах (G=1)        S' = w12·D^(−w13)·((S+1)^w14 − 1)·e^(w15·(1−R))
//
// ЧЕСТНЫЕ ГРАНИЦЫ (закон Д2/10_SOURCE_TRUST):
//   1) Числа весов — публичные значения по умолчанию; КАЛИБРОВАННЫЕ веса (подгонка под
//      ученика/фонд песен) загружаются через владельческий люк параметров — люкВесов().
//      Канон ничего не обучает, не хранит калибровок и не гарантирует, что зашитые
//      константы — последняя калибровка open-spaced-repetition. То же про затухание:
//      в полной FSRS-6 оно подгоняется — канон честно фиксирует умолчание −0.5.
//   2) Межсессионный (тот же день) рост стабильности FSRS-5/6 (веса коротких интервалов)
//      не включён: при нулевом приращении времени успешная оценка консервативно не растит
//      стабильность (S'=S выходит из формулы при R=1), а промах честно режет S.
//   3) «Ступени обучения» в минутах (кротовые норы Anki: снова через 1/10 мин) —
//      ответственность тренажёра/хранения: канон отдаёт честный интервал FSRS.
//   4) Время ВСЕГДА аргументом (момент в миллисекундах передаёт вызывающий); часов,
//      случайности и сети в модуле нет — детерминизм полнейший, повтор вызова байт-в-байт.
//   5) Хранилище вне канона: только схема ключей ключХранилища() —
//      «контур.тренажёры.<тренажёр>.<ид>», отдельно от kv.контур (требование линии КС4).
//   6) Карточка иммутабельна: оценить() возвращает новый объект, вход не мутируется.

export const СХЕМА = 'fsrs6/0.1';

// --- оценки (панель КС4: «1 Забыл / 2 Трудно / 3 Норм / 4 Легко») ---
export const ОЦЕНКИ = Object.freeze({ опять: 1, трудно: 2, хорошо: 3, легко: 4 });
export const СОСТОЯНИЯ = Object.freeze(['нова', 'учится', 'повтор', 'догоняет']);

// --- веса: ядро FSRS из 17 весов (индексы 0..16; в записи ТЗ — w1..w17) ---
// Публичные значения по умолчанию (open-spaced-repetition); калиброванные — через люкВесов().
export const ВЕСА_ПО_УМОЛЧАНИЮ = Object.freeze([
  0.4872,  // w1  — стартовая стабильность после «опять»
  1.4003,  // w2  — … после «трудно»
  3.7145,  // w3  — … после «хорошо»
  13.8206, // w4  — … после «легко»
  5.1618,  // w5  — стартовая затруднённость (база)
  1.2298,  // w6  — шаг затруднённости за градацию
  0.8975,  // w7  — наклон обновления затруднённости
  0.031,   // w8  — вес возврата к среднему (mean reversion к D0(4))
  1.6474,  // w9  — коэффициент роста стабильности при успехе
  0.1367,  // w10 — затухание роста по стабильности
  1.0461,  // w11 — влияние ретривабилити на рост
  2.1072,  // w12 — пост-промах: база
  0.0793,  // w13 — пост-промах: степень затруднённости
  0.3246,  // w14 — пост-промах: степень стабильности
  1.587,   // w15 — пост-промах: влияние ретривабилити
  0.2272,  // w16 — штраф «трудно»
  2.8755,  // w17 — бонус «легко»
]);

// --- кривая удерживаемости FSRS-5/6: R(t,S) = (1 + ФАКТОР·t/S)^ЗАТУХАНИЕ ---
export const ЗАТУХАНИЕ = -0.5; // FSRS-6: подгоняемый параметр, умолчание −0.5 (калибровка — через люк)
export const ФАКТОР = 19 / 81; // 0.9^(1/ЗАТУХАНИЕ) − 1: при t = S удерживаемость ровно 0.9
export const ЖЕЛАЕМАЯ_УДЕРЖИВАЕМОСТЬ_ПО_УМОЛЧАНИЮ = 0.9;
export const МИН_ЖЕЛАЕМАЯ_УДЕРЖИВАЕМОСТЬ = 0.7;  // честный рекомендованный диапазон FSRS
export const МАКС_ЖЕЛАЕМАЯ_УДЕРЖИВАЕМОСТЬ = 0.98;

export const МС_В_СУТ = 86400000;
export const МИН_СТАБИЛЬНОСТЬ_СУТ = 0.01;   // ~14.4 минуты — пол не даёт интервалу умереть в ноль
export const МАКС_СТАБИЛЬНОСТЬ_СУТ = 36500; // кэп 100 лет (как в FSRS) — интервал не растёт бесконечно

export const ТРЕНАЖЁРЫ = Object.freeze(['диктант', 'пропуски', 'эхо-план']);

