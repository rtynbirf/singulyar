/**
 * Новая карточка. момент — миллисекунды от вызывающего (часов внутри нет).
 * @returns {Readonly<object>} замороженная карточка состояния «нова»
 */
export function создатьКарточку(ид, момент) {
  const метка = typeof ид === 'string' ? ид : String(ид);
  if (!метка) throw new Error('создатьКарточку: ид — непустая строка');
  проверитьМомент(момент, 'создатьКарточку');
  return Object.freeze({
    схема: СХЕМА,
    ид: метка,
    состояние: 'нова',
    стабильностьСут: 0,
    затруднённость: 0, // 0 = ещё не задана (нова); после первой оценки — 1..10
    моментПоследнего: момент,
    повторов: 0,
    промахов: 0,
    интервалСекунды: null, // после первой оценки — честный интервал FSRS в секундах
  });
}

/** Переход состояния (нова/учится/повтор/догоняет) по оценке 1..4. */
function переходСостояния(было, G) {
  if (было === 'нова' || было === 'учится') return G >= 3 ? 'повтор' : 'учится';
  if (было === 'повтор') return G === 1 ? 'догоняет' : 'повтор';
  return G >= 3 ? 'повтор' : 'догоняет'; // «догоняет» (переучивание)
}

/**
 * Оценить карточку — иммутабельно: вход не мутируется, возвращается новая карточка.
 * @param {object} карточка   результат создатьКарточку/оценить (схема fsrs6/0.1)
 * @param {string|number} оценка  «опять»/«трудно»/«хорошо»/«легко» или 1..4
 * @param {number} момент     миллисекунды оценки (время всегда аргументом)
 * @param {object} [опции]    { веса?: 17 чисел (люк), желаемаяУдерживаемость? }
 * @returns {{карточка: Readonly<object>, интервалСекунды: number}}
 */
export function оценить(карточка, оценка, момент, опции = {}) {
  if (!карточка || карточка.схема !== СХЕМА) throw new Error('оценить: карточка чужой схемы — честный отказ');
  const G = оценкаВЧисло(оценка);
  const сейчас = проверитьМомент(момент, 'оценить');
  if (карточка.моментПоследнего !== null && сейчас < карточка.моментПоследнего) {
    throw new Error('оценить: время не течёт назад (момент раньше последнего показа)');
  }
  const веса = люкВесов(опции.веса ?? ВЕСА_ПО_УМОЛЧАНИЮ);
  const r = желаемаяУдерживаемостьИзОпций(опции);

  let стабильность;
  let затруднённость;
  if (карточка.состояние === 'нова') {
    // первый показ: стартовые формулы FSRS, ретривабилити не участвует
    стабильность = веса[G - 1];                                        // S0(G) = w[G−1]
    затруднённость = зажать(веса[4] - (G - 3) * веса[5], 1, 10);       // D0(G)
  } else {
    const S = карточка.стабильностьСут;
    const D = карточка.затруднённость;
    const прошлооСут = Math.max(0, (сейчас - карточка.моментПоследнего) / МС_В_СУТ);
    const R = удерживаемость(прошлооСут, S);
    if (G === ОЦЕНКИ.опять) {
      // промах: пост-промах формула FSRS (ядро w12..w15)
      стабильность = веса[11] * Math.pow(D, -веса[12])
        * (Math.pow(S + 1, веса[13]) - 1)
        * Math.exp(веса[14] * (1 - R));
    } else {
      // успех: формула стабильности после успеха (ядро w9..w11 + штраф/бонус w16/w17)
      const штрафТрудно = G === ОЦЕНКИ.трудно ? веса[15] : 1;
      const бонусЛегко = G === ОЦЕНКИ.легко ? веса[16] : 1;
      стабильность = S * (1 + Math.exp(веса[8]) * (11 - D) * Math.pow(S, -веса[9])
        * (Math.exp(веса[10] * (1 - R)) - 1) * штрафТрудно * бонусЛегко);
    }
    // затруднённость: линейное демпфирование (уточнение FSRS-5/6) + возврат к среднему к D0(4)
    const дельтаD = -веса[6] * (G - 3);
    const демпфированная = зажать(D + дельтаD * (10 - D) / 9, 1, 10);
    затруднённость = зажать(веса[7] * (веса[4] - (ОЦЕНКИ.легко - 3) * веса[5]) + (1 - веса[7]) * демпфированная, 1, 10);
  }

  стабильность = зажать(стабильность, МИН_СТАБИЛЬНОСТЬ_СУТ, МАКС_СТАБИЛЬНОСТЬ_СУТ);
  const интервалСут = интервалПоСтабильности(стабильность, r);
  const интервалСекунды = интервалСут * 86400;

  const новая = {
    схема: СХЕМА,
    ид: карточка.ид,
    состояние: переходСостояния(карточка.состояние, G),
    стабильностьСут: стабильность,
    затруднённость,
    моментПоследнего: сейчас,
    повторов: карточка.повторов + 1,
    промахов: карточка.промахов + (G === ОЦЕНКИ.опять ? 1 : 0),
    интервалСекунды,
  };
  return { карточка: Object.freeze(новая), интервалСекунды };
}

/**
 * Очередь подтверждений: даты показов, сортированные по времени (ничья — по ид,
 * детерминизм). Новые карточки — срок «сейчас»; остальные — последний показ + интервал.
 * @param {Array<object>} карточки
 * @param {number} сейчас  миллисекунды (время всегда аргументом)
 * @returns {Array<{ид:string, момент:number, состояние:string, просроченоСек:number}>}
 */
export function планПодтверждений(карточки, сейчас) {
  if (!Array.isArray(карточки)) throw new Error('планПодтверждений: карточки — массив');
  проверитьМомент(сейчас, 'планПодтверждений');
  const очередь = [];
  for (const к of карточки) {
    if (!к || к.схема !== СХЕМА) throw new Error('планПодтверждений: карточка чужой схемы — честный отказ');
    const срокМс = к.состояние === 'нова'
      ? Math.max(сейчас, к.моментПоследнего)
      : к.моментПоследнего + (к.интервалСекунды ?? 0) * 1000;
    очередь.push({
      ид: к.ид,
      момент: срокМс,
      состояние: к.состояние,
      просроченоСек: Math.max(0, (сейчас - срокМс) / 1000),
    });
  }
  очередь.sort((а, б) => а.момент - б.момент || (а.ид < б.ид ? -1 : а.ид > б.ид ? 1 : 0));
  return очередь;
}

