/** Зажим числа в диапазон (концы включены). */
export function зажать(х, мин, макс) {
  return Math.min(макс, Math.max(мин, х));
}

/**
 * Владельческий люк параметров: валидация и заморозка калиброванных весов.
 * Принимает ровно 17 конечных чисел (w1..w17); отдельные диапазоны весов НЕ
 * проверяет — калибровка чужая, канон честно считает по формулам что дали.
 * @returns {ReadonlyArray<number>} замороженная КОПИЯ (вход не алиасится)
 */
export function люкВесов(веса) {
  if (!Array.isArray(веса) || веса.length !== 17) {
    throw new Error('люкВесов: нужно ровно 17 весов (w1..w17), получено ' + (Array.isArray(веса) ? веса.length : typeof веса));
  }
  for (const x of веса) {
    if (typeof x !== 'number' || !Number.isFinite(x)) throw new Error('люкВесов: все веса — конечные числа');
  }
  return Object.freeze([...веса]);
}

/** Удерживаемость (retrievability) через прошлооСут по кривой FSRS. t≤0 → 1 (только что видел). */
export function удерживаемость(прошлооСут, стабильностьСут) {
  if (!Number.isFinite(прошлооСут) || прошлооСут < 0) throw new Error('удерживаемость: прошлооСут — конечное число ≥ 0');
  if (!Number.isFinite(стабильностьСут) || стабильностьСут <= 0) throw new Error('удерживаемость: стабильностьСут — конечное число > 0');
  if (прошлооСут === 0) return 1;
  return Math.pow(1 + ФАКТОР * прошлооСут / стабильностьСут, ЗАТУХАНИЕ);
}

/** Интервал в СУТКАХ для желаемой удерживаемости (при r=0.9 интервал = стабильность). */
export function интервалПоСтабильности(стабильностьСут, желаемаяУдерживаемость = ЖЕЛАЕМАЯ_УДЕРЖИВАЕМОСТЬ_ПО_УМОЛЧАНИЮ) {
  const r = желаемаяУдерживаемостьИзОпций({ желаемаяУдерживаемость });
  return зажать(стабильностьСут / ФАКТОР * (Math.pow(r, 1 / ЗАТУХАНИЕ) - 1), 0, МАКС_СТАБИЛЬНОСТЬ_СУТ);
}

function желаемаяУдерживаемостьИзОпций(опции) {
  const сырая = опции && опции.желаемаяУдерживаемость !== undefined
    ? опции.желаемаяУдерживаемость
    : ЖЕЛАЕМАЯ_УДЕРЖИВАЕМОСТЬ_ПО_УМОЛЧАНИЮ;
  if (typeof сырая !== 'number' || !Number.isFinite(сырая) || сырая <= 0 || сырая >= 1) {
    throw new Error('желаемаяУдерживаемость — конечное число строго между 0 и 1');
  }
  // вне рекомендованного диапазона FSRS — зажимаем (не бросаем): честная логика панели
  return зажать(сырая, МИН_ЖЕЛАЕМАЯ_УДЕРЖИВАЕМОСТЬ, МАКС_ЖЕЛАЕМАЯ_УДЕРЖИВАЕМОСТЬ);
}

function оценкаВЧисло(оценка) {
  if (typeof оценка === 'string' && оценка in ОЦЕНКИ) return ОЦЕНКИ[оценка];
  if (typeof оценка === 'number' && Number.isInteger(оценка) && оценка >= 1 && оценка <= 4) return оценка;
  throw new Error('оценка — «опять»/«трудно»/«хорошо»/«легко» (или 1..4), получено: ' + String(оценка));
}

function проверитьМомент(момент, где) {
  if (typeof момент !== 'number' || !Number.isFinite(момент)) {
    throw new Error(где + ': момент — конечное число в миллисекундах (время всегда аргументом)');
  }
  return момент;
}

