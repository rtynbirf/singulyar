/**
 * Схема ключей тренажёров: «контур.тренажёры.<тренажёр>.<ид>».
 * Точка — разделитель схемы, поэтому в тренажёре/ид точка и пробел запрещены.
 */
export function ключХранилища(тренажёр, ид) {
  if (typeof тренажёр !== 'string' || !тренажёр) throw new Error('ключХранилища: тренажёр — непустая строка');
  if (typeof ид !== 'string' || !ид) throw new Error('ключХранилища: ид — непустая строка');
  if (/[.\s]/.test(тренажёр) || /[.\s]/.test(ид)) {
    throw new Error('ключХранилища: тренажёр/ид не должны содержать точку или пробел (схема «контур.тренажёры.<тренажёр>.<ид>»)');
  }
  return `контур.тренажёры.${тренажёр}.${ид}`;
}

// ---------------------------------------------------------------------------
// Три тренажёра КС4 — фабрики поверх карточек.
// Маппинг события тренажёра в оценку FSRS — детерминированный, время не читается:
// «быстро» решает тренажёр по СВОЕМУ аргументу-времени и ставит флаг; канон флагам верит.
// Нераспознанное событие → null → оценить() бросает честный отказ (без выдуманных оценок).
// ---------------------------------------------------------------------------

/** Диктант (Левенштейн: заменено/пропущено/лишнее). Ошибка → опять; подсказка → трудно; чисто быстро → легко; чисто → хорошо. */
export function оценкаДиктанта(событие) {
  if (!событие || typeof событие !== 'object') return null;
  const счёт = (x) => (typeof x === 'number' && Number.isFinite(x) && x > 0 ? x : 0);
  const правок = счёт(событие.заменено) + счёт(событие.пропущено) + счёт(событие.лишнее);
  if (событие.верно === false || правок > 0) return 'опять';
  if (событие.сПодсказкой) return 'трудно';
  if (событие.быстро) return 'легко';
  if (событие.верно === true) return 'хорошо';
  return null;
}

/** Пропуски (каждое k / отмеченные / случайные с зерном — выбор за тренажёром). ошибка → опять; … */
export function оценкаПропусков(событие) {
  if (!событие || typeof событие !== 'object') return null;
  const ошибок = typeof событие.ошибок === 'number' && Number.isFinite(событие.ошибок) && событие.ошибок > 0 ? событие.ошибок : 0;
  if (событие.верно === false || ошибок > 0) return 'опять';
  if (событие.сПодсказкой) return 'трудно';
  if (событие.быстро) return 'легко';
  if (событие.верно === true) return 'хорошо';
  return null;
}

/** Эхо-план (повтор за голосом). не совпало → опять; подсказка → трудно; чисто быстро → легко; чисто → хорошо. */
export function оценкаЭхоПлана(событие) {
  if (!событие || typeof событие !== 'object') return null;
  if (событие.совпало === false) return 'опять';
  if (событие.сПодсказкой) return 'трудно';
  if (событие.быстро) return 'легко';
  if (событие.совпало === true) return 'хорошо';
  return null;
}

function фабрикаТренажёра(тип, оценкаИзСобытия) {
  return Object.freeze({
    тип,
    схема: СХЕМА,
    ключХранилища: (ид) => ключХранилища(тип, ид),
    оценкаИзСобытия,
    создатьКарточку: (ид, момент) => создатьКарточку(ид, момент),
    оценить: (карточка, событие, момент, опции) => {
      const оценка = оценкаИзСобытия(событие);
      if (оценка === null) {
        throw new Error(`тренажёр «${тип}»: событие не распознано — честный отказ (нет ни ошибки, ни явного успеха)`);
      }
      return оценить(карточка, оценка, момент, опции);
    },
  });
}

