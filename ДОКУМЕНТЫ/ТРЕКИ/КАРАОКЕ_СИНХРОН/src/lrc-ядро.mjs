const РЕ_МЕТКА = /\[(\d{1,3}):(\d{1,2})(?:[.:](\d{1,3}))?\]/g;
const РЕ_СЛОВО = /<(\d{1,3}):(\d{1,2})(?:[.:](\d{1,3}))?>/g;
const РЕ_ТЕГ = /^\[([a-zA-Zа-яА-ЯёЁ#]{1,10}):([^\]]*)\]$/;

/* ── метка mm:ss.xx → мс (дробная часть 1–3 цифры: .5 == 500 мс) ─────────── */
function меткаВМиллисекунды(минуты, секунды, дробь) {
  const м = parseInt(минуты, 10);
  const с = parseInt(секунды, 10);
  if (с > 59) {
    throw new RangeError('метка ' + минуты + ':' + секунды + ' — секунд больше 59: это не mm:ss');
  }
  let миллисекунды = 0;
  if (дробь !== undefined) {
    const длина = дробь.length;
    const значение = parseInt(дробь, 10);
    /* .5 → 500 мс, .05 → 50 мс, .500 → 500 мс (позиционная дробь) */
    if (длина === 1) миллисекунды = значение * 100;
    else if (длина === 2) миллисекунды = значение * 10;
    else миллисекунды = значение;
  }
  return м * 60000 + с * 1000 + миллисекунды;
}

/* ── мс → [mm:ss.xxx] для обратной сборки ────────────────────────────────── */
function миллисекундыВМетку(времяМс) {
  if (typeof времяМс !== 'number' || Number.isNaN(времяМс) || !Number.isFinite(времяМс) || времяМс < 0 || !Number.isInteger(времяМс)) {
    throw new RangeError('времяМс должно быть целым неотрицательным числом');
  }
  const м = Math.floor(времяМс / 60000);
  const с = Math.floor((времяМс % 60000) / 1000);
  const мс = времяМс % 1000;
  const пад = function (число, ширина) {
    let стр = String(число);
    while (стр.length < ширина) стр = '0' + стр;
    return стр;
  };
  return '[' + пад(м, 2) + ':' + пад(с, 2) + '.' + пад(мс, 3) + ']';
}

/* ── разбор LRC/ELRC ─────────────────────────────────────────────────────── */
export function разобрать(текст, опции = {}) {
  if (typeof текст !== 'string') {
    throw new TypeError('разобрать принимает только строку LRC-текста');
  }
  if (опции === null || typeof опции !== 'object' || Array.isArray(опции)) {
    throw new TypeError('опции должны быть объектом');
  }

  /* offset-тег применяется ко всем меткам; ищем его ДО разбора строк */
  let офсет = 0;
  const теги = {};
  const сырыеСтроки = текст.split(/\r\n|\n|\r/);
  for (let индекс = 0; индекс < сырыеСтроки.length; индекс += 1) {
    const обрезанная = сырыеСтроки[индекс].trim();
    const совпадение = обрезанная.match(РЕ_ТЕГ);
    if (совпадение) {
      const ключ = совпадение[1];
      const значение = совпадение[2].trim();
      if (Object.prototype.hasOwnProperty.call(теги, ключ) && ключ === 'offset') {
        throw new RangeError('тег offset встречается дважды: какая из двух поправок настоящая?');
      }
      if (ключ === 'offset') {
        if (!/^[+-]?\d+$/.test(значение)) {
          throw new RangeError('тег offset не число миллисекунд: «' + значение + '»');
        }
        офсет = parseInt(значение, 10);
      }
      if (!Object.prototype.hasOwnProperty.call(теги, ключ)) теги[ключ] = значение;
    }
  }

  const строки = [];
  const слова = [];
  let виделСлова = false;
  let виделМетку = false;

  for (let индекс = 0; индекс < сырыеСтроки.length; индекс += 1) {
    const сырая = сырыеСтроки[индекс];
    const обрезанная = сырая.trim();
    if (обрезанная === '') continue;
    const тегСовпадение = обрезанная.match(РЕ_ТЕГ);
    if (тегСовпадение && тегСовпадение[0] === обрезанная) {
      continue; /* чистая ID-строка тега — не текст песни */
    }
    РЕ_МЕТКА.lastIndex = 0;
    const метки = [];
    let совпадение;
    let последняяПозиция = -1;
    while ((совпадение = РЕ_МЕТКА.exec(сырая)) !== null) {
      if (последняяПозиция === -1) {
        if (совпадение.index !== сырая.search(/\S/)) break; /* метки обязаны вести строку */
      } else if (совпадение.index !== последняяПозиция) {
        break; /* зазор между метками — дальше текст */
      }
      метки.push(меткаВМиллисекунды(совпадение[1], совпадение[2], совпадение[3]));
      последняяПозиция = РЕ_МЕТКА.lastIndex;
    }
    if (метки.length === 0) continue; /* строка без ведущих меток — честно мимо */
    виделМетку = true;

    const текстСтроки = сырая.slice(последняяПозиция);

    /* enhanced-слова <mm:ss.xx>слово */
    РЕ_СЛОВО.lastIndex = 0;
    let словоСовпадение;
    let нашлаСлова = false;
    while ((словоСовпадение = РЕ_СЛОВО.exec(текстСтроки)) !== null) {
      нашлаСлова = true;
      const абсолют = меткаВМиллисекунды(словоСовпадение[1], словоСовпадение[2], словоСовпадение[3]);
      const от = РЕ_СЛОВО.lastIndex;
      const далее = текстСтроки.indexOf('<', от);
      const кусок = (далее === -1 ? текстСтроки.slice(от) : текстСтроки.slice(от, далее)).trim();
      if (кусок.length > 0) {
        слова.push({ времяМс: абсолют + офсет, слово: кусок });
      }
    }
    if (нашлаСлова) виделСлова = true;

    const чистыйТекст = текстСтроки.replace(РЕ_СЛОВО, '').trim();
    for (let м = 0; м < метки.length; м += 1) {
      строки.push({ времяМс: метки[м] + офсет, текст: чистыйТекст });
    }
  }

  if (!виделМетку) {
    throw new RangeError('меток времени не найдено: это не LRC');
  }

  /* стабильная сортировка по времени (компаратор с равенством → 0
     сохраняет исходный порядок равных — V8 sort стабилен) */
  строки.sort(function (левое, правое) { return левое.времяМс - правое.времяМс; });
  if (виделСлова) слова.sort(function (левое, правое) { return левое.времяМс - правое.времяМс; });

  return {
    строки: строки,
    слова: виделСлова ? слова : null,
    теги: теги,
    версия: 'lrc-ядро/0.1',
  };
}

/* ── обратная сборка LRC из массива строк ────────────────────────────────── */
export function собратьLRC(строки) {
  if (!Array.isArray(строки)) {
    throw new TypeError('собратьLRC принимает массив строк { времяМс, текст }');
  }
  let вывод = '';
  for (let индекс = 0; индекс < строки.length; индекс += 1) {
    const запись = строки[индекс];
    if (запись === null || typeof запись !== 'object' || Array.isArray(запись)) {
      throw new TypeError('строка ' + индекс + ' должна быть объектом { времяМс, текст }');
    }
    вывод += миллисекундыВМетку(запись.времяМс) + String(запись.текст === undefined || запись.текст === null ? '' : запись.текст) + '\n';
  }
  return вывод;
}

export function версия() {
  return 'lrc-ядро/0.1';
}
