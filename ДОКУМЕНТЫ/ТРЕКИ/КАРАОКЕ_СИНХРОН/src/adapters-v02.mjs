// «Универсальный прототип v0.1 — 6 контрактов адаптеров — основа адаптеров Ж4».
//
// ИСТОЧНИК 1-В-1 — прототип Singulyar_Universal_Karaoke_Prototype_v0_1:
//   docs/TECHNICAL_SPEC_RU.md §6 «Модульные интерфейсы будущей версии» — шесть
//   контрактов: ASRAdapter, TranslationAdapter, SingingAlignmentAdapter,
//   VocalGenerationAdapter, QualityGate, TransportAdapter. Названия контрактов
//   английские — сохранены как идентификаторы канона; ошибки и комментарии —
//   по-русски (правило дома).
//   docs/ARCHITECTURE_RU.md §4 — «каждый модуль должен иметь интерфейс, версию,
//   языковую пару, входной и выходной формат, тайм-аут, оценку уверенности и
//   диагностические метрики».
//   docs/RESEARCH_NOTES_RU.md §5 — критерий инженерной честности (5 запретов).
//   FR-16 (переводчик заменяется без переписывания комнаты и UI), NFR-07 (у
//   каждого модуля версия и измеряемые показатели), NFR-08 (реестр возможностей).
//
// ЧТО ЭТО: канон ФОРМЫ. Для каждого из шести контрактов — фабрика валидатора,
// проверяющая объект-адаптер (обязательные поля, типы, подписи функций) и
// возвращающая вердикт {годен, причины[]}. Это фундамент адаптеров Ж4: комната
// и UI (FR-16) держатся за форму, а не за реализацию.
//
// КОНТРАКТ КАНОНА:
//   создатьВалидаторКонтракта(имяКонтракта) → валидатор(адаптер) → {годен, причины[]}
//   плюс шесть фабрик по контракту: создатьВалидаторАср, создатьВалидаторПеревода,
//   создатьВалидаторВыравнивания, создатьВалидаторВокальнойГенерации,
//   создатьВалидаторВоротКачества, создатьВалидаторТранспорта.
//   - дверь никогда не бросает: валидатор на ЛЮБОЙ вход возвращает честный
//     вердикт с перечнем несоответствий по-русски; причины собираются ВСЕ (не
//     первая попавшаяся), порядок проверок фиксирован;
//   - бросает только фабрика — и только на структурную ошибку вызова (имя
//     контракта не строка либо неизвестное имя): честный TypeError, как в доме;
//   - ноль мутаций входа: валидатор только читает (тест ставит замороженный
//     объект — строгий режим не прощает записей);
//   - детерминизм: один вход → один вердикт байт-в-байт (0 сети, 0 часов,
//     0 случайности); вердикт заморожен — чужой код не перепишет причины;
//   - валидатор несёт метку .контракт — чью форму он проверяет.
//
// 5 ЗАПРЕТОВ ЧЕСТНОСТИ (RESEARCH_NOTES_RU.md §5) и как канон их держит:
//   1) не называть TTS переводом певческого голоса — канон не имеет голосовых
//      обещаний: VocalGenerationAdapter проверяется как ФОРМА, реальная
//      генерация остаётся за испытаниями (дорожная карта, ворота G4);
//   2) не считать подстановку фраз из словаря машинным переводом —
//      TranslationAdapter валидируется как форма; демо-словарь прототипа
//      (index.html: «ДЕМО: для этой фразы нет записи…») канон не благословляет;
//   3) не считать передачу WebRTC подтверждением работы языкового перевода —
//      TransportAdapter проверяется как транспорт дорожек, ни слова о языке;
//   4) не утверждать сохранение личности голоса без субъективной и объективной
//      проверки — форма не доказывает тембр; согласие на чужой голос (ТЗ §6:
//      «Не использовать голос другого человека без отдельного явного согласия»)
//      — обязанность вызова, не формы;
//   5) не объявлять поддержку языка только потому, что модель принимает его
//      код — канон НЕ проверяет языки адаптера и не выдаёт «годен» за
//      декларацию покрытия (NFR-08: реестр возможностей — отдельная система).
//
// Честные границы (что в доках описано неполно — реализовано описанное, остальное честно):
//   - QualityGate и TransportAdapter: ТЗ §6 не описывает точную подпись вызова —
//     реализовано описанное: «принимает результат на проверку» / «принимает
//     дорожку» (минимум 1 аргумент); более строгая подпись — дело v0.3;
//   - SingingAlignmentAdapter: вход «текст и/или MIDI/ноты» — «и/или» даёт
//     минимум 2 аргумента (вокал + один из), а не 3;
//   - TranslationAdapter: контекст песни «если разрешено» — 4-й аргумент
//     необязателен по ТЗ; минимум — 3 (текст, исходный язык, целевой язык);
//   - «языковая пара» и «оценка уверенности» (ARCHITECTURE §4) не закреплены в
//     ТЗ как поля объекта-адаптера (NFR-08 относит пары к реестру возможностей,
//     уверенность — к результатам вызова): в форму v0.2 они не входят;
//   - подпись проверяется по Function.length: rest-параметр (...) даёт length 0,
//     параметры со значениями по умолчанию считаются необязательными — такой
//     адаптер честно не проходит (канон требует явных обязательных аргументов);
//   - валидатор проверяет ФОРМУ, не поведение: качество, лицензии, задержки,
//     согласие — за испытаниями и вызовом (TEST_PLAN_RU.md:
//     CLAIM → CODE → OFFICIAL SPEC → TEST → VERDICT).
//
// Экспорт: только ESM; импортов ноль — канон чист, даже базовых зависимостей нет.

