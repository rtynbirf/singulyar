export const ИМЕНА_КОНТРАКТОВ = Object.freeze(Object.keys(КОНТРАКТЫ));

// ---------------------------------------------------------------------------
// ЧЕСТНОЕ ОПИСАНИЕ ЗНАЧЕНИЯ для причин. Без JSON.stringify: циркули и функции
// делают его бросающим/тяжёлым; только тип и краткая детерминированная форма.
// Никогда не бросает.
// ---------------------------------------------------------------------------
function описать(значение) {
  if (значение === null) return 'null';
  const т = typeof значение;
  if (т === 'undefined') return 'undefined';
  if (т === 'string') return `строка(${JSON.stringify(значение)})`;
  if (т === 'number') return Number.isNaN(значение) ? 'число(NaN)' : `число(${String(значение)})`;
  if (т === 'boolean' || т === 'bigint') return `${т}(${String(значение)})`;
  if (т === 'symbol') return 'symbol';
  if (т === 'function') return `функция(${значение.name || 'безымянная'})`;
  return Array.isArray(значение) ? 'массив' : 'объект';
}

// Вердикт: замороженный конверт {годен, причины[]} — ровно два поля, порядок фиксирован.
function вердикт(причины) {
  return Object.freeze({ годен: причины.length === 0, причины: Object.freeze([...причины]) });
}

// ---------------------------------------------------------------------------
// ОБЩАЯ ФАБРИКА. имяКонтракта — точное английское имя из каталога; чужое имя —
// честный TypeError (структурная ошибка вызова, как принято в доме).
// Возвращаемый валидатор никогда не бросает и всегда отвечает вердиктом.
// ---------------------------------------------------------------------------
export function создатьВалидаторКонтракта(имяКонтракта) {
  if (typeof имяКонтракта !== 'string' || !Object.prototype.hasOwnProperty.call(КОНТРАКТЫ, имяКонтракта)) {
    throw new TypeError(
      `karaoke-adapters: создатьВалидаторКонтракта — имя контракта ожидается одним из шести (${ИМЕНА_КОНТРАКТОВ.join(', ')}), получено ${описать(имяКонтракта)}`,
    );
  }
  const спека = КОНТРАКТЫ[имяКонтракта];
  const фн = спека.функции[0];

  const валидатор = function валидаторКонтракта(адаптер) {
    const причины = [];

    // 0. Объект: не null, не массив, не примитив, не функция.
    if (адаптер === null || typeof адаптер !== 'object' || Array.isArray(адаптер)) {
      причины.push(`адаптер: ожидается объект (не null, не массив, не примитив), получено ${описать(адаптер)}`);
      return вердикт(причины);
    }

    // 1. Декларация контракта (FR-16): адаптер честно называет чью форму несёт.
    if (!('контракт' in адаптер)) {
      причины.push(`поле «контракт»: отсутствует — ожидалось «${имяКонтракта}» (адаптер обязан назвать свой контракт)`);
    } else if (адаптер.контракт !== имяКонтракта) {
      причины.push(`поле «контракт»: ожидалось «${имяКонтракта}», получено ${описать(адаптер.контракт)} — валидатор проверяет ровно одну форму`);
    }

    // 2. Версия модуля (NFR-07, ARCHITECTURE §4).
    if (!('версия' in адаптер)) {
      причины.push('поле «версия»: отсутствует — у каждого модуля есть версия (NFR-07)');
    } else if (typeof адаптер.версия !== 'string' || адаптер.версия.trim() === '') {
      причины.push(`поле «версия»: ожидается непустая строка, получено ${описать(адаптер.версия)}`);
    }

    // 3. Тайм-аут (ARCHITECTURE §4) — конечное положительное число миллисекунд.
    if (!('таймАутМс' in адаптер)) {
      причины.push('поле «таймАутМс»: отсутствует — модуль обязан объявить тайм-аут (ARCHITECTURE_RU.md §4)');
    } else if (typeof адаптер.таймАутМс !== 'number' || !Number.isFinite(адаптер.таймАутМс) || адаптер.таймАутМс <= 0) {
      причины.push(`поле «таймАутМс»: ожидается конечное положительное число (мс), получено ${описать(адаптер.таймАутМс)}`);
    }

    // 4. Диагностические метрики (ARCHITECTURE §4, NFR-07) — функция.
    if (!('метрики' in адаптер)) {
      причины.push('поле «метрики»: отсутствует — модуль обязан отдавать диагностические метрики (ARCHITECTURE_RU.md §4, NFR-07)');
    } else if (typeof адаптер.метрики !== 'function') {
      причины.push(`поле «метрики»: ожидается функция, получено ${описать(адаптер.метрики)}`);
    }

    // 5. Контрактная функция с подписью по ТЗ §6.
    if (!(фн.имя in адаптер)) {
      причины.push(`функция «${фн.имя}»: отсутствует — контракт ${имяКонтракта} требует ${фн.подпись}`);
    } else if (typeof адаптер[фн.имя] !== 'function') {
      причины.push(`функция «${фн.имя}»: ожидается функция, получено ${описать(адаптер[фн.имя])} — контракт ${имяКонтракта}: ${фн.подпись}`);
    } else if (адаптер[фн.имя].length < фн.минАргументов) {
      причины.push(`функция «${фн.имя}»: подпись не по контракту — объявлено ${адаптер[фн.имя].length} параметр(а/ов), минимум ${фн.минАргументов} (${фн.подпись})`);
    }

    return вердикт(причины);
  };

  валидатор.контракт = имяКонтракта; // метка валидатора: чью форму он проверяет
  return валидатор;
}

