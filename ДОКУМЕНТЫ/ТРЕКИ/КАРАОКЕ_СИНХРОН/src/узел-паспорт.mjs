// Дом СИНГУЛЯР, такт v11.47 «ЗАКРЫТИЕ» (С125), цех канонов.
// Двери: ·28 УЗЕЛ, ·42 КОЛОНКА, ·51 ADAPTER-OS (Hardware Integrity Agent).
// Донор-референс: ДОКУМЕНТЫ/ПОЛИМАТ_ВИТОК_2/iac_v3/generate_node_passport.py —
// семантика та же: данные узла + публичный JWK + отпечаток + подпись.
//
// ЗАКОНЫ ДОМА (нарушать нельзя — это шрамы прежних тактов):
//   • 0 сети — этот файл ничего не открывает и не слушает;
//   • 0 случайности — с честной границей: канонизация, отпечаток и порядок
//     полей детерминированы; подпись ECDSA — верифицируемая, не
//     байт-детерминированная; отпечаток и канонизация детерминированы.
//     (Случайный k внутри WebCrypto по FIPS 186-5 канон не контролирует —
//     тесты проверяют верифицируемость подписи, а не байт-равенство.)
//   • 0 часов — время (опции.создан) передаёт вызывающий; если не передал —
//     поле честно отсутствует и в паспорте, и в подписываемом каноне
//     (никакого фальшивого времени канон не подставляет);
//   • вход не мутируется;
//   • честные русские отказы (TypeError/RangeError/Error) — никаких
//     молчаливых null;
//   • криптопровайдер внедряется: аргумент/опция «крипто» (объект с subtle),
//     по умолчанию globalThis.crypto.
//
// Канон значения (детерминированная канонизация): null, логическое, конечное
// число (как JSON.stringify), строка (как JSON.stringify), массив (порядок
// сохранён), запись [object Object] (ключи отсортированы по кодовым единицам
// UTF-16 — порядок детерминирован). undefined-поля, NaN/Infinity,
// Date/Map/Set/RegExp, функции, символы и bigint — честный отказ, а не
// молчаливый пропуск или «null».
//
// Паспорт узла: { версия, узел, публичный: {kty,crv,x,y}, отпечаток,
// создан?, подпись }. Подписывается канон { узел, публичный, отпечаток,
// создан? } — те же поля, без «версии» и «подписи». JWK вычищен до ровно
// kty/crv/x/y (детерминизм: без ext/key_ops/случайных полей провайдера).
//
// Экспорт: канонизировать, отпечаток, создать, проверить,
//          base64urlИзБайтов, байтыИзBase64url, версия.
// ============================================================================

export const версия = 'узел-паспорт/0.1';

const АЛФАВИТ_B64URL = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';
const ОБРАТНЫЙ_B64URL = (() => {
  const карта = Object.create(null);
  for (let i = 0; i < АЛФАВИТ_B64URL.length; i += 1) карта[АЛФАВИТ_B64URL[i]] = i;
  return карта;
})();

/* ── честное описание значения для русских отказов ──────────────────────── */

function описать(значение) {
  if (значение === null) return 'null';
  const тип = typeof значение;
  if (тип === 'string') {
    const кусок = значение.length > 40 ? значение.slice(0, 37) + '…' : значение;
    return 'строка ' + JSON.stringify(кусок);
  }
  if (тип === 'number') return 'число (' + String(значение) + ')';
  if (тип === 'boolean') return 'логическое (' + String(значение) + ')';
  if (тип === 'undefined') return 'undefined';
  if (тип === 'function') return 'функция';
  if (тип === 'symbol') return 'символ';
  if (тип === 'bigint') return 'bigint (' + String(значение) + ')';
  if (Array.isArray(значение)) return 'массив (длина ' + значение.length + ')';
  return Object.prototype.toString.call(значение);
}

// Запись — простой объект-словарь. Object.prototype.toString работает между
// реalm'ами (vm, iframe), поэтому проверка честна и для чужих контекстов.
function являетсяЗаписью(значение) {
  return (
    typeof значение === 'object' &&
    значение !== null &&
    !Array.isArray(значение) &&
    Object.prototype.toString.call(значение) === '[object Object]'
  );
}

/* ── канонизация: детерминированный JSON ────────────────────────────────── */

function канонЗначение(значение, путь) {
  if (значение === null) return 'null';
  const тип = typeof значение;
  if (тип === 'string') return JSON.stringify(значение);
  if (тип === 'boolean') return значение ? 'true' : 'false';
  if (тип === 'number') {
    if (!Number.isFinite(значение)) {
      throw new RangeError(
        'канонизировать: по пути ' + путь + ' стоит ' + String(значение) +
        ' — NaN и Infinity не входят в JSON-канон',
      );
    }
    return JSON.stringify(значение);
  }
  if (Array.isArray(значение)) {
    const части = new Array(значение.length);
    for (let i = 0; i < значение.length; i += 1) {
      части[i] = канонЗначение(значение[i], путь + '[' + i + ']');
    }
    return '[' + части.join(',') + ']';
  }
  if (тип === 'object') {
    if (!являетсяЗаписью(значение)) {
      throw new TypeError(
        'канонизировать: по пути ' + путь + ' стоит ' + описать(значение) +
        ' — канон принимает только JSON-совместимые записи (не Date/Map/Set/RegExp)',
      );
    }
    const ключи = Object.keys(значение).sort(); // кодовые единицы UTF-16, детерминированно
    const части = [];
    for (const ключ of ключи) {
      const вложенное = значение[ключ];
      if (вложенное === undefined) {
        throw new TypeError(
          'канонизировать: по пути ' + путь + '.' + ключ + ' стоит undefined — канон не выбрасывает поля молча',
        );
      }
      части.push(JSON.stringify(ключ) + ':' + канонЗначение(вложенное, путь + '.' + ключ));
    }
    return '{' + части.join(',') + '}';
  }
  throw new TypeError(
    'канонизировать: по пути ' + путь + ' стоит ' + описать(значение) + ' — значение не JSON-совместимо',
  );
}

export function канонизировать(значение) {
  return канонЗначение(значение, '$');
}

/* ── байты, hex, base64url — свои, честные, без Node-специфики ──────────── */

function utf8Байты(строка) {
  if (typeof TextEncoder === 'function') return new TextEncoder().encode(строка);
  const байты = [];
  for (let i = 0; i < строка.length; i += 1) {
    let код = строка.charCodeAt(i);
    if (код >= 0xd800 && код <= 0xdbff && i + 1 < строка.length) {
      const младший = строка.charCodeAt(i + 1);
      if (младший >= 0xdc00 && младший <= 0xdfff) {
        код = 0x10000 + ((код - 0xd800) << 10) + (младший - 0xdc00);
        i += 1;
      }
    }
    if (код < 0x80) байты.push(код);
    else if (код < 0x800) байты.push(0xc0 | (код >>> 6), 0x80 | (код & 0x3f));
    else if (код < 0x10000) байты.push(0xe0 | (код >>> 12), 0x80 | ((код >>> 6) & 0x3f), 0x80 | (код & 0x3f));
    else байты.push(0xf0 | (код >>> 18), 0x80 | ((код >>> 12) & 0x3f), 0x80 | ((код >>> 6) & 0x3f), 0x80 | (код & 0x3f));
  }
  return Uint8Array.from(байты);
}

function hexИзБайтов(буфер) {
  const метка = Object.prototype.toString.call(буфер);
  let байты;
  if (метка === '[object ArrayBuffer]') байты = new Uint8Array(буфер);
  else if (ArrayBuffer.isView(буфер)) байты = new Uint8Array(буфер.buffer, буфер.byteOffset, буфер.byteLength);
  else throw new TypeError('hexИзБайтов: ожидаются байты, а не ' + описать(буфер));
  let hex = '';
  for (let i = 0; i < байты.length; i += 1) hex += байты[i].toString(16).padStart(2, '0');
  return hex;
}

export function base64urlИзБайтов(байты) {
  const метка = Object.prototype.toString.call(байты);
  let вид;
  if (метка === '[object ArrayBuffer]') вид = new Uint8Array(байты);
  else if (ArrayBuffer.isView(байты)) вид = new Uint8Array(байты.buffer, байты.byteOffset, байты.byteLength);
  else throw new TypeError('base64urlИзБайтов: ожидаются байты (Uint8Array/ArrayBuffer), а не ' + описать(байты));
  let строка = '';
  for (let i = 0; i < вид.length; i += 3) {
    const б0 = вид[i];
    const есть1 = i + 1 < вид.length;
    const есть2 = i + 2 < вид.length;
    const б1 = есть1 ? вид[i + 1] : 0;
    const б2 = есть2 ? вид[i + 2] : 0;
    строка += АЛФАВИТ_B64URL[б0 >>> 2];
    строка += АЛФАВИТ_B64URL[((б0 & 0x03) << 4) | (б1 >>> 4)];
    if (есть1) строка += АЛФАВИТ_B64URL[((б1 & 0x0f) << 2) | (б2 >>> 6)];
    if (есть2) строка += АЛФАВИТ_B64URL[б2 & 0x3f];
  }
  return строка;
}

export function байтыИзBase64url(строка) {
  if (typeof строка !== 'string') {
    throw new TypeError('байтыИзBase64url: ожидается строка, а не ' + описать(строка));
  }
  if (строка.length % 4 === 1) {
    throw new RangeError(
      'байтыИзBase64url: длина ' + строка.length + ' не может быть корректным base64url без заполнения',
    );
  }
  const байты = [];
  for (let i = 0; i < строка.length; i += 4) {
    const размер = Math.min(4, строка.length - i);
    let накопитель = 0;
    for (let j = 0; j < размер; j += 1) {
      const символ = строка[i + j];
      const индекс = ОБРАТНЫЙ_B64URL[символ];
      if (индекс === undefined) {
        throw new RangeError(
          'байтыИзBase64url: недопустимый символ «' + символ + '» на позиции ' + (i + j) +
          ' — алфавит base64url: A–Z, a–z, 0–9, «-», «_», без «=»',
        );
      }
      накопитель = (накопитель << 6) | индекс;
    }
    if (размер === 2) байты.push((накопитель >>> 4) & 0xff);
    else if (размер === 3) байты.push((накопитель >>> 10) & 0xff, (накопитель >>> 2) & 0xff);
    else байты.push((накопитель >>> 16) & 0xff, (накопитель >>> 8) & 0xff, накопитель & 0xff);
  }
  return Uint8Array.from(байты);
}

/* ── криптопровайдер внедряется, по умолчанию globalThis.crypto ─────────── */

function требоватьКрипто(крипто, зачем) {
  const провайдер = крипто === undefined ? globalThis.crypto : крипто;
  if (провайдер === null || typeof провайдер !== 'object' || !провайдер.subtle) {
    throw new Error('Web Crypto недоступен: ' + зачем);
  }
  return провайдер;
}

/* ── отпечаток: SHA-256 от канона, hex в нижнем регистре ────────────────── */

export async function отпечаток(объект, крипто) {
  const провайдер = требоватьКрипто(крипто, 'отпечаток требует crypto.subtle');
  const канон = канонизировать(объект);
  const дайджест = await провайдер.subtle.digest('SHA-256', utf8Байты(канон));
  return hexИзБайтов(дайджест);
}

/* ── подписываемый объект: узел + публичный + отпечаток (+ создан) ──────── */

function собратьОбъектПодписи(узел, публичный, отпечатокУзла, создан) {
  const объект = { узел, публичный, отпечаток: отпечатокУзла };
  if (создан !== undefined) объект.создан = создан;
  return объект;
}

function чистыйJwk(полныйJwk, откуда) {
  const jwk = { kty: полныйJwk.kty, crv: полныйJwk.crv, x: полныйJwk.x, y: полныйJwk.y };
  if (jwk.kty !== 'EC' || jwk.crv !== 'P-256' || typeof jwk.x !== 'string' || typeof jwk.y !== 'string') {
    throw new Error(
      'создать: ' + откуда + ' должен быть EC-ключом P-256, а получен kty=' +
      String(jwk.kty) + ', crv=' + String(jwk.crv),
    );
  }
  return jwk;
}

/* ── создать: паспорт узла ──────────────────────────────────────────────── */

export async function создать(данные, опции) {
  if (опции === undefined) опции = {};
  else if (!являетсяЗаписью(опции)) {
    throw new TypeError('создать: опции должны быть записью, а не ' + описать(опции));
  }
  const провайдер = требоватьКрипто(опции.крипто, 'паспорт узла требует crypto.subtle');
  if (!являетсяЗаписью(данные)) {
    throw new TypeError('создать: данные узла должны быть JSON-записью, а не ' + описать(данные));
  }
  if (
    опции.создан !== undefined &&
    (typeof опции.создан !== 'number' || !Number.isFinite(опции.создан) || опции.создан < 0)
  ) {
    throw new RangeError(
      'создать: «создан» должен быть конечным числом ≥ 0 (мс от начала эпохи), а не ' + описать(опции.создан),
    );
  }

  let приватныйКлюч;
  let jwk;
  if (опции.ключ !== undefined) {
    приватныйКлюч = опции.ключ;
    let полныйJwk;
    try {
      полныйJwk = await провайдер.subtle.exportKey('jwk', приватныйКлюч);
    } catch (ошибка) {
      throw new Error(
        'создать: приватный ключ не экспортируется (нужен извлекаемый EC-ключ P-256): ' +
        (ошибка && ошибка.message ? ошибка.message : String(ошибка)),
      );
    }
    jwk = чистыйJwk(полныйJwk, 'переданный приватный ключ');
  } else {
    let пара;
    try {
      пара = await провайдер.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify']);
    } catch (ошибка) {
      throw new Error(
        'создать: Web Crypto не смог породить ключ P-256: ' +
        (ошибка && ошибка.message ? ошибка.message : String(ошибка)),
      );
    }
    приватныйКлюч = пара.privateKey;
    let полныйJwk;
    try {
      полныйJwk = await провайдер.subtle.exportKey('jwk', пара.publicKey);
    } catch (ошибка) {
      throw new Error(
        'создать: публичный ключ не экспортируется: ' +
        (ошибка && ошибка.message ? ошибка.message : String(ошибка)),
      );
    }
    jwk = чистыйJwk(полныйJwk, 'порождённый публичный ключ');
  }

  const отпечатокУзла = await отпечаток(данные, провайдер);
  const паспорт = { версия, узел: данные, публичный: jwk, отпечаток: отпечатокУзла };
  if (опции.создан !== undefined) паспорт.создан = опции.создан;

  const байты = utf8Байты(
    канонизировать(собратьОбъектПодписи(паспорт.узел, паспорт.публичный, паспорт.отпечаток, паспорт.создан)),
  );
  const подписьБайты = await провайдер.subtle.sign({ name: 'ECDSA', hash: 'SHA-256' }, приватныйКлюч, байты);
  паспорт.подпись = base64urlИзБайтов(подписьБайты);
  return паспорт;
}

/* ── проверить: верифицируемость, никогда не бросает на битом паспорте ──── */

export async function проверить(паспорт, опции) {
  if (опции === undefined) опции = {};
  else if (!являетсяЗаписью(опции)) {
    throw new TypeError('проверить: опции должны быть записью, а не ' + описать(опции));
  }
  if (!являетсяЗаписью(паспорт)) {
    throw new TypeError('проверить: паспорт должен быть записью, а не ' + описать(паспорт));
  }
  const провайдер = требоватьКрипто(опции.крипто, 'проверка паспорта требует crypto.subtle');

  const причины = [];
  if (паспорт.версия !== версия) причины.push('версия паспорта не «' + версия + '»');
  const узелЕсть = паспорт.узел !== undefined;
  if (!узелЕсть) причины.push('поле «узел» отсутствует');
  const публичныйЕсть = являетсяЗаписью(паспорт.публичный);
  if (!публичныйЕсть) причины.push('поле «публичный» отсутствует или не запись');
  const отпечатокЕсть = typeof паспорт.отпечаток === 'string';
  if (!отпечатокЕсть) причины.push('поле «отпечаток» отсутствует или не строка');
  const подписьЕсть = typeof паспорт.подпись === 'string';
  if (!подписьЕсть) причины.push('поле «подпись» отсутствует или не строка');

  if (узелЕсть) {
    let пересчитанный = null;
    try {
      пересчитанный = await отпечаток(паспорт.узел, провайдер);
    } catch (ошибка) {
      причины.push('отпечаток узла не пересчитывается: ' + (ошибка && ошибка.message ? ошибка.message : String(ошибка)));
    }
    if (отпечатокЕсть && пересчитанный !== null && пересчитанный !== паспорт.отпечаток) {
      причины.push('отпечаток не совпал');
    }
  }

  let ключ = null;
  if (публичныйЕсть) {
    try {
      ключ = await провайдер.subtle.importKey(
        'jwk', паспорт.публичный, { name: 'ECDSA', namedCurve: 'P-256' }, true, ['verify'],
      );
    } catch (ошибка) {
      причины.push('публичный ключ не принят: ' + (ошибка && ошибка.message ? ошибка.message : String(ошибка)));
    }
  }

  let байтыПодписи = null;
  if (подписьЕсть) {
    try {
      байтыПодписи = байтыИзBase64url(паспорт.подпись);
    } catch (ошибка) {
      причины.push('подпись не является корректным base64url: ' + (ошибка && ошибка.message ? ошибка.message : String(ошибка)));
    }
  }

  if (ключ !== null && байтыПодписи !== null && узелЕсть && отпечатокЕсть) {
    try {
      const байты = utf8Байты(
        канонизировать(собратьОбъектПодписи(паспорт.узел, паспорт.публичный, паспорт.отпечаток, паспорт.создан)),
      );
      const верна = await провайдер.subtle.verify({ name: 'ECDSA', hash: 'SHA-256' }, ключ, байтыПодписи, байты);
      if (!верна) причины.push('подпись не совпала');
    } catch (ошибка) {
      причины.push('подпись не прошла проверку: ' + (ошибка && ошибка.message ? ошибка.message : String(ошибка)));
    }
  }

  return { верно: причины.length === 0, причины };
}
