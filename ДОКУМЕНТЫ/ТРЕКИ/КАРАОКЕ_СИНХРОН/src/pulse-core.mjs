/* ── Текстовые помощники (семантика ядра-образца) ──────────────────────────── */

/** Разбивка на слова: по пробелам (любые \s+), пустые отброшены. Как слова() ядра. */
export function слова(т) {
  return String(т == null ? '' : т).split(/\s+/).filter(Boolean);
}

/** Норм слова: нижний регистр, ё→е, всё кроме букв и цифр прочь (регистр/пунктуация).
 *  Как норм() ядра-образца. */
export function норм(т) {
  return String(т == null ? '' : т).toLowerCase().replace(/ё/g, 'е').replace(/[^\p{L}\p{N}]/gu, '');
}

/** Расстояние Левенштейна, два ряда, без случайности. Как лев() ядра-образца. */
export function лев(a, b) {
  if (a === b) return 0;
  const м = a.length, н = b.length;
  if (!м) return н;
  if (!н) return м;
  let пред = [], тек = [];
  for (let j = 0; j <= н; j++) пред[j] = j;
  for (let i = 1; i <= м; i++) {
    тек[0] = i;
    for (let j = 1; j <= н; j++) {
      тек[j] = Math.min(пред[j] + 1, тек[j - 1] + 1, пред[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
    }
    const t = пред; пред = тек; тек = t;
  }
  return пред[н];
}

/** Сходство [0..1]: 1 − лев/макс_длина; симметрично (лев(a,b) = лев(b,a)).
 *  Как сходство() ядра-образца. */
export function сходство(a, b) {
  if (!a && !b) return 1;
  const L = Math.max(a.length, b.length);
  return L ? 1 - лев(a, b) / L : 1;
}

/* ── внутреннее ────────────────────────────────────────────────────────────── */

function конечное(x) { return typeof x === 'number' && Number.isFinite(x); }

function типИмя(x) {
  if (x === null) return 'null';
  if (Array.isArray(x)) return 'массив';
  return typeof x;
}

/* ═══════════════════════════════════════════════════════════════════════════════
   1. нормализоватьASR — нормализованные слова ASR (регистр/пунктуация/пробелы)
   ═══════════════════════════════════════════════════════════════════════════════
   Строка  → массив норм-слов (пробелы → слова(), регистр/пунктуация → норм()).
   Массив  → диалекты ASR из ядра-образца:
             • {w, s, e}            — уже миллисекунды (диалект ядра);
             • {word, start, end}   — секунды → мс (WhisperX / faster-whisper);
             • {text, timestamp:[a,b]} — секунды → мс (transformers.js chunks);
             • {words:[{word,start,end}]} — segments-диалект;
             • строка-элемент — слово без времён.
             Текст каждого слова нормализуется тем же норм(); времена округляются
             до целых мс; слова без конечных времён остаются текстовыми {w}.
   null/undefined → [] (честное пусто).
   Иначе — честная ошибка TypeError. */
export function нормализоватьASR(текст) {
  if (текст == null) return [];
  if (typeof текст === 'string') return слова(текст).map(норм).filter(Boolean);

  if (Array.isArray(текст)) {
    const вых = [];
    const положи = (w, s, e) => {
      const н = норм(w);
      if (!н) return;                      // пустые после норм — мимо конвейера, честно
      const слово = { w: н };
      if (конечное(s)) слово.s = Math.round(s);
      if (конечное(e)) слово.e = Math.round(e);
      вых.push(слово);
    };
    текст.forEach((x, k) => {
      if (x == null) return;
      if (typeof x === 'string') { положи(x, undefined, undefined); return; }
      if (typeof x !== 'object') {
        throw new TypeError('нормализоватьASR: элемент №' + k + ' не строка и не объект ASR-слова, пришло: ' + типИмя(x));
      }
      if (x.w != null) положи(x.w, x.s, x.e);                                    // мс, как в ядре
      else if (x.word != null) положи(x.word, x.start * 1000, x.end * 1000);      // секунды → мс
      else if (x.text != null && Array.isArray(x.timestamp)) положи(x.text, x.timestamp[0] * 1000, x.timestamp[1] * 1000);
      else if (Array.isArray(x.words)) x.words.forEach(y => { if (y && y.word != null) положи(y.word, y.start * 1000, y.end * 1000); });
      else throw new TypeError('нормализоватьASR: элемент №' + k + ' не распознан (жду {w|word|text…} или {words:[…]})');
    });
    return вых;
  }

  throw new TypeError('нормализоватьASR: жду строку, массив ASR-слов или null/undefined, пришло: ' + типИмя(текст));
}

/* ═══════════════════════════════════════════════════════════════════════════════
   2. выровнять — Needleman–Wunsch: слова ASR ↔ слова строк синхрона
   ═══════════════════════════════════════════════════════════════════════════════
   выровнять(словаASR, строкиСинхро, опц) →
     { пары, пропущено, лишнее, всего, совпало, покрытие, порог, гэп, матрица }

   • словаASR    — массив строк ИЛИ объектов {w|word, s|start, e|end}
                   (нормализуется здесь же тем же норм() — операция идемпотентна);
   • строкиСинхро — массив строк или строк pulse-sync/1 { t, a, b, units:[{t,s,e}] };
                   слова берутся из units (если есть), иначе из t;
   • опц.штраф   — порог сходства пары (имя по приказу КС2; алиас опц.порог ядра);
                   по умолчанию ПС_ПОРОГ_СХОДСТВА = 0.6;
   • опц.гэп     — штраф за гэп, по умолчанию ПС_ШТРАФ_ГЭПА = −0.45.

   Оценки NW — из ядра-образца: диаг = D[i−1][j−1] + (sim ≥ порог ? 2·sim − 0.4 : −1.0),
   гэп = −0.45; обход детерминированный (эталон × ASR, при равенстве старшинствует
   диагональ, затем вверх, затем влево). Пара ставится только при sim ≥ порог.
   «Честная симметричная матрица»: матрица сходства S строится ЦЕЛИКОМ и симметрична
   (Левенштейн симметричен); оценки D — точные числа IEEE (не Float32, как в ядре).

   Вход не мутируется; пары/пропущено/лишнее — новые объекты.
   Крайние случаи: пусто с любой стороны → пар нет, покрытие 0 (как доля ядра:
   «нечем покрыть» — 0, не выдумка). */
export function выровнять(словаASR, строкиСинхро, опц) {
  if (опц == null) опц = {};
  if (typeof опц !== 'object' || Array.isArray(опц)) {
    throw new TypeError('выровнять: опц — жду объект опций, пришло: ' + типИмя(опц));
  }
  if (!Array.isArray(словаASR)) {
    throw new TypeError('выровнять: словаASR — жду массив, пришло: ' + типИмя(словаASR));
  }
  if (!Array.isArray(строкиСинхро)) {
    throw new TypeError('выровнять: строкиСинхро — жду массив строк pulse-sync/1, пришло: ' + типИмя(строкиСинхро));
  }

  const порог = опц.штраф != null ? опц.штраф : (опц.порог != null ? опц.порог : ПС_ПОРОГ_СХОДСТВА);
  if (typeof порог !== 'number' || !Number.isFinite(порог) || порог < 0 || порог > 1) {
    throw new TypeError('выровнять: опц.штраф (порог сходства) — жду число от 0 до 1, пришло: ' + типИмя(порог));
  }
  const гэп = опц.гэп != null ? опц.гэп : ПС_ШТРАФ_ГЭПА;
  if (typeof гэп !== 'number' || !Number.isFinite(гэп)) {
    throw new TypeError('выровнять: опц.гэп — жду конечное число, пришло: ' + типИмя(гэп));
  }

  /* Эталонная последовательность: слова строк в порядке дома, с пренадлежностью строке */
  const эт = [];
  строкиСинхро.forEach((стр, i) => {
    let юниты = null, текст = null;
    if (typeof стр === 'string') {
      текст = стр;
    } else if (стр && typeof стр === 'object') {
      if (Array.isArray(стр.units)) юниты = стр.units;
      if (стр.t != null) текст = String(стр.t);
      else if (юниты) текст = юниты.map(u => (u && u.t != null) ? String(u.t) : '').join(' ');
    }
    if (текст == null && !юниты) {
      throw new TypeError('выровнять: строка №' + i + ' без текста (t) и без юнитов (units)');
    }
    const словаСтроки = (юниты && юниты.length)
      ? юниты.map(u => (u && u.t != null) ? String(u.t) : '')
      : слова(текст);
    словаСтроки.forEach((сл, j) => {
      const н = норм(сл);
      if (!н) return;                     // пунктуационные/пустые — мимо матрицы (обе стороны норм)
      let юнит = null;
      if (юниты && юниты[j] && typeof юниты[j] === 'object') {
        const u = юниты[j];
        if (конечное(u.s) && конечное(u.e)) юнит = { t: String(u.t), s: u.s, e: u.e };
      }
      эт.push({ строка: i, позиция: j, н, юнит });
    });
  });

  /* Последовательность ASR: норм здесь же (идемпотентно), времена — целые мс или нет вовсе */
  const асОк = [];
  словаASR.forEach((x, k) => {
    if (typeof x === 'string') { const н = норм(x); if (н) асОк.push({ w: н, s: null, e: null }); return; }
    if (x && typeof x === 'object' && x.w != null) {
      const н = норм(x.w);
      if (н) асОк.push({ w: н, s: конечное(x.s) ? x.s : null, e: конечное(x.e) ? x.e : null });
      return;
    }
    throw new TypeError('выровнять: слово ASR №' + k + ' не строка и не {w…} (нормализуй через нормализоватьASR), пришло: ' + типИмя(x));
  });

  const n = эт.length, m = асОк.length;

  if (!n || !m) {
    return {
      пары: [],
      пропущено: эт.map(x => ({ строка: x.строка, позиция: x.позиция, слово: x.н })),
      лишнее: асОк.map((x, k) => ({ индекс: k, слово: x.w, ...(x.s != null ? { s: x.s } : {}), ...(x.e != null ? { e: x.e } : {}) })),
      всего: n,
      совпало: 0,
      покрытие: 0,
      порог, гэп,
      матрица: [],
    };
  }

  /* Честная симметричная матрица сходства (целиком, без отсечений) */
  const матрица = [];
  for (let i = 0; i < n; i++) {
    const ряд = new Array(m);
    for (let j = 0; j < m; j++) ряд[j] = сходство(эт[i].н, асОк[j].w);
    матрица.push(ряд);
  }

  /* Needleman–Wunsch: точные числа (не Float32), детерминированный обход */
  const D = [], T = [];
  for (let i = 0; i <= n; i++) { D.push(new Array(m + 1).fill(0)); T.push(new Array(m + 1).fill(0)); }
  for (let i = 1; i <= n; i++) { D[i][0] = i * гэп; T[i][0] = 1; }
  for (let j = 1; j <= m; j++) { D[0][j] = j * гэп; T[0][j] = 2; }
  for (let i = 1; i <= n; i++) {
    for (let j = 1; j <= m; j++) {
      const sim = матрица[i - 1][j - 1];
      const диаг = D[i - 1][j - 1] + (sim >= порог ? 2 * sim - 0.4 : -1.0);
      const вверх = D[i - 1][j] + гэп;
      const влево = D[i][j - 1] + гэп;
      if (диаг >= вверх && диаг >= влево) { D[i][j] = диаг; T[i][j] = 0; }
      else if (вверх >= влево) { D[i][j] = вверх; T[i][j] = 1; }
      else { D[i][j] = влево; T[i][j] = 2; }
    }
  }

  /* Обратный ход: пары по порогу, порядок — по эталонным словам (детерминирован) */
  const парыПоЭт = new Array(n).fill(null);
  const использованоАс = new Array(m).fill(false);
  let i = n, j = m;
  while (i > 0 || j > 0) {
    const t = (i > 0 && j > 0) ? T[i][j] : (i > 0 ? 1 : 2);
    if (t === 0) {
      if (матрица[i - 1][j - 1] >= порог) {
        const э = эт[i - 1], а = асОк[j - 1];
        парыПоЭт[i - 1] = {
          строка: э.строка,
          позиция: э.позиция,
          слово: э.н,
          asr: { w: а.w, ...(а.s != null ? { s: а.s } : {}), ...(а.e != null ? { e: а.e } : {}) },
          sim: матрица[i - 1][j - 1],
          точно: э.н === а.w,
          юнит: э.юнит ? { t: э.юнит.t, s: э.юнит.s, e: э.юнит.e } : null,
        };
        использованоАс[j - 1] = true;
      }
      i--; j--;
    } else if (t === 1) i--;
    else j--;
  }

  const пары = парыПоЭт.filter(Boolean);
  const пропущено = [];
  парыПоЭт.forEach((п, k) => { if (!п) пропущено.push({ строка: эт[k].строка, позиция: эт[k].позиция, слово: эт[k].н }); });
  const лишнее = асОк
    .map((x, k) => ({ индекс: k, слово: x.w, ...(x.s != null ? { s: x.s } : {}), ...(x.e != null ? { e: x.e } : {}) }))
    .filter((_, k) => !использованоАс[k]);

  return {
    пары,
    пропущено,
    лишнее,
    всего: n,
    совпало: пары.length,
    покрытие: n ? пары.length / n : 0,
    порог,
    гэп,
    матрица,
  };
}

/* ═══════════════════════════════════════════════════════════════════════════════
   3. сравнить — метрики выравнивания (совпадения/расхождения/покрытие)
   ═══════════════════════════════════════════════════════════════════════════════
   сравнить(выравнивание) →
     { времена, всего, совпало, точно, приблизительно, пропущено, лишнее,
       расхождения, покрытие, точностьТекста, дельты, деталь }

   • совпало — пары по порогу сходства; из них «точно» (норм-слова равны) и
     «приблизительно» (прошли порог, но тексты различны);
   • расхождения = приблизительно + пропущено + лишнее (всё, что не точное
     совпадение — определение конвейера, помечено честно);
   • покрытие = совпало/всего (0 при пустом эталоне — «нечем мерить», как в ядре);
   • дельты — |s_ASR − s_юнит| по парам с временами с обеих сторон; статистика
     в духе сравнить() ядра-образца (среднее/медиана/p90/доли ≤ 50 и ≤ 80 мс);
     без временных пар — null и времена: false (честное «нет данных»).
   Вход не мутируется: деталь — новые объекты (дельтаМс появляется только в копии). */
export function сравнить(выравнивание) {
  if (!выравнивание || typeof выравнивание !== 'object' || Array.isArray(выравнивание) || !Array.isArray(выравнивание.пары)) {
    throw new TypeError('сравнить: жду результат выровнять (объект с массивом «пары»), пришло: ' + типИмя(выравнивание));
  }

  const пропущено = Array.isArray(выравнивание.пропущено) ? выравнивание.пропущено.length : 0;
  const лишнее = Array.isArray(выравнивание.лишнее) ? выравнивание.лишнее.length : 0;
  const деталь = выравнивание.пары.map(п => {
    const дельтаМс = (п && п.asr && конечное(п.asr.s) && п.юнит && конечное(п.юнит.s))
      ? Math.abs(п.asr.s - п.юнит.s)
      : null;
    return { ...п, дельтаМс };
  });

  const точно = деталь.filter(п => п.точно === true).length;
  const приблизительно = деталь.length - точно;
  const всего = конечное(выравнивание.всего) ? выравнивание.всего : деталь.length + пропущено;
  const совпало = деталь.length;
  const покрытие = всего ? совпало / всего : 0;
  const точностьТекста = всего ? точно / всего : 0;

  const дельтыСписок = деталь.map(п => п.дельтаМс).filter(x => x != null).sort((a, b) => a - b);
  let дельты = null;
  if (дельтыСписок.length) {
    const k = дельтыСписок.length;
    const доля = лимит => Math.round(1000 * дельтыСписок.filter(x => x <= лимит).length / k) / 10;
    дельты = {
      n: k,
      среднее_мс: Math.round(дельтыСписок.reduce((x, y) => x + y, 0) / k),
      медиана_мс: дельтыСписок[Math.floor(k / 2)],
      p90_мс: дельтыСписок[Math.floor(k * 0.9)],
      в50_мс_процент: доля(ПС_ПРОФИ_МС),
      в80_мс_процент: доля(ПС_КОМФОРТ_МС),
    };
  }

  return {
    времена: дельты != null,
    всего,
    совпало,
    точно,
    приблизительно,
    пропущено,
    лишнее,
    расхождения: приблизительно + пропущено + лишнее,
    покрытие,
    точностьТекста,
    дельты,
    деталь,
  };
}

/* ═══════════════════════════════════════════════════════════════════════════════
   4. вHarm — вердикт гармонии строки с конвейерными метриками
   ═══════════════════════════════════════════════════════════════════════════════
   вHarm(метрики, строка, опц) →
     { гармония, причина, правила, строка, покрытие }

   • метрики — результат сравнить() (нужна «деталь»);
   • строка  — строка pulse-sync/1 { i, t, a, b, units:[{t,s,e}] }; i обязателен —
     по нему пары деталь сужаются до строки (честно: иначе повторы слов врут);
   • опц.порогПокрытия — порог правила покрытия (по умолчанию ПС_ПОРОГ_СХОДСТВА;
     решение конвейера, спека числа покрытия не задаёт).

   Правила вердикта:
   1) «покрытие»   — доля слов строки, покрытых парами выравнивания, ≥ порога;
   2) «комфорт80мс» — наибольшая дельта старта пар строки ≤ ПС_КОМФОРТ_МС (80);
      источник: 05_BEST… §2 «ПРАВИЛО 50–80 мс»;
   3) «хвост»      — e_юнита − e_ASR каждой временной пары ∈ [ПС_ХВОСТ_МИН_МС,
      ПС_ХВОСТ_МАКС_МС] = [20, 40]; источник: 05_BEST… §1 (подсветка = пение +
      хвост 20–40 мс). Буквальное прочтение §1 к парам «юнит ↔ ASR».

   «нет данных» (нет временных пар) честно помечается и НЕ валит вердикт:
   текстовая гармония подтверждена, временная — неизмерима без аудио.
   гармония = нет ни одного отклонённого правила; причина — по-русски. */
export function вHarm(метрики, строка, опц) {
  if (опц == null) опц = {};
  if (!метрики || typeof метрики !== 'object' || Array.isArray(метрики) || !Array.isArray(метрики.деталь)) {
    throw new TypeError('вHarm: жду метрики из сравнить (объект с массивом «деталь»), пришло: ' + типИмя(метрики));
  }
  if (!строка || typeof строка !== 'object' || Array.isArray(строка)) {
    throw new TypeError('вHarm: жду строку pulse-sync/1 (объект { i, t, a, b, units }), пришло: ' + типИмя(строка));
  }
  if (!конечное(строка.i) || !Number.isInteger(строка.i)) {
    throw new TypeError('вHarm: у строки должен быть целочисленный индекс i (pulse-sync/1), пришло: ' + типИмя(строка.i));
  }
  const юниты = Array.isArray(строка.units) ? строка.units : null;
  if (!юниты && строка.t == null) {
    throw new TypeError('вHarm: строка ' + строка.i + ' без юнитов (units) и без текста (t)');
  }
  const порогПокрытия = опц.порогПокрытия != null ? опц.порогПокрытия : ПС_ПОРОГ_СХОДСТВА;
  if (typeof порогПокрытия !== 'number' || !Number.isFinite(порогПокрытия) || порогПокрытия < 0 || порогПокрытия > 1) {
    throw new TypeError('вHarm: опц.порогПокрытия — жду число от 0 до 1, пришло: ' + типИмя(порогПокрытия));
  }

  const парыСтроки = метрики.деталь.filter(п => п && п.строка === строка.i);
  const словСтроки = юниты
    ? юниты.map(u => (u && u.t != null) ? норм(u.t) : '').filter(Boolean).length
    : слова(строка.t).map(норм).filter(Boolean).length;
  const покрытие = словСтроки ? парыСтроки.length / словСтроки : 0;

  const правила = [];

  /* 1) покрытие текста строки словами ASR */
  if (!словСтроки) {
    правила.push({ правило: 'покрытие', статус: 'нет данных', причина: 'строка без слов' });
  } else {
    const ок = покрытие >= порогПокрытия;
    правила.push({ правило: 'покрытие', статус: ок ? 'ok' : 'отклонено', значение: покрытие, порог: порогПокрытия });
  }

  /* 2) правило ≤80 мс (комфорт): дельты стартов пар строки */
  const временныеПары = парыСтроки.filter(п => п.дельтаМс != null);
  if (!временныеПары.length) {
    правила.push({ правило: 'комфорт80мс', статус: 'нет данных', причина: 'нет пар с временами старта с обеих сторон' });
  } else {
    const макс = Math.max(...временныеПары.map(п => п.дельтаМс));
    const ок = макс <= ПС_КОМФОРТ_МС;
    правила.push({ правило: 'комфорт80мс', статус: ок ? 'ok' : 'отклонено', значение: макс, порог: ПС_КОМФОРТ_МС });
  }

  /* 3) правило хвоста 20–40 мс: e_юнита − e_ASR (подсветка = пение + хвост) */
  const хвосты = парыСтроки
    .filter(п => п.юнит && конечное(п.юнит.e) && п.asr && конечное(п.asr.e))
    .map(п => п.юнит.e - п.asr.e);
  if (!хвосты.length) {
    правила.push({ правило: 'хвост', статус: 'нет данных', причина: 'нет пар с временами конца с обеих сторон' });
  } else {
    const ок = хвосты.every(х => х >= ПС_ХВОСТ_МИН_МС && х <= ПС_ХВОСТ_МАКС_МС);
    правила.push({ правило: 'хвост', статус: ок ? 'ok' : 'отклонено', значение: хвосты, диапазон: [ПС_ХВОСТ_МИН_МС, ПС_ХВОСТ_МАКС_МС] });
  }

  const отклонено = правила.find(r => r.статус === 'отклонено');
  const причина = отклонено
    ? ('правило «' + отклонено.правило + '» отклонено' +
       (отклонено.значение !== undefined ? ' (значение ' + JSON.stringify(отклонено.значение) + ')' : ''))
    : null;

  return {
    гармония: !отклонено,
    причина,
    правила,
    строка: строка.i,
    покрытие,
  };
}
