/* ── Часы Лампорта: монотонный порядок причинности ── */
export class ЧасыЛампорта {
  constructor(){ this.t = 0; }
  тик(){ this.t += 1; return this.t; }
  приём(чужое){
    if(!Number.isInteger(чужое) || чужое < 0) throw new Error("чужое время — целое ≥ 0");
    this.t = Math.max(this.t, чужое) + 1;
    return this.t;
  }
}

/* ── LWW-Element-Set: последнее-писавшее-побеждает по (т, уз) ──
   элемент → { б: true|false (добавлен/гробница), т: число, уз: строка }.
   Победитель при слиянии: больше т; при равенстве т — больше уз (лексика).
   Слияние коммутативно/ассоциативно/идемпотентно — CRDT-триада честная. */
export class LWWSet {
  constructor(){ this.записи = new Map(); }
  _победа(a, b){ return (a.т > b.т) || (a.т === b.т && a.уз > b.уз) ? a : b; }
  добавить(э, т, уз){
    if(!Number.isInteger(т) || т < 0) throw new Error("время — целое ≥ 0");
    if(!уз) throw new Error("узел обязателен (детерминированный тай-брейк)");
    const н = { б: true, т, уз: String(уз) };
    const с = this.записи.get(э);
    this.записи.set(э, с ? this._победа(с, н) : н);
    return н;
  }
  удалить(э, т, уз){
    if(!Number.isInteger(т) || т < 0) throw new Error("время — целое ≥ 0");
    if(!уз) throw new Error("узел обязателен");
    const н = { б: false, т, уз: String(уз) };
    const с = this.записи.get(э);
    this.записи.set(э, с ? this._победа(с, н) : н);
    return н;
  }
  /* живое = добавлен и не побит гробницей */
  живые(){
    const р = [];
    for(const [э, з] of this.записи) if(з.б) р.push(э);
    return р.sort();
  }
  /* слияние чужого состояния — запись-в-запись по правилу победы */
  слить(чужой){ /* чужой: LWWSet | объект-дифф */
    const записи = чужой instanceof LWWSet ? чужой.записи : new Map(Object.entries(чужой));
    for(const [э, з] of записи){
      const с = this.записи.get(э);
      this.записи.set(э, с ? this._победа(с, з) : з);
    }
    return this;
  }
  /* дифф: только верхние записи (для обмена) */
  дифф(){
    const о = {};
    for(const [э, з] of this.записи) о[э] = { б: з.б, т: з.т, уз: з.уз };
    return о;
  }
  изДиффа(д){ return this.слить(д); }
  /* чистка гробниц старше порога — purgeSet (гробница-кандидат удаляется,
     если её время < порога и живого элемента нет) */
  чистка(порог){
    let снято = 0;
    for(const [э, з] of [...this.записи]){
      if(!з.б && з.т < порог){ this.записи.delete(э); снято += 1; }
    }
    return снято;
  }
}

/* ── Меркль: 32-байтовый корень — НЕСЖАТЫЙ trie фиксированной глубины 64 ──
   канон: лист элемента = SHA-256("л:"+элемент); путь листа — первые 64 бита
   его хэша (2^64 адресов); узел = SHA-256(0x01 | левый | правый), пустая ветка =
   ∅-константа SHA-256("п:∅"). Фиксированная глубина: формы trie зависят только
   от множества — вставки не сдвигают чужие листья и не сжимают чужие пути,
   сверка пар точна; дифф — точный по множествам, обмен — log-N.
   фазы сверки: 1) обмен корнями; 2) спуск парами поддеревьев (только расхождения);
   3) дифф листьев. Proof включения: 64 шага, пустые соседи — маркер "∅"
   (proof ≤ ~2,3 КБ при фонде ≤ ~20 песен — влезает в QR-кадр канона qr-token 2953 Б). */
async function ша(байты){
  const б = typeof байты === "string" ? new TextEncoder().encode(байты) : байты;
  const х = await globalThis.crypto.subtle.digest("SHA-256", б);
  return new Uint8Array(х);
}
export function hex(б){ return [...б].map(x => x.toString(16).padStart(2, "0")).join(""); }
let _ПАД_КЭШ = null;
async function ПАД(){ if(!_ПАД_КЭШ) _ПАД_КЭШ = await ша("п:∅"); return _ПАД_КЭШ; }
export const МЕРКЛЬ_ГЛУБИНА = 64;

export const Меркль = {
  async лист(э){
    if(typeof э !== "string" || !э) throw new Error("элемент — непустая строка");
    return ша("л:" + э);
  },
  async узел(л, п){ /* 0x01-префикс домена узлов — защита от удлинённого сообщения */
    const с = new Uint8Array(л.length + п.length + 1);
    с[0] = 1; с.set(л, 1); с.set(п, 1 + л.length);
    return ша(с);
  },
  /* trie: узел { л:"элемент", х } | { д:[лево, право], х } | null (пустая ветка) */
  async дерево(элементы, глубина){
    if(элементы == null) throw new Error("элементы обязательны (пустой фонд — [])");
    const Г = Number.isInteger(глубина) && глубина > 0 && глубина <= 256 ? глубина : МЕРКЛЬ_ГЛУБИНА;
    const уникальные = [...new Set(элементы.map(String))].sort();
    уникальные.forEach(э => { if(!э) throw new Error("пустой элемент недопустим"); });
    const хэши = await Promise.all(уникальные.map(э => this.лист(э)));
    const биты = хэши.map(х => {
      const г = hex(х), м = new Array(г.length * 4);
      for(let i = 0; i < г.length; i++){ const v = parseInt(г[i], 16); м[i*4]=(v>>3)&1; м[i*4+1]=(v>>2)&1; м[i*4+2]=(v>>1)&1; м[i*4+3]=v&1; }
      return м;
    });
    const список = уникальные.map((э, i) => ({ э, х: хэши[i], б: биты[i] }));
    const сам = this;
    async function ветка(спис, г){
      if(спис.length === 0) return null;
      if(г >= Г){
        if(спис.length !== 1) throw new Error("коллизия путей листа — недопустима для канона");
        return { л: спис[0].э, х: спис[0].х };
      }
      const лев = спис.filter(х => !х.б[г]), прав = спис.filter(х => х.б[г]);
      const д = [await ветка(лев, г + 1), await ветка(прав, г + 1)];
      return { д, х: await сам.узел(д[0] ? д[0].х : await ПАД(), д[1] ? д[1].х : await ПАД()) };
    }
    const три = await ветка(список, 0);
    return { три, корень: три ? три.х : await ПАД(), листья: уникальные, глубина: Г };
  },
  async корень(элементы){ return hex((await this.дерево(элементы)).корень); },
  /* 3 фазы: корни → расходящиеся пары поддеревьев → дифф листьев (точный по множествам) */
  async сверка(элементыА, элементыБ){
    const дА = await this.дерево(элементыА), дБ = await this.дерево(элементыБ);
    const лишние = [], недостающие = [];
    async function обход(у, в_лишние){
      if(!у) return;
      if(у.л){ (в_лишние ? лишние : недостающие).push(у.л); return; }
      await обход(у.д[0], в_лишние); await обход(у.д[1], в_лишние);
    }
    async function спуск(а, б){
      if(!а && !б) return;
      if(а && б && hex(а.х) === hex(б.х)) return; /* куски равны — дальше не едем (log-N обмен) */
      if(а && б && а.л && б.л){ лишние.push(а.л); недостающие.push(б.л); return; }
      if(а && б && а.д && б.д){ await спуск(а.д[0], б.д[0]); await спуск(а.д[1], б.д[1]); return; }
      if(а) await обход(а, true); else await обход(б, false); /* лист против узла / сторона пуста */
    }
    await спуск(дА.три, дБ.три);
    return { равны: hex(дА.корень) === hex(дБ.корень), лишние: [...new Set(лишние)].sort(), недостающие: [...new Set(недостающие)].sort() };
  },
  /* proof включения листа: [{с: сосед|"∅", л: текущий слева}] — по trie-пути листа */
  async доказ(элементы, э, глубина){
    if(typeof э !== "string" || !э) throw new Error("элемент — непустая строка");
    const д = await this.дерево(элементы, глубина);
    if(!д.листья.includes(э)) throw new Error("листа нет в дереве: " + э);
    const путь = [];
    async function путьК(у, г){
      if(!у) return false;
      if(у.л) return у.л === э;
      for(let i = 0; i < 2; i++){
        путь.push({ с: у.д[1 - i] ? hex(у.д[1 - i].х) : "∅", л: i === 0 });
        if(await путьК(у.д[i], г + 1)) return true;
        путь.pop();
      }
      return false;
    }
    if(!(await путьК(д.три, 0))) throw new Error("путь к листу не нашёлся");
    return { элемент: э, корень: hex(д.корень), глубина: д.глубина, путь };
  },
  async проверьДоказ(пруф){
    if(!пруф || !Array.isArray(пруф.путь) || typeof пруф.элемент !== "string") throw new Error("proof неполон");
    let хб = await this.лист(пруф.элемент);
    for(const шаг of пруф.путь.slice().reverse()){ /* путь копится сверху вниз — подъём снизу вверх */
      if(typeof шаг.л !== "boolean") throw new Error("шаг пути бит");
      const сб = шаг.с === "∅" ? await ПАД()
        : (typeof шаг.с === "string" && шаг.с.length === 64 ? new Uint8Array((шаг.с.match(/../g) || []).map(b => parseInt(b, 16))) : null);
      if(!сб) throw new Error("шаг пути бит");
      хб = шаг.л ? await this.узел(хб, сб) : await this.узел(сб, хб);
    }
    return hex(хб) === пруф.корень;
  }
};
