// mesh-wire.mjs — трек МЕТАШАНСОН, линия М1 «GLOBAL MESH» дорожной карты:
// ПРОВОД между ядром mesh-core/0.1 и живой сетью. Такт v11.25 «МОСТ» (С103).
//
// ЛЕСТНИЦА ПРОВОДА (из лога М1: «BroadcastChannel → WebRTC → Nostr wss»):
//   «вещание» — BroadcastChannel одного происхождения (вкладки/окна у человека):
//               локальный эфир без сети вообще; в Node-песочнице слоя нет —
//               честный отказ слоя, остальная лестница жива;
//   «данные»  — ГОТОВЫЙ RTCDataChannel от моста КС5 (ЛАДОМ_СВЯЗЬ v0.2): провод
//               канал НЕ строит (сигналинг дуэта — дело моста), только
//               принимает готовый — инъекция { канал };
//   «релей»   — JSON-эфир дома поверх WebSocket к своему релею (КС8): клиент
//               шлёт {"эфир":…,"конверт":…}, релей рассылает всем в эфире.
//               Настоящий Nostr NIP-01 требует подписи события (secp256k1) —
//               «релеи без ключей» из лога М1 = ЭТАП 2: ECDSA ·24 подписывает
//               конверт, до приказа слой честно закрыт (не имитируем).
//
// КОНТРАКТ ЯДРА (mesh-core/0.1, не трогаем):
//   транспорт = { отправить(конверт), приПолучении(обработчик), открыть?, закрыть? }
//   ядро зовёт открыть()/закрыть() ТОЛЬКО из присоединиться()/остановить() —
//   «сеть по явному действию» (И-01). Провод держит контракт байт-в-байт.
//
// Честные границы:
//   • 0 сети при импорте: ни одного открытого сокета до открыть() (И-01);
//   • отказ слоя ≠ отказ провода: лестница деградирует честно, ядро живо;
//   • отправить() возвращает отчёт по слоям {имя: 'отправлено'|'закрыт'|'отказ'}
//     и НЕ бросает на закрытых слоях — ядро считает конверт отправленным, а
//     честный статус живёт в состоянии() (офлайн-узел не притворяется онлайн);
//   • отправить() ДО открыть() — честный TypeError: сеть не открыта;
//   • шифрование/подписи — НЕ здесь (ядро: «транспорт подписывает сам, если
//     умеет»); дедуп и своё эхо — в ядре (ОКНО_ДЕДУПА 512), провод не дедупит;
//   • конверт ходит строкой JSON; размер ограничивает релей/слой (мост: 16 КБ).
//
// Экспорт: только ESM; импортов ноль — канон чист (как mesh-core/0.1).

export const ver = 'mesh-wire/0.1';
export const СХЕМА = 'mesh-wire/0.1';

/** Имена встроенных слоёв (заморожено — лестница не расширяется молча). */
export const СЛОИ = Object.freeze(['вещание', 'данные', 'релей']);

const СТАТУСЫ = Object.freeze(['ждёт', 'открыт', 'отказ', 'закрыт']);

function честноУсловие(условие, сообщение) {
  if (условие) throw new TypeError(сообщение);
}

function честноСтрока(значение, имя) {
  честноУсловие(typeof значение !== 'string' || значение.length === 0,
    `mesh-wire: ${имя} обязана быть непустой строкой`);
}

/* ── Встроенные слои-фабрики ───────────────────────────────────────────────── */

/**
 * слойВещания({ эфир?, BroadcastChannelImpl? }) — слой «вещание».
 * BroadcastChannelImpl — инъекция для проб (0 сети в тестах); без неё берём
 * глобальный класс; нет и его (Node-песочница) — слой честно откажет при открыть().
 */
export function слойВещания(опции = {}) {
  const { эфир = 'singlyar-эфир/0.1', BroadcastChannelImpl } = опции;
  честноСтрока(эфир, 'эфир');
  let обработчик = null;
  return {
    имя: 'вещание',
    открыть() {
      const Класс = BroadcastChannelImpl ??
        (typeof BroadcastChannel !== 'undefined' ? BroadcastChannel : null);
      if (!Класс) throw new Error('mesh-wire: BroadcastChannel недоступен в этой среде — слой честно стоит в стороне');
      const ч = new Класс(эфир);
      if (typeof ч.unref === 'function') ч.unref(); // проба не должна висеть на эфире
      ч.onmessage = (событие) => {
        if (!обработчик) return;
        let сырое = null;
        try { сырое = JSON.parse(String(событие.data)); } catch { return; } // чужой мусор — не конверт, молча мимо
        if (сырое && typeof сырое === 'object' && сырое.эфир === эфир && сырое.конверт) {
          обработчик(сырое.конверт);
        }
      };
      return ч;
    },
    отправить(канал, строка) { канал.postMessage(JSON.stringify({ эфир, конверт: JSON.parse(строка) })); },
    закрыть(канал) { try { канал.close(); } catch (e) { /* уже закрыт — честно */ } },
    приДанных(х) { обработчик = х; },
  };
}

/**
 * слойДанных({ канал? }) — слой «данные»: готовый RTCDataChannel от моста КС5.
 * Канала нет при открыть() — слой честно стоит в стороне (провод сигналит сам
 * не умеет и не притворяется).
 */
export function слойДанных(опции = {}) {
  const { канал = null } = опции;
  let обработчик = null;
  return {
    имя: 'данные',
    открыть() {
      if (!канал || typeof канал.send !== 'function') {
        throw new Error('mesh-wire: готового DataChannel нет — слой честно стоит в стороне (сигналинг дуэта — мост КС5)');
      }
      канал.onmessage = (событие) => {
        if (!обработчик) return;
        try { обработчик(JSON.parse(String(событие.data))); } catch (e) { /* мусор — мимо */ }
      };
      return канал;
    },
    отправить(ч, строка) { ч.send(строка); },
    закрыть(ч) { try { ч.close(); } catch (e) { /* уже закрыт */ } },
    приДанных(х) { обработчик = х; },
  };
}

/**
 * слойРелея({ адрес, WebSocketImpl?, эфир? }) — слой «релей»: JSON-эфир дома
 * поверх WebSocket к СВОЕМУ релею (КС8/этап 2). Адрес обязан быть wss://
 * (политика дома КС5: UI принимает только защищённый WebSocket; в пробах
 * инъекция WebSocketImpl, реальной сети нет).
 */
export function слойРелея(опции) {
  const { адрес, WebSocketImpl, эфир = 'singlyar-эфир/0.1' } = опции || {};
  честноСтрока(адрес, 'адрес релея');
  if (!/^wss:\/\//i.test(адрес) && !WebSocketImpl) {
    throw new TypeError('mesh-wire: релей принимает только wss:// (политика дома; в пробах — инъекция WebSocketImpl)');
  }
  let обработчик = null;
  return {
    имя: 'релей',
    открыть() {
      const Класс = WebSocketImpl ?? (typeof WebSocket !== 'undefined' ? WebSocket : null);
      if (!Класс) throw new Error('mesh-wire: WebSocket недоступен — слой честно стоит в стороне');
      const ч = new Класс(адрес);
      ч.onmessage = (событие) => {
        if (!обработчик) return;
        let сырое = null;
        try { сырое = JSON.parse(String(событие.data)); } catch { return; }
        if (сырое && typeof сырое === 'object' && сырое.эфир === эфир && сырое.конверт) {
          обработчик(сырое.конверт);
        }
      };
      return ч;
    },
    отправить(ч, строка) {
      if (ч.readyState !== undefined && ч.readyState !== 1) {
        throw new Error('mesh-wire: релей не открыт — конверт не ушёл (честно)');
      }
      ч.send(JSON.stringify({ эфир, конверт: JSON.parse(строка) }));
    },
    закрыть(ч) { try { ч.close(); } catch (e) { /* уже закрыт */ } },
    приДанных(х) { обработчик = х; },
  };
}

/* ── Провод ─────────────────────────────────────────────────────────────────── */

/**
 * создатьПровод({ слои }) → транспорт для createMesh (контракт mesh-core/0.1).
 * слои — массив объектов { имя, открыть, отправить(канал,строка), закрыть(канал),
 * приДанных(обработчик) }: встроенные — слойВещания/слойДанных/слойРелея,
 * инъекции — для проб. Порядок слоёв = порядок лестницы.
 */
export function создатьПровод(опции = {}) {
  const { слои } = опции || {};
  честноУсловие(!Array.isArray(слои) || слои.length === 0,
    'mesh-wire: слои обязательны — массив лестницы { имя, открыть, отправить, закрыть, приДанных }');
  const имена = слои.map((с) => с.имя);
  честноУсловие(имена.some((и) => typeof и !== 'string' || !и),
    'mesh-wire: у каждого слоя есть непустое имя');
  честноУсловие(new Set(имена).size !== имена.length,
    'mesh-wire: имена слоёв не повторяются');

  /** имя → { канал, статус } ; статусы из СТАТУСЫ */
  const состояние = new Map(слои.map((с) => [с.имя, { канал: null, статус: 'ждёт' }]));
  let открыт = false;
  let закрыт = false;
  let вход = null;

  function раздача(обработчик) { вход = обработчик; }

  function открыть() {
    честноУсловие(закрыт, 'mesh-wire: провод закрыт — новый создатьПровод нужен');
    if (открыт) return отчёт();
    открыт = true;
    for (const слой of слои) {
      const ячейка = состояние.get(слой.имя);
      слой.приДанных(function отСлоя(конверт) {
        if (вход && конверт && typeof конверт === 'object') вход(конверт);
      });
      try {
        ячейка.канал = слой.открыть();
        ячейка.статус = 'открыт';
      } catch (e) {
        ячейка.канал = null;
        ячейка.статус = 'отказ'; // слой в стороне — лестница жива (честный отчёт в состоянии())
      }
    }
    return отчёт();
  }

  function отправить(конверт) {
    честноУсловие(!открыт, 'mesh-wire: сеть не открыта — открывает только ядро по явному действию (И-01)');
    честноУсловие(закрыт, 'mesh-wire: провод закрыт');
    честноУсловие(конверт == null || typeof конверт !== 'object',
      'mesh-wire: конверт — объект (канон mesh-core/0.1)');
    const строка = JSON.stringify(конверт);
    const отчёт = {};
    for (const слой of слои) {
      const ячейка = состояние.get(слой.имя);
      if (ячейка.статус !== 'открыт') { отчёт[слой.имя] = 'закрыт'; continue; }
      try {
        слой.отправить(ячейка.канал, строка);
        отчёт[слой.имя] = 'отправлено';
      } catch (e) {
        отчёт[слой.имя] = 'отказ'; // слой умер после открытия — честно, без падения провода
      }
    }
    return отчёт;
  }

  function закрыть() {
    if (закрыт) return;
    закрыт = true;
    for (const слой of слои) {
      const ячейка = состояние.get(слой.имя);
      if (ячейка.канал) слой.закрыть(ячейка.канал);
      ячейка.канал = null;
      ячейка.статус = 'закрыт';
    }
  }

  function отчёт() {
    const сл = {};
    for (const [имя, ячейка] of состояние) сл[имя] = ячейка.статус;
    return Object.freeze({ схема: СХЕМА, открыто: открыт, слои: Object.freeze(сл) });
  }

  return Object.freeze({
    СХЕМА, ver,
    отправить, приПолучении: раздача, открыть, закрыть, состояние: отчёт,
  });
}
