// целиком на устройстве, данные не покидают дом». Закрытие — честные метрики:
// 0 случайности (антипример из лога владельца: чужой прототип клал
// случайные числа в «эмоции» — дом так не умеет), бенчмарки без часов (один вход → один выход, байт-в-байт),
