/* ── Метаданные схемы ───────────────────────────────────────────────────────── */

export const СХЕМА = 'mesh-core/0.1';
export const ВЕРСИЯ_ЯДРА = '0.1.0';

/** Окно дедупа: сколько последних ид конвертов помнит узел. */
export const ОКНО_ДЕДУПА = 512;

/** Типы конвертов провода (заморожено — провод не расширяется молча). */
export const ТИПЫ = Object.freeze(['join', 'join-ack', 'leave', 'say']);

function честноУсловие(условие, сообщение) {
  if (условие) throw new TypeError(сообщение);
}

function честноСтрока(значение, имя) {
  честноУсловие(typeof значение !== 'string' || значение.length === 0,
    `mesh-core: ${имя} обязана быть непустой строкой`);
}

/* ── Ядро узла ──────────────────────────────────────────────────────────────── */

/**
 * createMesh({ id, транспорт, часы? }) → узел Global Mesh.
 *
 * @param {{id:string, транспорт:object, часы?:()=>number}} опции
 *   id        — уникальное имя узла в эфире (не пустая строка);
 *   транспорт — подставленный провод: { отправить(конверт), приПолучении(обработчик),
 *               открыть?, закрыть? }; ядро вызывает открыть()/закрыть() только
 *               из присоединиться()/остановить(), «сеть по явному действию»;
 *   часы      — необязательная () => число; пишется в конверт.тс. Без часов тс нет.
 * @returns узел { id, схема, версии, комнаты, счётчики,
 *                  присоединиться, войти, сказать, выйти, на, остановить }
 */
export function createMesh(опции) {
  честноУсловие(опции == null || typeof опции !== 'object',
    'mesh-core: createMesh ждёт опции { id, транспорт, часы? }');
  const { id, транспорт, часы } = опции || {};
  честноСтрока(id, 'id узла');
  честноУсловие(транспорт == null || typeof транспорт !== 'object',
    'mesh-core: транспорт обязателен — ядро сеть сама не открывает (И-01)');
  честноУсловие(typeof транспорт.отправить !== 'function',
    'mesh-core: транспорт.отправить(конверт) обязателен');
  честноУсловие(typeof транспорт.приПолучении !== 'function',
    'mesh-core: транспорт.приПолучении(обработчик) обязателен');
  if (часы !== undefined) {
    честноУсловие(typeof часы !== 'function', 'mesh-core: часы — функция () => число, если поданы');
  }

  /** комнаты: имя → true (порядок вставки — детерминизм обхода) */
  const комнаты = new Map();
  /** виденное: Set последних ид (выветривание по ОКНО_ДЕДУПА) */
  const виденное = new Set();
  const порядокИд = [];
  let счётчик = 0;
  let остановлен = false;
  const слушатели = new Map(); // событие → Set(обработчик)
  const счётчики = { послано: 0, получено: 0, дубли: 0, чужое: 0, своё: 0, создано_ид: 0 };

  function эмит(событие, payload) {
    const набор = слушатели.get(событие);
    if (!набор) return;
    for (const обработчик of Array.from(набор)) обработчик(payload);
  }

  /** транспорт → ядро: единственная точка входа провода */
  транспорт.приПолучении(function приКонверте(сырое) {
    if (остановлен) return;
    честноУсловие(сырое == null || typeof сырое !== 'object',
      'mesh-core: транспорт принёс не конверт (объект ожидается)');
    счётчики.получено += 1;
    if (сырое.от === id) { счётчики.своё += 1; return; } // своё эхо в эфире — не событие
    const ид = сырое.ид;
    if (typeof ид === 'string' && ид.length > 0) {
      if (виденное.has(ид)) { счётчики.дубли += 1; return; }
      виденное.add(ид);
      порядокИд.push(ид);
      if (порядокИд.length > ОКНО_ДЕДУПА) {
        const старый = порядокИд.shift();
        виденное.delete(старый);
      }
    }
    const тип = сырое.тип;
    const комната = сырое.комната;
    if (!ТИПЫ.includes(тип)) { счётчики.чужое += 1; return; }
    if (typeof комната !== 'string' || комната.length === 0) { счётчики.чужое += 1; return; }

    if (тип === 'join') {
      const первыйВход = !комнаты.has(комната);
      if (первыйВход) комнаты.set(комната, true);
      // автоответ join-ack ТОЛЬКО на join — без шторма:
      послать('join-ack', комната, undefined, { вОтветНа: ид });
      эмит('присоединился', { от: сырое.от, комната, тс: сырое.тс, мыВошли: первыйВход });
      return;
    }
    if (тип === 'join-ack') {
      эмит('присоединился', { от: сырое.от, комната, тс: сырое.тс, мыВошли: комнаты.has(комната) });
      return;
    }
    if (тип === 'leave') {
      эмит('отсоединился', { от: сырое.от, комната, тс: сырое.тс });
      return;
    }
    // say
    if (!комнаты.has(комната)) { счётчики.чужое += 1; return; }
    эмит('сказано', { от: сырое.от, комната, данные: сырое.данные, тс: сырое.тс });
  });

  function послать(тип, комната, данные, доп = {}) {
    const конверт = { тип, комната, от: id, ид: `${id}:${++счётчик}` };
    счётчики.создано_ид += 1;
    if (данные !== undefined) конверт.данные = данные;
    if (часы) конверт.тс = часы();
    if (доп.вОтветНа) конверт.вОтветНа = доп.вОтветНа;
    транспорт.отправить(конверт);
    счётчики.послано += 1;
    return конверт;
  }

  return {
    id,
    схема: СХЕМА,
    версия: ВЕРСИЯ_ЯДРА,
    /** имена комнат, в которых узел стоит (детерминированный порядок) */
    get комнаты() { return Array.from(комнаты.keys()); },
    счётчики,

    /** открыть провод — явное действие хозяина (сеть по приказу, И-01) */
    присоединиться() {
      честноУсловие(остановлен, 'mesh-core: узел остановлен — новый createMesh нужен');
      if (typeof транспорт.открыть === 'function') транспорт.открыть();
    },

    /** войти в комнату: шлёт join; комната — непустая строка */
    войти(комната) {
      честноУсловие(остановлен, 'mesh-core: узел остановлен');
      честноСтрока(комната, 'комната');
      if (!комнаты.has(комната)) комнаты.set(комната, true);
      return послать('join', комната);
    },

    /** сказать в комнату: только изнутри комнаты — иначе честный отказ */
    сказать(комната, данные) {
      честноУсловие(остановлен, 'mesh-core: узел остановлен');
      честноСтрока(комната, 'комната');
      if (!комнаты.has(комната)) {
        throw new Error(`mesh-core: сказать «${комната}» нельзя — узел не в комнате`);
      }
      return послать('say', комната, данные);
    },

    /** выйти из комнаты: шлёт leave и снимает состояние */
    выйти(комната) {
      честноУсловие(остановлен, 'mesh-core: узел остановлен');
      честноСтрока(комната, 'комната');
      const был = комнаты.delete(комната);
      if (был) послать('leave', комната);
      return был;
    },

    /** подписка: на('сказано', cb) → функция отписки */
    на(событие, обработчик) {
      честноУсловие(остановлен, 'mesh-core: узел остановлен');
      честноСтрока(событие, 'событие');
      честноУсловие(typeof обработчик !== 'function', 'mesh-core: обработчик — функция');
      if (!слушатели.has(событие)) слушатели.set(событие, new Set());
      const набор = слушатели.get(событие);
      набор.add(обработчик);
      return function отписаться() { набор.delete(обработчик); };
    },

    /** остановить: leave по всем комнатам, закрытие провода, тишина после */
    остановить() {
      if (остановлен) return;
      остановлен = true;
      for (const имя of Array.from(комнаты.keys())) {
        комнаты.delete(имя);
        послать('leave', имя);
      }
      слушатели.clear();
      if (typeof транспорт.закрыть === 'function') транспорт.закрыть();
    },
  };
}

/* ── Эфир-помощник для тестов и локальных комнат (0 сети) ──────────────────── */

/**
 * создатьЭфир() → { засунуть, подписаться, конверты }
 * Детерминированный эфир в памяти: узлы, чьи транспорта подключены к одному
 * эфиру, слышат друг друга. Ни сети, ни BroadcastChannel — для проб и локальных
 * вкладок-комнат хост пишет свой провод (например, BroadcastChannel), ядро
 * семантику не меняет.
 */
export function создатьЭфир() {
  const приёмники = new Set();
  return {
    подписаться(обработчик) { приёмники.add(обработчик); return () => приёмники.delete(обработчик); },
    засунуть(конверт) { for (const п of Array.from(приёмники)) п(конверт); },
    get конверты() { return []; }, // история — забота теста, эфир её не хранит
  };
}

/** Транспорт-провод узла на эфире (в тестах; хост может повторить образец). */
export function проводНаЭфир(эфир) {
  return {
    отправить(конверт) { эфир.засунуть(конверт); },
    приПолучении(обработчик) { эфир.подписаться(обработчик); },
  };
}
