//
// КРИТЕРИЙ СТРОКИ (ЕДИНАЯ КАРТА, линия МЕТАШАНСОН · М6): «фолбэк источников дома
// (Pages → Release-архив → локальный кэш sw15) + проверка целостности» и
// «реестр источников + SHA-проверка + честная страница „источник не прошёл
// проверку"».
//
// Что делает модуль:
//   РЕЕСТР_ИСТОЧНИКОВ        — три источника дома в порядке честного фолбэка,
//                              у каждого названы сеть/закон (И-01: сеть только по
//                              явному действию) и чем проверяется целостность;
//   планВосстановления(запрос) — упорядоченные шаги восстановления файла с
//                              критерием перехода между источниками; никаких
//                              подмен — шаг либо назван, либо честный отказ;
//   сверитьSHA(байты, ожидаемый) — SHA-256 через crypto.subtle, hex-сравнение;
//                              ожидаемого SHA нет — подмена ЗАПРЕЩЕНА (честный
//                              отказ: «целостность неизвестна — не выдаю за живое»);
//   честныйОтказТекст(диагноз)   — строки для честной страницы (массив, без DOM);
//   рисоватьОтказ(фабрика, диагноз) — честная страница отказа через
//                              createElement/textContent (разметка словами — закон дома);
//                              фабрика — внедрённая зависимость (в браузере document,
//                              в тестах — минимальный дублер), поэтому страница
//                              проверяется тестом без живого браузера.
//
// Честные границы:
//   - модуль НЕ качает сам: план — это план; сеть открывает только человек
//     (явное действие), транспорт приносит готовые байты;
//   - без SHA в манифесте источник не «плохой» и не «хороший» — он НЕПРОВЕРЯЕМЫЙ,
//     и это честно названо (отказы не превращаются в метрики, пустота — не успех);
//   - 0 часов, 0 рандома, 0 сети на импорте; ledger — только пометки вызовов.

export const ВЕРСИЯ = 'самовосстановление/0.1';
export const LEDGER_SCHEMA = 'ladom.самовосстановление.v1';

const список = [];
function пометка(событие) { список.push({ схема: LEDGER_SCHEMA, событие }); }

export const РЕЕСТР_ИСТОЧНИКОВ = [
  {
    id: 'pages',
    имя: 'GitHub Pages (ветка main)',
    сеть: 'same-origin — та же страница, без внешних серверов',
    проверка: 'SHA-256 из манифеста дома (SHA256SUMS)',
    порядок: 1,
  },
  {
    id: 'release',
    имя: 'GitHub Releases · архив ARHIV-2026-10-13',
    сеть: 'github.com — ТОЛЬКО по явному действию человека (закон И-01)',
    проверка: 'SHA-256 из манифеста выпуска',
    порядок: 2,
  },
  {
    id: 'sw15',
    имя: 'локальный кэш sw15 (поколение из data/versions.json)',
    сеть: 'нет — кэш сервис-воркера дома',
    проверка: 'поколение кэша vNNN + SHA-256, если манифест вшит',
    порядок: 3,
  },
];

function честныйОтказ(почему) {
  пометка('отказ: ' + почему);
  return { ok: false, отказ: почему, версия: ВЕРСИЯ };
}

export function планВосстановления(запрос) {
  if (!запрос || typeof запрос !== 'object') return честныйОтказ('запроса нет');
  const файл = typeof запрос.файл === 'string' ? запрос.файл.trim() : '';
  if (!файл) return честныйОтказ('файл не назван — восстанавливать нечего');
  if (файл.includes('..') || файл.startsWith('/')) {
    return честныйОтказ('путь за пределами дома (' + файл + ') — план даёт только пути внутри дома');
  }
  const диагноз = typeof запрос.диагноз === 'string' && запрос.диагноз.trim() ? запрос.диагноз.trim() : 'без диагноза — источник не ответил';
  const источники = РЕЕСТР_ИСТОЧНИКОВ.slice().sort((a, b) => a.порядок - b.порядок);
  const шаги = источники.map((и, i) => ({
    шаг: i + 1,
    источник: и.id,
    имя: и.имя,
    откуда: и.сеть,
    какПроверяем: и.проверка,
    переходДальше: 'SHA не сошёлся или источник недоступен — честный отказ этого шага, переход к следующему',
  }));
  пометка('план: ' + файл + ' — ' + шаги.length + ' источника');
  return {
    ok: true,
    файл,
    диагноз,
    шаги,
    итоговыйОтказ: 'все источники не прошли — дом говорит правду: файл сейчас недоступен, никаких подмен',
    версия: ВЕРСИЯ,
  };
}

function hex(buffer) {
  const б = new Uint8Array(buffer);
  let s = '';
  for (let i = 0; i < б.length; i++) s += б[i].toString(16).padStart(2, '0');
  return s;
}

export async function сверитьSHA(байты, ожидаемый) {
  if (!(байты instanceof Uint8Array) || байты.length === 0) return честныйОтказ('байтов нет — сверять нечего');
  if (typeof ожидаемый !== 'string' || ожидаемый.trim() === '') {
    return честныйОтказ('ожидаемый SHA не назван — целостность неизвестна, подмена запрещена');
  }
  if (!глобальныйCrypto()) return честныйОтказ('crypto.subtle недоступен в этой среде — проверка честно не выполнена');
  const дайджест = await глобальныйCrypto().subtle.digest('SHA-256', байты);
  const факт = hex(дайджест);
  const ожид = ожидаемый.trim().toLowerCase();
  const сошёлся = факт === ожид;
  пометка('SHA: ' + (сошёлся ? 'сошёлся' : 'РАСХОЖДЕНИЕ'));
  return { ok: true, сошёлся, факт, ожидаемый: ожид, версия: ВЕРСИЯ };
}

function глобальныйCrypto() {
  return (typeof crypto !== 'undefined' && crypto && crypto.subtle) ? crypto : null;
}

// ——— честная страница отказа ————————————————————————————————————————————

export function честныйОтказТекст(диагноз) {
  const план = планВосстановления(диагноз && диагноз.файл ? диагноз : { файл: (диагноз && диагноз.файл) || '' });
  if (!план.ok) return { ok: false, отказ: план.отказ, версия: ВЕРСИЯ };
  const строки = [
    'Источник не прошёл проверку — дом говорит правду.',
    'Файл: ' + план.файл,
    'Диагноз: ' + план.диагноз,
    'Порядок восстановления:',
  ];
  for (const ш of план.шаги) {
    строки.push('  ' + ш.шаг + '. ' + ш.имя + ' — проверка: ' + ш.какПроверяем + ' (' + ш.откуда + ')');
  }
  строки.push(план.итоговыйОтказ);
  return { ok: true, строки, версия: ВЕРСИЯ };
}

export function рисоватьОтказ(фабрика, диагноз) {
  if (!фабрика || typeof фабрика.createElement !== 'function') return честныйОтказ('фабрика DOM не передана');
  const текст = честныйОтказТекст(диагноз);
  if (!текст.ok) return честныйОтказ(текст.отказ);
  const узел = фабрика.createElement('div');
  узел.setAttribute('role', 'note');
  узел.setAttribute('aria-label', 'Источник не прошёл проверку');
  for (const s of текст.строки) {
    const p = фабрика.createElement('p');
    p.textContent = s; // только текст-узлы — закон дома
    узел.appendChild(p);
  }
  пометка('честная страница построена: ' + текст.строки.length + ' строк');
  return { ok: true, узел, версия: ВЕРСИЯ };
}

export function журнал() { return список.slice(); }
