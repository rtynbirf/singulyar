/*
 * ценность-ядро/0.1 — «VALUE-FOR-VALUE»: честное распределение ценности меташансона.
 *
 * Назначение: слой М3. Рецепт дома: 50% автор / 10% переводчик / 20% слушатели /
 * 15% сеть / 5% резерв. Канон распределяет целую сумму минорных единиц (копейки/
 * сатоши-класс) методом НАИБОЛЬШЕГО ОСТАТКА: базовая доля = floor(сумма×доля/100),
 * недостающие единицы идут категориям с наибольшей дробной частью; тай-брейк —
 * канонический порядок ключей (автор, переводчик, слушатели, сеть, резерв).
 * Сумма долей равна сумме РОВНО. Дробные минорные единицы не переводятся —
 * честный RangeError. Деньги выходят только с внешней подписью: подписатьДолю
 * канонизирует долю (стабильный JSON) и зовёт наружного подписанта.
 *
 * Законы дома (нарушать нельзя — это шрамы прежних тактов):
 *   0 сети                — канон никогда не обращается в сеть (fetch/XHR/WebSocket под запретом);
 *   0 случайности         — одинаковый вход даёт одинаковый выход (Math.random запрещён);
 *   0 часов               — время не вызывается никогда (Date.now/performance.now запрещены;
 *                           время — только аргументом);
 *   вход не мутируется    — канон не меняет свои аргументы;
 *   честные русские отказы — на неверный вход RangeError/TypeError/Error с русским сообщением,
 *                           никогда молчаливые undefined/null;
 *   русские имена         — функции и переменные канона говорят по-русски.
 *
 * такт v11.47 «ЗАКРЫТИЕ» (С125)
 */

/* ── канонический порядок ключей долей: фиксирован навсегда ─────────────── */

const КЛЮЧИ_ДОЛЕЙ = ['автор', 'переводчик', 'слушатели', 'сеть', 'резерв'];

/* ── рецепт дома: пять долей, дающих ровно 100; заморожен — не обсуждается ── */

export const РЕЦЕПТ = Object.freeze({
  автор: 50,
  переводчик: 10,
  слушатели: 20,
  сеть: 15,
  резерв: 5,
});

/* ── проверка рецепта ────────────────────────────────────────────────────── */

// Любое нарушение формы или суммы рецепта — честный отказ. Сумма долей обязана
// давать ровно 100: иначе канон не берётся угадывать, кому недостаёт.
function проверитьРецепт(рецепт) {
  if (рецепт === null || typeof рецепт !== 'object' || Array.isArray(рецепт)) {
    throw new TypeError('рецепт должен быть объектом с пятью долями: автор, переводчик, слушатели, сеть, резерв');
  }
  let сумма = 0;
  for (let индекс = 0; индекс < КЛЮЧИ_ДОЛЕЙ.length; индекс += 1) {
    const ключ = КЛЮЧИ_ДОЛЕЙ[индекс];
    const доля = рецепт[ключ];
    if (доля === undefined) {
      throw new RangeError('рецепт не сходится: доли должны давать 100');
    }
    if (typeof доля !== 'number' || Number.isNaN(доля)) {
      throw new TypeError('доля «' + ключ + '» в рецепте должна быть числом');
    }
    if (!Number.isInteger(доля) || доля < 0) {
      throw new RangeError('рецепт не сходится: доли должны давать 100');
    }
    сумма += доля;
  }
  const имена = Object.keys(рецепт);
  for (let индекс = 0; индекс < имена.length; индекс += 1) {
    if (КЛЮЧИ_ДОЛЕЙ.indexOf(имена[индекс]) === -1) {
      throw new RangeError('в рецепте лишний ключ «' + имена[индекс] + '»: канон знает ровно пять долей');
    }
  }
  if (сумма !== 100) {
    throw new RangeError('рецепт не сходится: доли должны давать 100');
  }
}

/* ── распределение ───────────────────────────────────────────────────────── */

export function распределить(сумма, рецепт = РЕЦЕПТ) {
  if (typeof сумма !== 'number' || Number.isNaN(сумма)) {
    throw new TypeError('сумма должна быть числом минорных единиц (копейки/сатоши-класс)');
  }
  if (!Number.isFinite(сумма)) {
    throw new RangeError('сумма должна быть конечным числом');
  }
  if (!Number.isInteger(сумма)) {
    throw new RangeError('сумма должна быть целым числом минорных единиц: дробные копейки не переводим');
  }
  if (сумма < 0) {
    throw new RangeError('сумма не может быть отрицательной');
  }
  if (сумма > Number.MAX_SAFE_INTEGER) {
    throw new RangeError('сумма превышает Number.MAX_SAFE_INTEGER: канон не рискует точностью');
  }
  проверитьРецепт(рецепт);

  // Точная арифметика без BigInt: сумма = 100×q + хвост, где q = floor(сумма/100),
  // хвост = сумма mod 100. Тогда floor(сумма×доля/100) = q×доля + floor(хвост×доля/100),
  // и все слагаемые строго меньше 2^53 (q ≤ (2^53−1)/100, q×доля ≤ q×100 < 2^53).
  const целыхСотен = Math.floor(сумма / 100);
  const хвост = сумма % 100;

  const базы = {};
  const остатки = [];
  for (let индекс = 0; индекс < КЛЮЧИ_ДОЛЕЙ.length; индекс += 1) {
    const ключ = КЛЮЧИ_ДОЛЕЙ[индекс];
    const доля = рецепт[ключ];
    базы[ключ] = целыхСотен * доля + Math.floor((хвост * доля) / 100);
    остатки.push({ ключ: ключ, индекс: индекс, дробь: (хвост * доля) % 100 });
  }

  // Сколько единиц ещё не разделено (в точности сумма дробных частей).
  let нераздано = сумма;
  for (let индекс = 0; индекс < КЛЮЧИ_ДОЛЕЙ.length; индекс += 1) {
    нераздано -= базы[КЛЮЧИ_ДОЛЕЙ[индекс]];
  }

  // Наибольший остаток вперёд; тай-брейк — канонический порядок ключей.
  остатки.sort(function (левое, правое) {
    return (правое.дробь - левое.дробь) || (левое.индекс - правое.индекс);
  });

  const доли = {};
  for (let индекс = 0; индекс < КЛЮЧИ_ДОЛЕЙ.length; индекс += 1) {
    доли[КЛЮЧИ_ДОЛЕЙ[индекс]] = базы[КЛЮЧИ_ДОЛЕЙ[индекс]];
  }
  for (let индекс = 0; индекс < остатки.length && нераздано > 0; индекс += 1, нераздано -= 1) {
    доли[остатки[индекс].ключ] += 1;
  }

  // Поле «остаток» честное: сумма минус фактически розданное.
  let роздано = 0;
  for (let индекс = 0; индекс < КЛЮЧИ_ДОЛЕЙ.length; индекс += 1) {
    роздано += доли[КЛЮЧИ_ДОЛЕЙ[индекс]];
  }

  return { доли: доли, остаток: сумма - роздано, версия: 'ценность-ядро/0.1' };
}

/* ── канонизировать: стабильный JSON с рекурсивной сортировкой ключей ────── */

// Сортировка ключей — по кодовым единицам UTF-16 (Array.prototype.sort без
// компаратора). Массивы хранят порядок. Циклы, NaN/Infinity, undefined,
// функции и символы — честные русские отказы, никакого молчаливого искажения.
function каноничнаяСтрока(значение, путь, увиденное) {
  if (значение === null) {
    return 'null';
  }
  const вид = typeof значение;
  if (вид === 'string') {
    return JSON.stringify(значение);
  }
  if (вид === 'boolean') {
    return значение ? 'true' : 'false';
  }
  if (вид === 'number') {
    if (Number.isNaN(значение) || !Number.isFinite(значение)) {
      throw new RangeError('канонизировать не принимает NaN и Infinity: это не JSON');
    }
    return JSON.stringify(значение);
  }
  if (вид !== 'object') {
    throw new TypeError('канонизировать принимает только JSON-значения (строка, число, булево, null, массив, объект), а получено: ' + вид);
  }
  for (let индекс = 0; индекс < увиденное.length; индекс += 1) {
    if (увиденное[индекс] === значение) {
      throw new RangeError('канонизировать нашёл циклическую ссылку по пути «' + путь.join('.') + '»: канонической строки не построить');
    }
  }
  увиденное.push(значение);
  let части;
  if (Array.isArray(значение)) {
    части = [];
    for (let индекс = 0; индекс < значение.length; индекс += 1) {
      части.push(каноничнаяСтрока(значение[индекс], путь.concat([индекс]), увиденное));
    }
    увиденное.pop();
    return '[' + части.join(',') + ']';
  }
  const ключи = Object.keys(значение).sort();
  части = [];
  for (let индекс = 0; индекс < ключи.length; индекс += 1) {
    const ключ = ключи[индекс];
    const вложенное = значение[ключ];
    if (вложенное === undefined) {
      throw new TypeError('канонизировать нашёл undefined по пути «' + путь.concat([ключ]).join('.') + '»: undefined — это не JSON');
    }
    части.push(JSON.stringify(ключ) + ':' + каноничнаяСтрока(вложенное, путь.concat([ключ]), увиденное));
  }
  увиденное.pop();
  return '{' + части.join(',') + '}';
}

export function канонизировать(значение) {
  return каноничнаяСтрока(значение, [], []);
}

/* ── внешняя подпись доли ────────────────────────────────────────────────── */

// Канон не знает ключей: он канонизирует долю и передаёт строку наружному
// подписанту (WebCrypto/сервер/что угодно). Деньги без подписи не выходят.
// Возвращает промис { канонСтрока, подпись } — подписано ровно то, что видно.
export function подписатьДолю(доля, подписант) {
  if (typeof подписант !== 'function') {
    throw new TypeError('подписант не передан: деньги без подписи не выходят');
  }
  if (доля === null || typeof доля !== 'object' || Array.isArray(доля)) {
    throw new TypeError('доля должна быть объектом долей (например, результат распределить)');
  }
  const канонСтрока = канонизировать(доля);
  let ответПодписанта;
  try {
    ответПодписанта = подписант(канонСтрока);
  } catch (отказ) {
    return Promise.reject(отказ);
  }
  return Promise.resolve(ответПодписанта).then(function (подпись) {
    return { канонСтрока: канонСтрока, подпись: подпись };
  });
}
