import { fnv1a, бакет, собрать } from '../src/агрегат-ядро.mjs';

/* ── FNV-1a и бакет ──────────────────────────────────────────────────────── */
test('fnv1a: известные векторы и детерминизм', () => {
  assert.equal(fnv1a(''), 0x811c9dc5);
  assert.equal(fnv1a('a'), 0xe40c292c);
  assert.equal(fnv1a('борода'), fnv1a('борода'));
  assert.equal(typeof fnv1a('x'), 'number');
});

test('бакет: детерминирован, в диапазоне, соль меняет расклад', () => {
  for (let i = 0; i < 100; i += 1) {
    const б = бакет('участник-' + i, 'соль-такта', 12);
    assert.ok(б >= 0 && б < 12);
    assert.equal(б, бакет('участник-' + i, 'соль-такта', 12));
  }
  const разные = new Set();
  for (let i = 0; i < 40; i += 1) разные.add(бакет('a', 'соль' + i, 100));
  assert.ok(разные.size > 1, 'соль должна менять расклад');
});

test('бакет: честные отказы', () => {
  assert.throws(() => бакет(42, 'соль', 10), TypeError);
  assert.throws(() => бакет('', 'соль', 10), RangeError);
  assert.throws(() => бакет('ид', 10, 10), TypeError);
  assert.throws(() => бакет('ид', 'соль', 0), RangeError);
  assert.throws(() => бакет('ид', 'соль', 1.5), RangeError);
});

/* ── k-анонимная сборка ──────────────────────────────────────────────────── */
test('собрать: категории ≥ k идут наружу, < k скрыты', () => {
  const события = [
    { категория: 'пение' }, { категория: 'пение' }, { категория: 'пение' },
    { категория: 'пение' }, { категория: 'пение' },                       // 5 == k
    { категория: 'слушание' }, { категория: 'слушание' },                  // 2 < k
    { категория: 'тишина' }, { категория: 'тишина' }, { категория: 'тишина' },
    { категория: 'тишина' }, { категория: 'тишина' }, { категория: 'тишина' },
    { категория: 'тишина' }, { категория: 'тишина' }, { категория: 'тишина' }, // 9
  ];
  const р = собрать(события, { k: 5 });
  assert.deepEqual(р.агрегат, { пение: 5, тишина: 9 });
  assert.deepEqual(р.скрыто, { слушание: 'меньше k' });
  assert.equal(р.k, 5);
  assert.equal(р.всего, 16);
  assert.equal(р.вырожден, false);
});

test('собрать: вырожденный агрегат — честная пометка, не выдумка', () => {
  const р = собрать([{ категория: 'а' }, { категория: 'б' }], { k: 5 });
  assert.deepEqual(р.агрегат, {});
  assert.deepEqual(р.скрыто, { а: 'меньше k', б: 'меньше k' });
  assert.equal(р.вырожден, true);
});

test('собрать: порядок ключей агрегата детерминирован', () => {
  const события = [];
  for (let i = 0; i < 6; i += 1) события.push({ категория: 'якорь' });
  for (let i = 0; i < 6; i += 1) события.push({ категория: 'база' });
  const а = JSON.stringify(собрать(события));
  const б = JSON.stringify(собрать(события.slice().reverse()));
  const к = JSON.parse(а);
  const м = JSON.parse(б);
  assert.deepEqual(Object.keys(к.агрегат).sort(), Object.keys(м.агрегат).sort());
  assert.deepEqual(к.агрегат, м.агрегат);
});

test('собрать: внедрённая категоризация работает', () => {
  const события = [{ час: 1 }, { час: 1 }, { час: 1 }, { час: 1 }, { час: 1 }, { час: 2 }];
  const р = собрать(события, { категоризация: (с) => 'час-' + с.час, k: 5 });
  assert.deepEqual(р.агрегат, { 'час-1': 5 });
  assert.deepEqual(р.скрыто, { 'час-2': 'меньше k' });
});

test('собрать: недетерминированная категоризация — честный TypeError', () => {
  let счёт = 0;
  assert.throws(() => собрать([{ категория: 'x' }], { категоризация: () => (счёт += 1) + '' }), TypeError);
});

test('собрать: закон «наружу только агрегат» — исходных идов в результате нет', () => {
  const события = [];
  for (let i = 0; i < 6; i += 1) события.push({ категория: 'пение', личность: 'секрет-' + i });
  const р = собрать(события, { k: 5 });
  const строка = JSON.stringify(р);
  for (let i = 0; i < 6; i += 1) {
    assert.ok(!строка.includes('секрет-' + i), 'личность утекла в агрегат!');
  }
});

test('собрать: честные отказы', () => {
  assert.throws(() => собрать('мусор'), TypeError);
  assert.throws(() => собрать([{ категория: '' }]), RangeError);
  assert.throws(() => собрать([{ категория: 5 }]), RangeError);
  assert.throws(() => собрать([42]), TypeError);
  assert.throws(() => собрать([{ категория: 'а' }], { k: 0 }), RangeError);
  assert.throws(() => собрать([{ категория: 'а' }], { k: 1.5 }), RangeError);
  assert.throws(() => собрать([{ категория: 'а' }], { категоризация: 'не функция' }), TypeError);
});

test('собрать: немутация и детерминизм', () => {
  const события = [{ категория: 'а' }, { категория: 'а' }, { категория: 'а' }, { категория: 'а' }, { категория: 'а' }];
  const копия = JSON.stringify(события);
  const а = JSON.stringify(собрать(события));
  const б = JSON.stringify(собрать(события));
  assert.equal(JSON.stringify(события), копия);
  assert.equal(а, б);
});

/* ── Порт ≡ канон (vm) ───────────────────────────────────────────────────── */
test('порт aggregate-core.js ≡ канон', async () => {
  const кодПорта = await readFile(join(dirname(fileURLToPath(import.meta.url)), '../../../../js/aggregate-core.js'), 'utf8');
  const песочница = { window: {}, console };
  vm.createContext(песочница);
  vm.runInContext(кодПорта, песочница, { filename: '../../../../js/aggregate-core.js' });
  const порт = песочница.window.__АГРЕГАТ;
  assert.ok(порт, 'порт не поставил __АГРЕГАТ');

  assert.equal(порт.fnv1a(''), fnv1a(''));
  assert.equal(порт.fnv1a('караоке'), fnv1a('караоке'));
  assert.equal(порт.бакет('узел', 'соль', 9), бакет('узел', 'соль', 9));

  const векторы = [
    [{ категория: 'а' }, { категория: 'а' }, { категория: 'а' }, { категория: 'а' }, { категория: 'а' }],
    [{ категория: 'а' }, { категория: 'б' }],
    [{ категория: 'пение' }, { категория: 'пение' }, { категория: 'пение' }, { категория: 'пение' }, { категория: 'пение' }, { категория: 'тишина' }],
  ];
  for (const в of векторы) {
    const к = JSON.stringify(собрать(в.map((с) => ({ ...с }))));
    const п = JSON.stringify(порт.собрать(в.map((с) => ({ ...с }))));
    assert.equal(п, к);
  }
  // с k
  const к7 = JSON.stringify(собрать(векторы[2], { k: 6 }));
  const п7 = JSON.stringify(порт.собрать(векторы[2], { k: 6 }));
  assert.equal(п7, к7);
  // отказы: имя+сообщение
  const случаи = ['мусор', [{ категория: '' }], [42]];
  for (const с of случаи) {
    let оКан = null, оПор = null;
    try { собрать(JSON.parse(JSON.stringify(с))); } catch (е) { оКан = е; }
    try { порт.собрать(JSON.parse(JSON.stringify(с))); } catch (е) { оПор = е; }
    assert.ok(оКан && оПор);
    assert.equal(оПор.message, оКан.message);
  }
  // идиомпотентность
  assert.equal(JSON.stringify(порт.собрать(векторы[0])), JSON.stringify(порт.собрать(векторы[0])));
});
