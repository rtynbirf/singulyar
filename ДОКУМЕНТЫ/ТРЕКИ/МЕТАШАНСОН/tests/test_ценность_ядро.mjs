/* ── 1. Рецепт-константа ─────────────────────────────────────────────────── */
test('РЕЦЕПТ дома: 50/10/20/15/5 и заморожен', () => {
  assert.deepEqual({ ...РЕЦЕПТ }, { автор: 50, переводчик: 10, слушатели: 20, сеть: 15, резерв: 5 });
  assert.equal(Object.isFrozen(РЕЦЕПТ), true);
});

/* ── 2. Точность распределения ───────────────────────────────────────────── */
test('распределить 100: ровно 50/10/20/15/5', () => {
  const р = распределить(100);
  assert.deepEqual(р.доли, { автор: 50, переводчик: 10, слушатели: 20, сеть: 15, резерв: 5 });
  assert.equal(р.остаток, 0);
  assert.equal(р.версия, 'ценность-ядро/0.1');
});

test('распределить 1: единица уходит автору (наибольший остаток, тай-брейк канонического порядка)', () => {
  const р = распределить(1);
  assert.equal(р.доли.автор, 1);
  assert.equal(р.доли.переводчик, 0);
  assert.equal(р.доли.слушатели, 0);
  assert.equal(р.доли.сеть, 0);
  assert.equal(р.доли.резерв, 0);
  assert.equal(р.остаток, 0);
});

test('распределить 7: сумма долей == 7 ровно', () => {
  const р = распределить(7);
  const с = Object.values(р.доли).reduce((a, b) => a + b, 0);
  assert.equal(с, 7);
  assert.equal(р.остаток, 0);
});

test('распределить 0: все нули', () => {
  const р = распределить(0);
  assert.deepEqual(р.доли, { автор: 0, переводчик: 0, слушатели: 0, сеть: 0, резерв: 0 });
});

test('распределить 999: детерминированный наибольший остаток', () => {
  const р = распределить(999);
  const с = Object.values(р.доли).reduce((a, b) => a + b, 0);
  assert.equal(с, 999);
  // рука: базовые floor(999*д/100): 499, 99, 199, 149, 49 = 995; нераздано 4;
  // дроби: 990%100=90? — считаем честно: 999*50=49950 → база 499, дробь 50;
  // 999*10=9990 → 99, дробь 90; 999*20=19980 → 199, дробь 80; 999*15=14985 → 149, дробь 85; 999*5=4995 → 49, дробь 95.
  // наибольшие дроби: 95(резерв), 90(переводчик), 85(сеть), 80(слушатели) → +1 каждому из четырёх.
  assert.deepEqual(р.доли, { автор: 499, переводчик: 100, слушатели: 200, сеть: 150, резерв: 50 });
});

test('инвариант суммы на 1000 детерминированных суммах', () => {
  for (let i = 0; i < 1000; i += 1) {
    const сумма = (i * 7919) % 1000000000;
    const р = распределить(сумма);
    const с = Object.values(р.доли).reduce((a, b) => a + b, 0);
    assert.equal(с + р.остаток, сумма, 'сумма разошлась на ' + сумма);
  }
});

test('свой рецепт тоже работает: 100/0/0/0/0', () => {
  const р = распределить(50, { автор: 100, переводчик: 0, слушатели: 0, сеть: 0, резерв: 0 });
  assert.deepEqual(р.доли, { автор: 50, переводчик: 0, слушатели: 0, сеть: 0, резерв: 0 });
});

/* ── 3. Честные отказы ───────────────────────────────────────────────────── */
test('отказы суммы: не число / дробное / отрицательное / бесконечность / переполнение', () => {
  assert.throws(() => распределить('100'), TypeError);
  assert.throws(() => распределить(NaN), TypeError);
  assert.throws(() => распределить(10.5), RangeError);
  assert.throws(() => распределить(-1), RangeError);
  assert.throws(() => распределить(Infinity), RangeError);
  assert.throws(() => распределить(Number.MAX_SAFE_INTEGER + 1), RangeError);
});

test('отказы рецепта: не сходится / лишний ключ / не число', () => {
  assert.throws(() => распределить(100, { автор: 60, переводчик: 10, слушатели: 20, сеть: 15, резерв: 5 }), RangeError);
  assert.throws(() => распределить(100, { автор: 50, переводчик: 10, слушатели: 20, сеть: 15 }), RangeError);
  assert.throws(() => распределить(100, { автор: 50, переводчик: 10, слушатели: 20, сеть: 15, резерв: 4, бонус: 1 }), RangeError);
  assert.throws(() => распределить(100, { автор: '50', переводчик: 10, слушатели: 20, сеть: 15, резерв: 5 }), TypeError);
});

/* ── 4. Немутация и детерминизм ──────────────────────────────────────────── */
test('вход не мутируется, двойной вызов байт-в-байт', () => {
  const рецепт = { автор: 50, переводчик: 10, слушатели: 20, сеть: 15, резерв: 5 };
  const копия = JSON.stringify(рецепт);
  const а = распределить(12345, рецепт);
  const б = распределить(12345, рецепт);
  assert.equal(JSON.stringify(рецепт), копия);
  assert.equal(JSON.stringify(а), JSON.stringify(б));
});

/* ── 5. канонизировать ───────────────────────────────────────────────────── */
test('канонизация: ключи отсортированы рекурсивно', () => {
  assert.equal(канонизировать({ b: 1, a: 2 }), '{"a":2,"b":1}');
  assert.equal(канонизировать({ z: { y: 1, x: [3, { b: 2, a: 1 }] } }), '{"z":{"x":[3,{"a":1,"b":2}],"y":1}}');
  assert.equal(канонизировать([]), '[]');
});

test('канонизация: честные отказы на не-JSON', () => {
  assert.throws(() => канонизировать(undefined), TypeError);
  assert.throws(() => канонизировать(NaN), RangeError);
  const цикл = {}; цикл.я = цикл;
  assert.throws(() => канонизировать(цикл), RangeError);
});

/* ── 6. подписатьДолю ────────────────────────────────────────────────────── */
test('подпись доли: фейковый подписант получает полный канон', async () => {
  const р = распределить(100);
  const видели = [];
  const подписант = async (строка) => { видели.push(строка); return 'sig:' + строка.length; };
  const ответ = await подписатьДолю(р.доли, подписант);
  assert.equal(видели.length, 1);
  assert.equal(ответ.канонСтрока, видели[0]);
  assert.equal(ответ.подпись, 'sig:' + ответ.канонСтрока.length);
  assert.ok(ответ.канонСтрока.includes('"автор"'));
});

test('подпись доли: без подписанта честный TypeError', () => {
  assert.throws(() => подписатьДолю({ автор: 1 }), TypeError);
  assert.throws(() => подписатьДолю('доля', () => {}), TypeError);
});

/* ── 7. Порт ≡ канон (vm) ────────────────────────────────────────────────── */
test('порт value-core.js ≡ канон на 15+ векторах', async () => {
  const кодПорта = await readFile(join(dirname(fileURLToPath(import.meta.url)), '../../../../js/value-core.js'), 'utf8');
  const песочница = { window: {}, console };
  vm.createContext(песочница);
  vm.runInContext(кодПорта, песочница, { filename: '../../../../js/value-core.js' });
  const порт = песочница.window.__ЦЕННОСТЬ;
  assert.ok(порт, 'порт не поставил __ЦЕННОСТЬ');

  const векторы = [0, 1, 7, 99, 100, 123, 456, 999, 1000, 12345, 99999, 100000, 500050, 999999999, 123456789];
  for (const в of векторы) {
    const кан = JSON.stringify(распределить(в));
    const по = JSON.stringify(порт.распределить(в));
    assert.equal(по, кан, 'расхождение на сумме ' + в);
  }
  // отказы: имя+сообщение
  const случаи = [10.5, -3, 'x', NaN];
  for (const с of случаи) {
    let оКан = null, оПор = null;
    try { распределить(с); } catch (е) { оКан = е; }
    try { порт.распределить(с); } catch (е) { оПор = е; }
    assert.ok(оКан && оПор, 'оба должны отказать на ' + с);
    assert.equal(оПор.name, оКан.name);
    assert.equal(оПор.message, оКан.message);
  }
  // рецепт-отказ (сумма долей != 100)
  let окКан = null, окПор = null;
  try { распределить(100, { автор: 98, переводчик: 1, слушатели: 0, сеть: 0, резерв: 0 }); } catch (е) { окКан = е; }
  try { порт.распределить(100, { автор: 98, переводчик: 1, слушатели: 0, сеть: 0, резерв: 0 }); } catch (е) { окПор = е; }
  assert.ok(окКан && окПор, 'оба должны отказать на несходящемся рецепте');
  assert.equal(окПор.message, окКан.message);
  // идиомпотентность порта
  assert.equal(JSON.stringify(порт.распределить(100)), JSON.stringify(порт.распределить(100)));
});
