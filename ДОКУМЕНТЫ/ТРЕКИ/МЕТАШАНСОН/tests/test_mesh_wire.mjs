/** шина в памяти: слои одного воздуха слышат друг друга (0 сети, своё не возвращается) */
function шина() {
  const участники = new Set();
  return {
    слой(имя) {
      const канал = { _обработчик: null, _получи(строка) { if (канал._обработчик) канал._обработчик(строка); } };
      const слой = {
        имя,
        открыть() { участники.add(канал); слой._канал = канал; return канал; },
        отправить(_канал, строка) {
          for (const ч of [...участники]) {
            if (ч === канал) continue;
            setTimeout(() => ч._получи(строка), 0);
          }
        },
        закрыть(ч) { участники.delete(ч); },
        приДанных(х) { канал._обработчик = (сырое) => { try { х(JSON.parse(сырое)); } catch (e) { /* мусор мимо */ } }; },
      };
      return слой;
    },
    /** ручная доставка строки в канал слоя (для дедупа/петли) */
    отправьВ(слой, строка) { setTimeout(() => слой._канал._получи(строка), 0); },
  };
}

class ФальшивыйWebSocket {
  constructor(адрес) { this.адрес = адрес; this.readyState = 1; this.onmessage = null; this.послано = []; ФальшивыйWebSocket.все.push(this); }
  send(строка) { this.послано.push(строка); }
  close() { this.readyState = 3; }
}
ФальшивыйWebSocket.все = [];
const сброс = () => { ФальшивыйWebSocket.все = []; };

const пауза = (мс = 8) => new Promise((р) => setTimeout(р, мс));

/* ── пробы ──────────────────────────────────────────────────────────────────── */

test('метаданные канона', () => {
  assert.equal(ver, 'mesh-wire/0.1');
  assert.equal(СХЕМА, 'mesh-wire/0.1');
  assert.deepEqual([...СЛОИ], ['вещание', 'данные', 'релей']);
});

test('0 сети при импорте: до открыть() отправить кидает честный TypeError', () => {
  const воздух = шина();
  const провод = создатьПровод({ слои: [воздух.слой('эфир')] });
  assert.throws(() => провод.отправить({ тип: 'join', комната: 'зал', от: 'а', ид: 'а:1' }), /сеть не открыта/);
  const ст = провод.состояние();
  assert.equal(ст.открыто, false);
  assert.equal(ст.слои['эфир'], 'ждёт');
});

test('структурные честные отказы фабрики провода', () => {
  assert.throws(() => создатьПровод({}), /слои обязательны/);
  assert.throws(() => создатьПровод({ слои: [] }), /слои обязательны/);
  const воздух = шина();
  assert.throws(() => создатьПровод({ слои: [{ имя: '', открыть() {} }] }), /непустое имя/);
  assert.throws(() => создатьПровод({ слои: [воздух.слой('а'), воздух.слой('а')] }), /не повторяются/);
  assert.throws(() => слойРелея({ адрес: 'ws://небезопасно' }), /только wss/);
  assert.throws(() => слойРелея({ адрес: '' }), /непустой строкой/);
});

test('лестница деградирует честно: отказ слоя ≠ отказ провода', async () => {
  сброс();
  const провод = создатьПровод({
    слои: [
      слойВещания({}),                                   // в Node BC нет → честный отказ
      слойДанных({ канал: null }),                       // канала нет → честный отказ
      слойРелея({ адрес: 'wss://релей.дома/эфир', WebSocketImpl: ФальшивыйWebSocket }), // жив
    ],
  });
  const ст = провод.открыть();
  // честность среды: в Node 18+ BroadcastChannel — глобальный, слой жив;
  // в средах без BC слой честно отказал бы ('отказ'). Проверяем ОБЕ правды:
  assert.ok(['открыт', 'отказ'].includes(ст.слои['вещание']), 'вещание: открыт или честный отказ');
  assert.equal(ст.слои['данные'], 'отказ');
  assert.equal(ст.слои['релей'], 'открыт');
  const отчёт = провод.отправить({ тип: 'join', комната: 'зал', от: 'узел', ид: 'узел:1' });
  assert.equal(отчёт['релей'], 'отправлено');
  assert.equal(отчёт['данные'], 'закрыт');
  assert.equal(отчёт['вещание'], ст.слои['вещание'] === 'открыт' ? 'отправлено' : 'закрыт');
  провод.закрыть(); // не держим эфир — 0 сети после пробы
  assert.equal(ФальшивыйWebSocket.все[0].послано.length, 1);
  const сырое = JSON.parse(ФальшивыйWebSocket.все[0].послано[0]);
  assert.equal(сырое.эфир, 'singlyar-эфир/0.1');   // релей шлёт конверт эфира
  assert.equal(сырое.конверт.тип, 'join');
  await пауза();
});

test('полный контур с ядром: join → say → leave, своё эхо отброшено', async () => {
  const воздух = шина();
  const проводА = создатьПровод({ слои: [воздух.слой('воздух')] });
  const проводБ = создатьПровод({ слои: [воздух.слой('воздух')] });
  const узелА = createMesh({ id: 'Аня', транспорт: проводА, часы: () => 1 });
  const узелБ = createMesh({ id: 'Боря', транспорт: проводБ, часы: () => 2 });

  const события_Б = [];
  узелБ.на('присоединился', (п) => события_Б.push({ э: 'присоединился', от: п.от }));
  узелБ.на('сказано', (п) => события_Б.push({ э: 'сказано', от: п.от, данные: п.данные }));
  узелБ.на('отсоединился', (п) => события_Б.push({ э: 'отсоединился', от: п.от }));

  assert.equal(узелА.схема, СХЕМА_ЯДРА); // ядро не тронули
  узелА.присоединиться();               // явное действие хозяина → провод.открыть()
  узелБ.присоединиться();
  assert.equal(проводА.состояние().открыто, true);

  узелА.войти('зал');
  await пауза();
  узелБ.войти('зал'); // Б слышал join Ани — входит следом (семантика ядра)
  await пауза();
  узелА.сказать('зал', { текст: 'привет залу' });
  await пауза();
  узелА.выйти('зал');
  await пауза();

  assert.ok(события_Б.some((с) => с.э === 'присоединился' && с.от === 'Аня'), 'Б видит join Ани');
  assert.ok(события_Б.some((с) => с.э === 'сказано' && с.от === 'Аня' && с.данные.текст === 'привет залу'), 'Б слышит Аню');
  assert.ok(события_Б.some((с) => с.э === 'отсоединился' && с.от === 'Аня'), 'Б видит leave Ани');
  assert.equal(узелБ.счётчики.своё, 0, 'своё эхо Б не слышал');
  узелА.остановить(); узелБ.остановить();
  assert.equal(проводА.состояние().слои['воздух'], 'закрыт');
  await пауза();
});

test('дедуп ядра на проводе: чужой конверт дважды — дубль один', async () => {
  const воздух = шина();
  const слойЦа = воздух.слой('воздух');
  const проводЦа = создатьПровод({ слои: [слойЦа] });
  const узелЦа = createMesh({ id: 'Ца', транспорт: проводЦа });
  узелЦа.присоединиться();
  узелЦа.войти('зал');
  // чужой join в комнату, где Ца стоит, — дважды с тем же ид
  const чужой = { тип: 'join', комната: 'зал', от: 'Кем', ид: 'Кем:7' };
  воздух.отправьВ(слойЦа, JSON.stringify(чужой));
  await пауза();
  воздух.отправьВ(слойЦа, JSON.stringify(чужой));
  await пауза();
  assert.equal(узелЦа.счётчики.дубли, 1, 'второй тот же ид — дубль');
  assert.equal(узелЦа.счётчики.своё, 0);
  узелЦа.остановить();
  await пауза();
});

test('офлайн: отказавшие слои не врут — ядро живо, отчёт честный', () => {
  const провод = создатьПровод({ слои: [слойВещания({}), слойДанных({ канал: null })] });
  провод.открыть();
  const узел = createMesh({ id: 'Пусто', транспорт: провод });
  узел.присоединиться();
  const отчёт = провод.отправить({ тип: 'join', комната: 'зал', от: 'Пусто', ид: 'Пусто:1' });
  // каждый слой в отчёте — правда: живой слой «отправлено», мёртвый «закрыт»;
  // никакого «отправлено» там, где слой отказал при открытии
  for (const [имя, статус] of Object.entries(отчёт)) {
    const приОткрытии = провод.состояние().слои[имя];
    assert.equal(статус, приОткрытии === 'открыт' ? 'отправлено' : 'закрыт');
  }
  assert.equal(отчёт['данные'], 'закрыт'); // канала не было — честно
  assert.doesNotThrow(() => узел.войти('зал'), 'честный офлайн-узел жив: войти не падает');
  узел.остановить();
});

test('закрытый провод честно молчит', () => {
  const воздух = шина();
  const провод = создатьПровод({ слои: [воздух.слой('эфир')] });
  провод.открыть(); провод.закрыть();
  assert.equal(провод.состояние().слои['эфир'], 'закрыт');
  assert.throws(() => провод.отправить({ тип: 'join', комната: 'з', от: 'х', ид: 'х:1' }), /закрыт/);
  assert.throws(() => провод.открыть(), /закрыт/);
});
