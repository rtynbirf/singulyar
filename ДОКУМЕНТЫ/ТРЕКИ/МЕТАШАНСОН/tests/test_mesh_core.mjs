/** Ручной транспорт: всё в руки теста (без эфира). */
function ручнойТранспорт() {
  const полученные = [];
  const посланные = [];
  let обработчик = null;
  let открыт = 0, закрыт = 0;
  return {
    полученные, посланные,
    get открыт() { return открыт; },
    get закрыт() { return закрыт; },
    доставить(конверт) { полученные.push(конверт); if (обработчик) обработчик(конверт); },
    отправить(конверт) { посланные.push(конверт); },
    приПолучении(фн) { обработчик = фн; },
    открыть() { открыт += 1; },
    закрыть() { закрыт += 1; },
  };
}

const ЧАСЫ = () => 1700000000000;

/* ── Честные отказы (контракт) ─────────────────────────────────────────────── */

describe('createMesh · контракт и честные отказы', () => {
  it('отказ: без опций', () => {
    assert.throws(() => createMesh(), /опции/);
    assert.throws(() => createMesh(null), /опции/);
  });
  it('отказ: без id / пустой id / не строка', () => {
    const т = ручнойТранспорт();
    assert.throws(() => createMesh({ транспорт: т }), /id/);
    assert.throws(() => createMesh({ id: '', транспорт: т }), /id/);
    assert.throws(() => createMesh({ id: 7, транспорт: т }), /id/);
  });
  it('отказ: без транспорта — ядро сеть само не открывает (И-01)', () => {
    assert.throws(() => createMesh({ id: 'а' }), /транспорт/);
  });
  it('отказ: транспорт без отправить / без приПолучении', () => {
    assert.throws(() => createMesh({ id: 'а', транспорт: {} }), /отправить/);
    assert.throws(() => createMesh({ id: 'а', транспорт: { отправить() {} } }), /приПолучении/);
  });
  it('отказ: часы не функция', () => {
    const т = ручнойТранспорт();
    assert.throws(() => createMesh({ id: 'а', транспорт: т, часы: 5 }), /часы/);
  });
  it('отказ: войти/выйти/сказать с пустой или не-строкой комнаты', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    assert.throws(() => узел.войти(''), /комната/);
    assert.throws(() => узел.войти(42), /комната/);
    assert.throws(() => узел.выйти(''), /комната/);
    assert.throws(() => узел.сказать(''), /комната/);
  });
  it('отказ: сказать до входа — честный Error, не тихий успех', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    assert.throws(() => узел.сказать('зал', { раз: 1 }), /не в комнате/);
  });
  it('отказ: на() с не-функцией', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    assert.throws(() => узел.на('сказано', 'нет'), /функция/);
  });
  it('метаданные: схема/версия/типы провода заморожены', () => {
    assert.equal(СХЕМА, 'mesh-core/0.1');
    assert.equal(ВЕРСИЯ_ЯДРА, '0.1.0');
    assert.deepEqual([...ТИПЫ], ['join', 'join-ack', 'leave', 'say']);
    assert.throws(() => { ТИПЫ.push('взлом'); }, TypeError);
    assert.equal(ОКНО_ДЕДУПА, 512);
  });
});

/* ── Семантика провода ─────────────────────────────────────────────────────── */

describe('семантика комнат', () => {
  it('войти шлёт ровно один join с детерминированным ид', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т, часы: ЧАСЫ });
    узел.войти('зал');
    assert.equal(т.посланные.length, 1);
    const к = т.посланные[0];
    assert.equal(к.тип, 'join');
    assert.equal(к.комната, 'зал');
    assert.equal(к.от, 'а');
    assert.equal(к.ид, 'а:1');
    assert.equal(к.тс, 1700000000000);
    assert.deepEqual(узел.комнаты, ['зал']);
  });
  it('без часов тс в конверте отсутствует (0 часов внутри ядра)', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    узел.войти('зал');
    assert.equal('тс' in т.посланные[0], false);
  });
  it('входящий join: авто-join-ack (вОтветНа) + событие присоединился', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    let событие = null;
    узел.на('присоединился', (п) => { событие = п; });
    т.доставить({ тип: 'join', комната: 'зал', от: 'б', ид: 'б:7', тс: 5 });
    assert.equal(событие.от, 'б');
    assert.equal(событие.комната, 'зал');
    assert.equal(событие.мыВошли, true); // услышали живую комнату — вошли сами
    assert.equal(т.посланные.length, 1);
    const ак = т.посланные[0];
    assert.equal(ак.тип, 'join-ack');
    assert.equal(ак.комната, 'зал');
    assert.equal(ак.вОтветНа, 'б:7');
    assert.deepEqual(узел.комнаты, ['зал']);
  });
  it('входящий join-ack: событие есть, обратного ack НЕТ (нет шторма)', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    узел.войти('зал'); // наш join:1
    assert.equal(т.посланные.length, 1);
    let событие = null;
    узел.на('присоединился', (п) => { событие = п; });
    т.доставить({ тип: 'join-ack', комната: 'зал', от: 'б', ид: 'б:2', тс: 6 });
    assert.equal(событие.от, 'б');
    assert.equal(событие.мыВошли, true);
    assert.equal(т.посланные.length, 1, 'join-ack не порождает ответа');
  });
  it('сказать: say из комнаты уходит; чужой say в комнате — событие сказано', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    узел.войти('зал');
    узел.сказать('зал', { текст: 'раз' });
    const say = т.посланные[1];
    assert.equal(say.тип, 'say');
    assert.deepEqual(say.данные, { текст: 'раз' });
    let событие = null;
    узел.на('сказано', (п) => { событие = п; });
    т.доставить({ тип: 'say', комната: 'зал', от: 'б', ид: 'б:3', данные: [1, 2] });
    assert.equal(событие.от, 'б');
    assert.deepEqual(событие.данные, [1, 2]);
  });
  it('чужой say в не-вошедшую комнату тихо отброшен (счётчик чужое)', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    let событие = null;
    узел.на('сказано', (п) => { событие = п; });
    т.доставить({ тип: 'say', комната: 'чужая', от: 'б', ид: 'б:9', данные: 'шум' });
    assert.equal(событие, null);
    assert.equal(узел.счётчики.чужое, 1);
  });
  it('выйти: leave уходит, состояние снято, сказать после — честный отказ', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    узел.войти('зал');
    assert.equal(узел.выйти('зал'), true);
    assert.deepEqual(узел.комнаты, []);
    assert.equal(т.посланные[1].тип, 'leave');
    assert.throws(() => узел.сказать('зал', 'х'), /не в комнате/);
    assert.equal(узел.выйти('зал'), false, 'повторный выйти честно false');
  });
  it('входящий leave: событие отсоединился', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    узел.войти('зал');
    let событие = null;
    узел.на('отсоединился', (п) => { событие = п; });
    т.доставить({ тип: 'leave', комната: 'зал', от: 'б', ид: 'б:4' });
    assert.equal(событие.от, 'б');
    assert.equal(событие.комната, 'зал');
  });
});

/* ── Дедуп, своё эхо, остановка, детерминизм ───────────────────────────────── */

describe('дедуп, эхо, остановка', () => {
  it('повтор конверта с тем же ид отброшен (счётчик дубли)', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    let счёт = 0;
    узел.на('присоединился', () => { счёт += 1; });
    const к = { тип: 'join', комната: 'зал', от: 'б', ид: 'б:1' };
    т.доставить(к); т.доставить({ ...к });
    assert.equal(счёт, 1);
    assert.equal(узел.счётчики.дубли, 1);
  });
  it('окно дедупа 512: 513-й старый ид выветривается — повтор принят заново (честно)', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    let счёт = 0;
    узел.на('присоединился', () => { счёт += 1; });
    т.доставить({ тип: 'join', комната: 'зал', от: 'б', ид: 'б:старый' });
    for (let i = 0; i < ОКНО_ДЕДУПА; i++) {
      т.доставить({ тип: 'join', комната: 'зал', от: `у${i}`, ид: `у${i}:${i}` });
    }
    assert.equal(узел.счётчики.дубли, 0);
    т.доставить({ тип: 'join', комната: 'зал', от: 'б', ид: 'б:старый' });
    assert.equal(узел.счётчики.дубли, 0, 'старый ид выветрился');
    assert.equal(счёт, ОКНО_ДЕДУПА + 2);
  });
  it('своё эхо отброшено со счётчиком своё — узел не отвечает сам себе', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    let счёт = 0;
    узел.на('присоединился', () => { счёт += 1; });
    узел.войти('зал');
    т.доставить({ тип: 'join', комната: 'зал', от: 'а', ид: 'а:1' }); // своё эхо
    assert.equal(счёт, 0);
    assert.equal(узел.счётчики.своё, 1);
    assert.equal(т.посланные.length, 1, 'никакого join-ack самому себе');
  });
  it('неизвестный тип конверта тихо отброшен (провод не расширяется молча)', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    т.доставить({ тип: 'взлом', комната: 'зал', от: 'б', ид: 'б:1' });
    т.доставить({ тип: 'say', комната: '', от: 'б', ид: 'б:2' });
    assert.equal(узел.счётчики.чужое, 2);
  });
  it('остановить: leave по всем комнатам, закрытие провода, тишина после', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    узел.войти('зал');
    узел.войти('хор');
    узел.остановить();
    const типы = т.посланные.map((к) => к.тип);
    assert.deepEqual(типы, ['join', 'join', 'leave', 'leave']);
    assert.equal(т.закрыт, 1);
    assert.deepEqual(узел.комнаты, []);
    assert.throws(() => узел.войти('зал'), /остановлен/);
    assert.throws(() => узел.сказать('зал', 1), /остановлен/);
    узел.остановить(); // повторный останов честно тих
    assert.equal(т.закрыт, 1);
  });
  it('остановленный узел игнорирует входящие (тишина провода)', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    узел.остановить();
    const до = узел.счётчики.получено;
    т.доставить({ тип: 'join', комната: 'зал', от: 'б', ид: 'б:1' });
    assert.equal(узел.счётчики.получено, до);
  });
  it('ид монотонны и детерминированы (от:N), счётчик создано_ид честный', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    узел.войти('зал'); узел.сказать('зал', 1); узел.сказать('зал', 2);
    assert.deepEqual(т.посланные.map((к) => к.ид), ['а:1', 'а:2', 'а:3']);
    assert.equal(узел.счётчики.создано_ид, 3);
  });
  it('вход не мутируется: доставленный конверт остался как был', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    const к = Object.freeze({ тип: 'say', комната: 'зал', от: 'б', ид: 'б:5', данные: { т: [1] } });
    узел.войти('зал');
    assert.doesNotThrow(() => т.доставить(к));
    assert.deepEqual(к, { тип: 'say', комната: 'зал', от: 'б', ид: 'б:5', данные: { т: [1] } });
  });
  it('отписка: на() возвращает функцию, после неё событий нет', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    let счёт = 0;
    const отписаться = узел.на('присоединился', () => { счёт += 1; });
    т.доставить({ тип: 'join', комната: 'зал', от: 'б', ид: 'б:1' });
    assert.equal(счёт, 1);
    отписаться();
    т.доставить({ тип: 'join', комната: 'два', от: 'в', ид: 'в:1' });
    assert.equal(счёт, 1);
  });
  it('несколько подписчиков получают одно событие в порядке подписки', () => {
    const т = ручнойТранспорт();
    const узел = createMesh({ id: 'а', транспорт: т });
    const след = [];
    узел.на('сказано', (п) => след.push(`первый:${п.данные}`));
    узел.на('сказано', (п) => след.push(`второй:${п.данные}`));
    узел.войти('зал');
    т.доставить({ тип: 'say', комната: 'зал', от: 'б', ид: 'б:1', данные: 'раз' });
    assert.deepEqual(след, ['первый:раз', 'второй:раз']);
  });
});

/* ── Сквозной танец двух узлов через эфир (0 сети) ─────────────────────────── */

describe('эфир в памяти: танец двух узлов', () => {
  it('join → join-ack → say → leave, оба всё видят, своего не слышат', () => {
    const эфир = создатьЭфир();
    const трА = ручнойТранспорт(); // события эфира пускаем вручную: эфир → узел
    // настоящий провод: отправить → эфир; эфир → приПолучении обоих узлов
    const приёмники = [];
    const эфирПровести = (конверт) => { for (const п of приёмники) п(конверт); };
    const провод = () => ({
      отправить: (к) => эфирПровести(к),
      приПолучении: (фн) => приёмники.push(фн),
    });
    const А = createMesh({ id: 'А', транспорт: провод(), часы: ЧАСЫ });
    const Б = createMesh({ id: 'Б', транспорт: провод() });
    const видА = [], видБ = [];
    А.на('присоединился', (п) => видА.push(['+', п.от, п.комната]));
    А.на('сказано', (п) => видА.push(['=', п.от, п.данные]));
    А.на('отсоединился', (п) => видА.push(['-', п.от, п.комната]));
    Б.на('присоединился', (п) => видБ.push(['+', п.от, п.комната]));
    Б.на('сказано', (п) => видБ.push(['=', п.от, п.данные]));
    Б.на('отсоединился', (п) => видБ.push(['-', п.от, п.комната]));

    А.присоединиться();
    А.войти('зал');
    assert.deepEqual(видБ, [['+', 'А', 'зал']], 'Б услышал вход А');
    assert.deepEqual(видА, [['+', 'Б', 'зал']], 'А услышал авто-ack Б');

    Б.сказать('зал', { строка: 'Мы бежим по кругу' });
    assert.deepEqual(видА.pop(), ['=', 'Б', { строка: 'Мы бежим по кругу' }]);
    assert.deepEqual(видБ.filter((х) => х[0] === '='), [], 'Б своего say не слышит');

    А.выйти('зал');
    assert.deepEqual(видБ.pop(), ['-', 'А', 'зал'], 'Б услышал выход А');

    // свои эхо-конверты отброшены у обоих
    assert.equal(А.счётчики.своё >= 1, true);
    assert.equal(Б.счётчики.своё >= 1, true);
    assert.equal(трА.открыт, 0, 'ручной транспорт тут ни при чём');
  });
  it('остановка узла в эфире: уход из всех комнат объявлен, провод закрыт', () => {
    const приёмники = [];
    const эфирПровести = (к) => { for (const п of приёмники) п(к); };
    const провод = () => ({
      отправить: (к) => эфирПровести(к),
      приПолучении: (фн) => приёмники.push(фн),
      закрыть() { this.закрыт = (this.закрыт || 0) + 1; },
    });
    const А = createMesh({ id: 'А', транспорт: провод() });
    const Б = createMesh({ id: 'Б', транспорт: провод() });
    const уходы = [];
    Б.на('отсоединился', (п) => уходы.push([п.от, п.комната]));
    А.войти('зал'); А.войти('хор');
    А.остановить();
    assert.deepEqual(уходы.sort(), [['А', 'зал'], ['А', 'хор']]);
  });
});
