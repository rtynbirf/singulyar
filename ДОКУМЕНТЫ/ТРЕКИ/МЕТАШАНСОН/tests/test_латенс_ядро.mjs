import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import vm from 'node:vm';

import { смещение, компенсировать, окно } from '../src/латенс-ядро.mjs';

/* ── 1. Медиана смещения ─────────────────────────────────────────────────── */
test('смещение: нечётное число проб — средняя разность', () => {
  const пары = [
    { здесь: 1000, там: 1250 },   // +250
    { здесь: 2000, там: 2240 },   // +240
    { здесь: 3000, там: 3260 },   // +260
  ];
  const р = смещение(пары);
  assert.equal(р.смещениеМс, 250);
  assert.equal(р.проб, 3);
  assert.equal(р.версия, 'латенс-ядро/0.1');
});

test('смещение: чётное число проб — среднее двух средних', () => {
  const пары = [
    { здесь: 0, там: 10 },   // +10
    { здесь: 0, там: 20 },   // +20
    { здесь: 0, там: 30 },   // +30
    { здесь: 0, там: 40 },   // +40
  ];
  const р = смещение(пары);
  assert.equal(р.смещениеМс, 25);
});

test('смещение: отрицательное смещение честное', () => {
  const р = смещение([{ здесь: 5000, там: 4900 }, { здесь: 6000, там: 5890 }, { здесь: 7000, там: 6910 }]);
  assert.equal(р.смещениеМс, -100);
});

test('смещение: разбросМс считается детерминированно (p75−p25)', () => {
  const пары = [];
  for (let i = 0; i < 9; i += 1) пары.push({ здесь: 0, там: (i + 1) * 10 }); // 10..90
  const р = смещение(пары);
  assert.equal(р.смещениеМс, 50);
  assert.equal(typeof р.разбросМс, 'number');
  assert.ok(р.разбросМс >= 0);
});

test('смещение: минПроб кастомный — 5 проб при пороге 5', () => {
  const пары = [{ здесь: 0, там: 1 }, { здесь: 0, там: 2 }, { здесь: 0, там: 3 }, { здесь: 0, там: 4 }];
  assert.throws(() => смещение(пары, { минПроб: 5 }), RangeError);
  пары.push({ здесь: 0, там: 5 });
  const р = смещение(пары, { минПроб: 5 });
  assert.equal(р.проб, 5);
});

/* ── 2. Честные отказы ───────────────────────────────────────────────────── */
test('смещение: мало проб — честный RangeError без выдумки', () => {
  assert.throws(() => смещение([]), RangeError);
  assert.throws(() => смещение([{ здесь: 0, там: 1 }]), RangeError);
  assert.throws(() => смещение([{ здесь: 0, там: 1 }, { здесь: 0, там: 2 }]), RangeError);
});

test('смещение: мусор во входе — TypeError/RangeError', () => {
  assert.throws(() => смещение('пары'), TypeError);
  /* канон проверяет длину раньше элементов: короткий мусор — «мало проб» */
  assert.throws(() => смещение([{}]), RangeError);
  assert.throws(() => смещение([{ здесь: 0, там: 1 }, { здесь: 0, там: 2 }, {}, { здесь: 0, там: 4 }]), TypeError);
  assert.throws(() => смещение([{ здесь: 0, там: 1 }, { здесь: 0, там: 2 }, { здесь: 0, там: 3 }, { здесь: 'x', там: 4 }]), TypeError);
  assert.throws(() => смещение([{ здесь: 0, там: 1 }, { здесь: 0, там: 2 }, { здесь: 0, там: 3 }, { здесь: 0, там: Infinity }]), RangeError);
  assert.throws(() => смещение([{ здесь: 0, там: 1 }], { минПроб: 'много' }), TypeError);
  assert.throws(() => смещение([{ здесь: 0, там: 1 }, { здесь: 0, там: 2 }, { здесь: 0, там: 3 }], { минПроб: 0 }), RangeError);
});

/* ── 3. Компенсация ──────────────────────────────────────────────────────── */
test('компенсировать: сдвиг метки', () => {
  assert.equal(компенсировать(1000, -250), 750);
  assert.equal(компенсировать(1000, 250), 1250);
  assert.equal(компенсировать(0, 0), 0);
});

test('компенсировать: не числа — TypeError', () => {
  assert.throws(() => компенсировать('1000', 1), TypeError);
  assert.throws(() => компенсировать(1000, NaN), TypeError);
  assert.throws(() => компенсировать(Infinity, 1), RangeError);
});

/* ── 4. Окно ─────────────────────────────────────────────────────────────── */
test('окно: слайд 1, финальное неполное честно входит', () => {
  const метки = [10, 20, 30, 40, 50];
  const о = окно(метки, 3);
  assert.equal(о.length, 3);
  assert.deepEqual(о[0], [10, 20, 30]);
  assert.deepEqual(о[1], [20, 30, 40]);
  assert.deepEqual(о[2], [30, 40, 50]);
});

test('окно: размер больше длины — одно неполное окно', () => {
  const о = окно([1, 2], 5);
  assert.equal(о.length, 1);
  assert.deepEqual(о[0], [1, 2]);
});

test('окно: отказы', () => {
  assert.throws(() => окно('x', 3), TypeError);
  assert.throws(() => окно([1, 2], 0), RangeError);
  assert.throws(() => окно([1, 2], 1.5), RangeError);
});

/* ── 5. Немутация и детерминизм ──────────────────────────────────────────── */
test('вход не мутируется; двойной вызов байт-в-байт', () => {
  const пары = [{ здесь: 100, там: 150 }, { здесь: 200, там: 260 }, { здесь: 300, там: 340 }];
  const копия = JSON.stringify(пары);
  const а = смещение(пары);
  const б = смещение(пары);
  assert.equal(JSON.stringify(пары), копия);
  assert.equal(JSON.stringify(а), JSON.stringify(б));
});

/* ── 6. Порт ≡ канон (vm) ────────────────────────────────────────────────── */
test('порт latency-core.js ≡ канон', async () => {
  const кодПорта = await readFile(join(dirname(fileURLToPath(import.meta.url)), '../../../../js/latency-core.js'), 'utf8');
  const песочница = { window: {}, console };
  vm.createContext(песочница);
  vm.runInContext(кодПорта, песочница, { filename: '../../../../js/latency-core.js' });
  const порт = песочница.window.__ЛАТЕНС;
  assert.ok(порт, 'порт не поставил __ЛАТЕНС');

  const векторы = [
    [{ здесь: 0, там: 5 }, { здесь: 0, там: 10 }, { здесь: 0, там: 15 }],
    [{ здесь: 1e9, там: 1e9 + 42 }, { здесь: 2e9, там: 2e9 + 50 }, { здесь: 3e9, там: 3e9 + 44 }],
  ];
  for (const в of векторы) {
    assert.equal(JSON.stringify(порт.смещение(в.map((п) => ({ ...п })))), JSON.stringify(смещение(в)));
  }
  // компенсировать
  assert.equal(порт.компенсировать(1000, -250), компенсировать(1000, -250));
  // окно
  assert.equal(JSON.stringify(порт.окно([1, 2, 3, 4, 5], 3)), JSON.stringify(окно([1, 2, 3, 4, 5], 3)));
  // отказы: имя+сообщение
  const случаи = [[], [{ здесь: 0, там: 1 }], 'мусор'];
  for (const с of случаи) {
    let оКан = null, оПор = null;
    try { смещение(JSON.parse(JSON.stringify(с))); } catch (е) { оКан = е; }
    try { порт.смещение(typeof с === 'string' ? с : JSON.parse(JSON.stringify(с))); } catch (е) { оПор = е; }
    assert.ok(оКан && оПор);
    assert.equal(оПор.message, оКан.message);
  }
  // идиомпотентность
  assert.equal(JSON.stringify(порт.окно([1, 2, 3], 2)), JSON.stringify(порт.окно([1, 2, 3], 2)));
});
