/* знак прописной: латиница — точка 6 (международная), кириллица/греческий — 46 (по таблицам) */
const BR_CAP = { L: "6", C: "46", G: "46" };
/* числовой знак ⠼ + a..j: сверено для латиницы, кириллицы, греческого, арабского */
const BR_DIGITS = { L: true, C: true, G: true, A: true };
const BR_DIGIT_CELL = { "1": "1", "2": "12", "3": "14", "4": "145", "5": "15",
                        "6": "124", "7": "1245", "8": "125", "9": "24", "0": "245" };
/* тонос: знак ⠐ перед гласной (Modern Greek Braille); ϊ/ϋ — просто гласная */
const BR_G_ACCENT = { "ά": "α", "έ": "ε", "ή": "η", "ί": "ι", "ό": "ο", "ύ": "υ", "ώ": "ω" };

function scriptOfChar(ch) {
  if (/[a-z]/i.test(ch)) return "L";
  if (/[а-яё]/i.test(ch)) return "C";
  if (/[\u0386-\u03CE]/i.test(ch)) return "G";
  if (/[\u05D0-\u05EA]/.test(ch)) return "H";
  if (/[\u0621-\u0652]/.test(ch)) return "A";
  return "";
}
function scriptOfText(text) {
  for (const ch of String(text)) {
    const s = scriptOfChar(ch);
    if (s) return s;
  }
  return "L";
}

/* текст → брайль: буквы — по своей письменности, знаки — по языку сообщения,
   цифры — ⠼ + клетка (где сверено); незнакомый знак проходит как есть */
export function textToBraille(text) {
  const punct = (BR[scriptOfText(text)] || BR.L).знаки;
  let out = "", digits = false;
  for (const chRaw of String(text)) {
    const lower = chRaw.toLowerCase();
    const isUpper = chRaw !== lower;
    if (chRaw === " ") { out += "\u2800"; digits = false; continue; }
    const s = scriptOfChar(chRaw);
    if (s === "G" && BR_G_ACCENT[lower]) {                 /* тонос перед гласной */
      if (digits) { out += "\u2800"; digits = false; }
      if (isUpper) out += cell(BR_CAP.G);
      out += cell("5") + cell(BR.G.м[BR_G_ACCENT[lower]]);
      continue;
    }
    const t = BR[s];
    if (t && t.м[lower] != null) {
      if (digits) { out += "\u2800"; digits = false; }
      if (isUpper && BR_CAP[s]) out += cell(BR_CAP[s]);
      out += cell(t.м[lower]);
      continue;
    }
    if (/[0-9]/.test(chRaw) && BR_DIGITS[scriptOfText(text)]) {
      if (!digits) out += cell("3456");                    /* ⠼ */
      out += cell(BR_DIGIT_CELL[chRaw]);
      digits = true;
      continue;
    }
    if (punct[chRaw] != null) { out += cell(punct[chRaw]); digits = false; continue; }
    out += chRaw;                                          /* дом не выдумывает */
    digits = false;
  }
  return out;
}
