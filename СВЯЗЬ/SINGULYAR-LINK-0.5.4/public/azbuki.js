/* знаки письма по азбукам */
const M_SIGNS = {
  L: M_PUNCT, C: M_PUNCT, G: M_PUNCT,
  P: { ".": "......", "،": ".-.-.-", "؛": ".-.-.-", "؟": "..--..", "!": "--..--",
       ":": "---...", "(": "-.--.", ")": "-.--.-", "-": "-.....-", "/": "------" },
  J: { "゛": "..", "゜": "..--.", "ー": ".--.-", "、": ".-.-.-", "。": ".-.-.",
       "(": "-.-.-.", ")": "...-." }
};
/* при чтении уступают (код занят более частым знаком этой же азбуки) */
const M_SKIP_DECODE = { C: ["ї", "ъ"] };

export const MORSE_ORDER = ["L", "C", "G", "H", "A", "P", "K", "J"];
const TABLES = {};
for (const key of MORSE_ORDER) {
  const м = M[key].м, знаки = M_SIGNS[key] || {};
  const skip = M_SKIP_DECODE[key] || [];
  const rev = {};
  for (const [ch, code] of Object.entries(м)) if (!(code in rev) && !skip.includes(ch)) rev[code] = ch;
  for (const [ch, code] of Object.entries(M_DIGITS)) if (!(code in rev)) rev[code] = ch;
  for (const [ch, code] of Object.entries(знаки)) if (!(code in rev)) rev[code] = ch;
  TABLES[key] = { имя: M[key].имя, м, цифры: M_DIGITS, знаки, rev };
}
/* «Авто»: латиница → кириллица → греческая → иврит → арабская → персидская → хангыль → кана */
const REV_AUTO = {};
for (const key of MORSE_ORDER)
  for (const [code, ch] of Object.entries(TABLES[key].rev))
    if (!(code in REV_AUTO)) REV_AUTO[code] = ch;

export const morseAlphabets = Object.fromEntries(MORSE_ORDER.map(k => [k, { имя: TABLES[k].имя }]));
export const MORSE_REV = REV_AUTO; /* совместимость: чтение «Авто» */

/* буква/цифра/знак → точка-тире (ищем по всем письмам мира) */
export function morseCodeOf(ch) {
  ch = String(ch).toLowerCase();
  for (const key of MORSE_ORDER) {
    const t = TABLES[key];
    if (t.м[ch]) return t.м[ch];
    if (t.цифры[ch]) return t.цифры[ch];
    if (t.знаки[ch]) return t.знаки[ch];
  }
  return "";
}
/* текст → «·· ·− ··−» (слова через « / ») */
export function morseOf(text) {
  return String(text).toLowerCase().split(/\s+/).filter(Boolean)
    .map(w => [...w].map(morseCodeOf).filter(Boolean).join(" "))
    .filter(Boolean).join(" / ");
}
/* точка-тире → буква выбранной азбуки («*» — авто) */
export function morseDecode(seq, key = "*") {
  const rev = key === "*" ? REV_AUTO : (TABLES[key] || {}).rev;
  return rev ? (rev[seq] || "") : "";
}

