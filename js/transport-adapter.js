/**
 * СИНГУЛЯР · ТРАНСПОРТ-АДАПТЕР (js/transport-adapter.js) — такт v11.31 «ГЕРМЕТИЧНО» (С109, PAT №33)
 * Канон transport-adapter/0.1 · шаг WP-07 карты ЗЕЛЁНОЙ (контракт адаптеров пакета «Контур человеческой связи»).
 *
 * Контракт: адаптер — честная карта маршрута намерения. send() возвращает состояние машины
 * (accepted_by_transport | refused) и НИКОГДА не молчит. В доме сейчас живёт только fake-loopback
 * (режим "fake": петля на локальный журнал, 0 сети). Режим "manual" — маршрут под ручку человека
 * (экспорт файла / QR). Режим "network" контрактом ОТКЛОНЯЕТСЯ: 0 внешних запросов без явного слова
 * владельца (И-01; будущие WP-10/WP-11 — отдельные ходы с отдельным словом).
 * Законы: 0 сети, 0 DOM, 0 случайности (кроме случайных id объекта — они приходят снаружи), append-only журнал.
 */
(function (глобал) {
  'use strict';

  var канон = 'singulyar.transport/0.1';
  var допустимыеВозможности = ['text', 'file', 'voice', 'call_invite', 'value_intent', 'contact_invite', 'email'];
  var допустимыеРежимы = ['fake', 'manual'];
  var допустимыеСостояния = ['accepted_by_transport', 'refused'];

  var реестр = {};
  var порядок = [];

  function честныйОтказ(причина) { return { состояние: 'refused', причина: причина }; }

  function проверитьОписаниеАдаптера(описание) {
    if (!описание || typeof описание !== 'object') return 'описание адаптера отсутствует';
    if (typeof описание.id !== 'string' || !/^[a-zа-яё][a-zа-яё0-9-]{1,63}$/.test(описание.id)) return 'id: ожидается строка в нижнем регистре (латиница/кириллица/цифры/дефис) длиной 2–64 (получено ' + JSON.stringify(описание.id || null) + ')';
    if (реестр[описание.id]) return 'адаптер "' + описание.id + '" уже зарегистрирован — дубликат отклонён';
    if (typeof описание.название !== 'string' || !описание.название.trim()) return 'название: непустая строка обязательна';
    if (допустимыеРежимы.indexOf(описание.режим) === -1) return 'режим "' + String(описание.режим) + '" не поддержан (доступны: fake, manual; network — только по явному слову владельца, И-01)';
    if (!Array.isArray(описание.возможности) || описание.возможности.length === 0) return 'возможности: непустой массив обязателен';
    for (var i = 0; i < описание.возможности.length; i++) {
      if (допустимыеВозможности.indexOf(описание.возможности[i]) === -1) return 'возможность "' + String(описание.возможности[i]) + '" неизвестна контракту';
    }
    if (typeof описание.границы !== 'string' || !описание.границы.trim()) return 'границы: честная строка о том, что адаптер НЕ делает, обязательна';
    if (typeof описание.send !== 'function') return 'send: функция обязательна';
    return null;
  }

  function определитьАдаптер(описание) {
    var ошибка = проверитьОписаниеАдаптера(описание);
    if (ошибка) throw new Error('transport-adapter: ' + ошибка);
    var закрыт = false;
    var обёртка = {
      id: описание.id,
      название: описание.название,
      режим: описание.режим,
      возможности: описание.возможности.slice(),
      границы: описание.границы,
      send: function (объект) {
        if (закрыт) return Promise.resolve(честныйОтказ('адаптер "' + описание.id + '" закрыт — отправка честно отказывает'));
        if (!объект || typeof объект !== 'object' || Array.isArray(объект)) return Promise.resolve(честныйОтказ('send: ожидается объект намерения (получено ' + (объект === null ? 'null' : typeof объект) + ')'));
        if (описание.возможности.indexOf(объект.kind) === -1) return Promise.resolve(честныйОтказ('адаптер "' + описание.id + '" не ведёт возможности "' + String(объект.kind) + '"'));
        var журналЗапись = {
          id: (объект && typeof объект.id === 'string') ? объект.id : null,
          kind: объект.kind,
          состояние: null,
          дубликат: false,
          когда: new Date().toISOString()
        };
        for (var i = 0; i < журнал_.length; i++) {
          if (журнал_[i].id && журнал_[i].id === журналЗапись.id && журнал_[i].состояние === 'accepted_by_transport') {
            /* идемпотентность: повтор того же объекта не скатывает состояние и не плодит вторую доставку */
            журналЗапись.дубликат = true;
            журнал_.push(журналЗапись);
            return Promise.resolve({ состояние: 'accepted_by_transport', дубликат: true, адаптер: описание.id });
          }
        }
        return Promise.resolve(описание.send(объект)).then(function (ответ) {
          if (!ответ || допустимыеСостояния.indexOf(ответ.состояние) === -1) {
            журналЗапись.состояние = 'refused';
            журнал_.push(журналЗапись);
            return честныйОтказ('адаптер "' + описание.id + '" вернул недопустимое состояние (допустимы: accepted_by_transport, refused)');
          }
          журналЗапись.состояние = ответ.состояние;
          журнал_.push(журналЗапись);
          var итог = { состояние: ответ.состояние, адаптер: описание.id };
          if (ответ.причина) итог.причина = ответ.причина;
          return итог;
        });
      },
      закрыть: function () { закрыт = true; }
    };
    реестр[описание.id] = обёртка;
    порядок.push(описание.id);
    return обёртка;
  }

  var журнал_ = [];

  /* встроенный честный адаптер: петля на локальный журнал, 0 сети */
  определитьАдаптер({
    id: 'fake-loopback',
    название: 'Локальная петля (без сети)',
    режим: 'fake',
    возможности: ['text', 'file', 'voice', 'call_invite', 'value_intent', 'contact_invite', 'email'],
    границы: 'Ничего не отправляет наружу: объект остаётся на устройстве, состояние accepted_by_transport означает «принято локальной петлёй этого адаптера», не «доставлено человеку».',
    send: function () { return Promise.resolve({ состояние: 'accepted_by_transport' }); }
  });

  var SingulyarTransport = {
    канон: канон,
    определитьАдаптер: определитьАдаптер,
    получить: function (id) { return Object.prototype.hasOwnProperty.call(реестр, id) ? реестр[id] : null; },
    список: function () { return порядок.slice(); },
    журнал: function () { return журнал_.slice(); },
    допустимыеВозможности: допустимыеВозможности.slice(),
    допустимыеРежимы: допустимыеРежимы.slice()
  };

  if (typeof module !== 'undefined' && module.exports) module.exports = SingulyarTransport;
  else глобал.SingulyarTransport = SingulyarTransport;
})(typeof window !== 'undefined' ? window : globalThis);
