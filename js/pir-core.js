'use strict';

/* appId для Trystero-комнат дома */
const ИД_ПРИЛОЖЕНИЯ = 'singulyar-pir-0.1';

/* STUN — только для рукопожатия (обход NAT), контент через них не течёт */
const СЕРВЕРА_СТУН = [
  { urls: 'stun:stun.l.google.com:19302' },
  { urls: 'stun:stun.cloudflare.com:3478' }
];

/* Лимит текста сообщения — честный, известен заранее (прецедент Г0: 4000) */
export const ЛИМИТ_ТЕКСТА = 2000;

/* Слова для честного имени комнаты — имя комнаты и есть пропуск */
const СЛОВА = ['янтарь','мост','свет','лад','полюс','гавань','купол','маяк','ветер','якорь','ткань','узел','пульс','даль','гром','перо','сокол','кристалл','очаг','фарватер'];

/* Честное имя комнаты: слово + число из crypto.getRandomValues (не метрика — пропуск) */
export function родитьИмяКомнаты() {
  const б = new Uint32Array(2);
  globalThis.crypto.getRandomValues(б);
  const слово = СЛОВА[б[0] % СЛОВА.length];
  const число = (б[1] % 9000 + 1000); /* 1000…9999 */
  return 'пир-' + слово + '-' + число;
}

/* Короткая печать пира для людей: первые 10 знаков ид */
export function печатьПира(ид) {
  return String(ид || '').slice(0, 10);
}

/* ───────────────────────────────────────────────────────────────────────────
   СЕТЬ (основной режим): Trystero-Nostr.
   Конструктор ничего не соединяет. войти() — явное действие.
   ─────────────────────────────────────────────────────────────────────────── */
export function создатьСеть(уха) {
  /* уха — колбэки: {статус, пирПришёл, пирУшёл, имяПира, потокПришёл, потокУшёл, текстПришёл} */
  if (!уха || typeof уха !== 'object') throw new Error('пир-сеть: нужен слушатель событий');
  let комната = null;
  let действиеТекст = null;
  let действиеИмя = null;
  let мойПоток = null;
  const имена = new Map();   /* ид пира → имя */
  const своиПотоки = new Set();

  async function войти(имяКомнаты, ключ, моёИмя) {
    if (комната) throw new Error('уже в комнате — сначала покинуть');
    const имя = String(имяКомнаты || '').trim();
    if (!имя) throw new Error('имя комнаты пусто — комната и есть адрес');
    if (имя.length > 128) throw new Error('имя комнаты длиннее 128 знаков');
    уха.статус('Ищу пиров: рукопожатие через релеи Nostr…');
    /* Динамический импорт — транспорт грузится только по явному действию (И-01) */
    const т = await import('../БИБЛИОТЕКИ/trystero-nostr.bundle.mjs');
    const конфиг = { appId: ИД_ПРИЛОЖЕНИЯ };
    const ключСтрока = String(ключ || '').trim();
    if (ключСтрока) {
      if (ключСтрока.length < 4) throw new Error('ключ короче 4 знаков — либо пусто, либо длиннее');
      конфиг.password = ключСтрока; /* шифрует рукопожатие (SDP) у релеев */
    }
    комната = т.joinRoom(конфиг, имя);

    const текст = комната.makeAction('сообщение');
    const имяДействие = комната.makeAction('имя');
    действиеТекст = текст;
    действиеИмя = имяДействие;

    /* эта версия транспорта: onMessage — свойство-приёмник (присваиваем),
       приём даёт (данные, метка{peerId,…}); send(данные, {target}) */
    текст.onMessage = (данные, м) => {
      const ид = м && м.peerId;
      const т0 = typeof данные === 'string' ? данные : '';
      if (!т0 || !ид) return; /* пустое не сообщение */
      уха.текстПришёл(т0.slice(0, ЛИМИТ_ТЕКСТА), ид, имена.get(ид) || '');
    };
    имяДействие.onMessage = (имяПира, м) => {
      const ид = м && м.peerId;
      if (!ид || typeof имяПира !== 'string' || !имяПира.trim()) return;
      имена.set(ид, имяПира.trim().slice(0, 64));
      уха.имяПира(ид, имена.get(ид));
    };

    комната.onPeerJoin = (ид) => {
      /* имя и живой поток — сразу новому пиру (очередь действий у транспорта честная) */
      имяДействие.send(String(моёИмя || '').slice(0, 64), { target: ид });
      if (мойПоток) комната.addStream(мойПоток, { target: ид });
      уха.пирПришёл(ид, имена.get(ид) || '');
      уха.статус('Пир подключился: ' + печатьПира(ид) + '. Связь прямая — релеи в контенте не участвуют.');
    };
    комната.onPeerLeave = (ид) => {
      имена.delete(ид);
      уха.пирУшёл(ид);
      уха.статус('Пир ушёл: ' + печатьПира(ид) + '.');
    };
    комната.onPeerStream = (поток, ид, метка) => {
      уха.потокПришёл(поток, ид, (метка && метка.тип) || 'камера', имена.get(ид) || '');
    };
    return комната;
  }

  function покинуть() {
    if (!комната) return;
    try { комната.leave(); } catch (_) { /* транспорт уже мёртв — это не ложь */ }
    комната = null; действиеТекст = null; действиеИмя = null;
    имена.clear();
    своиПотоки.clear();
    уха.статус('Комната покинута. Сеть выключена — ничего не уходит.');
  }

  function послатьТекст(текст) {
    if (!действиеТекст) throw new Error('не в комнате — тексту некуда идти');
    const т0 = String(текст || '');
    if (!т0.trim()) throw new Error('пустое не отправляется');
    if (т0.length > ЛИМИТ_ТЕКСТА) throw new Error('текст длиннее ' + ЛИМИТ_ТЕКСТА + ' знаков');
    действиеТекст.send(т0);
  }

  function датьИмя(моёИмя) {
    if (!действиеИмя) return;
    действиеИмя.send(String(моёИмя || '').slice(0, 64));
  }

  function датьПоток(поток, тип) {
    if (!комната) throw new Error('не в комнате — потоку некуда идти');
    if (!поток) throw new Error('поток пуст');
    мойПоток = поток;
    своиПотоки.add(поток);
    /* без цели — всем живым пирам; новым пирам отдаётся в onPeerJoin */
    комната.addStream(поток, { metadata: { тип: тип || 'камера' } });
  }

  function снятьПоток(поток) {
    if (!комната || !поток) return;
    try { комната.removeStream(поток); } catch (_) { /* уже снят */ }
    if (мойПоток === поток) мойПоток = null;
    своиПотоки.delete(поток);
  }

  function вКомнате() { return !!комната; }

  return { войти, покинуть, послатьТекст, датьИмя, датьПоток, снятьПоток, вКомнате };
}

/* ───────────────────────────────────────────────────────────────────────────
   ГЛУХОЙ РЕЖИМ: рукопожатие вручную (код приглашения ↔ код ответа).
   Ноль сети для сигналинга — коды передаются любым своим каналом
   (голосом, письмом, бумагой). Связь 1-на-1, видео+аудио+текст.
   ─────────────────────────────────────────────────────────────────────────── */
function вКод(строка) {
  const байты = new TextEncoder().encode(строка);
  let двоичное = '';
  for (const б of байты) двоичное += String.fromCharCode(б);
  return btoa(двоичное);
}
function изКода(код) {
  const двоичное = atob(String(код || '').replace(/\s+/g, ''));
  const байты = new Uint8Array(двоичное.length);
  for (let i = 0; i < двоичное.length; i++) байты[i] = двоичное.charCodeAt(i);
  return new TextDecoder().decode(байты);
}

export function создатьГлухойРежим(уха) {
  if (!уха || typeof уха !== 'object') throw new Error('глухой режим: нужен слушатель событий');
  let ст = null;            /* RTCPeerConnection */
  let канал = null;         /* RTCDataChannel */
  let инициатор = false;

  function чистить() {
    if (канал) { try { канал.close(); } catch (_) {} канал = null; }
    if (ст) { try { ст.close(); } catch (_) {} ст = null; }
    инициатор = false;
  }

  function собрать(безСерверов) {
    /* безСерверов=true — даже STUN не зовём: обе стороны в одной сети */
    ст = new RTCPeerConnection(безСерверов ? {} : { iceServers: СЕРВЕРА_СТУН });
    ст.oniceconnectionstatechange = () => {
      const с = ст && ст.iceConnectionState;
      if (с === 'connected') уха.статус('Глухой режим: прямая связь установлена.');
      else if (с === 'failed') уха.статус('Глухой режим: связь не сошлась (адреса не встретились). Попробуйте ещё раз или ту же сеть.');
      else if (с === 'disconnected') уха.статус('Глухой режим: пир пропал.');
      else if (с === 'closed') уха.статус('Глухой режим: соединение закрыто.');
    };
    ст.ontrack = (е) => {
      if (е.streams && е.streams[0]) уха.потокПришёл(е.streams[0], 'глухой', 'камера', 'пир');
    };
  }

  function каналМой() {
    канал = ст.createDataChannel('пир-текст');
    канал.onmessage = (е) => {
      const т0 = typeof е.data === 'string' ? е.data : '';
      if (т0) уха.текстПришёл(т0.slice(0, ЛИМИТ_ТЕКСТА), 'глухой', 'пир');
    };
  }

  /* Шаг инициатора: сделать приглашение (код — самодискриптный JSON: type+sdp) */
  async function сделатьПриглашение(опции) {
    чистить();
    инициатор = true;
    собрать(!!(опции && опции.безСерверов));
    каналМой();
    if (опции && опции.поток) for (const т of опции.поток.getTracks()) ст.addTrack(т, опции.поток); /* медиа — в рукопожатие */
    const оффер = await ст.createOffer();
    await ст.setLocalDescription(оффер);
    await ждатьГотовности(ст.iceGatheringState === 'complete', () => ст.iceGatheringState === 'complete', 4000);
    уха.статус('Приглашение готово. Передайте код пиру любым своим каналом и дождитесь кода-ответа.');
    return вКод(JSON.stringify({ тип: ст.localDescription.type, sdp: ст.localDescription.sdp }));
  }

  /* Шаг отвечающего: принять приглашение, отдать код-ответ */
  async function принятьПриглашение(код, опции) {
    чистить();
    инициатор = false;
    собрать(!!(опции && опции.безСерверов));
    ст.ondatachannel = (е) => {
      канал = е.channel;
      канал.onmessage = (ев) => {
        const т0 = typeof ев.data === 'string' ? ев.data : '';
        if (т0) уха.текстПришёл(т0.slice(0, ЛИМИТ_ТЕКСТА), 'глухой', 'пир');
      };
    };
    const пакет = JSON.parse(изКода(код));
    if (!пакет || пакет.тип !== 'offer' || typeof пакет.sdp !== 'string') throw new Error('это не приглашение (нужен код из «Сделать приглашение»)');
    await ст.setRemoteDescription({ type: 'offer', sdp: пакет.sdp });
    if (опции && опции.поток) for (const т of опции.поток.getTracks()) ст.addTrack(т, опции.поток); /* медиа — в ответ */
    const ответ = await ст.createAnswer();
    await ст.setLocalDescription(ответ);
    await ждатьГотовности(ст.iceGatheringState === 'complete', () => ст.iceGatheringState === 'complete', 4000);
    уха.статус('Ответ готов. Отдайте код инициатору — связь установится сама.');
    return вКод(JSON.stringify({ тип: ст.localDescription.type, sdp: ст.localDescription.sdp }));
  }

  /* Шаг инициатора: принять код-ответ — соединение живёт */
  async function завершитьСоединение(код) {
    if (!ст || !инициатор) throw new Error('нет приглашения — сначала сделать приглашение');
    const пакет = JSON.parse(изКода(код));
    if (!пакет || пакет.тип !== 'answer' || typeof пакет.sdp !== 'string') throw new Error('это не код-ответ (ожидается answer)');
    await ст.setRemoteDescription({ type: 'answer', sdp: пакет.sdp });
    уха.статус('Ответ принят — сходимся…');
  }

  function свойПоток(поток) {
    if (!ст) throw new Error('режим не начат');
    for (const т of поток.getTracks()) ст.addTrack(т, поток);
  }

  function послатьТекст(текст) {
    if (!канал || канал.readyState !== 'open') throw new Error('канал текста ещё не открыт');
    const т0 = String(текст || '');
    if (!т0.trim()) throw new Error('пустое не отправляется');
    if (т0.length > ЛИМИТ_ТЕКСТА) throw new Error('текст длиннее ' + ЛИМИТ_ТЕКСТА + ' знаков');
    канал.send(т0);
  }

  function остановить() {
    чистить();
    уха.статус('Глухой режим: соединение закрыто, медиа остановлены.');
  }

  return { сделатьПриглашение, принятьПриглашение, завершитьСоединение, свойПоток, послатьТекст, остановить };
}

/* мелкий обещанный таймер для сбора ICE — честный тайм-аут, не молчание */
function ждатьГотовности(сразу, готово, предел) {
  if (сразу) return Promise.resolve();
  return new Promise((решить) => {
    const т0 = setTimeout(() => { clearInterval(ин); решить(); }, предел);
    const ин = setInterval(() => {
      if (готово()) { clearTimeout(т0); clearInterval(ин); решить(); }
    }, 100);
  });
}
