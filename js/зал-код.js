/* ═══════════════════════════════════════════════════════════════════
   СИНГУЛЯР · КОД ЗАЛА — общее правило кода зала дома (ЛАТКА 2026-11-11,
   инцидент «ссылка ?зал=ТЕСТ1 рассыпала людей по случайным залам»).

   ОДИН ВХОД = ОДИН ЗАЛ на любом устройстве:
     1) норм(вход)  — кириллица → латиница (детерминированная таблица),
        затем только A-Z0-9, длина 4…5; «ТЕСТ1» → «TEST1» у всех.
     2) дет(вход)   — вход не распознан в буквы (или короче 4), но не пуст:
        FNV-1a → 5 знаков алфавита дома. Тот же вход — тот же зал.
     3) код(вход, фолбэк) — единая точка: норм ≥4, иначе дет для
        непустого входа, иначе фолбэк (случайный код зала).

   До латки: replace(/[^A-Z0-9]/) стирал кириллицу молча, короткий хвост
   заменялся случайным кодом — приглашение на русском собирало пустоту.
   Алфавит кода дома: 'ABCDEFGHJKMNPQRSTUVWXYZ23456789' (без I, L, O, 0, 1).

   Закон дома: ES2019, без innerHTML, каждое действие под try/catch,
   скрипт не имеет права ломать страницу, в которую вшит.
   Страж: ИНСТРУМЕНТЫ/test_зал_код.mjs (node --test).
   ═══════════════════════════════════════════════════════════════════ */
(function (глоб) {
  'use strict';

  var АЛФАВИТ = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';

  /* Транслит кириллицы: ГОСТ-подобная таблица, одна на дом. */
  var ТАБЛИЦА = {
    'А': 'A', 'Б': 'B', 'В': 'V', 'Г': 'G', 'Д': 'D', 'Е': 'E', 'Ё': 'E',
    'Ж': 'ZH', 'З': 'Z', 'И': 'I', 'Й': 'Y', 'К': 'K', 'Л': 'L', 'М': 'M',
    'Н': 'N', 'О': 'O', 'П': 'P', 'Р': 'R', 'С': 'S', 'Т': 'T', 'У': 'U',
    'Ф': 'F', 'Х': 'X', 'Ц': 'C', 'Ч': 'CH', 'Ш': 'SH', 'Щ': 'SCH',
    'Ъ': '', 'Ы': 'Y', 'Ь': '', 'Э': 'E', 'Ю': 'YU', 'Я': 'YA',
    /* соседи дома: украинский/белорусский */
    'І': 'I', 'Ї': 'YI', 'Є': 'E', 'Ґ': 'G', 'Ў': 'U'
  };

  function норм(вход) {
    try {
      var с = String(вход == null ? '' : вход).toUpperCase();
      var из = '';
      for (var i = 0; i < с.length; i++) {
        var ч = с.charAt(i);
        из += Object.prototype.hasOwnProperty.call(ТАБЛИЦА, ч) ? ТАБЛИЦА[ч] : ч;
      }
      return из.replace(/[^A-Z0-9]/g, '').slice(0, 5);
    } catch (е) { return ''; }
  }

  /* Детерминированный код из любого непустого входа: FNV-1a 32 бита.
     Чистая арифметика — одинаковый результат на всех устройствах. */
  function дет(вход) {
    try {
      var с = String(вход == null ? '' : вход);
      if (!с) return '';
      var h = 0x811c9dc5;
      for (var i = 0; i < с.length; i++) {
        h ^= с.charCodeAt(i);
        h = (h * 0x01000193) >>> 0;
      }
      h = (h ^ 0x9e3779b9) >>> 0;
      var код = '';
      for (var k = 0; k < 5; k++) {
        код += АЛФАВИТ.charAt(h % АЛФАВИТ.length);
        h = ((h * 31) + 0x68e31fe4) >>> 0;
      }
      return код;
    } catch (е) { return ''; }
  }

  /* Единая точка: норм ≥4 → он; вход непуст → дет; пусто → фолбэк. */
  function код(вход, фолбэк) {
    try {
      var н = норм(вход);
      if (н.length >= 4) return н;
      if (String(вход == null ? '' : вход) !== '') return дет(вход);
      return typeof фолбэк === 'function' ? фолбэк() : (фолбэк || '');
    } catch (е) {
      return typeof фолбэк === 'function' ? фолбэк() : (фолбэк || '');
    }
  }

  глоб.ЗАЛКОД = { норм: норм, дет: дет, код: код, алфавит: АЛФАВИТ, версия: 1 };
})(typeof window !== 'undefined' ? window : globalThis);
