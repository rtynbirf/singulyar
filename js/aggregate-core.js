/* ═══════════════════════════════════════════════════════════════════════════
   СИНГУЛЯР · порт агрегат-ядро/0.1 (слой М5 «КОЛЛЕКТИВНЫЙ ИНТЕЛЛЕКТ»)
   такт v11.47 «ЗАКРЫТИЕ» (С125) · для дверей дома, Chromium 76 (ES2019)

   Порт ≡ канону агрегат-ядро.mjs байт-в-байт по результатам (vm-доказано).
   Ставится в окно как запечатанный __АГРЕГАТ; повторная загрузка безопасна.
   • 0 сети / 0 случайности / 0 часов; вход не мутируется.
   • DOM не трогает — никакого innerHTML; только window.__АГРЕГАТ.
   • без window честно отказывается и не ставится (не молчит).
   ═══════════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';
  var корень = typeof window !== 'undefined' ? window : null;
  if (!корень) {
    throw new Error('агрегат-ядро: порт живёт в браузере — window не найден');
  }

  /* ── FNV-1a 32-бит ── */
  function fnv1a(строка) {
    if (typeof строка !== 'string') {
      throw new TypeError('fnv1a принимает только строку');
    }
    var хэш = 0x811c9dc5;
    for (var индекс = 0; индекс < строка.length; индекс += 1) {
      хэш ^= строка.charCodeAt(индекс);
      хэш = Math.imul(хэш, 0x01000193);
    }
    return хэш >>> 0;
  }

  /* ── детерминированный анонимный бакет ── */
  function бакет(ид, соль, модуль) {
    if (typeof ид !== 'string') {
      throw new TypeError('бакет: ид должен быть строкой');
    }
    if (ид.length === 0) {
      throw new RangeError('бакет: ид пуст — анонимизация не работает с пустыми личностями');
    }
    if (typeof соль !== 'string') {
      throw new TypeError('бакет: соль должна быть строкой');
    }
    if (typeof модуль !== 'number' || Number.isNaN(модуль)) {
      throw new TypeError('бакет: модуль должен быть числом');
    }
    if (!Number.isInteger(модуль) || модуль < 1) {
      throw new RangeError('бакет: модуль должен быть целым числом ≥ 1');
    }
    return fnv1a(соль + '\u0000' + ид) % модуль;
  }

  /* ── сборка k-анонимного агрегата ── */
  function собрать(события, опции) {
    if (события === null || typeof события !== 'object' || !Array.isArray(события)) {
      throw new TypeError('события должны быть массивом');
    }
    if (опции === undefined || опции === null) опции = {};
    if (typeof опции !== 'object' || Array.isArray(опции)) {
      throw new TypeError('опции должны быть объектом');
    }
    var k = 5;
    if (опции.k !== undefined) {
      if (typeof опции.k !== 'number' || Number.isNaN(опции.k)) {
        throw new TypeError('опции.k должна быть числом');
      }
      if (!Number.isInteger(опции.k) || опции.k < 1) {
        throw new RangeError('опции.k должна быть целым числом ≥ 1');
      }
      k = опции.k;
    }
    var категоризация = null;
    if (опции.категоризация !== undefined) {
      if (typeof опции.категоризация !== 'function') {
        throw new TypeError('опции.категоризация должна быть функцией');
      }
      категоризация = опции.категоризация;
    }
    var счётчики = Object.create(null); /* null-прототип: «toString»/«__proto__» не бакеты */
    var имена = [];
    for (var номер = 0; номер < события.length; номер += 1) {
      var событие = события[номер];
      if (событие === null || typeof событие !== 'object' || Array.isArray(событие)) {
        throw new TypeError('событие ' + номер + ' должно быть объектом');
      }
      var категория;
      if (категоризация !== null) {
        var первые = категоризация(событие);
        var второй = категоризация(событие);
        var третий = категоризация(событие);
        if (typeof первые !== 'string' || typeof второй !== 'string' || typeof третий !== 'string') {
          throw new TypeError('категоризация события ' + номер + ' вернула не строку: бакетам нужны строки');
        }
        if (первые !== второй || второй !== третий) {
          throw new TypeError('категоризация не детерминирована: событие ' + номер + ' получило разные категории при трёх вызовах');
        }
        категория = первые;
      } else {
        категория = событие.категория;
      }
      if (typeof категория !== 'string' || категория.length === 0) {
        throw new RangeError('категория пуста (событие ' + номер + '): анонимизация не выдумывает бакеты');
      }
      if (!Object.prototype.hasOwnProperty.call(счётчики, категория)) {
        счётчики[категория] = 0;
        имена.push(категория);
      }
      счётчики[категория] += 1;
    }
    имена.sort();
    var агрегат = {};
    var скрыто = {};
    var вырожден = true;
    for (var индекс = 0; индекс < имена.length; индекс += 1) {
      var имя = имена[индекс];
      if (счётчики[имя] >= k) {
        агрегат[имя] = счётчики[имя];
        вырожден = false;
      } else {
        скрыто[имя] = 'меньше k';
      }
    }
    return {
      агрегат: агрегат,
      скрыто: скрыто,
      k: k,
      всего: события.length,
      вырожден: вырожден,
      версия: 'агрегат-ядро/0.1',
    };
  }

  function версия() {
    return 'агрегат-ядро/0.1';
  }

  var API = Object.freeze({
    fnv1a: fnv1a,
    бакет: бакет,
    собрать: собрать,
    версия: версия,
  });

  if (Object.prototype.hasOwnProperty.call(корень, '__АГРЕГАТ')) {
    return; /* повторная загрузка — честный no-op (идемпотентность) */
  }
  Object.defineProperty(корень, '__АГРЕГАТ', {
    value: API,
    writable: false,
    enumerable: true,
    configurable: false,
  });
})();
