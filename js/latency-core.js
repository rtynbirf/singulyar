/*
 * latency-core.js — порт канона латенс-ядро/0.1 «ГЛОБАЛЬНЫЙ ВРЕМЕННОЙ СИНХРОН»
 * для окон дома (без модулей, ES2019). Копия алгоритмов канона латенс-ядро/0.1:
 * медиана разностей рукопожатий { здесь, там }, разброс p75−p25 с линейной
 * интерполяцией, компенсация меток, скользящие окна. Ставится в окно как
 * запечатанный __ЛАТЕНС; повторная загрузка скрипта безопасна.
 *
 * Законы дома (нарушать нельзя — это шрамы прежних тактов):
 *   0 сети                — порт никогда не обращается в сеть (fetch/XHR/WebSocket под запретом);
 *   0 случайности         — одинаковый вход даёт одинаковый выход (Math.random запрещён);
 *   0 часов               — время не вызывается никогда (Date.now/performance.now запрещены);
 *   вход не мутируется    — порт не меняет свои аргументы;
 *   честные русские отказы — на неверный вход RangeError/TypeError/Error с русским сообщением;
 *   DOM не трогает        — никакого innerHTML и прикосновений к документу; только window.__ЛАТЕНС.
 *
 * такт v11.47 «ЗАКРЫТИЕ» (С125)
 */
(function () {
  'use strict';
  try {
    function перцентиль(отсортированные, доляКвантиля) {
      var длина = отсортированные.length;
      var место = (длина - 1) * доляКвантиля;
      var нижнее = Math.floor(место);
      var верхнее = Math.ceil(место);
      if (нижнее === верхнее) {
        return отсортированные[нижнее];
      }
      var доля = место - нижнее;
      return отсортированные[нижнее] * (1 - доля) + отсортированные[верхнее] * доля;
    }

    function смещение(пары, опции) {
      if (опции === undefined) опции = {};
      if (опции === null || typeof опции !== 'object' || Array.isArray(опции)) {
        throw new TypeError('опции должны быть объектом');
      }
      if (!Array.isArray(пары)) {
        throw new TypeError('пары должны быть массивом рукопожатий { здесь, там }');
      }
      var минимум = 3;
      if (опции.минПроб !== undefined) {
        if (typeof опции.минПроб !== 'number' || Number.isNaN(опции.минПроб)) {
          throw new TypeError('опции.минПроб должна быть числом');
        }
        if (!Number.isInteger(опции.минПроб) || опции.минПроб < 1) {
          throw new RangeError('опции.минПроб должна быть целым числом ≥ 1');
        }
        минимум = опции.минПроб;
      }
      if (пары.length < минимум) {
        throw new RangeError('мало проб: смещение не выдумываем (нужно ≥' + минимум + ')');
      }

      var разности = [];
      for (var номер = 0; номер < пары.length; номер += 1) {
        var пара = пары[номер];
        if (пара === null || typeof пара !== 'object' || Array.isArray(пара)) {
          throw new TypeError('пара ' + номер + ' должна быть объектом { здесь, там }');
        }
        if (typeof пара.здесь !== 'number' || Number.isNaN(пара.здесь)) {
          throw new TypeError('пара ' + номер + ': поле «здесь» должно быть числом');
        }
        if (typeof пара.там !== 'number' || Number.isNaN(пара.там)) {
          throw new TypeError('пара ' + номер + ': поле «там» должно быть числом');
        }
        if (!Number.isFinite(пара.здесь) || !Number.isFinite(пара.там)) {
          throw new RangeError('пара ' + номер + ': метки времени должны быть конечными числами');
        }
        разности.push(пара.там - пара.здесь);
      }

      var упорядоченные = разности.slice().sort(function (левое, правое) { return левое - правое; });
      var p25 = перцентиль(упорядоченные, 0.25);
      var p75 = перцентиль(упорядоченные, 0.75);

      return {
        смещениеМс: перцентиль(упорядоченные, 0.5),
        проб: пары.length,
        разбросМс: p75 - p25,
        версия: 'латенс-ядро/0.1'
      };
    }

    function компенсировать(метка, смещениеМс) {
      if (typeof метка !== 'number' || Number.isNaN(метка)) {
        throw new TypeError('метка должна быть числом');
      }
      if (!Number.isFinite(метка)) {
        throw new RangeError('метка должна быть конечным числом');
      }
      if (typeof смещениеМс !== 'number' || Number.isNaN(смещениеМс)) {
        throw new TypeError('смещение должно быть числом');
      }
      if (!Number.isFinite(смещениеМс)) {
        throw new RangeError('смещение должно быть конечным числом');
      }
      return метка + смещениеМс;
    }

    function окно(метки, размер) {
      if (!Array.isArray(метки)) {
        throw new TypeError('метки должны быть массивом чисел');
      }
      if (typeof размер !== 'number' || Number.isNaN(размер)) {
        throw new TypeError('размер окна должен быть числом');
      }
      if (!Number.isInteger(размер) || размер < 1) {
        throw new RangeError('размер окна должен быть целым числом ≥ 1');
      }
      for (var номер = 0; номер < метки.length; номер += 1) {
        var метка = метки[номер];
        if (typeof метка !== 'number' || Number.isNaN(метка)) {
          throw new TypeError('метка ' + номер + ' должна быть числом');
        }
        if (!Number.isFinite(метка)) {
          throw new RangeError('метка ' + номер + ' должна быть конечным числом');
        }
      }
      if (метки.length === 0) {
        return [];
      }
      var окна = [];
      var последнийСтарт = Math.max(0, метки.length - размер);
      for (var старт = 0; старт <= последнийСтарт; старт += 1) {
        окна.push(метки.slice(старт, Math.min(старт + размер, метки.length)));
      }
      return окна;
    }

    var ЛАТЕНС = Object.freeze({
      смещение: смещение,
      компенсировать: компенсировать,
      окно: окно
    });

    var корень = typeof window !== 'undefined' ? window : null;
    if (корень === null) {
      throw new Error('латенс-ядро: нет window — порт живёт только в браузере');
    }
    Object.defineProperty(корень, '__ЛАТЕНС', {
      value: ЛАТЕНС,
      configurable: false
    });
  } catch (ошибка) {
    if (typeof console !== 'undefined' && console && typeof console.error === 'function') {
      console.error('латенс-ядро: порт не установлен —', ошибка && ошибка.message ? ошибка.message : ошибка);
    }
  }
})();
