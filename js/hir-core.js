    function сравнитьПоКодовымТочкам(левая, правая) {
      if (левая === правая) return 0;
      var нитиЛевой = Array.from(левая);
      var нитиПравой = Array.from(правая);
      var общаяДлина = Math.min(нитиЛевой.length, нитиПравой.length);
      for (var шаг = 0; шаг < общаяДлина; шаг += 1) {
        var точкаЛевой = нитиЛевой[шаг].codePointAt(0);
        var точкаПравой = нитиПравой[шаг].codePointAt(0);
        if (точкаЛевой !== точкаПравой) return точкаЛевой < точкаПравой ? -1 : 1;
      }
      if (нитиЛевой.length !== нитиПравой.length) {
        return нитиЛевой.length < нитиПравой.length ? -1 : 1;
      }
      return 0;
    }

    function частотыNграмм(строка, минимум, максимум) {
      var частоты = new Map();
      for (var длина = минимум; длина <= максимум; длина += 1) {
        for (var старт = 0; старт + длина <= строка.length; старт += 1) {
          var грамма = строка.slice(старт, старт + длина);
          частоты.set(грамма, (частоты.get(грамма) || 0) + 1);
        }
      }
      return частоты;
    }

    function нормализованныйВекторL2(частоты) {
      var сумма = 0;
      for (const частота of частоты.values()) сумма += частота * частота;
      var норма = Math.sqrt(сумма);
      if (!(норма > 0)) return new Map();
      var вектор = new Map();
      for (const [грамма, вес] of частоты) вектор.set(грамма, вес / норма);
      return вектор;
    }

    function скалярноеПроизведение(левый, правый) {
      var сумма = 0;
      var меньший = левый.size <= правый.size ? левый : правый;
      var больший = меньший === левый ? правый : левый;
      for (const [грамма, вес] of меньший) {
        var чужойВес = больший.get(грамма);
        if (чужойВес !== undefined) сумма += вес * чужойВес;
      }
      return сумма;
    }

