/*
 * value-core.js — порт канона ценность-ядро/0.1 «VALUE-FOR-VALUE» для окон дома
 * (без модулей, ES2019). Копия алгоритмов канона ценность-ядро/0.1: рецепт
 * 50/10/20/15/5, метод наибольшего остатка, честные русские отказы, внешняя
 * подпись доли. Ставится в окно как запечатанный __ЦЕННОСТЬ; повторная загрузка
 * скрипта безопасна — свойство не переопределяется и не стирается.
 *
 * Законы дома (нарушать нельзя — это шрамы прежних тактов):
 *   0 сети                — порт никогда не обращается в сеть (fetch/XHR/WebSocket под запретом);
 *   0 случайности         — одинаковый вход даёт одинаковый выход (Math.random запрещён);
 *   0 часов               — время не вызывается никогда (Date.now/performance.now запрещены);
 *   вход не мутируется    — порт не меняет свои аргументы;
 *   честные русские отказы — на неверный вход RangeError/TypeError/Error с русским сообщением;
 *   DOM не трогает        — никакого innerHTML и прикосновений к документу; только window.__ЦЕННОСТЬ.
 *
 * такт v11.47 «ЗАКРЫТИЕ» (С125)
 */
(function () {
  'use strict';
  try {
    var КЛЮЧИ_ДОЛЕЙ = ['автор', 'переводчик', 'слушатели', 'сеть', 'резерв'];

    var РЕЦЕПТ = Object.freeze({
      автор: 50,
      переводчик: 10,
      слушатели: 20,
      сеть: 15,
      резерв: 5
    });

    function проверитьРецепт(рецепт) {
      if (рецепт === null || typeof рецепт !== 'object' || Array.isArray(рецепт)) {
        throw new TypeError('рецепт должен быть объектом с пятью долями: автор, переводчик, слушатели, сеть, резерв');
      }
      var сумма = 0;
      for (var индекс = 0; индекс < КЛЮЧИ_ДОЛЕЙ.length; индекс += 1) {
        var ключ = КЛЮЧИ_ДОЛЕЙ[индекс];
        var доля = рецепт[ключ];
        if (доля === undefined) {
          throw new RangeError('рецепт не сходится: доли должны давать 100');
        }
        if (typeof доля !== 'number' || Number.isNaN(доля)) {
          throw new TypeError('доля «' + ключ + '» в рецепте должна быть числом');
        }
        if (!Number.isInteger(доля) || доля < 0) {
          throw new RangeError('рецепт не сходится: доли должны давать 100');
        }
        сумма += доля;
      }
      var имена = Object.keys(рецепт);
      for (var лишний = 0; лишний < имена.length; лишний += 1) {
        if (КЛЮЧИ_ДОЛЕЙ.indexOf(имена[лишний]) === -1) {
          throw new RangeError('в рецепте лишний ключ «' + имена[лишний] + '»: канон знает ровно пять долей');
        }
      }
      if (сумма !== 100) {
        throw new RangeError('рецепт не сходится: доли должны давать 100');
      }
    }

    function распределить(сумма, рецепт) {
      if (рецепт === undefined) рецепт = РЕЦЕПТ;
      if (typeof сумма !== 'number' || Number.isNaN(сумма)) {
        throw new TypeError('сумма должна быть числом минорных единиц (копейки/сатоши-класс)');
      }
      if (!Number.isFinite(сумма)) {
        throw new RangeError('сумма должна быть конечным числом');
      }
      if (!Number.isInteger(сумма)) {
        throw new RangeError('сумма должна быть целым числом минорных единиц: дробные копейки не переводим');
      }
      if (сумма < 0) {
        throw new RangeError('сумма не может быть отрицательной');
      }
      if (сумма > Number.MAX_SAFE_INTEGER) {
        throw new RangeError('сумма превышает Number.MAX_SAFE_INTEGER: канон не рискует точностью');
      }
      проверитьРецепт(рецепт);

      var целыхСотен = Math.floor(сумма / 100);
      var хвост = сумма % 100;

      var базы = {};
      var остатки = [];
      for (var шаг = 0; шаг < КЛЮЧИ_ДОЛЕЙ.length; шаг += 1) {
        var ключБазы = КЛЮЧИ_ДОЛЕЙ[шаг];
        var доляБазы = рецепт[ключБазы];
        базы[ключБазы] = целыхСотен * доляБазы + Math.floor((хвост * доляБазы) / 100);
        остатки.push({ ключ: ключБазы, индекс: шаг, дробь: (хвост * доляБазы) % 100 });
      }

      var нераздано = сумма;
      for (var счётБаз = 0; счётБаз < КЛЮЧИ_ДОЛЕЙ.length; счётБаз += 1) {
        нераздано -= базы[КЛЮЧИ_ДОЛЕЙ[счётБаз]];
      }

      остатки.sort(function (левое, правое) {
        return (правое.дробь - левое.дробь) || (левое.индекс - правое.индекс);
      });

      var доли = {};
      for (var развод = 0; развод < КЛЮЧИ_ДОЛЕЙ.length; развод += 1) {
        доли[КЛЮЧИ_ДОЛЕЙ[развод]] = базы[КЛЮЧИ_ДОЛЕЙ[развод]];
      }
      for (var добавка = 0; добавка < остатки.length && нераздано > 0; добавка += 1, нераздано -= 1) {
        доли[остатки[добавка].ключ] += 1;
      }

      var роздано = 0;
      for (var счётДолей = 0; счётДолей < КЛЮЧИ_ДОЛЕЙ.length; счётДолей += 1) {
        роздано += доли[КЛЮЧИ_ДОЛЕЙ[счётДолей]];
      }

      return { доли: доли, остаток: сумма - роздано, версия: 'ценность-ядро/0.1' };
    }

    function каноничнаяСтрока(значение, путь, увиденное) {
      if (значение === null) {
        return 'null';
      }
      var вид = typeof значение;
      if (вид === 'string') {
        return JSON.stringify(значение);
      }
      if (вид === 'boolean') {
        return значение ? 'true' : 'false';
      }
      if (вид === 'number') {
        if (Number.isNaN(значение) || !Number.isFinite(значение)) {
          throw new RangeError('канонизировать не принимает NaN и Infinity: это не JSON');
        }
        return JSON.stringify(значение);
      }
      if (вид !== 'object') {
        throw new TypeError('канонизировать принимает только JSON-значения (строка, число, булево, null, массив, объект), а получено: ' + вид);
      }
      for (var поиск = 0; поиск < увиденное.length; поиск += 1) {
        if (увиденное[поиск] === значение) {
          throw new RangeError('канонизировать нашёл циклическую ссылку по пути «' + путь.join('.') + '»: канонической строки не построить');
        }
      }
      увиденное.push(значение);
      var части;
      if (Array.isArray(значение)) {
        части = [];
        for (var элемент = 0; элемент < значение.length; элемент += 1) {
          части.push(каноничнаяСтрока(значение[элемент], путь.concat([элемент]), увиденное));
        }
        увиденное.pop();
        return '[' + части.join(',') + ']';
      }
      var ключи = Object.keys(значение).sort();
      части = [];
      for (var шагКлюча = 0; шагКлюча < ключи.length; шагКлюча += 1) {
        var ключ = ключи[шагКлюча];
        var вложенное = значение[ключ];
        if (вложенное === undefined) {
          throw new TypeError('канонизировать нашёл undefined по пути «' + путь.concat([ключ]).join('.') + '»: undefined — это не JSON');
        }
        части.push(JSON.stringify(ключ) + ':' + каноничнаяСтрока(вложенное, путь.concat([ключ]), увиденное));
      }
      увиденное.pop();
      return '{' + части.join(',') + '}';
    }

    function канонизировать(значение) {
      return каноничнаяСтрока(значение, [], []);
    }

    function подписатьДолю(доля, подписант) {
      if (typeof подписант !== 'function') {
        throw new TypeError('подписант не передан: деньги без подписи не выходят');
      }
      if (доля === null || typeof доля !== 'object' || Array.isArray(доля)) {
        throw new TypeError('доля должна быть объектом долей (например, результат распределить)');
      }
      var канонСтрока = канонизировать(доля);
      var ответПодписанта;
      try {
        ответПодписанта = подписант(канонСтрока);
      } catch (отказ) {
        return Promise.reject(отказ);
      }
      return Promise.resolve(ответПодписанта).then(function (подпись) {
        return { канонСтрока: канонСтрока, подпись: подпись };
      });
    }

    var ЦЕННОСТЬ = Object.freeze({
      РЕЦЕПТ: РЕЦЕПТ,
      распределить: распределить,
      подписатьДолю: подписатьДолю,
      канонизировать: канонизировать
    });

    var корень = typeof window !== 'undefined' ? window : null;
    if (корень === null) {
      throw new Error('ценность-ядро: нет window — порт живёт только в браузере');
    }
    Object.defineProperty(корень, '__ЦЕННОСТЬ', {
      value: ЦЕННОСТЬ,
      configurable: false
    });
  } catch (ошибка) {
    if (typeof console !== 'undefined' && console && typeof console.error === 'function') {
      console.error('ценность-ядро: порт не установлен —', ошибка && ошибка.message ? ошибка.message : ошибка);
    }
  }
})();
