(function () {
  'use strict';
  if (window.__ВСОЛА) return; /* повторная вставка — молча, один канон */

  var ИМЯ = 'wsola-core/0.1';
  var УМОЛЧАНИЯ = Object.freeze({
    окноМс: 30,
    поискМс: 15,
    частотаСэмплов: 44100,
    коэффициентМин: 0.25,
    коэффициентМакс: 4.0
  });

  function число(х) { return (typeof х === 'number' && isFinite(х)) ? х : null; }

  function проверитьВход(x) {
    if (!(x instanceof Float32Array)) {
      throw new TypeError('вход должен быть Float32Array, пришло ' + (x === null ? 'null' : typeof x));
    }
    if (x.length === 0) return 'вход пуст: растягивать нечего';
    return null;
  }

  function проверитьДлину(x, N, T) {
    if (x.length < N + T) return 'вход короче кадра с окном поиска: ' + x.length + ' < ' + (N + T) + ' сэмплов';
    return null;
  }

  function проверитьКоэффициент(к) {
    var х = число(к);
    if (х === null) return 'коэффициент должен быть конечным числом, пришло ' + String(к);
    if (х < УМОЛЧАНИЯ.коэффициентМин || х > УМОЛЧАНИЯ.коэффициентМакс) {
      return 'коэффициент ' + х + ' вне честного диапазона ' + УМОЛЧАНИЯ.коэффициентМин + '–' + УМОЛЧАНИЯ.коэффициентМакс;
    }
    return null;
  }

  function собратьОпоры(опции) {
    var о = опции || {};
    var окноМс = УМОЛЧАНИЯ.окноМс;
    if (о.окноМс !== undefined) {
      if (число(о.окноМс) === null) throw new RangeError('окноМс должно быть конечным числом, пришло ' + String(о.окноМс));
      if (о.окноМс < 5 || о.окноМс > 100) throw new RangeError('окноМс ' + о.окноМс + ' вне честного диапазона 5–100 мс');
      окноМс = о.окноМс;
    }
    var поискМс = УМОЛЧАНИЯ.поискМс;
    if (о.поискМс !== undefined) {
      if (число(о.поискМс) === null) throw new RangeError('поискМс должно быть конечным числом, пришло ' + String(о.поискМс));
      if (поискМс < 1 || поискМс > 50) throw new RangeError('поискМс ' + поискМс + ' вне честного диапазона 1–50 мс');
      поискМс = о.поискМс;
    }
    var ср = УМОЛЧАНИЯ.частотаСэмплов;
    if (о.частотаСэмплов !== undefined) {
      if (число(о.частотаСэмплов) === null || о.частотаСэмплов < 8000 || о.частотаСэмплов > 192000) {
        throw new RangeError('частотаСэмплов ' + о.частотаСэмплов + ' вне честного диапазона 8000–192000 Гц');
      }
      ср = о.частотаСэмплов;
    }
    var N = Math.round(окноМс * ср / 1000);
    if (N % 2 !== 0) N += 1;
    var Ha = N >> 1;
    var T = Math.max(1, Math.round(поискМс * ср / 1000));
    var Δ = T;
    var Ханн = new Float64Array(N);
    for (var i = 0; i < N; i++) Ханн[i] = 0.5 - 0.5 * Math.cos(2 * Math.PI * i / (N - 1));
    return { ср: ср, N: N, Ha: Ha, T: T, Δ: Δ, Ханн: Ханн, окноМс: окноМс, поискМс: поискМс };
  }

  function корреляция(a, a0, б, б0, длина) {
    var п = 0, са = 0, сб = 0;
    for (var i = 0; i < длина; i++) {
      var х = a[a0 + i], у = б[б0 + i];
      п += х * у; са += х * х; сб += у * у;
    }
    var з = Math.sqrt(са * сб);
    return з > 1e-12 ? п / з : 0;
  }

  function смещения(x, коэффициент, опции) {
    var брак = проверитьКоэффициент(коэффициент);
    if (брак) throw new RangeError('смещения: ' + брак);
    проверитьВход(x);
    var о = собратьОпоры(опции);
    var пусто = проверитьВход(x);
    if (пусто) throw new RangeError('смещения: ' + пусто);
    var б = проверитьДлину(x, о.N, о.Δ);
    if (б) throw new RangeError('смещения: ' + б);
    if (коэффициент === 1) return new Int32Array(0);
    var Hs = о.Ha * коэффициент;
    var K = Math.max(1, Math.floor((x.length - о.N - о.Δ) / Hs));
    var τ = new Int32Array(K);
    for (var k = 1; k < K; k++) {
      var номинал = Math.round(k * Hs);
      var пред = τ[k - 1];
      var прод = пред + Math.round((k - 1) * Hs) + о.Ha;
      var лучший = 0, макс = -2;
      for (var сдвиг = -о.Δ; сдвиг <= о.Δ; сдвиг++) {
        var канд = номинал + сдвиг;
        if (канд < 0 || канд + о.N + о.T > x.length || прод + о.T > x.length) continue;
        var c = корреляция(x, прод, x, канд, о.T);
        if (c > макс + 1e-12 || (Math.abs(c - макс) <= 1e-12 &&
            (Math.abs(сдвиг) < Math.abs(лучший) || (Math.abs(сдвиг) === Math.abs(лучший) && сдвиг < лучший)))) {
          макс = c; лучший = сдвиг;
        }
      }
      τ[k] = лучший;
    }
    return τ;
  }

  function растянуть(x, опции) {
    опции = опции || {};
    var коэффициент = опции.коэффициент !== undefined ? опции.коэффициент : опции.rate;
    var брак = проверитьКоэффициент(коэффициент);
    if (брак) throw new RangeError('растянуть: ' + брак);
    проверитьВход(x);
    var о = собратьОпоры(опции);
    var пусто = проверитьВход(x);
    if (пусто) throw new RangeError('растянуть: ' + пусто);
    var б = проверитьДлину(x, о.N, о.Δ);
    if (б) throw new RangeError('растянуть: ' + б);
    if (коэффициент === 1) return new Float32Array(x);
    var τ = смещения(x, коэффициент, опции);
    var K = τ.length;
    var outN = (K - 1) * о.Ha + о.N;
    var out = new Float64Array(outN);
    var winSum = new Float64Array(outN);
    var Hs = о.Ha * коэффициент;
    for (var k = 0; k < K; k++) {
      var старт = Math.round(k * Hs) + τ[k];
      var база = k * о.Ha;
      for (var i = 0; i < о.N; i++) {
        out[база + i] += о.Ханн[i] * x[старт + i];
        winSum[база + i] += о.Ханн[i];
      }
    }
    var рез = new Float32Array(outN);
    for (var j = 0; j < outN; j++) рез[j] = winSum[j] > 1e-9 ? out[j] / winSum[j] : 0;
    return рез;
  }

  function растянутьСтерео(каналы, опции) {
    опции = опции || {};
    if (!Array.isArray(каналы) || каналы.length < 1) {
      throw new TypeError('растянутьСтерео: каналы должны быть массивом Float32Array');
    }
    var коэффициент = опции.коэффициент !== undefined ? опции.коэффициент : опции.rate;
    var брак = проверитьКоэффициент(коэффициент);
    if (брак) throw new RangeError('растянутьСтерео: ' + брак);
    var длина = каналы[0].length;
    for (var c = 0; c < каналы.length; c++) {
      if (!(каналы[c] instanceof Float32Array)) throw new TypeError('растянутьСтерео: канал ' + c + ' не Float32Array');
      if (каналы[c].length !== длина) throw new RangeError('растянутьСтерео: длины каналов не равны (' + каналы[c].length + ' ≠ ' + длина + ')');
    }
    if (каналы.length === 1) return { каналы: [растянуть(каналы[0], опции)] };
    if (коэффициент === 1) {
      var копии = [];
      for (var ч = 0; ч < каналы.length; ч++) копии.push(new Float32Array(каналы[ч]));
      return { каналы: копии };
    }
    var микс = new Float32Array(длина);
    for (var i = 0; i < длина; i++) {
      var s = 0;
      for (var к = 0; к < каналы.length; к++) s += каналы[к][i];
      микс[i] = s / каналы.length;
    }
    var τ = смещения(микс, коэффициент, опции);
    var о = собратьОпоры(опции);
    var K = τ.length;
    var outN = (K - 1) * о.Ha + о.N;
    var Hs = о.Ha * коэффициент;
    var рез = [];
    for (var р = 0; р < каналы.length; р++) рез.push(new Float64Array(outN));
    var winSum = new Float64Array(outN);
    for (var k2 = 0; k2 < K; k2++) {
      var старт = Math.round(k2 * Hs) + τ[k2];
      var база = k2 * о.Ha;
      for (var i2 = 0; i2 < о.N; i2++) {
        var w = о.Ханн[i2];
        winSum[база + i2] += w;
        for (var к2 = 0; к2 < каналы.length; к2++) рез[к2][база + i2] += w * каналы[к2][старт + i2];
      }
    }
    var готово = [];
    for (var г = 0; г < рез.length; г++) {
      var f = new Float32Array(outN);
      for (var j = 0; j < outN; j++) f[j] = winSum[j] > 1e-9 ? рез[г][j] / winSum[j] : 0;
      готово.push(f);
    }
    return { каналы: готово };
  }

  function инфо() {
    return {
      имя: ИМЯ,
      метод: 'WSOLA (Verhelst & Roelandts 1993): поиск по взаимной корреляции + перекрытие-сложение Ханна',
      умеет: ['моно Float32Array', 'стерео одним набором смещений (микс-поиск)', 'коэффициент 0.25–4.0', 'высота и форманты стоят'],
      не_умеет: ['потоковое растяжение на лету (следующая генерация — AudioWorklet)', 'сдвиг тональности (это detune, не тайм-стретч)', 'WASM-ускорение (честный хвост)'],
      границы: УМОЛЧАНИЯ,
      честность: '0 сети, 0 случайности, вход не мутируется, отказы по-русски'
    };
  }

  window.__ВСОЛА = {
    имя: ИМЯ,
    растянуть: растянуть,
    растянутьСтерео: растянутьСтерео,
    смещения: смещения,
    инфо: инфо
  };
})();
